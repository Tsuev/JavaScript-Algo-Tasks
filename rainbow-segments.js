// Задача: Rainbow Segments
// Сложность: medium
// Дата генерации: 2026-09-10

// Условие задачи
// Радуга состоит из семи цветов. Закодируем их первыми семью строчными латинскими буквами: 'a', 'b', 'c', 'd', 'e', 'f', 'g'. Дана строка s, состоящая только из этих букв.
// 
// Отрезком (подстрокой) будем называть непрерывную часть строки, задаваемую парой индексов l ≤ r. Отрезок называется радужным, если в нём встречаются все семь букв — каждая хотя бы один раз.
// 
// Требуется посчитать количество радужных отрезков строки.
// 
// Формат входных данных:
// Одна строка s, состоящая из символов 'a'..'g'. Длина строки n удовлетворяет 1 ≤ n ≤ 10^6.
// 
// Формат результата:
// Одно целое число — количество отрезков, содержащих все семь различных букв.
// 
// Примеры:
// 1) s = "abcdefg"        → 1   (радужный только весь отрезок [0..6])
// 2) s = "abcdefga"       → 3   (подходят [0..6], [0..7], [1..7])
// 3) s = "aabbccddeeffgg" → 4   (по 2 конца на последнюю букву g — начала 0 и 1)
// 4) s = "abcabc"         → 0   (в строке нет всех семи цветов)
// 
// Ограничения: n ≤ 10^6, ожидаемое время работы O(n), дополнительная память O(1).

/**
 * Считает количество отрезков строки s, в которых встречаются все семь
 * «радужных» букв 'a'..'g' (каждая хотя бы один раз).
 *
 * Идея — метод двух указателей (скользящее окно), работает за O(n).
 * Фиксируем правый конец right и поддерживаем минимально возможный левый
 * конец left, при котором окно [left, right] ещё содержит все 7 цветов.
 * После этого любое начало из диапазона [0, left - 1] тоже даёт валидный
 * отрезок, заканчивающийся в right, поэтому добавляем к ответу left.
 *
 * @param {string} s — строка из букв 'a'..'g'
 * @returns {number} количество радужных отрезков
 */
function countRainbowSegments(s) {
  const COLORS = 7;
  const counts = new Array(COLORS).fill(0); // сколько раз каждый цвет лежит в текущем окне
  let distinct = 0; // сколько различных цветов сейчас в окне
  let left = 0;     // левая граница окна
  let total = 0;    // ответ

  for (let right = 0; right < s.length; right++) {
    const c = s.charCodeAt(right) - 97; // 'a' -> 0, ..., 'g' -> 6
    if (counts[c] === 0) distinct++;
    counts[c]++;

    // Сужаем окно слева, пока в нём ещё присутствуют все семь цветов.
    // Как только какой-то цвет исчез полностью — окно стало «почти радужным»
    // и дальше сужать нельзя.
    while (distinct === COLORS) {
      const lc = s.charCodeAt(left) - 97;
      counts[lc]--;
      if (counts[lc] === 0) distinct--;
      left++;
    }

    // Сейчас left — первая позиция, при которой отрезок [left, right]
    // уже не радужный. Значит, для правого конца right подходят все начала
    // от 0 до left - 1 включительно, то есть ровно left отрезков.
    total += left;
  }

  return total;
}
