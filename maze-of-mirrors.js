// Задача: Maze of Mirrors
// Сложность: medium
// Дата генерации: 2026-09-09

// Условие задачи
// В прямоугольной комнате, разбитой на N строк и M столбцов, лазерный луч движется по клеткам. Клетка может быть пустой ('.') или содержать зеркало '/' или '\'. Луч входит через левую границу в строке R и сначала движется вправо.
// 
// Правила отражения:
// - Для '/': вверх -> вправо, вправо -> вверх, вниз -> влево, влево -> вниз.
// - Для '\': вверх -> влево, вправо -> вниз, вниз -> вправо, влево -> вверх.
// 
// Если луч выходит за границы, выведите `EXIT SIDE INDEX`; если зацикливается — `LOOP`.
// 
// Формат входных данных:
// Первая строка содержит N и M (1 <= N, M <= 1000).
// Далее N строк по M символов: '.', '/' или '\'.
// Последняя строка содержит R (0 <= R < N).
// 
// Формат результата:
// Строка `EXIT SIDE INDEX` или `LOOP`.
// SIDE — одно из LEFT, RIGHT, TOP, BOTTOM.
// INDEX — номер строки, если SIDE = LEFT или RIGHT, и номер столбца, если SIDE = TOP или BOTTOM.
// 
// Пример 1:
// Ввод:
// 2 2
// .\
// ..
// 0
// Вывод:
// EXIT BOTTOM 1
// 
// Пример 2:
// Ввод:
// 2 2
// ./
// ..
// 0
// Вывод:
// EXIT TOP 1

function solve(n, m, grid, startRow) {
  // visited[i][j] хранит битовую маску направлений, с которыми луч уже был в клетке
  const visited = Array.from({ length: n }, () => new Uint8Array(m));

  // Направления: 0 - вверх, 1 - вправо, 2 - вниз, 3 - влево
  const dr = [-1, 0, 1, 0];
  const dc = [0, 1, 0, -1];

  let row = startRow;
  let col = 0;
  let dir = 1; // входим слева направо

  while (true) {
    const mask = 1 << dir;
    if ((visited[row][col] & mask) !== 0) {
      return 'LOOP'; // уже были в таком состоянии - цикл
    }
    visited[row][col] |= mask;

    // Отражаем луч от зеркала, если оно есть в клетке
    const ch = grid[row][col].charCodeAt(0);
    if (ch === 47) { // символ '/'
      dir ^= 1;      // вверх<->вправо, вниз<->влево
    } else if (ch === 92) { // обратный слэш (код 92)
      dir = 3 - dir; // вверх<->влево, вниз<->вправо
    }

    const nr = row + dr[dir];
    const nc = col + dc[dir];

    if (nr < 0 || nr >= n || nc < 0 || nc >= m) {
      let side, index;
      if (dir === 0) { side = 'TOP'; index = col; }
      else if (dir === 1) { side = 'RIGHT'; index = row; }
      else if (dir === 2) { side = 'BOTTOM'; index = col; }
      else { side = 'LEFT'; index = row; }
      return `EXIT ${side} ${index}`;
    }

    row = nr;
    col = nc;
  }
}
