// Задача: Lantern Tether Partition
// Сложность: medium
// Дата генерации: 2026-10-02

// Условие задачи
// Вдоль карниза подвешены n фонарей в ряд (нумерация с 1 слева направо). Фонарь i светит с яркостью a[i]. Между двумя соседними фонарями i и i+1 натянут трос, разрезать который стоит c[i] монет. Разрезав часть тросов, гирлянда распадается на группы подряд идущих фонарей: внутри группы фонари связаны неразрезанными тросами, а между группами стоит разрезанный трос.
// 
// Яркость группы — сумма яркостей входящих в неё фонарей. У вас есть бюджет B монет на разрезы. Нужно так разрезать тросы (потратив не больше B монет), чтобы максимальная яркость группы была как можно меньше.
// 
// Формат входных данных. Решение — функция, которая получает три аргумента:
// • brightness — массив длины n, где brightness[i] = a[i+1];
// • cutCost — массив длины n−1, где cutCost[i] = c[i+1] — стоимость разреза троса между фонарями i+1 и i+2;
// • budget — целое число B (бюджет на разрезы).
// 
// Формат результата. Одно целое число — минимально возможная максимальная суммарная яркость группы.
// 
// Ограничения. 1 ≤ n ≤ 100000, 1 ≤ a[i] ≤ 10^9, 0 ≤ c[i] ≤ 10^9, 0 ≤ B ≤ 10^14.
// 
// Пример 1. brightness = [3, 7, 5], cutCost = [2, 9], budget = 2 → 12.
// Пояснение: за 2 монеты можно разрезать только трос между фонарями 1 и 2. Получим группы [3] и [7, 5] с яркостями 3 и 12, максимум равен 12. Если не резать вообще, максимум будет 15, а разрез между фонарями 2 и 3 стоит 9 и в бюджет не влезает. Поэтому ответ 12.
// 
// Пример 2. brightness = [5], cutCost = [], budget = 0 → 5.
// 
// Пример 3. brightness = [1, 2, 3, 4, 5], cutCost = [1, 1, 1, 1], budget = 2 → 6.
// Пояснение: бюджет позволяет сделать не больше двух разрезов. Разрезав тросы между фонарями 3 и 4, а также между 4 и 5, получим группы [1, 2, 3], [4], [5] с максимумом 6. Меньше 6 не получится: при максимуме 5 понадобилось бы минимум три разреза, а это уже 3 монеты.

function minMaxGroupBrightness(brightness, cutCost, budget) {
  const n = brightness.length;
  if (n === 0) return 0;

  // Префиксные суммы яркостей: prefix[i] — сумма первых i фонарей.
  const prefix = new Array(n + 1).fill(0);
  for (let i = 0; i < n; i++) prefix[i + 1] = prefix[i] + brightness[i];

  const INF = Infinity;

  // Проверяем, можно ли разбить гирлянду так, чтобы яркость каждой группы
  // не превышала limit, а суммарная стоимость разрезов уложилась в бюджет.
  const feasible = (limit) => {
    // Фонарь, который сам ярче limit, разрезать нельзя — такой предел не годится.
    for (let i = 0; i < n; i++) if (brightness[i] > limit) return false;

    // dp[i] — минимальная суммарная стоимость разрезов для первых i фонарей.
    const dp = new Array(n + 1).fill(INF);
    dp[0] = 0;

    // "Цена" начала новой группы на позиции j: разрез сразу после фонаря j
    // (перед первым фонарём резать нечего, поэтому для j = 0 цена нулевая).
    const cost = (j) => dp[j] + (j > 0 ? cutCost[j - 1] : 0);

    // Монотонная очередь (дек) хранит индексы j в порядке возрастания cost(j).
    // Это позволяет за O(1) брать минимум по скользящему окну допустимых начал.
    const dq = new Array(n + 1);
    let head = 0;
    let tail = 0;

    for (let i = 1; i <= n; i++) {
      // Новое допустимое начало j = i - 1: группа состоит из одного фонаря i.
      const j = i - 1;
      if (dp[j] < INF) {
        const v = cost(j);
        while (tail > head && cost(dq[tail - 1]) >= v) tail--;
        dq[tail++] = j;
      }
      // Выбрасываем начала, для которых группа (j+1 .. i) стала слишком тяжёлой.
      while (tail > head && prefix[i] - prefix[dq[head]] > limit) head++;
      if (tail > head) dp[i] = cost(dq[head]);
    }

    // Если минимальная стоимость разрезов влезает в бюджет — предел достижим.
    return dp[n] <= budget;
  };

  // Нижняя граница — самый яркий фонарь, верхняя — вся гирлянда без разрезов.
  let lo = 0;
  for (let i = 0; i < n; i++) if (brightness[i] > lo) lo = brightness[i];
  let hi = prefix[n];

  // Двоичный поиск по ответу: свойство "уложиться в бюджет" монотонно по limit.
  while (lo < hi) {
    const mid = lo + Math.floor((hi - lo) / 2);
    if (feasible(mid)) hi = mid;
    else lo = mid + 1;
  }
  return lo;
}
