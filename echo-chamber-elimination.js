// Задача: Echo Chamber Elimination
// Сложность: medium
// Дата генерации: 2026-09-14

// Условие задачи
// Эхо-камера
// 
// В звукозаписывающей студии записали последовательность из n звуковых сигналов — целых чисел. Из-за плохой акустики часть сигналов «эхом» повторяется друг за другом.
// 
// Сигналы считаются «эхом», если подряд идут ровно k одинаковых чисел. Как только в записи появляется такая группа, помещение её заглушает, и вся группа из k чисел исчезает из записи. После исчезновения группы соседние сигналы смыкаются и могут снова образовать группу из k одинаковых чисел — тогда исчезает и она, и так далее, пока это возможно.
// 
// Гарантируется, что итоговая запись не зависит от того, в каком порядке удалять группы.
// 
// Формат входных данных
// Первая строка содержит два целых числа n и k (1 ≤ k ≤ n ≤ 200000).
// Вторая строка содержит n целых чисел a1, a2, ..., an (|ai| ≤ 10^9) — исходная запись.
// 
// Формат результата
// Выведите две строки:
// 1) число m — сколько сигналов осталось в записи;
// 2) m оставшихся чисел через пробел. Если не осталось ничего, вторая строка выводится пустой.
// 
// Пример 1
// Вход:
// 6 2
// 1 2 2 3 2 2
// Выход:
// 2
// 1 3
// Пояснение: удаляется группа «2 2» (позиции 2–3), получаем 1 3 2 2. Теперь снова есть группа «2 2» — она тоже исчезает. Остаётся 1 3.
// 
// Пример 2
// Вход:
// 5 3
// 5 5 5 5 7
// Выход:
// 2
// 5 7
// Пояснение: четыре пятёрки подряд. Любые три из них — эхо, после их исчезновения остаётся 5 7, а двух одинаковых мало.
// 
// Пример 3
// Вход:
// 4 5
// 9 9 9 9
// Выход:
// 4
// 9 9 9 9
// Пояснение: k больше всей последовательности, ни одна группа не набирает нужную длину.
// 
// Пример 4
// Вход:
// 6 2
// 1 2 1 1 2 1
// Выход:
// 0
// Пояснение: 1 2 [1 1] 2 1 → 1 [2 2] 1 → [1 1] → пусто. Каскад из трёх исчезновений.
// 
// Пример 5
// Вход:
// 3 1
// 7 7 7
// Выход:
// 0
// Пояснение: при k = 1 каждый одиночный сигнал сам себе эхо, поэтому исчезает всё.

function eliminateEchoes(n, k, values) {
  // Основная идея: идём по последовательности слева направо и держим стек
  // вида [значение, сколько раз подряд оно сейчас лежит на вершине].
  // В стеке соседние группы всегда имеют разные значения, а счётчик
  // каждой группы не превышает k - 1 (иначе группа уже была бы удалена).
  // Поэтому одного прохода достаточно: смыкание «через дырку» происходит
  // автоматически, когда после удаления группы сверху оказывается
  // предыдущая группа, готовая слиться с новым сигналом.
  const stack = [];

  for (let i = 0; i < n; i += 1) {
    const value = values[i];

    if (stack.length > 0 && stack[stack.length - 1][0] === value) {
      // Такой же сигнал, как на вершине — просто увеличиваем счётчик группы.
      stack[stack.length - 1][1] += 1;
    } else {
      // Значение другое — начинаем новую группу.
      stack.push([value, 1]);
    }

    // Ровно k одинаковых подряд — это эхо, стираем всю группу.
    // Каскад не нужен: после удаления счётчики остальных групп меньше k.
    if (stack[stack.length - 1][1] === k) {
      stack.pop();
    }
  }

  // Разворачиваем стек обратно в плоскую последовательность.
  const result = [];
  for (let g = 0; g < stack.length; g += 1) {
    const value = stack[g][0];
    const count = stack[g][1];
    for (let c = 0; c < count; c += 1) {
      result.push(value);
    }
  }

  return result;
}

// Алгоритм работает за O(n) по времени и O(n) по памяти:
// каждый сигнал добавляется в стек один раз и максимум один раз из него удаляется.
