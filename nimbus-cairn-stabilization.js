// Задача: Nimbus Cairn Stabilization
// Сложность: medium
// Дата генерации: 2026-11-02

// Условие задачи
// «Небесный каирн» — это груда камней, сложенная снизу вверх. Даны n камней; их высоты h[1], h[2], ..., h[n] перечислены в порядке снизу вверх.
// 
// Каирн считается устойчивым, если каждый камень не выше того камня, который лежит непосредственно под ним, то есть выполнено условие:
// h[1] ≥ h[2] ≥ ... ≥ h[n].
// 
// Разрешено только уменьшать камни — «срезать» верхнюю часть. Если камень высоты a уменьшили до высоты b (0 ≤ b ≤ a), стоимость операции равна a − b. Уменьшение до 0 означает, что камень полностью убран из груды.
// 
// Нужно найти минимальную суммарную стоимость операций, после которых каирн станет устойчивым.
// 
// Формат входных данных:
// Функция stabilizeCairn(heights) принимает массив целых неотрицательных чисел heights — высоты камней снизу вверх. Длина массива от 0 до 2000, каждая высота от 0 до 10^9.
// 
// Формат результата:
// Функция возвращает одно целое число — минимальную суммарную стоимость уменьшений.
// 
// Примеры:
// 1) heights = [5, 4, 3]  ->  0
//    Каирн уже устойчив, ничего делать не нужно.
// 
// 2) heights = [3, 5, 2]  ->  2
//    Уменьшаем второй камень с 5 до 3, получаем [3, 3, 2]; стоимость 2. Дешевле нельзя.
// 
// 3) heights = [4, 1, 4, 1]  ->  3
//    Уменьшаем третий камень с 4 до 1, получаем [4, 1, 1, 1]; стоимость 3.
// 
// 4) heights = [1, 2, 3]  ->  3
//    Приводим к [1, 1, 1]: 0 + 1 + 2 = 3.
// 
// 5) heights = []  ->  0
// 
// Пояснение по сложности: высоты могут быть очень большими (до 10^9), поэтому перебирать все возможные высоты нельзя — в решении используется сжатие координат, и время работы составляет O(n^2).

/**
 * Стабилизация каирна: минимизируем суммарную стоимость уменьшения камней,
 * чтобы высоты шли по невозрастанию (снизу вверх).
 *
 * Ключевая идея — динамическое программирование.
 * dp[j] = минимальная стоимость обработки уже просмотренных камней,
 *         если последний обработанный камень имеет высоту values[j].
 *
 * Перебирать высоты от 0 до 10^9 невозможно, поэтому заметим: в оптимальном
 * решении каждый камень либо остаётся исходной высоты, либо уменьшается ровно
 * до высоты какого-то другого камня, либо убирается в 0. Значит, достаточно
 * сжать координаты — взять все исходные высоты плюс 0 и отсортировать.
 *
 * Переход между камнями: предыдущий камень обязан быть не ниже текущего,
 * поэтому нужен минимум dp по всем высотам не меньше текущей — это суффиксный
 * минимум, который считается за один проход.
 *
 * @param {number[]} heights высоты камней снизу вверх
 * @returns {number} минимальная суммарная стоимость уменьшений
 */
function stabilizeCairn(heights) {
  const n = heights.length;
  if (n === 0) return 0;

  // Возможные итоговые высоты: 0 (камень убран) и все исходные высоты.
  const values = Array.from(new Set([0, ...heights])).sort((a, b) => a - b);
  const m = values.length;

  const INF = Number.POSITIVE_INFINITY;

  // Первый камень: его можно только уменьшить, стоимость = heights[0] - values[j].
  let dp = new Array(m).fill(INF);
  for (let j = 0; j < m; j++) {
    if (values[j] <= heights[0]) {
      dp[j] = heights[0] - values[j];
    }
  }

  for (let i = 1; i < n; i++) {
    // suffixMin[j] = минимум dp[j..m-1]. Он нужен потому, что нижний камень
    // должен быть не ниже текущего, то есть его индекс в values не меньше j.
    const suffixMin = new Array(m).fill(INF);
    suffixMin[m - 1] = dp[m - 1];
    for (let j = m - 2; j >= 0; j--) {
      suffixMin[j] = Math.min(dp[j], suffixMin[j + 1]);
    }

    const next = new Array(m).fill(INF);
    for (let j = 0; j < m; j++) {
      const target = values[j];
      // Камень нельзя сделать выше исходного — только срезать.
      if (target > heights[i]) continue;
      if (suffixMin[j] === INF) continue; // такой вариант недостижим

      next[j] = suffixMin[j] + (heights[i] - target);
    }

    dp = next;
  }

  // Последний камень может иметь любую высоту — берём лучший вариант.
  let answer = INF;
  for (let j = 0; j < m; j++) {
    if (dp[j] < answer) answer = dp[j];
  }
  return answer;
}

// Небольшая самопроверка при запуске файла напрямую.
if (typeof module !== 'undefined' && require.main === module) {
  const tests = [
    [[5, 4, 3], 0],
    [[3, 5, 2], 2],
    [[4, 1, 4, 1], 3],
    [[1, 2, 3], 3],
    [[], 0],
  ];
  for (const [input, expected] of tests) {
    const got = stabilizeCairn(input);
    if (got !== expected) {
      throw new Error(`Для [${input}] ожидалось ${expected}, получено ${got}`);
    }
  }
}
