// Задача: Sundial Slat Rotation
// Сложность: hard
// Дата генерации: 2026-10-05

// Условие задачи
// ## Sundial Slat Rotation (Вращение пластин солнечных часов)
// 
// На солнечных часах по кругу закреплено `n` пластин. Пластины пронумерованы по часовой стрелке числами `0, 1, ..., n-1`. Пластина с номером `i` сейчас направлена под углом `a[i]` градусов (`0 <= a[i] < 360`, угол отсчитывается по часовой стрелке от направления «на север»).
// 
// За одну операцию можно выбрать любой непрерывный участок кольца (он может «переходить через край», т.е. содержать пластины `n-1` и `0` одновременно) и повернуть **все** пластины этого участка на 1 градус по часовой стрелке или против часовой стрелки. Поворот всего кольца целиком — это тоже допустимая операция (участок из всех `n` пластин).
// 
// Нужно за минимальное число операций сделать так, чтобы **все пластины смотрели в одну и ту же сторону**. Направление не задано — годится любое.
// 
// ### Формат ввода
// 
// Реализуйте функцию
// 
// ```js
// minRotations(n, a)
// ```
// 
// * `n` — целое число, `1 <= n <= 200000`, количество пластин;
// * `a` — массив из `n` целых чисел, `0 <= a[i] < 360`.
// 
// ### Формат результата
// 
// Функция возвращает одно целое число — минимальное количество операций.
// 
// ### Примеры
// 
// **Пример 1:**
// ```
// minRotations(2, [0, 180])  ->  180
// ```
// Нужно повернуть одну из пластин на 180 градусов (180 операций), иначе углы не совпадут.
// 
// **Пример 2:**
// ```
// minRotations(3, [10, 20, 30])  ->  20
// ```
// Поворачиваем участок из пластин `1` и `2` на -10 градусов: получаем `[10, 10, 20]` (10 операций), затем пластину `2` ещё на -10: получаем `[10, 10, 10]` (ещё 10 операций). Итого 20.
// 
// **Пример 3:**
// ```
// minRotations(3, [350, 10, 20])  ->  30
// ```
// Поворачиваем участок из пластин `1` и `2` на -20 градусов: `[350, 350, 0]` (20 операций), затем пластину `2` на -10: `[350, 350, 350]` (10 операций). Итого 30. Обратите внимание: участок «перескакивает» через 0.
// 
// **Пример 4:**
// ```
// minRotations(5, [0, 1, 2, 3, 4])  ->  4
// ```
// Поворачиваем участки `[1..4]`, `[2..4]`, `[3..4]`, `[4]` каждый раз на -1 градус — всего 4 операции.
// 
// **Пример 5:**
// ```
// minRotations(3, [0, 0, 0])  ->  0
// ```

"use strict";

/**
 * Минимальное число операций, чтобы все пластины солнечных часов
 * смотрели в одну сторону.
 *
 * Одна операция — повернуть любой непрерывный участок кольца
 * на 1 градус по или против часовой стрелки.
 *
 * Ключевая идея: важен не сам угол каждой пластины, а разности углов
 * между соседними пластинами. Если в итоге все углы равны, то для
 * сдвигов b[i] (сколько градусов прибавили пластине i) должно быть
 *
 *     b[i] - b[i-1] ≡ a[i-1] - a[i]  (mod 360).
 *
 * Обозначим d[i] = (a[i-1] - a[i]) mod 360 (значение из [0, 360)).
 * Каждая операция над участком [L..R] увеличивает b на 1 на этом участке,
 * а это меняет всего две разности: d[L] на +1 и d[R+1] на -1
 * (индексы по кольцу). Значит, число операций, нужное чтобы «выровнять»
 * набор разностей, равно сумме положительных частей этих разностей.
 *
 * Настоящие разности имеют вид c[i] = d[i] + 360*k[i], причём
 * сумма всех c[i] обязана быть нулём (это телескопическая сумма по кольцу),
 * поэтому сумма всех k[i] жёстко фиксирована: она равна -D/360, где D = Σ d[i].
 * Полезно лишь уменьшать k[i] на 1: тогда c[i] = d[i] - 360 < 0, и вклад этой
 * разности в ответ становится нулевым, то есть мы «экономим» d[i] операций.
 * Таких уменьшений надо ровно D/360 штук. Чтобы сэкономить максимум,
 * выбираем D/360 самых больших значений d[i].
 *
 * Итоговый ответ: D - (сумма M наибольших d[i]), где M = D / 360.
 * Сложность O(n log n).
 */
function minRotations(n, a) {
  // Кольцо из одной пластины (или пустое) уже выровнено.
  if (n <= 1) return 0;

  // d[i] — требуемое изменение разности углов между пластинами (i-1) и i.
  const d = new Array(n);
  let total = 0; // D = сумма всех d[i]

  for (let i = 0; i < n; i++) {
    const prev = a[(i - 1 + n) % n]; // соседняя пластина по кольцу
    let diff = (prev - a[i]) % 360;
    if (diff < 0) diff += 360; // приводим к диапазону [0, 360)
    d[i] = diff;
    total += diff;
  }

  // Сумма разностей всегда кратна 360: это «лишний» суммарный поворот,
  // который нужно разложить по разностям.
  const whole = total / 360;
  if (whole === 0) return 0; // все пластины уже смотрят одинаково

  // Берём ровно `whole` самых больших разностей: каждое такое уменьшение
  // на 360 делает вклад разности нулевым и экономит ровно d[i] операций.
  d.sort((x, y) => y - x);
  let saved = 0;
  for (let i = 0; i < whole; i++) saved += d[i];

  return total - saved;
}

module.exports = { minRotations };
