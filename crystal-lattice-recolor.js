// Условие задачи
// Кристаллическая решётка — это таблица из n строк и m столбцов, в каждой клетке которой находится атом некоторого цвета. Цвета задаются целыми числами.
// 
// За одну операцию разрешено выбрать любую строку или любой столбец решётки и перекрасить все атомы в нём в один произвольный цвет (любой целочисленный цвет).
// 
// Требуется найти минимальное количество операций, после которых все n·m атомов решётки станут одного цвета.
// 
// Формат ввода
// В первой строке заданы два натуральных числа n и m (1 ≤ n, m ≤ 300) — размеры решётки.
// В следующих n строках записано по m целых чисел — цвета атомов соответствующей строки. Число различных цветов в решётке не превосходит 60.
// 
// Формат вывода
// Выведите одно целое число — минимальное количество операций, делающих всю решётку одноцветной.
// 
// Пример 1
// Ввод:
// 2 2
// 1 2
// 3 4
// Вывод:
// 2
// (перекрашиваем, например, строку 1 в 1 и столбец 1 в 1 — получаем все единицы)
// 
// Пример 2
// Ввод:
// 3 3
// 1 2 1
// 2 1 2
// 1 2 1
// Вывод:
// 2
// (перекрашиваем столбец 2 и строку 2 в цвет 1)
// 
// Пример 3
// Ввод:
// 2 3
// 5 5 5
// 5 5 5
// Вывод:
// 0
// (решётка уже одноцветная — операции не нужны)
// 
// Пример 4
// Ввод:
// 1 4
// 7 7 3 7
// Вывод:
// 1
// (у решётки всего одна строка — перекрашиваем её целиком в цвет 7)

// ============================================================
// Crystal Lattice Recolor
// Есть решётка n x m, в каждой клетке — цвет (целое число).
// Одна операция: выбрать строку ИЛИ столбец и перекрасить весь
// его в любой цвет. Найти минимум операций, чтобы вся решётка
// стала одноцветной.
// ============================================================

/**
 * Основная функция решения.
 * @param {number[][]} grid — матрица цветов размера n x m (n >= 1, m >= 1)
 * @returns {number} минимальное число операций
 */
function solve(grid) {
  const n = grid.length;
  const m = grid[0].length;

  // Итоговый цвет имеет смысл выбирать только из уже присутствующих:
  // для совсем «нового» цвета несовпадающими становятся вообще все клетки,
  // а это заведомо не лучше, чем взять цвет какой-нибудь существующей клетки.
  const colors = new Set();
  for (let i = 0; i < n; i++) {
    for (let j = 0; j < m; j++) colors.add(grid[i][j]);
  }

  // Ключевое наблюдение: пусть финальный цвет решётки — F.
  // Тогда любая операция, красящая не в F, бесполезна: покрашенные ею клетки
  // всё равно обязаны быть позже перекрашены в F. Значит, можно считать,
  // что каждая операция красит свой ряд/столбец именно в F, а тогда порядок
  // операций не важен — важна лишь «затронутость» каждой клетки.
  //
  // Клетка, изначально не равная F, обязана быть затронута, то есть её строка
  // или её столбец должны быть выбраны. Получаем задачу о минимальном
  // вершинном покрытии в двудольном графе (слева строки, справа столбцы,
  // ребро соединяет строку i и столбец j, если grid[i][j] != F).
  // По теореме Кёнига размер минимального вершинного покрытия в двудольном
  // графе равен размеру максимального паросочетания — его и посчитаем.
  let answer = Infinity;
  for (const F of colors) {
    const cover = minVertexCover(grid, n, m, F);
    if (cover < answer) answer = cover;
    if (answer === 0) break; // решётка уже одноцветная
  }
  return answer;
}

/**
 * Минимальное вершинное покрытие графа несовпадений для финального цвета F
 * (для двудольного графа оно равно максимальному паросочетанию).
 */
function minVertexCover(grid, n, m, F) {
  // adjacency[i] — список столбцов j, где цвет клетки (i, j) не равен F
  const adjacency = new Array(n);
  for (let i = 0; i < n; i++) {
    const row = [];
    for (let j = 0; j < m; j++) {
      if (grid[i][j] !== F) row.push(j);
    }
    adjacency[i] = row;
  }
  return maxMatching(adjacency, n, m);
}

/**
 * Максимальное паросочетание в двудольном графе (алгоритм Хопкрофта–Карпа).
 * Левая доля — строки (n вершин), правая доля — столбцы (m вершин).
 */
function maxMatching(adjacency, n, m) {
  const pairLeft = new Int32Array(n).fill(-1);  // строка -> столбец
  const pairRight = new Int32Array(m).fill(-1); // столбец -> строка
  const INF = 1 << 30;
  const NIL = n; // фиктивная вершина для поиска в ширину
  const dist = new Int32Array(n + 1);

  // BFS строит слои: dist[u] — длина кратчайшего увеличивающего префикса
  // от свободной вершины слева до u.
  const bfs = () => {
    const queue = [];
    for (let u = 0; u < n; u++) {
      if (pairLeft[u] === -1) {
        dist[u] = 0;
        queue.push(u);
      } else {
        dist[u] = INF;
      }
    }
    dist[NIL] = INF;

    for (let head = 0; head < queue.length; head++) {
      const u = queue[head];
      if (dist[u] < dist[NIL]) {
        for (const v of adjacency[u]) {
          const next = pairRight[v] === -1 ? NIL : pairRight[v];
          if (dist[next] === INF) {
            dist[next] = dist[u] + 1;
            if (next !== NIL) queue.push(next);
          }
        }
      }
    }
    return dist[NIL] !== INF; // найден хотя бы один увеличивающий путь
  };

  // DFS ищет увеличивающий путь строго по слоям, построенным BFS.
  const dfs = (u) => {
    if (u === NIL) return true;
    for (const v of adjacency[u]) {
      const next = pairRight[v] === -1 ? NIL : pairRight[v];
      if (dist[next] === dist[u] + 1 && dfs(next)) {
        pairLeft[u] = v;
        pairRight[v] = u;
        return true;
      }
    }
    dist[u] = INF; // из этой вершины больше ничего не найдём
    return false;
  };

  let matching = 0;
  while (bfs()) {
    for (let u = 0; u < n; u++) {
      if (pairLeft[u] === -1 && dfs(u)) matching++;
    }
  }
  return matching;
}

// Итоговая сложность: O(K * sqrt(n) * n * m), где K — число различных цветов
// (не более 60), что укладывается в ограничения при n, m <= 300.
