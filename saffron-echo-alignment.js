// Условие задачи
// Сафрановое эхо-выравнивание
// 
// Даны две строки A и B, состоящие из строчных латинских букв. Требуется преобразовать строку A в строку B с минимальной суммарной стоимостью, используя следующие операции:
// 
// 1. Вставка символа: вставить любой символ в любую позицию строки. Стоимость 1.
// 2. Удаление символа: удалить любой символ из строки. Стоимость 1.
// 3. Замена символа: заменить любой символ на любой другой. Стоимость 1.
// 4. Эхо: выбрать любой символ в текущей строке и заменить его на k ≥ 1 копий этого же символа. Стоимость 1. (При k = 1 операция не меняет строку, но стоит 1, поэтому её никогда не используют.)
// 
// Найдите минимальную стоимость преобразования A в B.
// 
// Формат входных данных:
// В первой строке записана строка A, во второй — строка B. Длины строк от 1 до 2000 символов.
// 
// Формат выходных данных:
// Выведите одно целое число — минимальную стоимость.
// 
// Примеры:
// 1. A = "a", B = "aaa" → 1
// 2. A = "ab", B = "aab" → 1
// 3. A = "aa", B = "aaa" → 1
// 4. A = "abc", B = "abbc" → 1

function saffronEchoAlignment(A, B) {
  const n = A.length;
  const m = B.length;

  // Предпосчитаем длину максимального блока одинаковых символов, начинающегося с позиции j
  const runLength = new Array(m).fill(1);
  for (let j = m - 2; j >= 0; j--) {
    if (B[j] === B[j + 1]) {
      runLength[j] = runLength[j + 1] + 1;
    }
  }

  // dp[i][j] — минимальная стоимость преобразования A[0..i) в B[0..j)
  const dp = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(Infinity));
  dp[0][0] = 0;

  for (let i = 0; i <= n; i++) {
    for (let j = 0; j <= m; j++) {
      if (dp[i][j] === Infinity) continue;

      // Удаление символа A[i]
      if (i < n) {
        dp[i + 1][j] = Math.min(dp[i + 1][j], dp[i][j] + 1);
      }

      // Сопоставление или замена A[i] и B[j]
      if (i < n && j < m) {
        const substituteCost = A[i] === B[j] ? 0 : 1;
        dp[i + 1][j + 1] = Math.min(dp[i + 1][j + 1], dp[i][j] + substituteCost);

        // Эхо-сопоставление: A[i] покрывает весь блок одинаковых символов в B, начиная с j
        if (A[i] === B[j]) {
          const L = runLength[j];
          const echoCost = L > 1 ? 1 : 0;
          dp[i + 1][j + L] = Math.min(dp[i + 1][j + L], dp[i][j] + echoCost);
        }
      }

      // Массовая вставка блока одинаковых символов из B, начиная с j
      if (j < m) {
        const L = runLength[j];
        const insertCost = L === 1 ? 1 : 2;
        dp[i][j + L] = Math.min(dp[i][j + L], dp[i][j] + insertCost);
      }
    }
  }

  return dp[n][m];
}
