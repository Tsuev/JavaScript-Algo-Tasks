// Задача: Tephra Layer Interleaving
// Сложность: medium
// Дата генерации: 2026-10-16

// Условие задачи
// Тефра — это слои вулканического пепла, оседающие на дно озёр и океанов после крупных извержений. У каждого извержения есть уникальный номер, а его слой узнаваем в отложениях.
// 
// Геологи подняли K кернов (вертикальных колонок донных отложений). В каждом керне перечислены слои тефры, которые в нём сохранились, — строго от самого древнего (низ колонки) к самому молодому (верх). Разные керны содержат разные подмножества извержений, но относительный порядок слоёв внутри одного керна всегда достоверен: если слой a лежит ниже слоя b, то извержение a случилось раньше извержения b.
// 
// Требуется восстановить лексикографически наименьший глобальный хронологический порядок всех встретившихся извержений, который не противоречит ни одному керну. Если такого порядка не существует (керны взаимно противоречивы), ответ — IMPOSSIBLE.
// 
// Формат входных данных:
// Первая строка содержит целое число K (0 ≤ K ≤ 10^5) — количество кернов. Далее идут K строк; каждая начинается с числа m_i (0 ≤ m_i ≤ 10^5) — количества слоёв в этом керне, а затем содержит m_i целых чисел — номера слоёв в порядке от древнего к молодому. Суммарное количество слоёв по всем кернам не превосходит 2·10^5, номера слоёв — целые числа от 0 до 10^9, внутри одного керна повторов нет.
// 
// Формат результата:
// Одна строка с номерами всех встретившихся извержений в лексикографически наименьшем допустимом порядке, разделёнными пробелами. Если допустимого порядка нет — строка IMPOSSIBLE.
// 
// Пример 1:
// Вход:
// 2
// 3 1 2 3
// 3 2 3 4
// Выход:
// 1 2 3 4
// Пояснение: первый керн требует 1→2→3, второй — 2→3→4; вместе это даёт единственный порядок 1, 2, 3, 4.
// 
// Пример 2:
// Вход:
// 2
// 2 1 2
// 2 2 1
// Выход:
// IMPOSSIBLE
// Пояснение: первый керн требует 1 раньше 2, второй — 2 раньше 1; противоречие.
// 
// Пример 3:
// Вход:
// 2
// 2 3 1
// 2 2 1
// Выход:
// 2 3 1
// Пояснение: оба керна требуют, чтобы слой 1 был моложе, а слои 2 и 3 между собой не связаны; лексикографически наименьший порядок начинается с 2, затем идёт 3.

// Двоичная min-куча. Нужна, чтобы на каждом шаге топологической сортировки
// выбирать минимальный по номеру слой среди «доступных» (тех, у кого уже
// обработаны все более древние предки). Так получается лексикографически
// наименьший корректный порядок.
class MinHeap {
  constructor() {
    this.data = [];
  }

  get size() {
    return this.data.length;
  }

  push(value) {
    const d = this.data;
    d.push(value);
    let i = d.length - 1;
    while (i > 0) {
      const parent = (i - 1) >> 1;
      if (d[parent] <= d[i]) break;
      [d[parent], d[i]] = [d[i], d[parent]];
      i = parent;
    }
  }

  pop() {
    const d = this.data;
    const top = d[0];
    const last = d.pop();
    if (d.length > 0) {
      d[0] = last;
      let i = 0;
      for (;;) {
        const left = 2 * i + 1;
        const right = left + 1;
        let smallest = i;
        if (left < d.length && d[left] < d[smallest]) smallest = left;
        if (right < d.length && d[right] < d[smallest]) smallest = right;
        if (smallest === i) break;
        [d[smallest], d[i]] = [d[i], d[smallest]];
        i = smallest;
      }
    }
    return top;
  }
}

/**
 * Восстанавливает глобальную хронологию извержений по набору кернов.
 *
 * Каждый керн — массив номеров слоёв от самого древнего к самому молодому.
 * Каждая пара соседних слоёв задаёт ограничение «древний -> молодой»,
 * то есть ребро ориентированного графа. Лексикографически наименьший
 * корректный порядок слоёв — это топологическая сортировка этого графа,
 * в которой из доступных вершин всегда берётся минимальная. Если граф
 * содержит цикл (керны противоречат друг другу), порядка не существует.
 *
 * Сложность: O(M log N), где N — число различных слоёв, M — общее число слоёв.
 *
 * @param {number[][]} cores список кернов
 * @returns {number[]|null} порядок слоёв либо null, если порядок невозможен
 */
function findChronology(cores) {
  // adj[id] — слои, которые обязаны быть моложе слоя id.
  // indegree[id] — сколько более древних слоёв ещё не обработано.
  const adj = new Map();
  const indegree = new Map();

  const ensureNode = (id) => {
    if (!adj.has(id)) {
      adj.set(id, []);
      indegree.set(id, 0);
    }
  };

  for (const core of cores) {
    for (const id of core) ensureNode(id);

    // Соседние слои в одном керне строго упорядочены по времени.
    for (let i = 0; i + 1 < core.length; i++) {
      const older = core[i];
      const younger = core[i + 1];
      adj.get(older).push(younger);
      indegree.set(younger, indegree.get(younger) + 1);
    }
  }

  // Стартуем с самых древних слоёв — у них нет необработанных предков.
  const heap = new MinHeap();
  for (const [id, deg] of indegree) {
    if (deg === 0) heap.push(id);
  }

  const order = [];
  while (heap.size > 0) {
    const current = heap.pop();
    order.push(current);

    for (const next of adj.get(current)) {
      const deg = indegree.get(next) - 1;
      indegree.set(next, deg);
      // Как только все более древние слои для next обработаны,
      // слой становится доступным для вывода.
      if (deg === 0) heap.push(next);
    }
  }

  // Если вывести удалось не все слои, значит ограничения образовали цикл.
  return order.length === adj.size ? order : null;
}

