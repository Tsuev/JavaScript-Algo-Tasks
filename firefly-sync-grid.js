// Условие задачи
// **Firefly Sync Grid**
// 
// В ночном лесу на прямоугольной поляне размером n × m расселись светлячки. У каждого светлячка свой ритм свечения: светлячок в клетке (i, j) вспыхивает в те моменты времени t, которые кратны числу r[i][j] (то есть в моменты t = r, 2r, 3r, ...). Время t — целое положительное.
// 
// Наблюдатель хочет выделить «хор» — прямоугольный блок из ровно h подряд идущих строк и ровно w подряд идущих столбцов, то есть подматрицу размера h × w. Светлячки хора вспыхнут одновременно в те моменты t, которые кратны ритму каждого из них, иными словами — кратны числу
// 
//     sync = НОК( r[i][j] для всех клеток блока ).
// 
// Чем меньше значение sync, тем чаще хор вспыхивает вместе. Найдите минимально возможное значение sync среди всех подматриц размера h × w.
// 
// Значение НОК может получиться очень большим (например, для ста чисел, не превосходящих 100, оно сравнимо с 7·10^41), поэтому ответ нужно вернуть в виде десятичной строки — он не обязан помещаться в 64-битное целое.
// 
// **Формат входных данных**
// 
// Первая строка: четыре целых числа n, m, h, w, разделённые пробелами.
// Далее n строк по m целых чисел: ритмы светлячков r[i][j].
// Ограничения: 1 ≤ h ≤ n ≤ 100, 1 ≤ w ≤ m ≤ 100, 1 ≤ r[i][j] ≤ 100.
// 
// **Формат результата**
// 
// Одна строка — минимальное значение sync в десятичной записи, без ведущих нулей.
// 
// **Пример 1**
// 
// Вход:
// 2 3 1 2
// 2 4 3
// 6 1 5
// 
// Выход:
// 4
// 
// Пояснение. Блоки размера 1 × 2: [2, 4] → НОК 4; [4, 3] → НОК 12; [6, 1] → НОК 6; [1, 5] → НОК 5. Минимум равен 4.
// 
// **Пример 2**
// 
// Вход:
// 1 3 1 3
// 4 6 9
// 
// Выход:
// 36
// 
// Пояснение. Единственный блок — вся строка, НОК(4, 6, 9) = 2^2 · 3^2 = 36.
// 
// **Пример 3**
// 
// Вход:
// 1 5 1 5
// 97 89 83 79 71
// 
// Выход:
// 4019067251
// 
// Пояснение. Числа взаимно просты, поэтому НОК равен их произведению: 97 · 89 · 83 · 79 · 71 = 4 019 067 251. Это больше 2^31, но всё ещё помещается в 64 бита; в общем случае ответ может быть существенно больше.
// 
// **Пример 4**
// 
// Вход:
// 2 2 2 2
// 2 3
// 5 7
// 
// Выход:
// 210
// 
// Пояснение. Блок только один — вся сетка, НОК(2, 3, 5, 7) = 210.

/**
 * Задача «Firefly Sync Grid».
 *
 * Ключевая идея.
 * НОК набора чисел раскладывается по простым: для каждого простого p его степень
 * в НОК равна максимуму степеней p по всем числам набора. Значит, для окна нужно
 * знать максимум v_p(r[i][j]) по его клеткам для каждого простого p.
 *
 * Так как все r[i][j] <= 100, различных пар (p, p^e) совсем немного.
 * Зафиксируем простое p и его степень pe = p^e. Клетка делится на pe тогда и только
 * тогда, когда её личный вклад в степень p не меньше e. Уровень e попадает в НОК окна
 * ровно тогда, когда в окне есть хотя бы одна клетка, делящаяся на pe. Уровни вложены
 * друг в друга (делится на p^e => делится на p^(e-1)), поэтому число «сработавших»
 * уровней как раз и равно максимальной степени p в НОК окна.
 *
 * «Есть ли в окне хотя бы одна клетка, делящаяся на pe» проверяем за O(1) с помощью
 * двумерных префиксных сумм. Итоговая сложность — O(K · n · m), где K — количество
 * пар (простое, его степень), то есть порядка нескольких десятков.
 *
 * @param {number[][]} rhythm матрица ритмов размера n × m, значения от 1 до 100
 * @param {number} h высота выбираемого блока (число строк)
 * @param {number} w ширина выбираемого блока (число столбцов)
 * @returns {string} минимальное значение НОК в десятичной записи
 */
function fireflySyncGrid(rhythm, h, w) {
  const n = rhythm.length;
  const m = rhythm[0].length;

  // Сколько всего положений у окна размера h × w на нашей сетке.
  const rows = n - h + 1;
  const cols = m - w + 1;

  // Больше этого числа ни одна клетка не содержит, значит большие степени простых
  // рассматривать бессмысленно.
  let maxValue = 0;
  for (const row of rhythm) {
    for (const v of row) {
      if (v > maxValue) maxValue = v;
    }
  }

  // lcms[k] — НОК ритмов окна с номером k = i * cols + j.
  // Начинаем с 1 и постепенно домножаем на простые, набирая нужные степени.
  // Используем BigInt: итоговое число легко перерастает 64-битный диапазон.
  const lcms = new Array(rows * cols).fill(1n);

  const stride = m + 1; // длина строки префиксной матрицы

  for (let p = 2; p <= maxValue; p++) {
    if (!isPrime(p)) continue;

    // Перебираем степени pe = p^e, которые вообще могут встретиться в данных.
    for (let pe = p; pe <= maxValue; pe *= p) {
      // pref[i][j] — количество клеток в прямоугольнике [0..i) × [0..j),
      // делящихся на pe. Обычные двумерные префиксные суммы.
      const pref = new Int32Array((n + 1) * stride);
      for (let i = 0; i < n; i++) {
        let rowSum = 0;
        for (let j = 0; j < m; j++) {
          if (rhythm[i][j] % pe === 0) rowSum++;
          pref[(i + 1) * stride + (j + 1)] = pref[i * stride + (j + 1)] + rowSum;
        }
      }

      // Проходим по всем возможным окнам и смотрим, попала ли в окно клетка,
      // делящаяся на pe. Если да — окно получает ещё один множитель p.
      for (let i = 0; i < rows; i++) {
        const top = i * stride;
        const bottom = (i + h) * stride;
        for (let j = 0; j < cols; j++) {
          const cnt =
            pref[bottom + j + w] - pref[top + j + w] -
            pref[bottom + j] + pref[top + j];
          if (cnt > 0) lcms[i * cols + j] *= BigInt(p);
        }
      }
    }
  }

  // Среди всех посчитанных НОК выбираем наименьший.
  let best = lcms[0];
  for (const value of lcms) {
    if (value < best) best = value;
  }

  return best.toString();
}

/** Проверка числа на простоту. Значения маленькие, хватает перебора делителей. */
function isPrime(x) {
  if (x < 2) return false;
  for (let d = 2; d * d <= x; d++) {
    if (x % d === 0) return false;
  }
  return true;
}
