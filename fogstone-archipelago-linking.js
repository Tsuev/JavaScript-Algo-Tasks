// Сложность: medium
// Дата генерации: 2026-11-12

// Условие задачи
// # Fogstone Archipelago Linking (Соединение архипелага Туманного камня)
// 
// ## Легенда
// 
// В море Туманного камня разбросан архипелаг из `n` островов. Каждый остров задан целочисленными координатами `(x, y)`. Жители хотят соединить все острова мостами так, чтобы из любого острова можно было добраться до любого другого (не обязательно напрямую).
// 
// Мост можно построить только между двумя островами, и он не может быть длиннее `D` — дальше туман слишком плотный. Стоимость моста измеряется в единицах фогстоуна и равна манхэттенскому расстоянию между островами: `|x1 - x2| + |y1 - y2|`.
// 
// Найдите минимальную суммарную стоимость мостов, которые соединят все острова в одну связную сеть. Если это невозможно (архипелаг распадается на части, недостижимые друг для друга), выведите `-1`.
// 
// ## Формат входных данных
// 
// - Первая строка: два целых числа `n` и `D` — количество островов и максимально допустимая длина одного моста.
// - Следующие `n` строк: по два целых числа `x_i`, `y_i` — координаты `i`-го острова.
// 
// Ограничения: `1 ≤ n ≤ 2000`, `0 ≤ D ≤ 10^9`, `-10^9 ≤ x_i, y_i ≤ 10^9`. Острова могут совпадать по координатам (расстояние между ними равно `0`).
// 
// ## Формат выходных данных
// 
// Одно целое число — минимальная суммарная стоимость мостов, либо `-1`, если соединить все острова невозможно.
// 
// ## Примеры
// 
// ### Пример 1
// Вход:
// ```
// 5 15
// 0 0
// 5 0
// 12 4
// 20 10
// 25 0
// ```
// Выход:
// ```
// 45
// ```
// Пояснение: допустимы мосты `(0,0)-(5,0)` длиной `5`, `(5,0)-(12,4)` длиной `11`, `(12,4)-(20,10)` длиной `14` и `(20,10)-(25,0)` длиной `15`. Все они укладываются в предел `D = 15`, вместе дают связную сеть и минимальную сумму `5 + 11 + 14 + 15 = 45`. Мост `(0,0)-(12,4)` длиной `16` уже запрещён.
// 
// ### Пример 2
// Вход:
// ```
// 3 1
// 0 0
// 10 10
// 0 10
// ```
// Выход:
// ```
// -1
// ```
// Пояснение: расстояния между всеми парами островов (`20`, `10`, `10`) больше `D = 1`, поэтому нельзя построить ни одного моста.
// 
// ### Пример 3
// Вход:
// ```
// 1 0
// 7 7
// ```
// Выход:
// ```
// 0
// ```
// Пояснение: единственный остров уже образует связную сеть, мосты не нужны.
// 
// ## Идея решения
// 
// Это задача о минимальном остовном дереве на графе, где вершины — острова, а рёбра — разрешённые мосты (`расстояние ≤ D`), с весом, равным манхэттенскому расстоянию. Граф полный, но рёбра с расстоянием больше `D` просто отсутствуют. Алгоритм Прима за `O(n^2)` находит минимальное остовное дерево; если на каком-то шаге не осталось ни одного достижимого острова, сеть построить нельзя — ответ `-1`.

/**
 * Соединяем острова архипелага в единую сеть мостами минимальной суммарной длины.
 *
 * @param {number[][]} islands — массив пар [x, y] с координатами островов
 * @param {number} maxBridgeLength — максимально допустимая длина одного моста (D)
 * @returns {number} минимальная суммарная стоимость мостов или -1, если соединить всё нельзя
 */
function linkIslands(islands, maxBridgeLength) {
  const n = islands.length;

  // Ноль или один остров уже образуют связную сеть — строить нечего.
  if (n <= 1) return 0;

  // Алгоритм Прима.
  // best[i] — минимальная стоимость моста, которым остров i можно подключить
  // к уже собранной части сети. Infinity означает «пока недостижим».
  const best = new Array(n).fill(Infinity);
  const taken = new Array(n).fill(false);
  best[0] = 0;

  let total = 0;

  for (let step = 0; step < n; step++) {
    // Выбираем ещё не подключённый остров с самым дешёвым мостом до сети.
    let v = -1;
    for (let i = 0; i < n; i++) {
      if (!taken[i] && (v === -1 || best[i] < best[v])) v = i;
    }

    // Если самый дешёвый вариант бесконечно дорог, остров отрезан туманом — сеть не собрать.
    if (v === -1 || best[v] === Infinity) return -1;

    taken[v] = true;
    total += best[v];

    // Пересчитываем оценки остальных островов через только что добавленный.
    const [x, y] = islands[v];
    for (let u = 0; u < n; u++) {
      if (taken[u]) continue;
      const dist = Math.abs(x - islands[u][0]) + Math.abs(y - islands[u][1]);
      // Слишком длинный мост построить нельзя, поэтому такое ребро просто не рассматриваем.
      if (dist <= maxBridgeLength && dist < best[u]) best[u] = dist;
    }
  }

  return total;
}
