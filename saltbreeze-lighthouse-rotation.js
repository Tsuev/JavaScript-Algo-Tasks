// Задача: Saltbreeze Lighthouse Rotation
// Сложность: medium
// Дата генерации: 2026-11-15

// Условие задачи
// Маяк «Солёный бриз» стоит на скале и медленно вращает луч шириной `w` градусов по часовой стрелке. В море вокруг него находятся `n` кораблей, про каждый из которых известен пеленг — угол в градусах от направления на север, отсчитанный по часовой стрелке.
// 
// Луч занимает дугу `[a, a + w]`, где `a` — направление левого края луча. Корабль с пеленгом `x` освещён, если от `a` до `x` по часовой стрелке не больше `w` градусов, то есть `(x - a) mod 360 ≤ w`. За полный оборот `a` принимает все значения от 0 до 360 (по модулю 360).
// 
// Нужно найти, какое наибольшее число кораблей луч может осветить одновременно, и при каком наименьшем значении `a` (в градусах, `0 ≤ a < 360`) это достигается.
// 
// Формат входных данных (параметры функции):
// - `angles` — массив целых чисел, `0 ≤ angles[i] < 360`, длина `n` от 0 до 200000. Это пеленги кораблей; два корабля могут стоять на одном пеленге — это два разных корабля, и оба считаются.
// - `beamWidth` — целое число, `0 ≤ beamWidth ≤ 360` — угловая ширина луча в градусах.
// 
// Формат результата: объект `{ count, start }`:
// - `count` — максимальное число одновременно освещённых кораблей;
// - `start` — наименьший угол `a` из полуинтервала `[0, 360)`, при котором освещено ровно `count` кораблей.
// 
// Примеры:
// 1) `angles = [0, 45, 90, 180, 270]`, `beamWidth = 90` → `{ count: 3, start: 0 }` — луч `[0, 90]` накрывает корабли на 0, 45 и 90 градусах.
// 2) `angles = [350, 10, 20]`, `beamWidth = 30` → `{ count: 3, start: 350 }` — луч `[350, 380]` проходит через север и накрывает все три корабля (350, 10, 20).
// 3) `angles = []`, `beamWidth = 45` → `{ count: 0, start: 0 }`.
// 4) `angles = [10, 200]`, `beamWidth = 360` → `{ count: 2, start: 0 }` — луч шириной в полный оборот видит всё при любом `a`, поэтому берём наименьший угол.
// 
// Ограничения и идея: алгоритм должен работать за `O(n log n)`. Достаточно рассматривать только такие `a`, которые совпадают с пеленгом какого-то корабля: если луч освещает корабль, левый край можно бесплатно довести по часовой стрелке до первого освещённого корабля, и число освещённых не уменьшится. Окружность удобно «разрезать», добавив к отсортированным пеленгам их копии со сдвигом на 360, и пройти по окну двумя указателями.

/**
 * Маяк «Солёный бриз»: ищем положение вращающегося луча,
 * при котором он освещает максимум кораблей.
 *
 * @param {number[]} angles пеленги кораблей (целые, 0..359), корабли могут совпадать по пеленгу
 * @param {number} beamWidth ширина луча в градусах (0..360)
 * @returns {{count: number, start: number}} максимум освещённых кораблей и наименьший подходящий угол
 */
function lighthouseRotation(angles, beamWidth) {
  const n = angles.length;

  // Кораблей нет — освещать некого; наименьший возможный угол равен 0.
  if (n === 0) return { count: 0, start: 0 };

  // Луч шириной в полный оборот видит все корабли при любом a,
  // поэтому самое маленькое подходящее начало — 0.
  if (beamWidth >= 360) return { count: n, start: 0 };

  const sorted = [...angles].sort((x, y) => x - y);

  // Приём «разрезания» окружности: добавляем копии пеленгов со сдвигом на 360.
  // Теперь дуга, которая переезжает через 0, становится обычным отрезком
  // на прямой, и по нему можно идти скользящим окном.
  const doubled = sorted.concat(sorted.map((x) => x + 360));

  let bestCount = 0;
  let bestStart = 0;
  let right = 0;

  // Левый край луча достаточно ставить на пеленг корабля: если он стоит где-то
  // между кораблями, его можно двигать по часовой стрелке до первого освещённого
  // корабля, ничего не потеряв. Обход слева направо гарантирует, что первое
  // найденное максимальное значение даст наименьший угол start.
  for (let left = 0; left < n; left++) {
    if (right < left) right = left;

    // Правая граница только растёт: как только корабль перестал попадать
    // в дугу [a, a + w], при дальнейшем сдвиге a он тем более не попадёт.
    // Ограничение right < left + n не даёт пройти по окружности больше одного раза.
    while (right < left + n && doubled[right] - doubled[left] <= beamWidth) {
      right++;
    }

    const count = right - left; // сколько кораблей попало в текущую дугу
    if (count > bestCount) {
      bestCount = count;
      bestStart = sorted[left];
    }
  }

  return { count: bestCount, start: bestStart };
}
