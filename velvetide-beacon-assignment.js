// Задача: Velvetide Beacon Assignment
// Сложность: medium
// Дата генерации: 2026-11-18

// Условие задачи
// Вдоль побережья пролива Велентайд стоят n маяков. Их координаты на числовой прямой заданы массивом целых чисел beacons. Ночью в пролив заходят m кораблей в точках с координатами ships. Каждому кораблю нужно назначить ровно один маяк, и каждый маяк может обслужить не более одного корабля за ночь. Расстояние между кораблём и его маяком равно |beacons[i] - ships[j]|.
// 
// Нужно распределить маяки так, чтобы максимальное из расстояний «корабль — маяк» по всем кораблям было как можно меньше. Верните это минимально возможное максимальное расстояние.
// 
// Если кораблей больше, чем маяков (m > n), назначить каждому кораблю отдельный маяк невозможно — верните -1. Если кораблей нет (m = 0), ответ 0.
// 
// Формат входных данных:
// - beacons — массив целых координат маяков (n >= 0);
// - ships — массив целых координат кораблей (m >= 0).
// 
// Формат результата: одно целое число — минимально возможный максимум расстояния, либо -1 при m > n.
// 
// Пример 1:
// beacons = [1, 5, 10], ships = [2, 6]
// Ответ: 1
// Пояснение: корабль в точке 2 обслуживает маяк в 1 (расстояние 1), корабль в точке 6 — маяк в 5 (расстояние 1). Максимум равен 1, меньше нельзя.
// 
// Пример 2:
// beacons = [0], ships = [3, 7]
// Ответ: -1 (кораблей больше, чем маяков).
// 
// Пример 3:
// beacons = [4, 4, 4], ships = [4, 4]
// Ответ: 0 (все совпадает).

function minMaxBeaconDistance(beacons, ships) {
  const n = beacons.length;
  const m = ships.length;

  // Крайние случаи: нет кораблей или маяков не хватает на всех.
  if (m === 0) return 0;
  if (m > n) return -1;

  // На прямой при фиксированном пороге расстояния выгодно обрабатывать
  // маяки и корабли в порядке возрастания координат.
  const a = [...beacons].sort((x, y) => x - y);
  const b = [...ships].sort((x, y) => x - y);

  // Проверяем, можно ли при ограничении d назначить каждому кораблю маяк.
  // Идём по кораблям слева направо и жадно берём самый левый подходящий маяк:
  // если маяк годится текущему кораблю, нет смысла оставлять его на потом.
  const feasible = (d) => {
    let i = 0; // указатель по маякам
    for (let j = 0; j < m; j++) {
      // Пропускаем маяки, которые слишком далеко слева от текущего корабля.
      while (i < n && a[i] < b[j] - d) i++;
      // Если ближайший доступный маяк правее допустимой зоны — этот корабль не прикрыть.
      if (i >= n || a[i] > b[j] + d) return false;
      i++; // маяк занят, переходим к следующему
    }
    return true;
  };

  // Верхняя граница ответа: максимальный разброс между крайними точками.
  // Любая пара «маяк — корабль» не дальше этой величины, значит ответ не больше неё.
  const span = Math.max(
    Math.abs(a[0] - b[m - 1]),
    Math.abs(a[n - 1] - b[0])
  );

  // Двоичный поиск по ответу: ищем минимальное d, при котором назначение возможно.
  let lo = 0;
  let hi = span;
  while (lo < hi) {
    const mid = Math.floor((lo + hi) / 2);
    if (feasible(mid)) hi = mid;
    else lo = mid + 1;
  }
  return lo;
}
