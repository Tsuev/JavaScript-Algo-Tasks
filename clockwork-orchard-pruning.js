// Задача: Clockwork Orchard Pruning
// Сложность: hard
// Дата генерации: 2026-09-25

// Условие задачи
// ## Условие задачи «Clockwork Orchard Pruning»
// 
// В волшебном саду растут `n` деревьев, соединённых `n − 1` дорожками так, что схема связей образует **дерево** (связный граф без циклов). У каждого дерева `i` есть циферблат с целым числом `a[i]`.
// 
// Садовник делает **синхронную обрезку**: выбирает некоторое (возможно, пустое) множество дорожек и убирает их. После этого сад распадается на несколько связных частей (компонент). Обрезка называется синхронной, если в **каждой** получившейся компоненте сумма чисел на циферблатах делится на `K` — период главных часов сада.
// 
// Пустая обрезка тоже допустима: тогда весь сад остаётся одной компонентой, и требуется делимость общей суммы на `K`.
// 
// Посчитайте количество синхронных обрезок **по модулю 1 000 000 007**.
// 
// ### Формат входных данных
// 
// * Первая строка: два целых числа `n` и `K` (`1 ≤ n ≤ 2000`, `1 ≤ K ≤ 100`).
// * Вторая строка: `n` целых чисел `a[1..n]` (`0 ≤ a[i] ≤ 10^9`).
// * Далее `n − 1` строк: пары `u v` — дорожка между деревьями `u` и `v` (`1 ≤ u, v ≤ n`, нумерация с 1).
// 
// ### Формат результата
// 
// Одно число — количество синхронных обрезок по модулю `1 000 000 007`.
// 
// ### Примеры
// 
// **Пример 1**
// ```
// Ввод:
// 3 2
// 1 1 0
// 1 2
// 2 3
// Вывод:
// 2
// ```
// Пояснение: рёбер 2. Перебираем:
// * ничего не режем → компонента {1,2,3}, сумма 2 делится на 2 ✔;
// * режем 1–2 → компоненты {1} (сумма 1) ✘;
// * режем 2–3 → {3} (сумма 0) ✔ и {1,2} (сумма 2) ✔;
// * режем оба → {2} (сумма 1) ✘.
// Итого 2 способа.
// 
// **Пример 2**
// ```
// Ввод:
// 2 3
// 1 2
// 1 2
// Вывод:
// 1
// ```
// Пояснение: не режем — сумма 3 делится на 3 ✔; режем — компонента {1} с суммой 1 ✘.
// 
// **Пример 3**
// ```
// Ввод:
// 1 5
// 3
// Вывод:
// 0
// ```
// Пояснение: дорожек нет, вариант только один — компонента {1} с суммой 3, не делится на 5.
// 
// ### Идея решения
// 
// Корневой динамикой по дереву. Для каждой вершины `v` храним массив `dp[v][r]` — число способов обрезать рёбра **внутри** поддерева `v` так, чтобы все уже «закрытые» компоненты делились на `K`, а компонента, содержащая саму `v`, имела сумму остатков `r` по модулю `K`. При обработке ребёнка `u` есть два варианта: оставить ребро (слить остатки, `(r+s) mod K`) или отрезать его (тогда поддерево `u` обязано быть полностью валидным, то есть `dp[u][0]`). Ответ — `dp[root][0]`. Сложность `O(n · K²)`.

const MOD = 1000000007;

// Умножение по модулю без потери точности.
// a и b меньше MOD < 2^30, значит их произведение может превысить 2^53,
// и обычное a*b даст неверный результат. Поэтому разбиваем b на две
// 16-битные части и считаем по модулю на каждом шаге.
function mulmod(a, b) {
  const hi = Math.floor(b / 65536);
  const lo = b % 65536;
  return ((a * hi % MOD) * 65536 + a * lo) % MOD;
}

/**
 * Считает количество «синхронных обрезок» дерева.
 *
 * @param {number} n     количество вершин
 * @param {number} K     мастер-период: сумма в каждой компоненте кратна K
 * @param {number[]} values  значения циферблатов, индексация с 0
 * @param {Array<[number,number]>} edges  рёбра, индексация с 0
 * @returns {number} ответ по модулю 1 000 000 007
 */
function countSynchronizedPrunings(n, K, values, edges) {
  // Списки смежности.
  const adj = Array.from({ length: n }, () => []);
  for (const [u, v] of edges) {
    adj[u].push(v);
    adj[v].push(u);
  }

  // Итеративный обход в глубину от корня 0: получаем порядок обработки
  // и массив родителей. parent[v] = -2 означает «ещё не посещали».
  const parent = new Array(n).fill(-2);
  parent[0] = -1;
  const order = [];
  const stack = [0];
  while (stack.length > 0) {
    const v = stack.pop();
    order.push(v);
    for (const u of adj[v]) {
      if (parent[u] === -2) {
        parent[u] = v;
        stack.push(u);
      }
    }
  }

  // dp[v][r] — сколько способов обрезать рёбра внутри поддерева v так, чтобы
  //   * каждая компонента, НЕ содержащая v, имела сумму, кратную K;
  //   * компонента, содержащая v, имела сумму ≡ r (mod K).
  const dp = new Array(n);

  // Идём по вершинам в обратном порядке обхода — дети всегда раньше родителя.
  for (let idx = order.length - 1; idx >= 0; idx--) {
    const v = order[idx];

    // Сначала компонента — это само дерево v.
    let cur = new Array(K).fill(0);
    cur[((values[v] % K) + K) % K] = 1;

    // Присоединяем поддеревья детей.
    for (const u of adj[v]) {
      if (u === parent[v]) continue; // это родитель, а не ребёнок — пропускаем
      const child = dp[u];
      const next = new Array(K).fill(0);
      // Вариант «отрезать ребро»: поддерево u должно быть целиком валидным.
      const cutWays = child[0];

      for (let r = 0; r < K; r++) {
        const cv = cur[r];
        if (cv === 0) continue;

        // Оставляем ребро: компоненты сливаются, остатки складываются.
        for (let s = 0; s < K; s++) {
          const cs = child[s];
          if (cs === 0) continue;
          const t = (r + s) % K;
          next[t] = (next[t] + mulmod(cv, cs)) % MOD;
        }

        // Режем ребро: остаток компоненты v не меняется.
        if (cutWays !== 0) {
          next[r] = (next[r] + mulmod(cv, cutWays)) % MOD;
        }
      }

      cur = next;
    }

    dp[v] = cur;
  }

  // Вся конструкция целиком должна делиться на K, то есть остаток 0.
  return dp[0][0];
}
