// Условие задачи
// Название: Umberlight Weir Sequencing
// Сложность: hard
// 
// Вдоль реки расположены n участков, на каждом из которых добывается минерал умберлайт. На i-м участке залегает a_i единиц умберлайта (a_i >= 0). Чтобы организовать последовательную добычу, реку перегораживают k-1 плотинами (weir). Плотины можно ставить только между участками, тем самым разбивая всю последовательность участков на ровно k непустых непрерывных сегментов. Стоимость обслуживания одного сегмента равна квадрату суммарного количества умберлайта на этом сегменте. Требуется минимизировать суммарную стоимость обслуживания всех k сегментов.
// 
// Формат входа: функция minWeirCost(a, k), где a — массив целых чисел длины n (1 <= n <= 100000), k — целое число (1 <= k <= min(n, 100)). Элементы массива: 0 <= a[i] <= 100.
// Формат выхода: целое число — минимальная суммарная стоимость.
// 
// Пример:
// a = [1, 2, 3, 4], k = 2.
// Возможные разбиения:
// - [1] и [2,3,4]: 1^2 + (2+3+4)^2 = 1 + 81 = 82
// - [1,2] и [3,4]: (1+2)^2 + (3+4)^2 = 9 + 49 = 58
// - [1,2,3] и [4]: (1+2+3)^2 + 4^2 = 36 + 16 = 52
// Минимум равен 52. Ответ: 52.

function minWeirCost(a, k) {
  const n = a.length;
  if (k < 1 || k > n) {
    throw new Error('k должно быть в диапазоне от 1 до n');
  }

  // Префиксные суммы для быстрого вычисления суммы на отрезке
  const P = new Array(n + 1);
  P[0] = 0;
  for (let i = 0; i < n; i++) {
    P[i + 1] = P[i] + a[i];
  }

  // dpPrev[j] — минимальная стоимость разбиения первых j элементов на t-1 сегментов
  let dpPrev = new Array(n + 1).fill(Infinity);
  dpPrev[0] = 0;

  // Вспомогательная функция для добавления линии в нижнюю выпуклую оболочку.
  // Линии добавляются в порядке убывания наклона (m не возрастает).
  // head — индекс первой активной линии в массиве hull.
  function addLine(hull, head, m, b) {
    // Если наклон совпадает с последней линией, оставляем только лучшую (с меньшим b)
    if (hull.length > head && hull[hull.length - 1].m === m) {
      if (hull[hull.length - 1].b <= b) {
        return head; // существующая линия не хуже
      } else {
        hull.pop(); // новая линия лучше, удаляем старую
      }
    }
    // Удаляем последнюю линию, если она перестаёт быть оптимальной на оболочке
    while (hull.length - head >= 2) {
      const l1 = hull[hull.length - 2];
      const l2 = hull[hull.length - 1];
      // Проверяем, что пересечение l1 и l2 не правее пересечения l2 и новой линии.
      // Учитываем, что l1.m > l2.m > m, поэтому знаменатели положительны.
      if ((l2.b - l1.b) * (l2.m - m) >= (b - l2.b) * (l1.m - l2.m)) {
        hull.pop();
      } else {
        break;
      }
    }
    hull.push({ m, b });
    return head;
  }

  for (let t = 1; t <= k; t++) {
    const dpCur = new Array(n + 1).fill(Infinity);
    const hull = [];
    let head = 0;

    // j — граница предыдущего сегмента. Для t сегментов j >= t-1.
    for (let i = t; i <= n; i++) {
      const j = i - 1;
      // Добавляем линию, соответствующую границе j, если такое разбиение достижимо
      if (dpPrev[j] !== Infinity) {
        const m = -2 * P[j];
        const b = dpPrev[j] + P[j] * P[j];
        head = addLine(hull, head, m, b);
      }

      // Запрос минимума в точке x = P[i]
      const x = P[i];
      while (
        head + 1 < hull.length &&
        hull[head].m * x + hull[head].b >= hull[head + 1].m * x + hull[head + 1].b
      ) {
        head++;
      }
      const best = hull[head].m * x + hull[head].b;
      dpCur[i] = P[i] * P[i] + best;
    }

    dpPrev = dpCur;
  }

  return dpPrev[n];
}
