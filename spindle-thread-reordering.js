// Задача: Spindle Thread Reordering
// Сложность: hard
// Дата генерации: 2026-10-25

// Условие задачи
// На веретено наматывают нити разных цветов. Веретено состоит из n позиций, изначально все позиции пусты. За один проход мастер выбирает цвет c и непрерывный отрезок позиций [l, r], после чего наматывает нить цвета c на все позиции этого отрезка. Новая нить полностью перекрывает всё, что было намотано на этих позициях раньше (в том числе нити других цветов). Нити, намотанные вне отрезка, не меняются.
// 
// Требуется получить заданную последовательность цветов a[1..n], сделав как можно меньше проходов. Цвета задаются целыми числами (одинаковые числа — одинаковые цвета).
// 
// Формат входных данных:
// В первой строке записано целое число n (1 ≤ n ≤ 500) — количество позиций на веретене.
// Во второй строке записаны n целых чисел a[1..n] (1 ≤ a[i] ≤ 10^9) — требуемые цвета позиций.
// 
// Формат результата:
// Одно целое число — минимальное количество проходов.
// 
// Примеры:
// 1) Вход: n = 3, a = [1, 2, 1]. Выход: 2.
//    Пояснение: проход 1 — цвет 1 на [1, 3] (получаем 1,1,1), проход 2 — цвет 2 на [2, 2] (получаем 1,2,1).
// 2) Вход: n = 3, a = [1, 2, 3]. Выход: 3.
//    Пояснение: каждый цвет встречается один раз, поэтому три отдельных прохода неизбежны.
// 3) Вход: n = 1, a = [7]. Выход: 1.
// 4) Вход: n = 5, a = [1, 2, 1, 2, 1]. Выход: 3.
//    Пояснение: цвет 1 на [1, 5], затем цвет 2 на [2, 2] и цвет 2 на [4, 4].
// 
// Ограничения: n ≤ 500; допускается решение за O(n^3) по времени и O(n^2) по памяти.

function minPasses(colors) {
  const n = colors.length;
  if (n === 0) return 0;

  // dp[i][j] — минимум проходов, чтобы получить участок colors[i..j].
  // Заполняем таблицу по возрастанию длины участка.
  const dp = Array.from({ length: n }, () => new Array(n).fill(0));
  for (let i = 0; i < n; i++) dp[i][i] = 1;

  for (let len = 2; len <= n; len++) {
    for (let i = 0; i + len - 1 < n; i++) {
      const j = i + len - 1;

      // Худший случай: правую позицию красим отдельным проходом.
      dp[i][j] = dp[i][j - 1] + 1;

      // Но если левее уже есть такой же цвет, как в позиции j, то нить
      // на позицию j можно нанести тем же проходом, что и на позицию k.
      // Идея: сначала полностью формируем участок [i..k], затем отдельно
      // заполняем «дырку» [k+1..j-1], а позиция j окажется закрыта тем же
      // слоем, что и позиция k (лишний кусок нити между ними перекроется
      // последующими проходами).
      for (let k = i; k < j; k++) {
        if (colors[k] !== colors[j]) continue;
        const middle = k + 1 <= j - 1 ? dp[k + 1][j - 1] : 0;
        const candidate = dp[i][k] + middle;
        if (candidate < dp[i][j]) dp[i][j] = candidate;
      }
    }
  }

  // Ответ — стоимость построения всего веретена целиком.
  return dp[0][n - 1];
}
