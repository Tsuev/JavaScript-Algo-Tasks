// Задача: Magnetic Filament Weaving
// Сложность: medium
// Дата генерации: 2026-09-23

// Условие задачи
// Магнитное плетение нитей
// 
// Магнитная нить — это последовательность полюсов, каждый из которых может быть северным (N) или южным (S). У вас есть две такие нити, заданные строками A и B. Вы хотите сплести их в одну нить, вплетая полюса одной нити в другую, сохраняя порядок полюсов в каждой исходной нити. Сплетённая нить называется магнитной, если в ней никакие два соседних полюса не совпадают (после N обязательно идёт S, и наоборот). Определите, можно ли сплести нити в магнитную нить, и если да, выведите одну из возможных сплетённых нитей. Если это невозможно, выведите строку impossible.
// 
// Входные данные:
// Две строки A и B, состоящие только из символов N и S. Длины строк не превосходят 1000.
// 
// Выходные данные:
// Если сплетение возможно, выведите сплетённую строку. Если нет — выведите impossible.
// 
// Пример 1:
// A = 'NS'
// B = 'SN'
// Выход: 'SNSN'
// 
// Пример 2:
// A = 'NN'
// B = 'SS'
// Выход: 'NSNS'
// 
// Пример 3:
// A = 'NN'
// B = 'NN'
// Выход: impossible

function weaveFilaments(A, B) {
  const n = A.length;
  const m = B.length;

  // dpN[i][j] = true, если можно сплести первые i символов A и первые j символов B,
  // заканчивая на N. Аналогично dpS для S.
  // Используем Uint8Array для экономии памяти.
  const dpN = Array.from({ length: n + 1 }, () => new Uint8Array(m + 1));
  const dpS = Array.from({ length: n + 1 }, () => new Uint8Array(m + 1));

  // Пустая строка может считаться как заканчивающаяся на любой полюс,
  // чтобы обеспечить свободу для первого символа.
  dpN[0][0] = 1;
  dpS[0][0] = 1;

  for (let i = 0; i <= n; i++) {
    for (let j = 0; j <= m; j++) {
      if (i === 0 && j === 0) continue;

      // Последний символ взят из A
      if (i > 0) {
        const c = A[i - 1];
        const opp = c === 'N' ? 'S' : 'N';
        const prev = opp === 'N' ? dpN[i - 1][j] : dpS[i - 1][j];
        if (prev) {
          if (c === 'N') dpN[i][j] = 1;
          else dpS[i][j] = 1;
        }
      }

      // Последний символ взят из B
      if (j > 0) {
        const c = B[j - 1];
        const opp = c === 'N' ? 'S' : 'N';
        const prev = opp === 'N' ? dpN[i][j - 1] : dpS[i][j - 1];
        if (prev) {
          if (c === 'N') dpN[i][j] = 1;
          else dpS[i][j] = 1;
        }
      }
    }
  }

  // Если ни один вариант не достижим, плетение невозможно
  if (!dpN[n][m] && !dpS[n][m]) {
    return 'impossible';
  }

  // Восстанавливаем сплетённую нить с конца
  let i = n;
  let j = m;
  // Выбираем любой возможный последний полюс
  let lastChar = dpN[n][m] ? 'N' : 'S';
  const result = [];

  while (i > 0 || j > 0) {
    // Пробуем взять последний символ из A
    if (i > 0 && A[i - 1] === lastChar) {
      const opp = lastChar === 'N' ? 'S' : 'N';
      const prev = opp === 'N' ? dpN[i - 1][j] : dpS[i - 1][j];
      if (prev) {
        result.push(A[i - 1]);
        i--;
        lastChar = opp;
        continue;
      }
    }
    // Иначе пробуем взять из B
    if (j > 0 && B[j - 1] === lastChar) {
      const opp = lastChar === 'N' ? 'S' : 'N';
      const prev = opp === 'N' ? dpN[i][j - 1] : dpS[i][j - 1];
      if (prev) {
        result.push(B[j - 1]);
        j--;
        lastChar = opp;
        continue;
      }
    }
    // Теоретически сюда попасть не должны, но на всякий случай
    break;
  }

  // result заполнен в обратном порядке
  return result.reverse().join('');
}
