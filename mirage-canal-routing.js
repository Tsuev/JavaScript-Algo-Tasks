// Задача: Mirage Canal Routing
// Сложность: hard
// Дата генерации: 2026-09-29

// Условие задачи
// ## Mirage Canal Routing
// 
// В пустыне Мираж планируют проложить канал. Рельеф задан прямоугольной сеткой размером n × m клеток, в каждой клетке известна высота над уровнем моря.
// 
// Часть клеток — настоящие миражи: заходить в них нельзя, потому что на самом деле это бездонные провалы. В данных такие клетки обозначены значением −1. Все остальные клетки (высота ≥ 0) проходимы.
// 
// Канал прокладывается по клеткам, соседним по стороне (вверх / вниз / влево / вправо). Когда канал переходит из клетки с высотой a в соседнюю клетку с высотой b, строителям нужно возвести стенку (шлюз), которая выдерживает перепад высот |a − b|. Прочность всего канала — это максимальный перепад высот по всем его шагам.
// 
// Дано q запросов, каждый задаёт стартовую и финишную клетку. Для каждого запроса найдите минимально возможную прочность канала, соединяющего эти клетки. Если соединить их нельзя (мешают клетки-миражи или клетка запроса сама непроходима), выведите −1.
// 
// ### Формат входных данных
// 
// ```
// n m
// h[0][0] h[0][1] ... h[0][m-1]
// ...
// h[n-1][0] ... h[n-1][m-1]
// q
// sx1 sy1 tx1 ty1
// ...
// sxq syq txq tyq
// ```
// 
// - n, m — размеры сетки (1 ≤ n, m ≤ 300, n·m ≤ 90000).
// - h[i][j] — высота клетки: 0 ≤ h ≤ 10^9, либо −1, если клетка непроходима.
// - q — число запросов (1 ≤ q ≤ 200000).
// - Каждый запрос — четыре числа sx, sy, tx, ty: координаты старта и финиша, нумерация строк и столбцов с 1.
// 
// ### Формат выходных данных
// 
// q строк: для каждого запроса — минимальная прочность канала или −1.
// 
// ### Пример 1
// 
// ```
// Ввод:
// 3 3
// 0 1 2
// 1 2 3
// 2 3 4
// 3
// 1 1 3 3
// 1 1 1 1
// 1 1 1 3
// 
// Вывод:
// 1
// 0
// 2
// ```
// 
// Пояснение: из (1,1) в (3,3) можно идти по клеткам с перепадом 1 на каждом шаге, значит минимум равен 1. Для одной и той же клетки прочность 0. Из (1,1) в (1,3) перепады равны 1 и 1, но суммарно нужен максимум по шагам: |0−1| = 1 и |1−2| = 1, значит ответ 2? — нет: путь (0,0)→(0,1)→(0,2) требует перепад не более 1, но для клеток-финиша с высотой 2 ответ равен 2, потому что в MST-пути встречается ребро веса 2 (маршрут с перепадом 1 невозможен).
// 
// ### Пример 2
// 
// ```
// Ввод:
// 3 3
// 0 5 0
// 5 -1 5
// 0 5 0
// 2
// 1 1 3 3
// 1 1 2 2
// 
// Вывод:
// 5
// -1
// ```
// 
// Пояснение: центральная клетка — миражи, её обходят по кольцу из клеток высоты 5 и 0; любой обход требует перепада 5. Вторая цель — сам миражи, поэтому −1.

// Mirage Canal Routing
//
// Идея решения.
// Канал между двумя клетками — это путь по сетке. Прочность канала = максимум
// по рёбрам пути величины |высота(u) - высота(v)|. Значит нужно для каждой пары
// вершин найти путь, у которого максимальное ребро минимально — это классическая
// задача о «минимаксном» (bottleneck) пути.
//
// Ключевой факт: в неориентированном взвешенном графе минимаксный путь между u и v
// совпадает с путём между ними в минимальном остовном дереве (MST). Достаточно
// построить MST (алгоритм Краскала) и для каждого запроса взять максимум ребра на
// пути в дереве. Чтобы отвечать на многие запросы быстро, используем LCA
// (двоичные подъёмы) и вместе с предком храним максимум ребра до него.
// Сложность: O(E log E) на построение и O(log V) на запрос.

function solve(input) {
  const tokens = input.trim().split(/\s+/).map(Number);
  let ptr = 0;
  const n = tokens[ptr++];
  const m = tokens[ptr++];

  const h = [];
  for (let i = 0; i < n; i++) {
    const row = new Array(m);
    for (let j = 0; j < m; j++) row[j] = tokens[ptr++];
    h.push(row);
  }

  const q = tokens[ptr++];
  const queries = new Array(q);
  for (let k = 0; k < q; k++) {
    queries[k] = [tokens[ptr++], tokens[ptr++], tokens[ptr++], tokens[ptr++]];
  }

  // 1) Нумеруем проходимые клетки (высота >= 0). Значение -1 — миражи, вход запрещён.
  const id = [];
  for (let i = 0; i < n; i++) id.push(new Int32Array(m).fill(-1));
  let V = 0;
  for (let i = 0; i < n; i++)
    for (let j = 0; j < m; j++)
      if (h[i][j] >= 0) id[i][j] = V++;

  const answers = new Array(q).fill(-1);
  if (V > 0) {
    // 2) Собираем рёбра между соседними проходимыми клетками.
    //    Вес ребра — нужный перепад высот между клетками.
    const eu = [];
    const ev = [];
    const ew = [];
    for (let i = 0; i < n; i++) {
      for (let j = 0; j < m; j++) {
        const u = id[i][j];
        if (u < 0) continue;
        if (j + 1 < m && id[i][j + 1] >= 0) {
          eu.push(u);
          ev.push(id[i][j + 1]);
          ew.push(Math.abs(h[i][j] - h[i][j + 1]));
        }
        if (i + 1 < n && id[i + 1][j] >= 0) {
          eu.push(u);
          ev.push(id[i + 1][j]);
          ew.push(Math.abs(h[i][j] - h[i + 1][j]));
        }
      }
    }
    const E = eu.length;

    // Индексы рёбер, отсортированные по весу (для Краскала).
    const order = new Array(E);
    for (let i = 0; i < E; i++) order[i] = i;
    order.sort((a, b) => ew[a] - ew[b]);

    // 3) Система непересекающихся множеств с эвристиками сжатия и объёма.
    const par = new Int32Array(V);
    const sz = new Int32Array(V).fill(1);
    for (let i = 0; i < V; i++) par[i] = i;
    const find = (x) => {
      while (par[x] !== x) {
        par[x] = par[par[x]];
        x = par[x];
      }
      return x;
    };

    // 4) Алгоритм Краскала: строим минимальное остовное дерево (или лес,
    //    если граф несвязный). Рёбра дерева кладём в списки смежности
    //    (массивы to / wgt / nxt + head, чтобы не плодить объекты).
    const head = new Int32Array(V).fill(-1);
    const to = [];
    const wgt = [];
    const nxt = [];
    const addEdge = (a, b, w) => {
      to.push(b);
      wgt.push(w);
      nxt.push(head[a]);
      head[a] = to.length - 1;
    };

    for (let i = 0; i < E; i++) {
      const e = order[i];
      const a = find(eu[e]);
      const b = find(ev[e]);
      if (a !== b) {
        if (sz[a] < sz[b]) {
          par[a] = b;
          sz[b] += sz[a];
        } else {
          par[b] = a;
          sz[a] += sz[b];
        }
        addEdge(eu[e], ev[e], ew[e]);
        addEdge(ev[e], eu[e], ew[e]);
      }
    }

    // 5) Обходим лес в глубину: считаем глубину, метку компоненты связи
    //    и «первый шаг» вверх (up[0], mx[0]).
    const LOG = Math.max(1, Math.floor(Math.log2(V)) + 1);
    const depth = new Int32Array(V).fill(-1);
    const comp = new Int32Array(V).fill(-1);
    const up = [new Int32Array(V).fill(-1)];
    const mx = [new Int32Array(V)];

    for (let s = 0; s < V; s++) {
      if (depth[s] !== -1) continue;
      depth[s] = 0;
      comp[s] = s; // представитель компоненты — её стартовая вершина
      const stack = [s];
      while (stack.length) {
        const u = stack.pop();
        for (let e = head[u]; e !== -1; e = nxt[e]) {
          const v = to[e];
          if (depth[v] === -1) {
            depth[v] = depth[u] + 1;
            up[0][v] = u;
            mx[0][v] = wgt[e];
            comp[v] = s;
            stack.push(v);
          }
        }
      }
    }

    // Двоичные подъёмы: up[k][v] — 2^k-й предок, mx[k][v] — максимум ребра
    // на участке пути между v и этим предком.
    for (let k = 1; k < LOG; k++) {
      const upP = up[k - 1];
      const mxP = mx[k - 1];
      const upC = new Int32Array(V).fill(-1);
      const mxC = new Int32Array(V);
      for (let v = 0; v < V; v++) {
        const mid = upP[v];
        if (mid !== -1) {
          upC[v] = upP[mid];
          mxC[v] = Math.max(mxP[v], mxP[mid]);
        }
      }
      up.push(upC);
      mx.push(mxC);
    }

    // 6) Отвечаем на запросы: поднимаем более глубокую вершину к уровню другой,
    //    затем поднимаем обе одновременно до LCA, накапливая максимум ребра.
    for (let k = 0; k < q; k++) {
      const [sx, sy, tx, ty] = queries[k];
      const a = id[sx - 1][sy - 1];
      const b = id[tx - 1][ty - 1];
      if (a < 0 || b < 0) continue; // старт или финиш — миражи
      if (comp[a] !== comp[b]) continue; // разные компоненты связи

      let u = a;
      let v = b;
      if (depth[u] < depth[v]) {
        const t = u;
        u = v;
        v = t;
      }

      let res = 0;
      let diff = depth[u] - depth[v];
      for (let j = 0; j < LOG; j++) {
        if ((diff >> j) & 1) {
          res = Math.max(res, mx[j][u]);
          u = up[j][u];
        }
      }

      if (u !== v) {
        for (let j = LOG - 1; j >= 0; j--) {
          if (up[j][u] !== up[j][v]) {
            res = Math.max(res, mx[j][u], mx[j][v]);
            u = up[j][u];
            v = up[j][v];
          }
        }
        // Осталось подняться на один шаг до самого LCA.
        res = Math.max(res, mx[0][u], mx[0][v]);
      }

      answers[k] = res;
    }
  }

  return answers.join('\n');
}
