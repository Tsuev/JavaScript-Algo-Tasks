// Условие задачи
// **Moonpier Tide Batching**
// 
// На лунном причале Moonpier приливы приходят волнами строго по очереди. За смену приходит `n` волн; волна с номером `i` (нумерация с 0) приносит `waves[i]` единиц воды.
// 
// Всю воду нужно перекачать в бассейн, разбив волны на **непрерывные партии**: каждая партия — это несколько подряд идущих волн, порядок волн менять нельзя, и каждая волна попадает ровно в одну партию. Пустых партий не бывает.
// 
// Правила:
// * Суммарный объём воды в одной партии не должен превышать `capacity` (иначе бассейн переполняется).
// * Стоимость одной партии = `baseFee` (фиксированная плата за запуск цикла перекачки) + `perWaveFee` за каждую волну, вошедшую в партию.
// 
// Нужно найти **минимальную суммарную стоимость** перекачки всех волн. Если хотя бы одна волна сама по себе больше `capacity`, то обработать её невозможно — в этом случае вернуть `-1`. Если волн нет, стоимость равна `0`.
// 
// **Формат входа (аргументы функции):**
// * `waves` — массив целых неотрицательных чисел, объёмы волн в порядке прибытия;
// * `capacity` — целое число, максимальный объём одной партии;
// * `baseFee` — целое число, плата за запуск одной партии;
// * `perWaveFee` — целое число, плата за каждую волну внутри партии.
// 
// **Формат результата:** одно целое число — минимальная суммарная стоимость, либо `-1`, если перекачка невозможна.
// 
// **Ограничения:** `0 <= n <= 200000`, `0 <= waves[i] <= 10^9`, `1 <= capacity <= 10^14`, `1 <= baseFee, perWaveFee <= 10^9`.
// 
// **Примеры:**
// 1. `waves = [2, 3, 4, 1]`, `capacity = 5`, `baseFee = 3`, `perWaveFee = 1` → `10`
//    Оптимально: партия `[2, 3]` (сумма 5, цена 3 + 2 = 5) и партия `[4, 1]` (сумма 5, цена 3 + 2 = 5). Итого 10.
// 2. `waves = [5, 5]`, `capacity = 5`, `baseFee = 10`, `perWaveFee = 1` → `22`
//    Вместе волны не помещаются, значит две партии по одной волне: (10 + 1) * 2 = 22.
// 3. `waves = [1, 1, 1]`, `capacity = 10`, `baseFee = 100`, `perWaveFee = 1` → `103`
//    Дешевле всё в одну партию: 100 + 3 = 103.
// 4. `waves = [6]`, `capacity = 5`, `baseFee = 1`, `perWaveFee = 1` → `-1`
//    Волна не влезает в бассейн ни одной партией.
// 5. `waves = []`, `capacity = 7`, `baseFee = 5`, `perWaveFee = 2` → `0`
// 
// **Идея решения (O(n)):** динамика `dp[i]` — минимум стоимости для первых `i` волн. Переход по началу последней партии `j`: `dp[i] = baseFee + perWaveFee * i + min(dp[j] - perWaveFee * j)`, где `j` пробегает окно, в котором сумма волн `j..i-1` не больше `capacity`. Левая граница окна только растёт, поэтому минимум поддерживается монотонной очередью.

/**
 * Moonpier Tide Batching.
 * Возвращает минимальную стоимость перекачки всех волн или -1, если это невозможно.
 *
 * Работает за O(n): динамика по префиксам + монотонная очередь для минимума по окну.
 */
function minTideBatchingCost(waves, capacity, baseFee, perWaveFee) {
  const n = waves.length;
  if (n === 0) return 0;

  // prefix[i] — суммарный объём первых i волн.
  const prefix = new Array(n + 1).fill(0);
  for (let i = 0; i < n; i++) prefix[i + 1] = prefix[i] + waves[i];

  const INF = Infinity;
  // dp[i] — минимальная стоимость обработки первых i волн.
  const dp = new Array(n + 1).fill(INF);
  dp[0] = 0;

  // Переход: dp[i] = baseFee + perWaveFee * i + min(dp[j] - perWaveFee * j),
  // где j — начало последней партии, а волны j..i-1 вместе влезают в capacity.
  // Допустимые j образуют скользящее окно с монотонно растущей левой границей,
  // поэтому храним минимум ключа в монотонной очереди (deque) по возрастанию ключа.
  const deque = new Array(n + 1);
  let head = 0;
  let tail = 0; // очередь занимает полуинтервал [head, tail)

  const key = (j) => dp[j] - perWaveFee * j;

  let left = 0; // наименьший допустимый j для текущего i

  for (let i = 1; i <= n; i++) {
    // Новый кандидат j = i - 1 — это партия, состоящая из последней волны.
    if (dp[i - 1] !== INF) {
      const v = key(i - 1);
      // Выбрасываем из хвоста тех, кто не лучше нового кандидата: они уже бесполезны,
      // потому что стоят раньше и вылетят из окна не позже.
      while (tail > head && key(deque[tail - 1]) >= v) tail--;
      deque[tail++] = i - 1;
    }

    // Двигаем левую границу, пока последняя партия не помещается в бассейн.
    while (prefix[i] - prefix[left] > capacity) left++;

    // Убираем из головы индексы, которые выпали из окна.
    while (tail > head && deque[head] < left) head++;

    // Если очередь пуста, значит волну i-1 нельзя обработать ни в какой партии.
    if (tail > head) dp[i] = baseFee + perWaveFee * i + key(deque[head]);
  }

  return dp[n] === INF ? -1 : dp[n];
}
