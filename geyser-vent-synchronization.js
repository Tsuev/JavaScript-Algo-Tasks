// Задача: Geyser Vent Synchronization
// Сложность: hard
// Дата генерации: 2026-10-13

// Условие задачи
// В долине гейзеров есть n вентов (отверстий). Вент i извергается в моменты времени a_i, a_i + p_i, a_i + 2p_i, ... где a_i — время первого извержения, p_i — период. Все времена — целые неотрицательные числа. Найдите самое раннее время T >= 0, в которое все n вентов извергаются одновременно. Если такого времени не существует, выведите -1.
// 
// Формат входных данных:
// В первой строке дано целое число n (1 <= n <= 2000).
// В следующих n строках записаны пары чисел a_i и p_i (0 <= a_i < p_i <= 10^9).
// 
// Формат выходных данных:
// Выведите одно число — искомое время T, или -1, если синхронизация невозможна.
// 
// Пример 1:
// Вход:
// 2
// 0 2
// 1 3
// Выход:
// 4
// 
// Пример 2:
// Вход:
// 2
// 0 2
// 1 4
// Выход:
// -1
// 
// Пример 3:
// Вход:
// 3
// 1 2
// 2 3
// 3 5
// Выход:
// 23

function solveGeyserSync(n, geysers) {
  // Инициализируем текущее решение: T = x (mod M)
  let x = 0n;
  let M = 1n;

  // Вычисление НОД двух BigInt
  function gcd(a, b) {
    while (b !== 0n) {
      [a, b] = [b, a % b];
    }
    return a;
  }

  // Расширенный алгоритм Евклида
  // Возвращает [g, x, y], такие что a*x + b*y = g
  function extendedGcd(a, b) {
    if (b === 0n) {
      return [a, 1n, 0n];
    }
    const [g, x1, y1] = extendedGcd(b, a % b);
    return [g, y1, x1 - (a / b) * y1];
  }

  // Модульный обратный элемент a по модулю m (a и m взаимно просты)
  function modInverse(a, m) {
    const [g, x, y] = extendedGcd(a, m);
    if (g !== 1n) {
      throw new Error('Обратный элемент не существует');
    }
    return ((x % m) + m) % m;
  }

  // Обрабатываем каждый гейзер
  for (let i = 0; i < n; i++) {
    const a = BigInt(geysers[i][0]);
    const p = BigInt(geysers[i][1]);

    // Нужно решить: T ≡ x (mod M) и T ≡ a (mod p)
    // T = x + k*M, тогда x + k*M ≡ a (mod p)
    // k*M ≡ a - x (mod p)

    const delta = ((a - x) % p + p) % p; // (a - x) mod p
    const g = gcd(M, p);

    if (delta % g !== 0n) {
      return -1; // Система несовместна
    }

    const m1 = M / g;
    const m2 = p / g;
    const diffDivG = delta / g;

    // Находим k: k ≡ diffDivG * inv(m1 mod m2) (mod m2)
    let k = 0n;
    if (m2 !== 1n) {
      const inv = modInverse(m1 % m2, m2);
      k = (diffDivG * inv) % m2;
    }

    // Обновляем решение
    x = x + k * M;
    M = m1 * p; // M / g * p = lcm(M, p)
    x = x % M;  // поддерживаем x в диапазоне [0, M-1]
  }

  return x.toString(); // возвращаем строку, чтобы избежать потери точности при выводе
}
