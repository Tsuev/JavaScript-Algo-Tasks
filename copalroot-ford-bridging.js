// Задача: Copalroot Ford Bridging
// Сложность: medium
// Дата генерации: 2026-11-14

// Условие задачи
// «Copalroot Ford Bridging»
// 
// Корнееды живут на островах посреди бурной реки и переходят между ними по подвесным мостам. Карта переправ задана неориентированным графом: острова — вершины, мосты — рёбра. По каждому мосту можно ходить в обе стороны; между одной парой островов может быть несколько мостов, а некоторые мосты могут соединять остров сам с собой (петли).
// 
// Мост называется критическим, если после его разрушения число компонент связности графа увеличивается — то есть какие-то острова теряют связь с остальными. Найдите все критические мосты.
// 
// Формат входных данных:
// В первой строке записаны два целых числа n и m (1 ≤ n ≤ 200000, 0 ≤ m ≤ 200000) — количество островов и мостов. Острова нумеруются от 1 до n. В каждой из следующих m строк записаны два числа u и v (1 ≤ u, v ≤ n) — мост между островами u и v.
// 
// Формат результата:
// В первой строке выведите k — количество критических мостов. В следующих k строках выведите сами мосты в виде «a b», где a < b. Строки должны быть отсортированы сначала по a, затем по b. Если критических мостов нет, выведите только «0».
// 
// Пример 1:
// Вход:
// 6 6
// 1 2
// 2 3
// 3 1
// 3 4
// 4 5
// 5 6
// Выход:
// 3
// 3 4
// 4 5
// 5 6
// Пояснение: острова 1, 2, 3 связаны в цикл, поэтому ни один из мостов внутри него не критичен; мосты 3–4, 4–5 и 5–6 — единственный путь к островам 4, 5 и 6.
// 
// Пример 2:
// Вход:
// 4 4
// 1 2
// 2 1
// 2 3
// 3 4
// Выход:
// 2
// 2 3
// 3 4
// Пояснение: между островами 1 и 2 два параллельных моста, поэтому разрушение одного из них ничего не меняет; мосты 2–3 и 3–4 критичны.
// 
// Ограничения по времени: решение должно работать за O(n + m).

/**
 * Находит все мосты (критические переправы) в неориентированном графе.
 *
 * Идея: обычный поиск в глубину, в котором для каждой вершины хранится
 * время входа tin и значение low — минимальное время входа, достижимое
 * из поддерева этой вершины (учитывая обратные рёбра к предкам).
 * Ребро из parent в v является мостом тогда и только тогда, когда
 * low[v] > tin[parent]: из поддерева v нельзя подняться до parent или выше,
 * значит другого пути между ними нет.
 *
 * Важные тонкости:
 *  - номер ребра хранится отдельно, чтобы правильно обрабатывать кратные
 *    рёбра (два параллельных моста не образуют мост);
 *  - обход итеративный, потому что глубина рекурсии могла бы достичь 2*10^5.
 *
 * @param {number} n количество вершин, вершины нумеруются 1..n
 * @param {Array<[number, number]>} edges список рёбер графа
 * @returns {Array<[number, number]>} отсортированный список мостов, a < b
 */
function findBridges(n, edges) {
  // Списки смежности: для каждой вершины — пары (сосед, номер ребра).
  const adj = Array.from({ length: n + 1 }, () => []);
  edges.forEach(([u, v], id) => {
    adj[u].push([v, id]);
    adj[v].push([u, id]);
  });

  const tin = new Int32Array(n + 1).fill(-1); // время входа в вершину, -1 = не посещена
  const low = new Int32Array(n + 1);          // минимальный достижимый tin
  const bridges = [];
  let timer = 0;

  // Граф может быть несвязным, поэтому запускаем обход из каждой непосещённой вершины.
  for (let start = 1; start <= n; start++) {
    if (tin[start] !== -1) continue;

    tin[start] = low[start] = timer++;

    // Кадр стека: вершина, номер ребра, по которому в неё пришли,
    // и позиция в её списке смежности — так мы эмулируем рекурсию.
    const stack = [{ v: start, parentEdge: -1, pos: 0 }];

    while (stack.length > 0) {
      const frame = stack[stack.length - 1];
      const v = frame.v;

      if (frame.pos < adj[v].length) {
        const [to, edgeId] = adj[v][frame.pos++];

        // Возврат по тому же самому ребру к родителю игнорируем.
        // Кратные рёбра имеют разные номера и потому не игнорируются.
        if (edgeId === frame.parentEdge) continue;

        if (tin[to] === -1) {
          // Ребро древа DFS: спускаемся в новую вершину.
          tin[to] = low[to] = timer++;
          stack.push({ v: to, parentEdge: edgeId, pos: 0 });
        } else {
          // Обратное ребро к предку — уточняем low текущей вершины.
          // В неориентированном DFS других вариантов нет: любые рёбра
          // ведут либо в потомка, либо в предка.
          if (tin[to] < low[v]) low[v] = tin[to];
        }
      } else {
        // Соседи закончились — выходим из вершины и отдаём low родителю.
        stack.pop();
        if (stack.length > 0) {
          const parent = stack[stack.length - 1].v;
          if (low[v] < low[parent]) low[parent] = low[v];

          // Если из поддерева v нельзя подняться до parent, ребро — мост.
          if (low[v] > tin[parent]) {
            bridges.push([Math.min(v, parent), Math.max(v, parent)]);
          }
        }
      }
    }
  }

  bridges.sort((x, y) => (x[0] - y[0]) || (x[1] - y[1]));
  return bridges;
}
