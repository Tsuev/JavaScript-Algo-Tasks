// Задача: Nacreous Shoal Rebalancing
// Сложность: hard
// Дата генерации: 2026-10-28

// Условие задачи
// Условие задачи «Nacreous Shoal Rebalancing».
// 
// Вдоль рифа выстроилась цепочка из n жемчужных рыбок. У рыбки с номером i известен показатель перламутрового блеска a[i]. Чтобы стая могла синхронно менять направление, её нужно разбить на ровно k непустых групп, идущих строго подряд: каждая группа — это непрерывный отрезок цепочки, все группы вместе покрывают всех рыбок без пропусков и пересечений.
// 
// Несогласованность одной группы — это разница между наибольшим и наименьшим блеском среди рыбок этой группы (если в группе одна рыбка, разброс равен 0).
// Несогласованность всей стаи — это максимум несогласованности по всем k группам.
// 
// Определите минимально возможную несогласованность стаи после такого разбиения.
// 
// Формат входных данных: целые числа n и k (1 ≤ k ≤ n ≤ 2·10^5), затем массив a из n целых чисел (0 ≤ a[i] ≤ 10^9).
// Формат результата: одно целое число — минимально возможная несогласованность стаи.
// 
// Пояснение к решению: ответ ищется бинарным поиском по величине X (допустимый разброс внутри группы). Для фиксированного X проверяем, можно ли разбить массив не более чем на k групп с разбросом ≤ X. Так как любую группу можно дополнительно раздробить, не увеличивая разброс, то «не более k» равносильно «ровно k» при k ≤ n. Проверка выполняется за O(n) с помощью двух монотонных деков (максимум и минимум текущего окна) и ещё одного дека, хранящего минимум dp на допустимом окне. Итоговая сложность O(n log(max−min)).
// 
// Примеры:
// 1) a = [1,5,3,2], k = 2 → ответ 3 (разбиение [1] и [5,3,2]: разбросы 0 и 3).
// 2) a = [9,1,1,9], k = 2 → ответ 8 (любое разбиение даёт максимум 8).
// 3) a = [4,1,7,2], k = 1 → ответ 6 (вся стая одна группа, 7−1=6).
// 4) a = [7,7,7], k = 3 → ответ 0 (каждая рыбка отдельно).

// Основная функция: минимально возможная «несогласованность» стаи
// при разбиении массива a на ровно k непрерывных непустых групп.
// Несогласованность группы = (максимум в группе) − (минимум в группе),
// несогласованность стаи = максимум по всем группам.
function rebalanceShoal(a, k) {
  const n = a.length;
  if (n === 0) return 0;
  // Если групп не меньше, чем рыбок, каждая рыбка образует свою группу — разброс 0.
  if (k >= n) return 0;

  let mn = a[0], mx = a[0];
  for (let i = 1; i < n; i++) {
    if (a[i] < mn) mn = a[i];
    if (a[i] > mx) mx = a[i];
  }

  // Буферы для монотонных деков (переиспользуются в каждой проверке).
  const dp = new Array(n + 1);
  const maxQ = new Array(n + 1);
  const minQ = new Array(n + 1);
  const dpQ = new Array(n + 1);

  // Можно ли разбить стаю не более чем на k групп с разбросом каждой ≤ X.
  // Поскольку группу всегда можно раздробить без роста разброса,
  // это то же самое, что «ровно k групп» при k ≤ n.
  function feasible(X) {
    dp[0] = 0;

    let hm = 0, tm = 0; // дек максимумов текущего окна
    let hn = 0, tn = 0; // дек минимумов текущего окна
    let hd = 0, td = 0; // дек индексов с минимальным dp на окне
    let L = 0;          // левая граница допустимого окна

    for (let i = 1; i <= n; i++) {
      const r = i - 1;

      // Добавляем элемент r и поддерживаем максимум/минимум окна [L, r].
      while (tm > hm && a[maxQ[tm - 1]] <= a[r]) tm--;
      maxQ[tm++] = r;
      while (tn > hn && a[minQ[tn - 1]] >= a[r]) tn--;
      minQ[tn++] = r;

      // dp[r] уже посчитан — он годится как левый конец будущей группы.
      while (td > hd && dp[dpQ[td - 1]] >= dp[r]) td--;
      dpQ[td++] = r;

      // Сжимаем окно слева, пока разброс внутри него больше X.
      while (a[maxQ[hm]] - a[minQ[hn]] > X) {
        L++;
        while (hm < tm && maxQ[hm] < L) hm++;
        while (hn < tn && minQ[hn] < L) hn++;
      }

      // Убираем из дека dp индексы, оказавшиеся левее L.
      while (hd < td && dpQ[hd] < L) hd++;

      // Минимальное число групп для первых i рыбок.
      dp[i] = dp[dpQ[hd]] + 1;

      // dp не убывает: если уже больше k, дальше только хуже.
      if (dp[i] > k) return false;
    }
    return dp[n] <= k;
  }

  // Бинарный поиск минимального X, при котором разбиение возможно.
  let lo = 0, hi = mx - mn;
  while (lo < hi) {
    const mid = Math.floor((lo + hi) / 2);
    if (feasible(mid)) hi = mid;
    else lo = mid + 1;
  }
  return lo;
}
