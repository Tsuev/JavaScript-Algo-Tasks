// Задача: Moonharrow Lantern Concordance
// Сложность: medium
// Дата генерации: 2026-11-20

// Условие задачи
// В ночь праздника Мунхарроу вдоль коридора развешаны n фонарей. У i-го фонаря задана яркость a[i] (целое число). Два фонаря образуют согласованную пару, если сумма их яркостей равна некоторому фиксированному значению S. Согласование — это набор попарно непересекающихся согласованных пар, у всех которых одно и то же значение S (каждый фонарь входит не более чем в одну пару). Требуется определить максимальное количество фонарей, которые удаётся разбить на одно согласование, то есть 2 * (максимальное число пар при каком-либо S).
// 
// Формат входных данных: в первой строке — целое n (0 ≤ n ≤ 2000); во второй строке — n целых чисел a[i] (1 ≤ a[i] ≤ 10^9), разделённых пробелами.
// 
// Формат выходных данных: одно целое число — максимальное количество фонарей, попавших в согласование.
// 
// Примеры:
// 1) n = 6, a = [1, 1, 2, 2, 3, 3].
//    При S = 4 пары: (1, 3) и (1, 3) — 2 пары, (2, 2) — 1 пара, итого 3 пары → 6 фонарей. Ответ: 6.
// 2) n = 4, a = [5, 5, 5, 5].
//    При S = 10 получаем 2 пары → 4 фонаря. Ответ: 4.
// 3) n = 3, a = [1, 2, 3].
//    Любое S даёт не более одной пары → 2 фонаря. Ответ: 2.
// 4) n = 0, a = []. Ответ: 0.

// Максимальное число фонарей, которые можно разбить на пары с одинаковой суммой.
function solve(glow) {
  if (!glow || glow.length < 2) return 0;

  // Считаем, сколько раз встречается каждая яркость.
  const count = new Map();
  for (const g of glow) {
    count.set(g, (count.get(g) ?? 0) + 1);
  }
  const values = [...count.keys()];

  // pairsBySum[S] — сколько непересекающихся пар можно собрать с суммой S.
  // Для фиксированного S пары вида (x, y), x < y, используют разные значения,
  // поэтому их вклады просто складываются, а пары (x, x) считаются отдельно.
  const pairsBySum = new Map();
  const addPairs = (sum, pairs) => {
    if (pairs > 0) pairsBySum.set(sum, (pairsBySum.get(sum) ?? 0) + pairs);
  };

  for (let i = 0; i < values.length; i++) {
    const x = values[i];

    // Пары из фонарей с одинаковой яркостью: floor(cnt[x] / 2) пар, сумма 2x.
    addPairs(2 * x, Math.floor(count.get(x) / 2));

    // Пары из разных значений: для пары (x, y) можно взять min(cnt[x], cnt[y]).
    for (let j = i + 1; j < values.length; j++) {
      const y = values[j];
      addPairs(x + y, Math.min(count.get(x), count.get(y)));
    }
  }

  // Берём сумму S, дающую максимум пар, и умножаем на 2 (фонарей вдвое больше).
  let bestPairs = 0;
  for (const p of pairsBySum.values()) {
    if (p > bestPairs) bestPairs = p;
  }
  return bestPairs * 2;
}
