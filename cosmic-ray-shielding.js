// Задача: Cosmic Ray Shielding
// Сложность: hard
// Дата генерации: 2026-10-16

// Условие задачи
// Космический корабль находится в опасной зоне, где присутствуют N источников космических лучей. Каждый источник излучает лучи во все стороны. Чтобы защититься, корабль может развернуть круговой щит радиуса R. Щит блокирует все лучи от источников, которые попадают внутрь или на границу щита. Требуется найти максимальное количество источников, которые можно заблокировать одним щитом.
// 
// Формат входных данных:
// Первая строка содержит два числа: N (1 ≤ N ≤ 2000) и R (вещественное число, 0 < R ≤ 10^4).
// Далее N строк, каждая содержит два числа x_i, y_i (-10^4 ≤ x_i, y_i ≤ 10^4) — координаты i-го источника.
// 
// Формат выходных данных:
// Одно целое число — максимальное количество источников, которые можно накрыть щитом радиуса R.
// 
// Пример:
// Вход:
// 3 1.0
// 0 0
// 0 1
// 1 0
// 
// Выход:
// 3
// 
// Пояснение: Щит радиуса 1 с центром в (0.5, 0.5) накрывает все три источника.

/**
 * Задача: Cosmic Ray Shielding (Защита от космических лучей)
 * 
 * Дано N источников космических лучей и радиус щита R.
 * Нужно найти максимальное число источников, которые можно накрыть
 * кругом радиуса R.
 * 
 * Алгоритм:
 * 1. Для каждой точки i предполагаем, что она лежит на границе щита.
 * 2. Центр щита тогда лежит на окружности радиуса R с центром в точке i.
 * 3. Для каждой другой точки j находим интервал углов, при которых центр щита
 *    находится на таком расстоянии от j, что j попадает внутрь щита.
 * 4. Находим максимальное пересечение всех таких интервалов для данной точки i.
 * 5. Максимум по всем i даёт ответ.
 * 
 * Сложность: O(N^2 log N), что приемлемо для N ≤ 2000.
 */
function maxShieldedSources(N, R, points) {
  const TWO_PI = 2 * Math.PI;
  let maxCovered = 0;

  for (let i = 0; i < N; i++) {
    const xi = points[i].x;
    const yi = points[i].y;
    let base = 0; // количество точек, совпадающих с i
    const intervals = [];

    for (let j = 0; j < N; j++) {
      const xj = points[j].x;
      const yj = points[j].y;

      // Если точка совпадает с i, она всегда накрыта вместе с i
      if (xi === xj && yi === yj) {
        base++;
        continue;
      }

      const dx = xj - xi;
      const dy = yj - yi;
      const d2 = dx * dx + dy * dy;

      // Если расстояние больше 2R, то точки i и j не могут одновременно
      // лежать в круге радиуса R (диаметр круга равен 2R)
      if (d2 > 4 * R * R) continue;

      const d = Math.sqrt(d2);
      const phi = Math.atan2(dy, dx); // угол вектора от i к j

      // Условие, что точка j попадает в круг, когда центр круга находится
      // на расстоянии R от i под углом theta:
      // |j - (i + R*(cos theta, sin theta))| <= R
      // => d^2 <= 2R * d * cos(theta - phi)
      // => cos(theta - phi) >= d / (2R)
      // => |theta - phi| <= arccos(d / (2R))
      const ratio = Math.min(1, d / (2 * R));
      const alpha = Math.acos(ratio);

      let start = phi - alpha;
      let end = phi + alpha;

      // Нормализуем углы в диапазон [0, 2π)
      start = (start % TWO_PI + TWO_PI) % TWO_PI;
      end = (end % TWO_PI + TWO_PI) % TWO_PI;

      if (start <= end) {
        intervals.push([start, end]);
      } else {
        // Интервал пересекает 0, разбиваем на два
        intervals.push([start, TWO_PI]);
        intervals.push([0, end]);
      }
    }

    // Находим максимальное пересечение интервалов
    const events = [];
    for (const [s, e] of intervals) {
      events.push({ angle: s, delta: 1 });
      events.push({ angle: e, delta: -1 });
    }

    // Сортируем события по углу. Если углы равны, сначала обрабатываем
    // начало интервала (+1), потом конец (-1), чтобы учесть граничные точки.
    events.sort((a, b) => {
      if (a.angle !== b.angle) return a.angle - b.angle;
      return b.delta - a.delta;
    });

    let cur = 0;
    let maxCur = 0;
    for (const ev of events) {
      cur += ev.delta;
      if (cur > maxCur) maxCur = cur;
    }

    const total = base + maxCur;
    if (total > maxCovered) maxCovered = total;
  }

  return maxCovered;
}
