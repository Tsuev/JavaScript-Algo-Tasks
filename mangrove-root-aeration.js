// Задача: Mangrove Root Aeration
// Сложность: medium
// Дата генерации: 2026-10-14

// Условие задачи
// ## Mangrove Root Aeration
// 
// В мангровом лесу корни впитывают кислород из воды. Болото можно представить как прямоугольную сетку `H × W`, в каждой клетке которой записано число `a[r][c]` — проницаемость грунта для кислорода в этой точке (чем больше, тем лучше аэрация).
// 
// Молодой корень растёт из клетки `(0, 0)` и должен добраться до клетки `(H-1, W-1)`. За один шаг корень может пройти в соседнюю клетку по горизонтали или по вертикали (по диагонали расти нельзя).
// 
// Аэрация всего маршрута определяется как **минимум** проницаемости по всем клеткам, которые корень посетил (включая стартовую и финальную). Нужно проложить маршрут так, чтобы эта величина была как можно больше.
// 
// ### Формат входных данных
// 
// Первая строка содержит два целых числа `H` и `W` (`1 ≤ H, W ≤ 500`). Далее идут `H` строк по `W` целых чисел `a[r][c]` (`0 ≤ a[r][c] ≤ 10^9`).
// 
// ### Формат результата
// 
// Одно целое число — максимально возможная аэрация маршрута (максимум по маршрутам от минимума по клеткам маршрута).
// 
// ### Пример 1
// 
// Вход:
// ```
// 3 3
// 7 6 5
// 4 5 6
// 3 8 7
// ```
// Выход:
// ```
// 5
// ```
// Пояснение: маршрут `(0,0) → (0,1) → (0,2) → (1,2) → (2,2)` даёт значения `7, 6, 5, 6, 7`, минимум равен `5`. Пути со всеми клетками строго больше `5` не существует: клетки со значением `≥ 6` распадаются на две несвязанные группы — `{(0,0), (0,1)}` и `{(1,2), (2,1), (2,2)}`.
// 
// ### Пример 2
// 
// Вход:
// ```
// 1 1
// 42
// ```
// Выход:
// ```
// 42
// ```
// Старт совпадает с финишем, маршрут состоит из одной клетки.
// 
// ### Пример 3
// 
// Вход:
// ```
// 2 3
// 3 3 3
// 3 3 3
// ```
// Выход:
// ```
// 3
// ```
// Все клетки одинаковы, минимум любого маршрута равен `3`.

function maxAeration(grid) {
  const h = grid.length;
  const w = grid[0].length;

  // Если старт и финиш — одна и та же клетка, весь маршрут состоит из неё.
  if (h === 1 && w === 1) return grid[0][0];

  // Все уникальные значения проницаемости, отсортированные по возрастанию.
  // По этому массиву будем бинарно искать ответ: он всегда лежит среди этих чисел,
  // ведь минимум маршрута — это проницаемость какой-то клетки.
  const values = [...new Set(grid.flat())].sort((x, y) => x - y);

  // Проверяет, существует ли путь из левого верхнего угла в правый нижний,
  // если разрешено наступать только на клетки со значением не меньше limit.
  function reachable(limit) {
    if (grid[0][0] < limit) return false;

    const seen = new Uint8Array(h * w);
    const stack = [0];        // обычный стек обхода в глубину: важен лишь факт достижимости
    seen[0] = 1;
    const target = h * w - 1;

    while (stack.length > 0) {
      const idx = stack.pop();
      if (idx === target) return true;

      const r = Math.floor(idx / w);
      const c = idx - r * w;

      // Четыре ортогональных соседа, каждый — только если проходит по проницаемости.
      if (r > 0) {
        const n = idx - w;
        if (!seen[n] && grid[r - 1][c] >= limit) { seen[n] = 1; stack.push(n); }
      }
      if (r + 1 < h) {
        const n = idx + w;
        if (!seen[n] && grid[r + 1][c] >= limit) { seen[n] = 1; stack.push(n); }
      }
      if (c > 0) {
        const n = idx - 1;
        if (!seen[n] && grid[r][c - 1] >= limit) { seen[n] = 1; stack.push(n); }
      }
      if (c + 1 < w) {
        const n = idx + 1;
        if (!seen[n] && grid[r][c + 1] >= limit) { seen[n] = 1; stack.push(n); }
      }
    }

    return false;
  }

  // Свойство монотонно: если путь есть при пороге limit, то он есть и при любом
  // меньшем пороге. Значит, можно бинарным поиском найти наибольший работающий порог.
  let lo = 0;
  let hi = values.length - 1;
  let best = values[0]; // минимальное значение доступно всегда: сетка связна

  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (reachable(values[mid])) {
      best = values[mid];
      lo = mid + 1;   // попробуем порог повыше
    } else {
      hi = mid - 1;   // такой порог уже недостижим
    }
  }

  return best;
}
