// Условие задачи
// Сонар глубоководного зонда «Hollow Reef» сканирует риф и выдаёт последовательность эхо-амплитуд.
// 
// Назовём непрерывный участок показаний a[l..r] впадиной (hollow), если в нём найдётся такая позиция m (l ≤ m ≤ r), что
//     a[l] > a[l+1] > ... > a[m]   и   a[m] < a[m+1] < ... < a[r].
// Иначе говоря, значения строго убывают до самого «глубокого» места m, а затем строго возрастают. Участок из одного элемента всегда считается впадиной; строго монотонный участок тоже подходит — тогда дно лежит на одном из его краёв.
// 
// Найдите длину самой длинной впадины в показаниях сонара.
// 
// Формат входных данных:
// - первая строка: целое число n (1 ≤ n ≤ 200000) — количество измерений;
// - вторая строка: n целых чисел a_i (−10^9 ≤ a_i ≤ 10^9), разделённых пробелами.
// 
// Формат результата:
// - одно целое число — максимальная длина впадины.
// 
// Пример 1:
// Вход:
// 7
// 4 3 2 5 6 1 0
// Выход:
// 5
// Пояснение: участок [4, 3, 2, 5, 6] убывает до 2 и затем возрастает, его длина 5. Продлить его нельзя: после 6 идёт 1, а условие 6 < 1 не выполнено.
// 
// Пример 2:
// Вход:
// 4
// 1 2 3 4
// Выход:
// 4
// Пояснение: дно можно поместить в самую левую точку — тогда весь массив является возрастающей частью впадины.
// 
// Пример 3:
// Вход:
// 5
// 0 0 0 0 0
// Выход:
// 1
// Пояснение: строгие неравенства не выполняются нигде, поэтому любая впадина состоит из одного элемента.

/**
 * Ищем самую длинную «впадину» в показаниях сонара.
 *
 * Ключевое наблюдение: любая впадина однозначно задаётся своей самой низкой точкой m.
 * Значит, достаточно для каждой позиции i посчитать:
 *   down[i] — сколько подряд идёт строгое убывание, заканчивающееся в i (спуск ко дну);
 *   up[i]   — сколько подряд идёт строгое возрастание, начинающееся в i (подъём от дна).
 * Тогда лучшая впадина с дном в позиции i имеет длину down[i] + up[i] - 1
 * (сама точка i посчитана дважды, поэтому вычитаем единицу).
 *
 * Сложность: O(n) по времени и O(n) по памяти.
 */
function longestHollow(a) {
  const n = a.length;
  if (n === 0) return 0;

  // Проход слева направо: длина строго убывающего «спуска», обрывающегося в позиции i.
  const down = new Array(n).fill(1);
  for (let i = 1; i < n; i++) {
    if (a[i - 1] > a[i]) down[i] = down[i - 1] + 1;
  }

  // Проход справа налево: длина строго возрастающего «подъёма», начинающегося в позиции i.
  const up = new Array(n).fill(1);
  for (let i = n - 2; i >= 0; i--) {
    if (a[i] < a[i + 1]) up[i] = up[i + 1] + 1;
  }

  // Перебираем кандидата на роль дна и «склеиваем» спуск с подъёмом.
  let best = 0;
  for (let i = 0; i < n; i++) {
    best = Math.max(best, down[i] + up[i] - 1);
  }
  return best;
}
