// Задача: Leyline Knot Untangling
// Сложность: hard
// Дата генерации: 2026-09-27

// Условие задачи
// Лей-линии соединяют магические якоря. Якоря расположены по окружности и пронумерованы по часовой стрелке числами от 1 до n. Каждая лей-линия задаётся парой якорей (a, b), a ≠ b, и рисуется как хорда окружности между ними.
// 
// Две лей-линии запутываются, если их хорды пересекаются во внутренней точке. Для точек, лежащих на окружности, это равносильно чередованию концов по кругу: при a < b и c < d хорды (a,b) и (c,d) пересекаются тогда и только тогда, когда a < c < b < d или c < a < d < b. Хорды, имеющие общий конец, пересекающимися не считаются.
// 
// Нужно убрать минимальное число лей-линий так, чтобы оставшиеся попарно не пересекались, то есть найти максимально большой набор попарно непересекающихся лей-линий.
// 
// Формат входных данных
// В первой строке записаны два целых числа n и m (1 ≤ n ≤ 100, 0 ≤ m ≤ 1000) — количество якорей и лей-линий.
// В следующих m строках записаны пары a_i, b_i (1 ≤ a_i, b_i ≤ n, a_i ≠ b_i). Все пары различны.
// 
// Формат результата
// Одно целое число — максимальное количество лей-линий, которое можно оставить, удалив остальные.
// 
// Пример 1
// Вход:
// 4 3
// 1 2
// 1 3
// 2 4
// Выход:
// 2
// Пояснение: (1,3) и (2,4) пересекаются, поэтому все три оставить нельзя; любые две из них не пересекаются.
// 
// Пример 2
// Вход:
// 6 3
// 1 4
// 2 5
// 3 6
// Выход:
// 1
// Пояснение: все три хорды попарно пересекаются.
// 
// Пример 3
// Вход:
// 8 4
// 1 8
// 2 7
// 3 6
// 4 5
// Выход:
// 4
// Пояснение: хорды вложены друг в друга и не пересекаются, можно оставить все четыре.

/*
 * Leyline Knot Untangling
 *
 * Нужно найти максимальный набор попарно непересекающихся хорд окружности.
 * Идея решения состоит из двух частей.
 *
 * 1) Сначала избавляемся от «общих концов». Несколько хорд могут выходить из
 *    одного якоря; такие хорды между собой не пересекаются. Мысленно заменим
 *    каждый якорь на столько близко стоящих копий, сколько к нему подходит
 *    хорд, и припишем каждую хорду своей копии. Если копии упорядочить по
 *    часовой стрелке в порядке УБЫВАНИЯ «ранга» второго конца, то веер хорд
 *    из одного якоря превращается в набор вложенных хорд: новых пересечений
 *    не возникает, а все старые сохраняются. После этого все 2m концов
 *    различны, и задача становится классической.
 *
 * 2) Для концов, стоящих в линейном порядке, работает интервальное ДП:
 *    f(i, j) — максимум хорд с обоими концами внутри отрезка [i, j], не
 *    пересекающихся между собой. Если взять самый левый конец i, то либо он
 *    не используется (f(i+1, j)), либо он принадлежит хорде (i, r). Тогда все
 *    остальные хорды набора лежат целиком внутри (i, r) либо правее r, и не
 *    зависят друг от друга: f(i+1, r-1) + f(r+1, j). Ответ — f(0, 2m-1).
 */
function maxNonCrossingLeylines(n, edges) {
  const m = edges.length;
  if (m === 0) return 0;

  // Шаг 1. Для каждого якоря собираем список инцидентных лей-линий.
  const incident = Array.from({ length: n + 1 }, () => []);
  for (let id = 0; id < m; id++) {
    const a = edges[id][0], b = edges[id][1];
    incident[a].push({ other: b, id });
    incident[b].push({ other: a, id });
  }

  // Шаг 2. Расщепляем якоря на копии.
  // end[id] — две позиции концов лей-линии id в новом линейном порядке.
  const end = Array.from({ length: m }, () => [-1, -1]);
  let cursor = 0;
  for (let p = 1; p <= n; p++) {
    const list = incident[p];
    if (list.length === 0) continue;
    // Ранг второго конца: 1 у якоря p+1, 2 у p+2, ..., n-1 у p-1.
    const rankOf = (q) => ((q - p + n) % n);
    // Копии идут подряд; чем дальше по часовой стрелке второй конец,
    // тем раньше стоит копия — так веер хорд становится вложенным.
    list.sort((x, y) => rankOf(y.other) - rankOf(x.other));
    for (const link of list) {
      const slots = end[link.id];
      if (slots[0] === -1) slots[0] = cursor++;
      else slots[1] = cursor++;
    }
  }

  // Шаг 3. Интервальное ДП по 2m позициям концов.
  const size = 2 * m;
  const chordsByLeft = Array.from({ length: size }, () => []);
  for (let id = 0; id < m; id++) {
    const l = Math.min(end[id][0], end[id][1]);
    const r = Math.max(end[id][0], end[id][1]);
    chordsByLeft[l].push(r);
  }

  const width = size + 1;
  const dp = new Int32Array((size + 1) * (size + 1));
  // f(i, j) = 0 при i > j (пустой отрезок).
  const get = (i, j) => (i > j ? 0 : dp[i * width + j]);

  // Идём по левой границе вниз, по правой — вверх: все нужные значения
  // для более коротких отрезков уже посчитаны.
  for (let i = size - 1; i >= 0; i--) {
    const row = i * width;
    for (let j = i; j < size; j++) {
      let best = get(i + 1, j); // позиция i ни с чем не соединена
      for (const r of chordsByLeft[i]) {
        if (r > j) continue; // хорда (i, r) не помещается в отрезок
        const cand = 1 + get(i + 1, r - 1) + get(r + 1, j);
        if (cand > best) best = cand;
      }
      dp[row + j] = best;
    }
  }

  return get(0, size - 1);
}

// Необязательная обёртка для запуска по строке входа в формате задачи.
function solve(input) {
  const t = input.trim().split(/\s+/).map(Number);
  let k = 0;
  const n = t[k++], m = t[k++];
  const edges = [];
  for (let i = 0; i < m; i++) edges.push([t[k++], t[k++]]);
  return maxNonCrossingLeylines(n, edges);
}
