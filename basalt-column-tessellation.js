// Условие задачи
// Базальтовые колонны имеют форму шестиугольных призм. Если посмотреть на торец такой колонны, мы увидим правильный шестиугольник, разбитый на маленькие равносторонние треугольники. Рассмотрим шестиугольную область, стороны которой (в единицах длины стороны треугольника) равны a, b и c; противоположные стороны равны. Требуется замостить эту область ромбами, каждый из которых состоит из двух смежных треугольников. Каждый такой ромб соответствует паре соседних граней базальтовых колонн. Найдите количество различных замощений.
// 
// Входные данные: три целых числа a, b, c (1 ≤ a, b, c ≤ 50) через пробел.
// Выходные данные: одно целое число — количество замощений. Так как число может быть очень большим, выведите его в десятичной записи без ведущих нулей.
// 
// Пример 1:
// Вход: 1 1 1
// Выход: 2
// 
// Пример 2:
// Вход: 2 2 2
// Выход: 20
// 
// Пример 3:
// Вход: 2 3 4
// Выход: 490

/**
 * Подсчёт числа замощений шестиугольника со сторонами a, b, c ромбами (lozenge tilings).
 * Используется формула Мак-Магона:
 *   ∏_{i=1..a} ∏_{j=1..b} ∏_{k=1..c} (i+j+k-1)/(i+j+k-2)
 * Внутреннее произведение по k телескопируется, поэтому достаточно двойного цикла:
 *   ∏_{i=1..a} ∏_{j=1..b} (i+j+c-1)/(i+j-1)
 * Чтобы избежать работы с огромными промежуточными дробями, считаем простые множители.
 */
function countBasaltTessellation(a, b, c) {
  const maxN = a + b + c; // максимальное число в числителе или знаменателе

  // Решето Эратосфена для простых чисел до maxN
  const isPrime = new Array(maxN + 1).fill(true);
  const primes = [];
  for (let i = 2; i <= maxN; i++) {
    if (isPrime[i]) {
      primes.push(i);
      for (let j = i * i; j <= maxN; j += i) isPrime[j] = false;
    }
  }

  // Храним показатели степеней простых множителей
  const exponent = new Map();

  // Добавляет простые множители числа n в карту с заданным знаком (+1 или -1)
  function addFactors(n, sign) {
    for (const p of primes) {
      if (p * p > n) break;
      while (n % p === 0) {
        exponent.set(p, (exponent.get(p) || 0) + sign);
        n /= p;
      }
    }
    if (n > 1) {
      exponent.set(n, (exponent.get(n) || 0) + sign);
    }
  }

  // Основной двойной цикл по формуле
  for (let i = 1; i <= a; i++) {
    for (let j = 1; j <= b; j++) {
      const num = i + j + c - 1;
      const den = i + j - 1;
      addFactors(num, 1);
      addFactors(den, -1);
    }
  }

  // Собираем результат как произведение простых в соответствующих степенях
  let result = 1n;
  for (const [p, exp] of exponent) {
    if (exp > 0) {
      result *= BigInt(p) ** BigInt(exp);
    }
  }

  return result.toString();
}
