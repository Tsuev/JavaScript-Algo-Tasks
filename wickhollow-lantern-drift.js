// Условие задачи
// Уикхоллоу — узкая ложбина, по дну которой течёт прямой канал. В сумерках по воде пускают бумажные фонарики, и каждый из них подхватывает ветер: фонарик движется вдоль канала с постоянной скоростью, не меняя её и не останавливаясь.
// 
// В момент времени t = 0 на канале выставлены n фонариков. Фонарик с номером i находится в точке с координатой positions[i] и движется со скоростью speeds[i] (скорость может быть отрицательной — тогда фонарик плывёт в противоположную сторону). Все начальные координаты различны. Координата фонарика в момент t равна positions[i] + speeds[i] * t.
// 
// Нужно посчитать, сколько пар фонариков встретятся — то есть окажутся в одной и той же точке в один и тот же момент времени t > 0. Момент t = 0 не считается: фонарики, стоящие в разных точках в начале, ещё не встретились. Если три и более фонарика сойдутся в одной точке, каждая пара из них считается отдельно.
// 
// Формат входных данных:
//   n         — целое число, 1 <= n <= 2 * 10^5
//   positions — массив из n целых чисел, все значения различны, |positions[i]| <= 10^9
//   speeds    — массив из n целых чисел, |speeds[i]| <= 10^9
// 
// Формат результата:
//   одно целое число — количество пар фонариков, которые встретятся в момент t > 0.
// 
// Решение должно работать за O(n log n).
// 
// Пример 1:
//   positions = [1, 3, 2, 4], speeds = [2, 1, 3, 0]
//   Ответ: 5
//   Пояснение: встречаются пары с координатами (1;3), (1;4), (3;2), (3;4), (2;4).
// 
// Пример 2:
//   positions = [5, 1, 3], speeds = [-1, 0, 2]
//   Ответ: 2
//   Пояснение: фонарик из точки 5 плывёт влево и догоняет неподвижный фонарик в точке 1, а фонарик из точки 3 догоняет фонарик из точки 5. Пара (1;3) не встречается: передний фонарик уходит вперёд.
// 
// Пример 3:
//   positions = [0, 10], speeds = [1, 1]
//   Ответ: 0
//   Пояснение: фонарики плывут с одинаковой скоростью, расстояние между ними не меняется.

/**
 * Сколько пар фонариков встретятся в одной точке в момент t > 0.
 * positions[i] — начальная координата i-го фонарика (все координаты различны),
 * speeds[i]    — его постоянная скорость (может быть отрицательной).
 */
function solve(positions, speeds) {
  const n = positions.length;
  if (n < 2) return 0;

  // Перебираем фонарики в порядке возрастания координаты: теперь для любых
  // двух индексов i < j в этом порядке гарантированно positions[i] < positions[j].
  const order = Array.from({ length: n }, (_, i) => i)
    .sort((a, b) => positions[a] - positions[b]);

  const velocity = order.map(i => speeds[i]);

  // Фонарик слева (x_i < x_j) догонит правый ровно тогда, когда его скорость
  // строго больше: v_i > v_j. Если скорость равна, расстояние не меняется,
  // а если меньше — просвет только растёт. Значит, ответ — это число инверсий
  // в массиве скоростей, выписанных слева направо.
  return countInversions(velocity);
}

/**
 * Классический подсчёт инверсий сортировкой слиянием за O(m log m).
 * Инверсия — пара индексов i < j, для которой arr[i] > arr[j].
 */
function countInversions(sequence) {
  const arr = sequence.slice();
  const buffer = new Array(arr.length);

  function sortRange(lo, hi) {
    if (hi - lo <= 1) return 0;

    const mid = (lo + hi) >> 1;
    let inversions = sortRange(lo, mid) + sortRange(mid, hi);

    let left = lo;
    let right = mid;
    let write = lo;

    while (left < mid && right < hi) {
      if (arr[left] <= arr[right]) {
        buffer[write++] = arr[left++];
      } else {
        // Все ещё не слитые элементы левой половины строго больше arr[right],
        // и каждый из них стоит в исходном массиве раньше него — это inversions.
        inversions += mid - left;
        buffer[write++] = arr[right++];
      }
    }

    while (left < mid) buffer[write++] = arr[left++];
    while (right < hi) buffer[write++] = arr[right++];

    // Возвращаем слитый кусок на место, чтобы родительские вызовы видели порядок.
    for (let t = lo; t < hi; t++) arr[t] = buffer[t];

    return inversions;
  }

  return sortRange(0, arr.length);
}
