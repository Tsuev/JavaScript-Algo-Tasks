// Задача: Whispering Gallery Foci
// Сложность: hard
// Дата генерации: 2026-09-27

// Условие задачи
// **Шепчущие фокусы**
// 
// В музее есть N эллиптических залов. Каждый зал — это эллипс, и для него выполняется классическое свойство «шепчущей галереи»: звук, испущенный в одном фокусе эллипса, после отражений от стенок собирается в другом фокусе, причём полная длина этого пути равна ровно 2a, где a — большая полуось эллипса. Это верно для любого направления испускания.
// 
// Зал с номером i задаётся:
// * центром (cx_i, cy_i),
// * большой полуосью a_i и малой полуосью b_i (a_i ≥ b_i > 0),
// * углом θ_i в градусах — наклоном большой полуоси к положительному направлению оси Ox.
// 
// Фокусы зала лежат на большой оси на расстоянии c_i = sqrt(a_i² − b_i²) от центра:
// 
//     F_i¹ = (cx_i + c_i·cos θ_i,  cy_i + c_i·sin θ_i)
//     F_i² = (cx_i − c_i·cos θ_i,  cy_i − c_i·sin θ_i)
// 
// Звуковой импульс стартует в точке S, летит по открытому пространству прямолинейно со скоростью 1 и должен побывать в каждом зале ровно один раз. «Побывать в зале» означает: войти в зал в одном из его фокусов, а выйти в другом фокусе; внутри зала импульс тратит ровно 2a_i единиц времени. Между залами (а также от S до первого зала и от последнего зала до T) импульс летит по прямой. Завершиться путь должен в точке T.
// 
// Найдите минимально возможное суммарное время пути.
// 
// **Формат входных данных**
// 
// Первая строка: целое число N — количество залов.
// Вторая строка: четыре вещественных числа sx, sy, tx, ty — координаты старта S и цели T.
// Далее N строк, в каждой: cx cy a b theta, где theta — угол в градусах.
// 
// **Формат результата**
// 
// Одно вещественное число — минимальное время пути. Ответ принимается с точностью не хуже 1e-6. Ответ всегда конечен.
// 
// **Ограничения**
// 
// 1 ≤ N ≤ 14; все координаты и полуоси по модулю не превосходят 10^4; 0 ≤ theta < 360; 0 < b ≤ a.
// 
// **Пример 1**
// 
// Вход:
// 
//     1
//     0 0 3 9
//     5 5 5 3 0
// 
// Выход:
// 
//     22.310122
// 
// Пояснение. c = sqrt(25 − 9) = 4, большая ось горизонтальна, фокусы: (1, 5) и (9, 5).
// Вариант «войти в (1,5), выйти в (9,5)»: sqrt(26) + 10 + sqrt(52) ≈ 5.099020 + 10 + 7.211103 = 22.310122.
// Вариант «войти в (9,5), выйти в (1,5)»: sqrt(106) + 10 + sqrt(20) ≈ 24.767766 — хуже.
// 
// **Пример 2**
// 
// Вход:
// 
//     2
//     0 0 20 0
//     5 0 4 2 0
//     15 0 4 2 0
// 
// Выход:
// 
//     22.143594
// 
// Пояснение. Первый зал: c = sqrt(16 − 4) = sqrt(12) ≈ 3.464102, фокусы (1.535898, 0) и (8.464102, 0). Второй зал: фокусы (11.535898, 0) и (18.464102, 0). Оптимально войти в ближний фокус первого зала, выйти в дальний, затем войти в ближний фокус второго и выйти в дальний:
// 1.535898 + 8 + 3.071797 + 8 + 1.535898 ≈ 22.143594.

function solve(input) {
  const tok = input.trim().split(/\s+/).map(Number);
  let p = 0;
  const n = tok[p++];
  const sx = tok[p++], sy = tok[p++], tx = tok[p++], ty = tok[p++];

  // Для каждого зала запоминаем координаты его двух фокусов и стоимость
  // прохода сквозь зал. По свойству шепчущей галереи она всегда равна 2a,
  // независимо от направления, в котором звук вошёл в зал.
  const fx = [], fy = [], inside = [];
  for (let i = 0; i < n; i++) {
    const cx = tok[p++], cy = tok[p++];
    const a = tok[p++], b = tok[p++];
    const theta = tok[p++] * Math.PI / 180;
    // c — половина расстояния между фокусами.
    const c = Math.sqrt(Math.max(0, a * a - b * b));
    const ux = Math.cos(theta), uy = Math.sin(theta);
    fx.push(cx + c * ux, cx - c * ux);
    fy.push(cy + c * uy, cy - c * uy);
    inside.push(2 * a);
  }

  // Вырожденный случай: залов нет, просто летим из S в T.
  if (n === 0) return Math.hypot(tx - sx, ty - sy);

  const V = 2 * n;            // всего фокусных узлов: по два на каждый зал
  const full = (1 << n) - 1;  // маска «все залы посещены»

  // dp[mask][v] — минимальное время, при котором посещены ровно залы из mask,
  // а импульс только что вышел из фокуса v (v — фокус последнего зала).
  const dp = [];
  for (let m = 0; m <= full; m++) dp.push(new Float64Array(V).fill(Infinity));

  // База: выбираем самый первый зал. Летим из S по прямой в его фокус входа,
  // затем тратим 2a внутри зала и оказываемся в противоположном фокусе.
  for (let k = 0; k < n; k++) {
    for (let e = 0; e < 2; e++) {
      const entryX = fx[2 * k + e], entryY = fy[2 * k + e];
      const out = 2 * k + (1 - e);
      const cost = Math.hypot(entryX - sx, entryY - sy) + inside[k];
      const m = 1 << k;
      if (cost < dp[m][out]) dp[m][out] = cost;
    }
  }

  // Основной переход: дописываем к текущей цепочке ещё один, пока не посещённый зал.
  // Маски перебираем по возрастанию: любой переход ведёт в строго большую маску,
  // поэтому к моменту обработки dp[mask] в ней уже учтены все способы туда попасть.
  for (let mask = 1; mask <= full; mask++) {
    const row = dp[mask];
    for (let v = 0; v < V; v++) {
      const cur = row[v];
      if (cur === Infinity) continue;
      const vx = fx[v], vy = fy[v];
      for (let k = 0; k < n; k++) {
        const bit = 1 << k;
        if (mask & bit) continue;              // этот зал уже пройден
        const nextRow = dp[mask | bit];
        for (let e = 0; e < 2; e++) {
          const entryX = fx[2 * k + e], entryY = fy[2 * k + e];
          const out = 2 * k + (1 - e);         // выходим в противоположном фокусе
          const cand = cur + Math.hypot(entryX - vx, entryY - vy) + inside[k];
          if (cand < nextRow[out]) nextRow[out] = cand;
        }
      }
    }
  }

  // Финал: все залы пройдены, из текущего фокуса летим по прямой в T.
  let ans = Infinity;
  for (let v = 0; v < V; v++) {
    const cur = dp[full][v];
    if (cur === Infinity) continue;
    const cand = cur + Math.hypot(tx - fx[v], ty - fy[v]);
    if (cand < ans) ans = cand;
  }
  return ans;
}
