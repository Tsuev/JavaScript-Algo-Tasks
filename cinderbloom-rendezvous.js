// Задача: Cinderbloom Rendezvous
// Сложность: medium
// Дата генерации: 2026-10-29

// Условие задачи
// В саду «Пепельный цвет» на числовой прямой растут n огнецветов. Каждый цветок описывается тройкой целых чисел (x, open, close): он находится в точке с координатой x и раскрыт (доступен для встречи) только в моменты времени от open до close включительно. В момент времени 0 двое путников находятся в точках p и q. За единицу времени каждый из них может сдвинуться не более чем на 1 (то есть двигаться со скоростью не больше 1 в любую сторону), а также может стоять на месте и ждать. Путники хотят встретиться ровно у одного из огнецветов, причём в момент встречи этот цветок обязан быть раскрыт. Требуется найти минимальное возможное время такой встречи, либо вернуть -1, если встретиться у раскрытого цветка невозможно.
// 
// Входные данные: массив flowers из n объектов вида { x, open, close } (все числа целые, |x|, |open|, |close|, |p|, |q| ≤ 10^9, open ≤ close), а также целые начальные координаты путников startA (соответствует p) и startB (соответствует q). Дополнительно в текстовом виде это выглядит так: первая строка — число n, далее n строк по три числа «x open close», последняя строка — два числа p q.
// 
// Выходные данные: одно целое число — минимальное время встречи или -1.
// 
// Пример 1. flowers = [{x:0, open:0, close:10}, {x:5, open:3, close:4}], p = -2, q = 7. Ответ: 7. Первый цветок раскрыт всё время, путникам нужно дойти до него: первому 2 шага, второму 7 шагов, значит встретиться они смогут не раньше момента 7, и это допустимо (7 ≤ 10). Второй цветок находится не дальше, но раскрыт только до момента 4 — встретиться там невозможно.
// 
// Пример 2. flowers = [{x:3, open:0, close:2}], p = 0, q = 0. Ответ: -1. Оба дойдут до цветка за 3 шага, но к моменту 3 он уже закрыт.
// 
// Пример 3. flowers = [{x:2, open:10, close:12}], p = 2, q = 2. Ответ: 10. Путники уже на месте, но обязаны дождаться раскрытия цветка в момент 10.

// Каждый цветок рассматриваем независимо: встреча именно у него даёт
// наименьшее время max(время, за которое дойдут оба, момент раскрытия).
function cinderbloomRendezvous(flowers, startA, startB) {
  let best = Infinity;

  for (const flower of flowers) {
    const { x, open, close } = flower;

    // Раньше этого момента оба путника физически не смогут оказаться в точке x:
    // каждый идёт со скоростью не больше 1, поэтому нужен max из двух расстояний.
    const arrival = Math.max(Math.abs(x - startA), Math.abs(x - startB));

    // Если цветок ещё не раскрылся к моменту прихода, путники просто ждут рядом,
    // поэтому встреча происходит в более поздний из двух моментов.
    const meetingTime = Math.max(arrival, open);

    // Цветок должен быть раскрыт в момент встречи, иначе вариант не подходит.
    if (meetingTime <= close && meetingTime < best) {
      best = meetingTime;
    }
  }

  // Ни один цветок не подошёл.
  return best === Infinity ? -1 : best;
}
