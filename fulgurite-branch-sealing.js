// Условие задачи
// ## Fulgurite Branch Sealing (Запечатывание ветвей фульгурита)
// 
// После удара молнии в песок образовался фульгурит — сеть стеклянных трубок, имеющая структуру **корневого дерева** из `n` узлов. Корень дерева — узел `1` (место входа разряда).
// 
// Такая сеть опасна: если в ней останется связная группа больше чем из `K` трубок, при следующем разряде она может расколоться и вызвать цепную реакцию. Поэтому часть трубок можно **запечатать**. Запечатывание трубки — это удаление соответствующего ребра дерева; каждое удалённое ребро считается одним запечатыванием.
// 
// Найдите **минимальное число рёбер, которые нужно запечатать**, чтобы в оставшемся лесу (наборе компонент связности) **каждая компонента содержала не более `K` узлов**.
// 
// ### Формат входных данных
// 
// - В первой строке два целых числа: `n` — количество узлов (`1 ≤ n ≤ 500`) и `K` — максимально допустимый размер компоненты (`1 ≤ K ≤ n`).
// - Далее `n − 1` строк, каждая содержит два числа `u` и `v` (`1 ≤ u, v ≤ n`, `u ≠ v`) — описание неориентированного ребра между узлами `u` и `v`. Гарантируется, что рёбра образуют дерево.
// 
// ### Формат результата
// 
// Одно целое число — минимальное количество рёбер, которые нужно удалить.
// 
// ### Примеры
// 
// **Пример 1**
// ```
// Вход:
// n = 5, K = 2
// рёбра: (1,2), (1,3), (2,4), (2,5)
// 
// Выход:
// 2
// ```
// Пояснение: если удалить рёбра (1,2) и (2,4), получатся компоненты `{1,3}` (размер 2), `{2,5}` (размер 2) и `{4}` (размер 1) — все не больше `K = 2`. Одним ребром обойтись нельзя, поэтому ответ `2`.
// 
// **Пример 2**
// ```
// Вход:
// n = 5, K = 2
// рёбра: (1,2), (2,3), (3,4), (4,5)
// 
// Выход:
// 2
// ```
// Пояснение: это путь `1-2-3-4-5`. Удаляем (2,3) и (4,5): компоненты `{1,2}`, `{3,4}`, `{5}` — все размера не больше `2`.
// 
// **Пример 3**
// ```
// Вход:
// n = 3, K = 3
// рёбра: (1,2), (1,3)
// 
// Выход:
// 0
// ```
// Пояснение: всё дерево целиком имеет размер `3 ≤ K`, запечатывать ничего не нужно.

/**
 * Fulgurite Branch Sealing.
 *
 * Задача: в корневом дереве удалить минимум рёбер так, чтобы каждая
 * оставшаяся компонента связности содержала не более K узлов.
 *
 * Идея — динамическое программирование по дереву (рюкзак на дереве).
 * Для каждого узла u считаем dp[u][s] = минимальное число разрезов внутри
 * поддерева u (не считая ребра к родителю), при котором компонента,
 * содержащая сам u, имеет ровно s узлов (s <= K), а все прочие компоненты
 * в поддереве тоже не превышают K.
 *
 * При слиянии с ребёнком v есть два варианта:
 *   1) запечатать ребро (u,v): поддерево v становится отдельной замкнутой
 *      частью, значит берём лучший (минимум по размеру) вариант dp[v] и
 *      добавляем 1 за разрез;
 *   2) оставить ребро: компонента v присоединяется к компоненте u,
 *      размеры складываются (нужно s + t <= K).
 *
 * Ответ — минимум dp[1][s] по всевозможным s для корня.
 * Сложность O(n * K^2).
 */
function sealBranches(n, K, edges) {
  if (n === 0) return 0;

  // Строим списки смежности неориентированного дерева.
  const adj = Array.from({ length: n + 1 }, () => []);
  for (const [u, v] of edges) {
    adj[u].push(v);
    adj[v].push(u);
  }

  const INF = Infinity;

  // Итеративный обход в глубину: получаем порядок и родителей.
  // Итеративность нужна, чтобы не упереться в переполнение стека
  // на длинных цепочках.
  const parent = new Array(n + 1).fill(0);
  const order = [];
  const stack = [1];
  parent[1] = -1;
  while (stack.length > 0) {
    const u = stack.pop();
    order.push(u);
    for (const v of adj[u]) {
      if (v !== parent[u]) {
        parent[v] = u;
        stack.push(v);
      }
    }
  }

  const dp = new Array(n + 1);

  // Обрабатываем узлы в обратном порядке обхода — дети готовы раньше родителя.
  for (let i = order.length - 1; i >= 0; i--) {
    const u = order[i];

    // Пока имеем только сам узел u: компонента размера 1, разрезов 0.
    let cur = new Array(K + 1).fill(INF);
    cur[1] = 0;

    for (const v of adj[u]) {
      if (v === parent[u]) continue;
      const dv = dp[v];

      // Лучший способ «закрыть» поддерево v отдельно (для разреза ребра).
      let bestClose = INF;
      for (let t = 1; t <= K; t++) {
        if (dv[t] < bestClose) bestClose = dv[t];
      }

      const next = new Array(K + 1).fill(INF);

      for (let s = 1; s <= K; s++) {
        if (cur[s] === INF) continue;

        // Вариант 1: запечатать ребро (u, v).
        if (bestClose !== INF) {
          const cost = cur[s] + 1 + bestClose;
          if (cost < next[s]) next[s] = cost;
        }

        // Вариант 2: оставить ребро, размеры компонент складываются.
        for (let t = 1; s + t <= K; t++) {
          if (dv[t] === INF) continue;
          const cost = cur[s] + dv[t];
          if (cost < next[s + t]) next[s + t] = cost;
        }
      }

      cur = next;
    }

    dp[u] = cur;
  }

  // Компонента корня тоже должна быть не больше K — берём лучший вариант.
  let answer = INF;
  for (let s = 1; s <= K; s++) {
    if (dp[1][s] < answer) answer = dp[1][s];
  }
  return answer;
}

// Небольшая самопроверка (без вывода в консоль, просто возврат результатов).
// sealBranches(5, 2, [[1,2],[1,3],[2,4],[2,5]]) === 2
// sealBranches(5, 2, [[1,2],[2,3],[3,4],[4,5]]) === 2
// sealBranches(3, 3, [[1,2],[1,3]]) === 0

module.exports = { sealBranches };
