// Задача: Petrified Willow Ring Counting
// Сложность: medium
// Дата генерации: 2026-11-02

// Условие задачи
// Петрифицированная ива (окаменевшее дерево) в разрезе описывается графом: n «центров роста» — это вершины, а m «древесных волокон» — рёбра, соединяющие пары вершин. Известно, что полученный граф является кактусом: это связный или несвязный неориентированный граф без кратных рёбер и петель, в котором каждое ребро принадлежит не более чем одному простому циклу (то есть любые два простых цикла имеют не более одной общей вершины и не имеют общих рёбер).
// 
// Кольцом ивы называется простой цикл в этом графе. Нужно посчитать количество различных простых циклов («колец»).
// 
// Формат входных данных:
// Первая строка содержит два целых числа n и m (1 ≤ n ≤ 2·10^5, 0 ≤ m ≤ 3·10^5) — количество вершин и рёбер.
// Следующие m строк содержат по два числа u, v (1 ≤ u, v ≤ n, u ≠ v) — концы очередного ребра.
// 
// Формат результата:
// Одно целое число — количество простых циклов в графе.
// 
// Пример 1:
// Вход:
// 5 6
// 1 2
// 2 3
// 3 1
// 1 4
// 4 5
// 5 1
// Выход:
// 2
// (Два треугольника 1-2-3-1 и 1-4-5-1, имеющие общую вершину 1 — это ровно два разных простых цикла.)
// 
// Пример 2:
// Вход:
// 4 3
// 1 2
// 2 3
// 3 4
// Выход:
// 0
// (Это дерево, циклов нет.)
// 
// Пример 3:
// Вход:
// 6 6
// 1 2
// 2 3
// 3 1
// 4 5
// 5 6
// 6 4
// Выход:
// 2
// (Два независимых треугольника 1-2-3-1 и 4-5-6-4.)

// Задача: посчитать число простых циклов («колец») в графе-кактусе.
//
// Ключевое наблюдение: в кактусе любые два простых цикла не делят ни одного
// ребра, поэтому все циклы независимы. Значит их число совпадает с
// цикломатическим числом графа (размерностью пространства циклов):
//
//     число простых циклов = m - n + C,
//
// где m — число рёбер, n — число вершин, C — число компонент связности.
// Для произвольного графа это была бы лишь размерность пространства циклов,
// но именно в кактусе ей равно само количество простых циклов.
//
// Сложность: O((n + m) * α(n)) по времени и O(n) по памяти.

function countRings(n, edges) {
  // Система непересекающихся множеств (DSU) для подсчёта компонент связности.
  const parent = new Array(n + 1);
  const rank = new Array(n + 1).fill(0);
  for (let i = 1; i <= n; i++) parent[i] = i;

  const find = (x) => {
    while (parent[x] !== x) {
      parent[x] = parent[parent[x]]; // сжатие путей
      x = parent[x];
    }
    return x;
  };

  const union = (a, b) => {
    a = find(a);
    b = find(b);
    if (a === b) return;
    if (rank[a] < rank[b]) [a, b] = [b, a]; // объединяем по рангу
    parent[b] = a;
    if (rank[a] === rank[b]) rank[a]++;
  };

  // Объединяем концы каждого ребра.
  for (const [u, v] of edges) union(u, v);

  // После всех объединений считаем, сколько получилось компонент связности.
  // Важно учитывать и изолированные вершины — они тоже отдельные компоненты.
  const roots = new Set();
  for (let i = 1; i <= n; i++) roots.add(find(i));
  const components = roots.size;

  // Цикломатическое число для кактуса равно количеству простых циклов.
  return edges.length - n + components;
}
