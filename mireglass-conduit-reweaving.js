// Задача: Mireglass Conduit Reweaving
// Сложность: medium
// Дата генерации: 2026-11-10

// Условие задачи
// В стране Миреглас есть сеть стеклянных кондуитов, соединяющих узлы-перекрёстки. Мастера решили переплести всю сеть заново в одну непрерывную нить: нужно выложить все имеющиеся кондуиты в таком порядке, чтобы каждый следующий кондуит начинался в том узле, где закончился предыдущий. Каждый кондуит обязан быть использован ровно один раз, добавлять новые кондуиты или обрезать существующие нельзя.
// 
// Формально: дан неориентированный граф с n вершинами (узлами) и m рёбрами (кондуитами). Рёбра могут быть кратными, а также могут быть петлями (кондуит из узла в него же). Требуется найти эйлеров путь — такой порядок всех m рёбер, в котором конец каждого ребра совпадает с началом следующего, — либо сообщить, что такого порядка не существует. Подходит любой корректный ответ.
// 
// Входные данные:
// В первой строке два целых числа n и m (1 <= n <= 2*10^5, 0 <= m <= 2*10^5) — число узлов и число кондуитов.
// В следующих m строках записаны по два целых числа u и v (1 <= u, v <= n) — кондуит соединяет узлы u и v. Кондуиты занумерованы с единицы в порядке появления во входных данных.
// 
// Выходные данные:
// Если переплести все кондуиты в одну нить невозможно, выведите в единственной строке NO.
// Иначе выведите две строки: в первой YES, во второй — m чисел через пробел: номера кондуитов в порядке их укладки (каждый номер от 1 до m ровно один раз). Если m = 0, вторая строка пустая.
// 
// Пример 1:
// Вход:
// 4 4
// 1 2
// 2 3
// 3 4
// 4 1
// Выход:
// YES
// 1 2 3 4
// (это замкнутое кольцо 1-2-3-4-1)
// 
// Пример 2:
// Вход:
// 4 3
// 1 2
// 2 3
// 3 4
// Выход:
// YES
// 1 2 3
// (нить начинается в узле 1 и заканчивается в узле 4)
// 
// Пример 3:
// Вход:
// 4 3
// 1 2
// 1 3
// 1 4
// Выход:
// NO
// (в узле 1 сходятся три кондуита, а в узлах 2, 3, 4 — по одному: нечётных вершин четыре, нить не собрать)
// 
// Пример 4:
// Вход:
// 4 2
// 1 2
// 3 4
// Выход:
// NO
// (две отдельные компоненты связности)
// 
// Пример 5:
// Вход:
// 2 3
// 1 1
// 1 2
// 2 2
// Выход:
// YES
// 1 2 3
// (петля в узле 1, затем переход в узел 2, затем петля в узле 2)
// 
// Ограничения: время O(n + m), память O(n + m).

/**
 * Переплетаем кондуиты: ищем эйлеров путь по графу.
 *
 * @param {number} n        количество узлов, пронумерованных 1..n
 * @param {number[][]} edges рёбра [u, v]; ребро с индексом i в массиве имеет номер i + 1
 * @returns {number[]|null}   порядок номеров рёбер (с 1) или null, если сплести нельзя
 */
function reweaveConduits(n, edges) {
  const m = edges.length;
  if (m === 0) return [];

  // Строим граф. Для каждого ребра храним пару [сосед, номер ребра],
  // чтобы не путаться с кратными рёбрами и петлями.
  const degree = new Array(n + 1).fill(0);
  const adj = Array.from({ length: n + 1 }, () => []);
  for (let i = 0; i < m; i++) {
    const [u, v] = edges[i];
    adj[u].push([v, i]);
    adj[v].push([u, i]);
    degree[u]++;
    degree[v]++; // для петли u === v это сразу даст +2, как и требуется
  }

  // Шаг 1. Все кондуиты должны лежать в одной компоненте связности,
  // иначе одна непрерывная нить принципиально невозможна.
  let start = 0;
  let verticesWithEdges = 0;
  for (let v = 1; v <= n; v++) {
    if (degree[v] > 0) {
      if (start === 0) start = v;
      verticesWithEdges++;
    }
  }

  const seen = new Array(n + 1).fill(false);
  const stack = [start];
  seen[start] = true;
  let reached = 0;
  while (stack.length > 0) {
    const v = stack.pop();
    reached++;
    for (const [to] of adj[v]) {
      if (!seen[to]) {
        seen[to] = true;
        stack.push(to);
      }
    }
  }
  if (reached !== verticesWithEdges) return null;

  // Шаг 2. Критерий Эйлера: нечётных вершин либо ноль (замкнутый цикл),
  // либо ровно две (нить начинается в одной и заканчивается в другой).
  const odd = [];
  for (let v = 1; v <= n; v++) {
    if (degree[v] % 2 === 1) odd.push(v);
  }
  if (odd.length !== 0 && odd.length !== 2) return null;

  const begin = odd.length === 2 ? odd[0] : start;

  // Шаг 3. Итеративный алгоритм Хиерхольцера: идём вперёд, пока есть
  // неиспользованные рёбра, а в тупике откатываемся и запоминаем ребро.
  const ptr = new Array(n + 1).fill(0); // сколько рёбер вершины уже просмотрено
  const used = new Array(m).fill(false);
  const walk = [{ v: begin, e: -1 }]; // текущая вершина и ребро, по которому в неё вошли
  const reversed = [];

  while (walk.length > 0) {
    const top = walk[walk.length - 1];
    const v = top.v;

    // Пропускаем рёбра, которые уже израсходованы (в том числе вторые копии петель).
    while (ptr[v] < adj[v].length && used[adj[v][ptr[v]][1]]) ptr[v]++;

    if (ptr[v] < adj[v].length) {
      const [to, id] = adj[v][ptr[v]];
      used[id] = true;
      walk.push({ v: to, e: id });
    } else {
      walk.pop();
      if (top.e !== -1) reversed.push(top.e);
    }
  }

  if (reversed.length !== m) return null; // страховка: такого быть не должно

  // Рёбра накапливались при откате, то есть в обратном порядке — разворачиваем.
  reversed.reverse();
  return reversed.map((id) => id + 1); // переводим в нумерацию с единицы
}
