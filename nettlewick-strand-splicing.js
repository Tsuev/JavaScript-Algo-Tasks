// Условие задачи
// В лаборатории Неттлвика работают с «нитями» — строками из символов A, C, G, T.
// 
// Две нити можно срастить. Если суффикс уже собранной нити длины k совпадает с префиксом присоединяемой нити длины k, то присоединяемая нить «надевается» на конец собранной, и к результату дописывается только её остаток, начиная с позиции k. Перекрытие k всегда берётся максимально возможным: оно может оказаться равным 0 (совпадений нет) и может оказаться равным всей длине присоединяемой нити (тогда не дописывается ничего).
// 
// Присоединяемую нить разрешается брать как в прямом, так и в перевёрнутом порядке символов. Выбирается та ориентация, которая даёт большее перекрытие; если перекрытия равны — берётся прямой порядок.
// 
// Даны n нитей. Сращивание идёт строго по порядку: первая нить становится текущим результатом, затем к нему по очереди пришивается каждая следующая (с выбором ориентации). Нужно вернуть итоговую нить.
// 
// Формат входных данных:
// — первая строка: целое число n (1 ≤ n ≤ 1000);
// — далее n строк: сами нити, суммарная длина всех нитей не превосходит 2·10^5, символы только из набора {A, C, G, T}.
// В программном виде на вход основной функции spliceStrands подаётся массив строк — нити в нужном порядке.
// 
// Формат результата:
// — одна строка — итоговая нить после всех сращиваний.
// 
// Примеры:
// 1) spliceStrands(["ACGG", "GGTA"]) → "ACGGTA"
//    Перекрытие «GG» (k = 2), обратный порядок «ATGG» перекрытия не даёт.
// 
// 2) spliceStrands(["ACGT", "TACG"]) → "ACGTACG"
//    Прямое перекрытие «T» (k = 1), перевёрнутая нить «GCAT» не перекрывается.
// 
// 3) spliceStrands(["TTTCCC", "GGGCCC"]) → "TTTCCCGGG"
//    Прямая нить не перекрывается (k = 0), а перевёрнутая «CCCGGG» даёт перекрытие «CCC» (k = 3).
// 
// 4) spliceStrands(["AACC", "GGTT"]) → "AACCGGTT"
//    Ни в одной ориентации перекрытия нет (k = 0), нити просто склеиваются.
// 
// 5) spliceStrands(["ACGT"]) → "ACGT"
//    Единственная нить остаётся как есть.

// Nettlewick Strand Splicing — жадное сращивание нитей с максимальным перекрытием.
// Перекрытие ищем через префикс-функцию, чтобы на больших входах не сравнивать
// строки «в лоб»: суммарная сложность получается линейной по длине всех нитей.

// Классическая префикс-функция: pi[i] — длина наибольшего собственного префикса,
// совпадающего с суффиксом подстроки s[0..i].
function prefixFunction(s) {
  const pi = new Array(s.length).fill(0);
  for (let i = 1; i < s.length; i++) {
    let k = pi[i - 1];
    while (k > 0 && s[i] !== s[k]) k = pi[k - 1];
    if (s[i] === s[k]) k++;
    pi[i] = k;
  }
  return pi;
}

// Наибольшее k, при котором суффикс prev длины k совпадает с префиксом next длины k.
function longestOverlap(prev, next) {
  const limit = Math.min(prev.length, next.length);
  if (limit === 0) return 0;

  // Берём только тот хвост собранной нити, который вообще может перекрыться.
  const tail = prev.slice(prev.length - limit);

  // Разделитель не встречается в нитях, поэтому найденное совпадение не «перепрыгнет»
  // границу между нитями: оно заведомо лежит внутри tail.
  const pi = prefixFunction(next + '\u0000' + tail);
  return Math.min(pi[pi.length - 1], limit);
}

// Основная функция: пришиваем нити по порядку, каждую можно перевернуть.
// Пример: spliceStrands(['ACGG', 'GGTA']) === 'ACGGTA'.
function spliceStrands(strands) {
  if (!strands || strands.length === 0) return '';

  let result = strands[0];

  for (let i = 1; i < strands.length; i++) {
    const strand = strands[i];
    const reversed = [...strand].reverse().join('');

    const direct = longestOverlap(result, strand);
    const flipped = longestOverlap(result, reversed);

    // При равном перекрытии оставляем прямой порядок — так ответ однозначен.
    const chosen = flipped > direct ? reversed : strand;
    const overlap = Math.max(direct, flipped);

    // Дописываем только неперекрывшийся остаток присоединяемой нити.
    result += chosen.slice(overlap);
  }

  return result;
}
