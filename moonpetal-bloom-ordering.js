// Задача: Moonpetal Bloom Ordering
// Сложность: medium
// Дата генерации: 2026-10-25

// Условие задачи
// Лунный сад готовится к цветению. Есть n лунных лепестков, пронумерованных от 1 до n. Лепестку с номером i нужно ровно p_i дней, чтобы раскрыться, и он обязан раскрыться не позднее дня d_i. Дни считаются с нуля: если начать растить лепесток в день S, он раскроется в конце дня S + p_i и должен уложиться в дедлайн, то есть S + p_i <= d_i.
// 
// Садовник может растить только один лепесток за раз и не может прерывать рост. Начинать можно с дня 0. Ясно, что вырастить все лепестки вовремя удаётся не всегда, поэтому нужно выбрать как можно больше лепестков (по количеству) так, чтобы их можно было посадить в некотором порядке и каждый успел раскрыться к своему дедлайну.
// 
// Требуется вывести максимальное количество таких лепестков k и сам порядок их посадки. Порядок в ответе задаётся однозначно: лепестки перечисляются по неубыванию дедлайна, а при равных дедлайнах — по возрастанию номера. Если наборов максимального размера несколько, подойдёт любой из них (порядок вывода всё равно определяется указанным правилом сортировки).
// 
// Формат ввода:
// В первой строке целое число n (1 <= n <= 100000).
// Далее n строк; в i-й строке два целых числа p_i и d_i (1 <= p_i, d_i <= 10^9) — время роста и дедлайн i-го лепестка.
// 
// Формат вывода:
// В первой строке одно целое число k — максимальное количество лепестков, которые успеют раскрыться.
// Если k > 0, во второй строке выведите k номеров лепестков через пробел в требуемом порядке посадки. Если k = 0, вторую строку выводить не нужно.
// 
// Пример 1:
// Вход:
// 4
// 3 5
// 2 2
// 1 3
// 4 8
// 
// Выход:
// 3
// 2 3 4
// 
// Пояснение к примеру 1: сажаем лепесток 2 (растёт 2 дня, раскрывается в день 2 при дедлайне 2), затем лепесток 3 (готов в день 3 при дедлайне 3), затем лепесток 4 (готов в день 7 при дедлайне 8). Лепесток 1 не влезает: если его добавить, суммарное время станет больше дедлайна 5.
// 
// Пример 2:
// Вход:
// 3
// 5 1
// 4 2
// 3 3
// 
// Выход:
// 1
// 3
// 
// Пояснение к примеру 2: лепестки 1 и 2 не успевают ни при каком порядке (их время роста больше дедлайна), а лепесток 3 успевает ровно к дню 3.
// 
// Пример 3:
// Вход:
// 2
// 5 1
// 10 2
// 
// Выход:
// 0
// 
// Ограничения: решение должно работать за O(n log n) по времени и O(n) по памяти, чтобы выдерживать n = 100000.

/**
 * Moonpetal Bloom Ordering.
 *
 * Идея решения — жадный алгоритм Мура–Ходжсона.
 * Сортируем лепестки по дедлайну и идём по ним, накапливая суммарное время роста.
 * Как только суммарное время превысило дедлайн текущего лепестка,
 * выбрасываем из уже выбранных тот, у которого самое большое время роста:
 * именно он «съедает» больше всего времени и мешает сильнее всех остальных.
 * В итоге в наборе остаётся максимальное число лепестков, успевающих раскрыться.
 */

class MaxHeap {
  constructor() {
    this.data = [];
  }

  get size() {
    return this.data.length;
  }

  // «Больше» тот элемент, у кого больше время роста p;
  // при равных p — тот, у кого больше номер, чтобы выбор был детерминированным.
  static beats(a, b) {
    return a.p !== b.p ? a.p > b.p : a.idx > b.idx;
  }

  push(value) {
    this.data.push(value);
    let i = this.data.length - 1;
    while (i > 0) {
      const parent = (i - 1) >> 1;
      if (!MaxHeap.beats(this.data[i], this.data[parent])) break;
      [this.data[i], this.data[parent]] = [this.data[parent], this.data[i]];
      i = parent;
    }
  }

  pop() {
    const top = this.data[0];
    const last = this.data.pop();
    if (this.data.length > 0) {
      this.data[0] = last;
      const n = this.data.length;
      let i = 0;
      while (true) {
        const left = 2 * i + 1;
        const right = 2 * i + 2;
        let best = i;
        if (left < n && MaxHeap.beats(this.data[left], this.data[best])) best = left;
        if (right < n && MaxHeap.beats(this.data[right], this.data[best])) best = right;
        if (best === i) break;
        [this.data[i], this.data[best]] = [this.data[best], this.data[i]];
        i = best;
      }
    }
    return top;
  }

  values() {
    return this.data.slice();
  }
}

/**
 * Основная функция решения.
 * @param {Array<[number, number]>} petals — массив пар [p_i, d_i] для каждого лепестка.
 * @returns {{count: number, order: number[]}} количество и номера лепестков (1-based) в порядке посадки.
 */
function moonpetalBloomOrdering(petals) {
  const items = petals.map(([p, d], idx) => ({ p, d, idx }));

  // Порядок просмотра и порядок посадки совпадают: сначала меньший дедлайн,
  // при равенстве — меньший номер. Это стандартный EDD-порядок.
  items.sort((a, b) => a.d - b.d || a.idx - b.idx);

  const heap = new MaxHeap();
  let currentDay = 0;

  for (const item of items) {
    heap.push(item);
    currentDay += item.p;

    // Не успеваем к дедлайну — убираем самый долгий из уже выбранных лепестков.
    // После удаления суммарное время снова не превосходит текущий дедлайн,
    // потому что удалённый лепесток был не короче только что добавленного.
    if (currentDay > item.d) {
      const removed = heap.pop();
      currentDay -= removed.p;
    }
  }

  // В куче остались ровно те лепестки, которые можно вырастить вовремя.
  const chosen = heap.values().map((x) => x.idx);

  // Перечисляем их по неубыванию дедлайна, при равенстве — по возрастанию номера.
  chosen.sort((a, b) => petals[a][1] - petals[b][1] || a - b);

  return {
    count: chosen.length,
    order: chosen.map((i) => i + 1),
  };
}

