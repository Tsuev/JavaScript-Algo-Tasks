// Задача: Palefern Ripple Arbitration
// Сложность: medium
// Дата генерации: 2026-11-17

// Условие задачи
// В долине палеороса (Palefern) происходят волновые колебания — ripples. Каждое колебание характеризуется временным интервалом [l, r] (включительно) и энергией w. Арбитр хочет выбрать набор колебаний, которые не пересекаются по времени (не имеют общих моментов), чтобы суммарная энергия была максимальной. Два колебания [l1, r1] и [l2, r2] считаются конфликтующими, если max(l1, l2) <= min(r1, r2). Требуется найти максимальную суммарную энергию непересекающихся колебаний.
// 
// Формат ввода:
// Первая строка содержит целое число n (0 <= n <= 100000) — количество колебаний.
// Далее n строк, каждая содержит три целых числа l, r, w (0 <= l <= r <= 10^9, 1 <= w <= 10^9) — начало, конец и энергия колебания.
// 
// Формат вывода:
// Одно целое число — максимальная суммарная энергия выбранных непересекающихся колебаний. Если n = 0, выведите 0.
// 
// Пример:
// Вход:
// 3
// 1 3 10
// 4 6 20
// 2 5 15
// Выход:
// 30
// Пояснение: можно выбрать колебания [1,3] и [4,6] с суммарной энергией 10 + 20 = 30. Колебание [2,5] конфликтует с обоими.

function solve(input) {
  const lines = input.trim().split('\n').filter(line => line.trim() !== '');
  if (lines.length === 0) return 0;
  const n = parseInt(lines[0], 10);
  if (n === 0) return 0;
  const intervals = [];
  for (let i = 1; i <= n; i++) {
    const [l, r, w] = lines[i].trim().split(/\s+/).map(Number);
    intervals.push({ l, r, w });
  }
  // Сортируем по правой границе — так проще искать совместимые интервалы.
  intervals.sort((a, b) => a.r - b.r);
  const ends = intervals.map(iv => iv.r);
  const dp = new Array(n).fill(0);
  for (let i = 0; i < n; i++) {
    const { l, w } = intervals[i];
    // Ищем последний интервал j < i, который заканчивается строго раньше начала i-го.
    // Используем бинарный поиск по массиву ends.
    let lo = 0, hi = i - 1, j = -1;
    while (lo <= hi) {
      const mid = (lo + hi) >> 1;
      if (ends[mid] < l) {
        j = mid;
        lo = mid + 1;
      } else {
        hi = mid - 1;
      }
    }
    const prev = j >= 0 ? dp[j] : 0;
    const take = w + prev;
    const skip = i > 0 ? dp[i - 1] : 0;
    dp[i] = Math.max(take, skip);
  }
  return dp[n - 1];
}
