// Задача: Opalfern Tide Reconciliation
// Сложность: hard
// Дата генерации: 2026-11-24

// Условие задачи
// Опалферн — архипелаг из n островов, вытянутых в одну цепочку вдоль берега и занумерованных 1..n. На каждом острове i стоит приливный маркер, зафиксировавший уровень воды a_i.
// 
// После шторма показания нужно согласовать (reconcile). Для каждого острова выбирается новое целое значение x_i (любое, в том числе отрицательное), и за это платится |x_i − a_i|. Согласование корректно, если вода не «прыгает» между соседними маркерами: для всех i от 1 до n−1 должно выполняться |x_i − x_{i+1}| ≤ d, где d задано. Требуется найти минимальную суммарную стоимость корректировки Σ|x_i − a_i|.
// 
// Формат входных данных:
// • n — количество островов, 1 ≤ n ≤ 2·10^5;
// • d — максимально допустимый перепад уровней между соседними островами, 0 ≤ d ≤ 10^9;
// • a — массив из n целых чисел, |a_i| ≤ 10^9.
// 
// Формат результата: одно целое число — минимальная суммарная стоимость. Ответ укладывается в 64-битный диапазон (в JavaScript — безопасное целое).
// 
// Примеры:
// 1) n = 2, d = 1, a = [0, 5] → 4. Годится x = [0, 1]: стоимость 0 + 4 = 4; меньше нельзя, потому что перепад в 5 единиц нужно «оплатить».
// 2) n = 3, d = 1, a = [0, 5, 0] → 4. Оптимум x = [0, 1, 0], стоимость 0 + 4 + 0.
// 3) n = 1, d = 7, a = [7] → 0. Один остров, менять нечего.
// 4) n = 4, d = 0, a = [1, 1, 1, 1] → 0. Все значения уже равны.
// 5) n = 2, d = 100, a = [0, 10] → 0. Ограничение не мешает: |0 − 10| ≤ 100.
// 
// Идея решения: это минимизация суммы |x_i − a_i| при липшицевом ограничении на цепочку. Функция «минимальная стоимость для префикса при фиксированном x_i = t» выпукла и кусочно-линейна, поэтому её хранят двумя кучами (slope trick) и получают O(n log n).

/**
 * Опалферн: согласование приливов.
 *
 * Идея (slope trick). Пусть F_i(t) — минимальная стоимость согласования
 * первых i островов при условии, что x_i = t. Это выпуклая кусочно-линейная
 * функция с целыми наклонами, и её полностью описывают две кучи точек излома:
 *
 *   F(t) = best + sum_{l in L} max(0, l - t) + sum_{r in R} max(0, t - r),
 *
 * где max(L) <= min(R), а best — значение функции в её минимуме.
 *
 * Переход к следующему острову — два действия:
 *   1) G(t) = min_{y in [t-d, t+d]} F(y). Для выпуклой функции это «сдвиг окна»:
 *      все точки из L сдвигаются на -d, все точки из R — на +d
 *      (минимум размазывается в отрезок, который расширился на d в обе стороны).
 *   2) F_new(t) = G(t) + |t - a_i| — добавление модуля.
 *
 * Модуль добавляется так: кладём a_i в обе кучи, и если max(L) > min(R),
 * меняем местами их вершины, увеличивая best на разницу.
 */
class Heap {
  // Универсальная двоичная куча: поведение задаёт предикат less.
  constructor(less) {
    this.h = [];
    this.less = less; // less(x, y) === true, если x должен стоять выше y
  }

  get size() {
    return this.h.length;
  }

  peek() {
    return this.h[0];
  }

  push(v) {
    const h = this.h;
    h.push(v);
    let i = h.length - 1;
    while (i > 0) {
      const p = (i - 1) >> 1; // родитель
      if (!this.less(h[i], h[p])) break;
      const tmp = h[i];
      h[i] = h[p];
      h[p] = tmp;
      i = p;
    }
  }

  pop() {
    const h = this.h;
    const top = h[0];
    const last = h.pop();
    if (h.length > 0) {
      h[0] = last;
      let i = 0;
      for (;;) {
        const l = 2 * i + 1;
        const r = l + 1;
        let m = i;
        if (l < h.length && this.less(h[l], h[m])) m = l;
        if (r < h.length && this.less(h[r], h[m])) m = r;
        if (m === i) break;
        const tmp = h[i];
        h[i] = h[m];
        h[m] = tmp;
        i = m;
      }
    }
    return top;
  }
}

/**
 * Основная функция решения.
 * n — число островов, d — максимальный перепад между соседями,
 * a — исходные показания маркеров (длина n).
 * Возвращает минимальную суммарную стоимость корректировки.
 */
function reconcileTide(n, d, a) {
  if (n <= 0) return 0;

  const L = new Heap((x, y) => x > y); // max-куча: левые точки излома
  const R = new Heap((x, y) => x < y); // min-куча: правые точки излома
  let offsetL = 0; // ленивая поправка ко всем точкам в L
  let offsetR = 0; // ленивая поправка ко всем точкам в R
  let best = 0;    // значение функции в точке минимума

  // Добавляет к текущей функции стоимости слагаемое |t - x|.
  const addAbs = (x) => {
    L.push(x - offsetL);
    R.push(x - offsetR);

    const l = L.peek() + offsetL; // настоящее значение вершины L
    const r = R.peek() + offsetR; // настоящее значение вершины R

    if (l > r) {
      // Инвариант max(L) <= min(R) нарушен — меняем вершины местами.
      L.pop();
      R.pop();
      best += l - r; // ровно столько стоит новый «излом»
      L.push(r - offsetL);
      R.push(l - offsetR);
    }
  };

  addAbs(a[0]);

  for (let i = 1; i < n; i++) {
    // Шаг 1: соседям разрешено отличаться на d — сдвигаем окно минимума.
    offsetL -= d;
    offsetR += d;
    // Шаг 2: учитываем стоимость изменения уровня на острове i.
    addAbs(a[i]);
  }

  return best;
}
