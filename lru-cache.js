// Условие задачи
// Необходимо спроектировать структуру данных для кэша, которая поддерживает операции get и put за среднее время O(1).
// 
// Реализуйте класс LRUCache:
// - LRUCache(int capacity) — инициализирует кэш с положительным размером capacity.
// - int get(int key) — возвращает значение, если ключ есть в кэше, иначе возвращает -1.
// - void put(int key, int value) — обновляет значение, если ключ существует; если ключа нет, добавляет пару ключ-значение. При этом запись считается использованной. Если количество ключей превышает capacity, из кэша удаляется наименее недавно использованный ключ.
// 
// Запросы к кэшу должны выполняться за O(1) по времени.
// 
// Пример:
// Вход:
// ["LRUCache", "put", "put", "get", "put", "get", "get"]
// [[2], [1, 1], [2, 2], [1], [3, 3], [2], [3]]
// 
// Выход:
// [null, null, null, 1, null, -1, 3]
// 
// Пояснение:
// - LRUCache инициализирован с capacity = 2.
// - put(1,1): кэш = {1=1}
// - put(2,2): кэш = {1=1, 2=2}
// - get(1): возвращает 1, теперь ключ 1 становится самым свежим. Кэш = {2=2, 1=1}
// - put(3,3): добавляем ключ 3, размер превышает 2, поэтому удаляем наименее свежий ключ 2. Кэш = {1=1, 3=3}
// - get(2): ключ 2 отсутствует, возвращает -1
// - get(3): возвращает 3.
// 
// Гарантируется, что capacity положительное число, а все ключи — целые числа.

class LRUCache {
  constructor(capacity) {
    this.capacity = capacity;
    this.map = new Map();
  }

  // Возвращает значение ключа или -1, если ключа нет.
  // Заодно делает ключ самым свежим: удаляет и вставляет в конец Map.
  get(key) {
    if (!this.map.has(key)) return -1;
    const value = this.map.get(key);
    this.map.delete(key);
    this.map.set(key, value);
    return value;
  }

  // Добавляет или обновляет значение по ключу.
  // Если после вставки размер превышает capacity, удаляем самый первый ключ —
  // он и есть наименее недавно использованный, так как Map хранит порядок вставки.
  put(key, value) {
    // Если ключ уже существует, удаляем его, чтобы обновлённая запись считалась свежей.
    if (this.map.has(key)) {
      this.map.delete(key);
    }
    this.map.set(key, value);

    // Избавляемся от переполнения, удаляя самый старый ключ.
    if (this.map.size > this.capacity) {
      const oldestKey = this.map.keys().next().value;
      this.map.delete(oldestKey);
    }
  }
}
