// Условие задачи
// Обсерватория Pulsar Timing Array наблюдает за N пульсарами. i-й пульсар испускает импульсы строго периодически: в моменты a_i, a_i + p_i, a_i + 2·p_i, ... (первый импульс в момент a_i, далее каждые p_i единиц времени).
// 
// Пульсары считаются «синхронизированными», если существует момент времени t ≥ 0, в который импульс приходит сразу от всех N пульсаров. Найдите минимальный такой момент t. Если одновременного импульса от всех пульсаров не бывает в пределах 0 ≤ t ≤ 10^18, выведите -1.
// 
// Формально: найдите наименьшее неотрицательное t ≤ 10^18, удовлетворяющее системе сравнений t ≡ a_i (mod p_i) для всех i.
// 
// Входные данные:
// - Первая строка: целое N (1 ≤ N ≤ 2·10^5).
// - Следующие N строк: пары целых a_i и p_i (0 ≤ a_i < p_i ≤ 10^9).
// 
// Выходные данные:
// - Единственное целое число — минимальный момент общей синхронизации, либо -1.
// 
// Пример 1:
// Вход:
// 1
// 0 5
// Выход:
// 0
// 
// Пример 2:
// Вход:
// 2
// 1 2
// 2 4
// Выход:
// -1
// 
// Пример 3:
// Вход:
// 2
// 2 4
// 6 8
// Выход:
// 6
// 
// Пример 4:
// Вход:
// 3
// 3 4
// 1 6
// 5 10
// Выход:
// 55
// 
// Пример 5:
// Вход:
// 3
// 0 2
// 0 3
// 0 5
// Выход:
// 0

// Решение задачи "Pulsar Timing Array".
// Момент импульса i-го пульсара описывается арифметической прогрессией
// a_i, a_i + p_i, a_i + 2*p_i, ... . Общий момент t существует тогда и только
// тогда, когда совместна система сравнений t = a_i (mod p_i).
// Такую систему решаем обобщённой китайской теоремой об остатках (CRT):
// последовательно "сливаем" сравнения попарно. Модули не обязаны быть
// взаимно простыми, поэтому шаг слияния использует расширенный алгоритм
// Евклида и проверку совместности.
// Все вычисления ведём в BigInt: НОК периодов может оказаться очень большим.

const HORIZON = 10n ** 18n; // ищем момент не позже 10^18

// Наибольший общий делитель (по модулю знака).
function gcd(a, b) {
  if (a < 0n) a = -a;
  if (b < 0n) b = -b;
  while (b !== 0n) {
    const r = a % b;
    a = b;
    b = r;
  }
  return a;
}

// Расширенный алгоритм Евклида: находит g = gcd(a, b) и коэффициенты x, y,
// для которых a*x + b*y = g. Реализован итеративно, чтобы не уходить
// в глубокую рекурсию на больших числах.
function extendedGcd(a, b) {
  let oldR = a, r = b;
  let oldX = 1n, x = 0n;
  let oldY = 0n, y = 1n;
  while (r !== 0n) {
    const q = oldR / r;
    const nr = oldR - q * r; oldR = r; r = nr;
    const nx = oldX - q * x; oldX = x; x = nx;
    const ny = oldY - q * y; oldY = y; y = ny;
  }
  return [oldR, oldX, oldY];
}

// Обратный элемент a по модулю m. Корректен, когда gcd(a, m) = 1.
function modInverse(a, m) {
  const [, x] = extendedGcd(a, m);
  return ((x % m) + m) % m;
}

// Основная функция. Принимает массив пар [a_i, p_i] (числа или BigInt),
// возвращает наименьший момент общей синхронизации (BigInt) или -1n.
function earliestCoincidence(pulsars) {
  // t — наименьшее неотрицательное решение уже обработанных сравнений,
  // M — их модуль (НОК периодов обработанных пульсаров).
  let t = 0n;
  let M = 1n;

  for (let i = 0; i < pulsars.length; i++) {
    const a = BigInt(pulsars[i][0]);
    const p = BigInt(pulsars[i][1]);

    // Если модуль уже превысил горизонт, любое решение оставшейся системы
    // лежит в множестве t + k*M, k >= 0. При k >= 1 момент выйдет за 10^18,
    // поэтому в пределах горизонта годится только k = 0: достаточно проверить,
    // что текущее t само подходит под оставшиеся сравнения.
    if (M > HORIZON) {
      if (((t - a) % p + p) % p !== 0n) return -1n;
      continue;
    }

    // Сливаем t ≡ a (mod M) и t ≡ a (mod p) в одно сравнение.
    const g = gcd(M, p);
    const diff = ((a - t) % p + p) % p; // (a - t) mod p
    if (diff % g !== 0n) return -1n;    // система несовместна

    const m2 = M / g;   // взаимно просто с p2 = p / g
    const p2 = p / g;
    const d2 = diff / g;

    // Ищем k: M*k ≡ diff (mod p). После деления на g получаем
    // m2*k ≡ d2 (mod p2), где m2 обратимо по модулю p2.
    let k = 0n;
    if (p2 !== 1n) {
      k = (d2 * modInverse(m2 % p2, p2)) % p2;
    }

    t = t + M * k;   // новое наименьшее решение
    M = m2 * p;      // новый модуль (НОК)
  }

  // Ответ должен укладываться в горизонт.
  return t <= HORIZON ? t : -1n;
}

