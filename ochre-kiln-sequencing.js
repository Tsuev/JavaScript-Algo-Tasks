// Условие задачи
// В печи для обжига охры (Ochre Kiln) необходимо обжечь n глиняных изделий. Каждое изделие имеет свой тип (целое число), определяющий вид охры. Печь может обжигать изделия по одному. Чтобы избежать смешивания цветов, после обжига изделия типа x следующее изделие того же типа x можно ставить в печь только после того, как будут обожжены как минимум k других изделий (любых типов). Это время называется временем остывания (cooldown).
// 
// Требуется определить минимальное количество слотов (включая возможные простои печи), необходимых для обжига всех изделий с соблюдением ограничения.
// 
// Формат входных данных:
// В первой строке задаются два целых числа n и k (0 ≤ n ≤ 10^5, 0 ≤ k ≤ 10^5) — количество изделий и время остывания.
// Во второй строке заданы n целых чисел — типы изделий (тип — целое число от 1 до 10^9).
// 
// Формат выходных данных:
// Выведите одно целое число — минимальное количество слотов.
// 
// Пример 1:
// Вход:
// 5 2
// 1 1 2 2 3
// Выход:
// 5
// Объяснение: последовательность 1, 2, 3, 1, 2 — между одинаковыми типами 1 и 2 стоят по два других изделия, что удовлетворяет k=2.
// 
// Пример 2:
// Вход:
// 6 1
// 1 1 1 2 2 3
// Выход:
// 6
// Объяснение: последовательность 1, 2, 1, 2, 1, 3 — между единицами стоит по одному изделию, что удовлетворяет k=1.
// 
// Пример 3:
// Вход:
// 4 0
// 1 1 2 2
// Выход:
// 4
// Объяснение: при k=0 ограничений нет, можно обжечь все изделия подряд.

function minTotalSlots(pieces, k) {
  if (pieces.length === 0) return 0;
  const freq = new Map();
  for (const type of pieces) {
    freq.set(type, (freq.get(type) || 0) + 1);
  }
  let maxFreq = 0;
  let numMaxFreq = 0;
  for (const count of freq.values()) {
    if (count > maxFreq) {
      maxFreq = count;
      numMaxFreq = 1;
    } else if (count === maxFreq) {
      numMaxFreq++;
    }
  }
  // Минимальная длина последовательности с учётом простоев:
  // между максимально частыми элементами нужно вставить по k других элементов.
  // Последний блок максимально частых элементов не требует простоев после себя.
  const minLength = (maxFreq - 1) * (k + 1) + numMaxFreq;
  return Math.max(minLength, pieces.length);
}

