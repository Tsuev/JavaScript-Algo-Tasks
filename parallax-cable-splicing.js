// Дата генерации: 2026-10-04

// Условие задачи
// Parallax Cable Splicing (Параллаксная сварка кабелей)
// 
// На заводе есть m концов кабелей, закреплённых на прямой в порядке слева направо. Каждый конец принадлежит ровно одному кабелю, а каждый кабель имеет ровно два конца. Концы пронумерованы 0..m−1 слева направо; конец i находится в точке с координатой x[i].
// 
// Нужно попарно сварить все концы (построить совершенное паросочетание), соблюдая три правила:
// 
// 1) Сварка концов i и j (i < j) стоит x[j] − x[i] — длину перемычки.
// 2) Сварки изображаются дугами над прямой и не должны пересекаться. Формально для двух сварок (i, j) и (p, q) с i < j и p < q запрещена ситуация i < p < j < q и симметричная ей.
// 3) Запрещено сваривать два конца одного и того же кабеля.
// 
// Найдите минимальную суммарную стоимость сварок. Если сварить всё невозможно, выведите −1 (например, при m = 2 единственный кабель нельзя сварить сам с собой).
// 
// Формат входных данных:
// Первая строка — целое m (чётное, 2 ≤ m ≤ 500).
// Вторая строка — m целых чисел c[0..m−1]: номер кабеля каждого конца. Каждый номер встречается ровно дважды.
// Третья строка — m целых чисел x[0..m−1]: координаты концов в порядке слева направо, строго возрастают (0 ≤ x[i] ≤ 10^9).
// 
// Формат результата:
// Одно целое число — минимальная суммарная стоимость сварок или −1.
// 
// Пример 1:
// Вход:
// 4
// 1 2 1 2
// 0 10 20 30
// Выход:
// 20
// Пояснение: оптимально сварить концы (0,1) и (2,3): (10−0)+(30−20)=20. Вариант (0,2) запрещён — это два конца кабеля 1.
// 
// Пример 2:
// Вход:
// 2
// 7 7
// 5 9
// Выход:
// −1
// Пояснение: оба конца принадлежат кабелю 7, сваривать их между собой нельзя.
// 
// Пример 3:
// Вход:
// 6
// 1 1 2 2 3 3
// 0 4 5 9 10 14
// Выход:
// 16
// Пояснение: свариваем (0,5), (1,2), (3,4): (14−0)+(5−4)+(10−9)=16. Пара соседних концов (0,1) запрещена — один кабель.
// 
// Ограничения по времени: решение должно работать за O(m^3), где m — число концов.

/**
 * Parallax Cable Splicing.
 *
 * Идея решения — интервальное динамическое программирование.
 * Если в непересекающемся паросочетании отрезка [l..r] левый конец l сваривается
 * с концом k, то остальные концы распадаются на два независимых куска:
 *   [l+1 .. k-1]  (внутри сварки)
 *   [k+1 .. r]    (справа от сварки)
 * и никакая сварка из одного куска не пересекает другую — правило 2 выполняется
 * автоматически, поэтому стоит просто сложить стоимости двух подзадач.
 *
 * @param {number} m       количество концов (чётное)
 * @param {number[]} cables номер кабеля для каждого конца
 * @param {number[]} xs     координаты концов в порядке слева направо
 * @returns {number} минимальная суммарная стоимость сварок или -1
 */
function parallaxSplice(m, cables, xs) {
  if (m % 2 !== 0) return -1;

  const INF = Number.POSITIVE_INFINITY;

  // dp[l][r] — минимальная стоимость полностью сварить концы с l по r включительно
  // (длина отрезка всегда чётная). Всё, что вне отрезка, на этот минимум не влияет.
  const dp = Array.from({ length: m }, () => new Array(m).fill(INF));

  // Сваривать пустой отрезок нечего — стоимость 0.
  const get = (l, r) => (l > r ? 0 : dp[l][r]);

  // Обрабатываем отрезки по возрастанию длины: к моменту работы с [l..r]
  // все внутренние отрезки меньшей длины уже посчитаны.
  for (let len = 2; len <= m; len += 2) {
    for (let l = 0; l + len - 1 < m; l++) {
      const r = l + len - 1;
      let best = INF;

      // Левый конец l обязан попасть в какую-то сварку (l, k).
      // k должно иметь ту же чётность, что и l: иначе левая и правая части
      // получат нечётную длину и их нельзя полностью сварить.
      for (let k = l + 1; k <= r; k += 2) {
        if (cables[l] === cables[k]) continue; // правило 3: концы одного кабеля

        const inner = get(l + 1, k - 1);
        if (inner === INF) continue;
        const right = get(k + 1, r);
        if (right === INF) continue;

        // Правило 1: длина сварки. Правило 2 обеспечено структурой разбиения.
        const cost = (xs[k] - xs[l]) + inner + right;
        if (cost < best) best = cost;
      }

      dp[l][r] = best;
    }
  }

  const ans = get(0, m - 1);
  return ans === INF ? -1 : ans;
}

