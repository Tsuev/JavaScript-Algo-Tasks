// Задача: Duskfall Circuit Reconciliation
// Сложность: medium
// Дата генерации: 2026-10-18

// Условие задачи
// В городе Даскфолл наступают сумерки, и диспетчеру нужно согласовать фазы в электрической сети.
// 
// Сеть состоит из n узлов (нумерация от 1 до n) и m проводов. У каждого узла есть фаза p[i] ∈ {0, 1}. Каждый провод задаёт жёсткое требование на фазы своих концов: p[u] XOR p[v] = s, где s ∈ {0, 1} — «фазовый сдвиг» провода.
// 
// Сеть называется согласованной, если существует такой набор фаз всех узлов, при котором одновременно выполнены требования всех проводов.
// 
// Что нужно найти:
// — если сеть согласовать невозможно, найти первый по порядку проверки провод (нумерация с 1), который делает систему противоречивой, и вывести «CONFLICT k»;
// — если сеть согласована, вывести «OK w», где w — число различных наборов фаз, удовлетворяющих всем проводам, по модулю 1 000 000 007.
// 
// Формат входных данных:
// Первая строка содержит два целых числа n и m (1 ≤ n ≤ 2·10^5, 0 ≤ m ≤ 2·10^5).
// Следующие m строк содержат по три целых числа u_i, v_i, s_i (1 ≤ u_i, v_i ≤ n, s_i ∈ {0, 1}). Провода неориентированные; провод может соединять узел с самим собой, а также могут встречаться кратные провода.
// 
// Формат результата:
// Одна строка — либо «CONFLICT k» (k — номер первого противоречивого провода, считая с 1), либо «OK w» (w — количество допустимых наборов фаз по модулю 1 000 000 007).
// 
// Пример 1:
// Вход:
// 5 1
// 1 2 1
// Выход: OK 16
// Пояснение: компонента {1, 2} даёт 2 варианта фаз; изолированные узлы 3, 4, 5 добавляют ещё по 2 варианта каждый, итого 2^4 = 16.
// 
// Пример 2:
// Вход:
// 3 3
// 1 2 0
// 2 3 1
// 1 3 0
// Выход: CONFLICT 3
// Пояснение: из первых двух проводов следует p1 XOR p3 = 0 XOR 1 = 1, а третий провод требует p1 XOR p3 = 0 — противоречие на третьем проводе.
// 
// Пример 3:
// Вход:
// 4 3
// 1 2 1
// 2 3 0
// 3 4 1
// Выход: OK 2
// Пояснение: граф связен, поэтому есть ровно 2 допустимых набора фаз — любой корректный набор и его полная инверсия.
// 
// Пример 4:
// Вход:
// 3 0
// Выход: OK 8
// Пояснение: проводов нет, каждый из трёх узлов независим, итого 2^3 = 8 наборов фаз.

// Duskfall Circuit Reconciliation
//
// Идея: каждому узлу сопоставляем фазу p[i] ∈ {0,1}, а каждый провод (u, v, s)
// накладывает условие p[u] XOR p[v] === s. Это система линейных уравнений
// над GF(2), и проверять её удобно «на лету» с помощью системы непересекающихся
// множеств, которая дополнительно хранит чётность (XOR) до корня компоненты.

const MOD = 1_000_000_007;

class ParityDSU {
  constructor(n) {
    this.parent = new Int32Array(n);
    this.rank = new Uint8Array(n);
    // parity[x] — это p[x] XOR p[parent[x]]; у корня компоненты всегда 0
    this.parity = new Uint8Array(n);
    for (let i = 0; i < n; i++) this.parent[i] = i;
    this.components = n; // пока каждый узел — отдельная компонента
  }

  // Находит корень и попутно сжимает путь, пересчитывая чётности относительно корня
  find(x) {
    const p = this.parent[x];
    if (p === x) return x;
    const root = this.find(p);
    // После рекурсии parity[p] уже посчитана относительно корня,
    // значит этой же операцией получаем и parity[x] относительно корня
    this.parity[x] ^= this.parity[p];
    this.parent[x] = root;
    return root;
  }

  // Добавляет требование p[u] XOR p[v] === s.
  // Возвращает false, если оно противоречит уже известным требованиям.
  unite(u, v, s) {
    const ru = this.find(u);
    const rv = this.find(v);
    const pu = this.parity[u]; // фаза u относительно корня ru
    const pv = this.parity[v]; // фаза v относительно корня rv

    if (ru === rv) {
      // Узлы уже в одной компоненте — условие обязано выполниться как есть
      return (pu ^ pv) === s;
    }

    // Нужно связать корни так, чтобы получилось p[u] XOR p[v] === s.
    // Из этого следует p[ru] XOR p[rv] === pu XOR pv XOR s.
    // XOR симметричен, поэтому одна и та же величина подходит независимо
    // от того, какой корень мы подвесим к какому.
    const link = pu ^ pv ^ s;

    if (this.rank[ru] < this.rank[rv]) {
      this.parent[ru] = rv;
      this.parity[ru] = link;
    } else {
      this.parent[rv] = ru;
      this.parity[rv] = link;
      if (this.rank[ru] === this.rank[rv]) this.rank[ru]++;
    }

    this.components--;
    return true;
  }
}

// Основная функция решения.
// n — количество узлов, wires — массив троек [u, v, s] с нумерацией узлов от 1.
// Возвращает строку «CONFLICT k» или «OK w».
function reconcile(n, wires) {
  const dsu = new ParityDSU(n);

  for (let i = 0; i < wires.length; i++) {
    const [u, v, s] = wires[i];
    if (!dsu.unite(u - 1, v - 1, s)) {
      // Провода обрабатываются по порядку, поэтому это и есть первый конфликт
      return `CONFLICT ${i + 1}`;
    }
  }

  // Если противоречий нет, компоненты независимы: фазы одной компоненты
  // можно инвертировать целиком и получить другое допустимое решение.
  // Значит всего наборов ровно 2^(число компонент), включая изолированные узлы.
  let ways = 1;
  for (let i = 0; i < dsu.components; i++) {
    ways = (ways * 2) % MOD; // промежуточное значение < 2·MOD, переполнения нет
  }

  return `OK ${ways}`;
}

// Необязательный помощник: превращает текст задачи в аргументы для reconcile.
// Работает со строкой, а не с потоком ввода, чтобы решение было самодостаточным.
function parseAndSolve(text) {
  const tokens = text.trim().split(/\s+/).map(Number);
  const n = tokens[0];
  const m = tokens[1];
  const wires = [];
  let k = 2;
  for (let i = 0; i < m; i++) {
    wires.push([tokens[k], tokens[k + 1], tokens[k + 2]]);
    k += 3;
  }
  return reconcile(n, wires);
}
