// Условие задачи
// Chrono-Network Routing
// 
// В сети «Хроно-Нет» есть n узлов, пронумерованных 1..n, и m направленных каналов связи. Каждый канал описывается шестью числами (u, v, w, p, s, d): он ведёт из узла u в узел v, передача по нему занимает w единиц времени, а начать передачу разрешено только в «открытое окно доступа». Окна периодичны: канал открыт в те моменты времени t, для которых t mod p ∈ [s, s + d), то есть окна открываются в моменты s, s + p, s + 2p, ... и каждое длится d единиц времени. Начав передачу в открытый момент t, вы окажетесь в узле v в момент t + w (длительность передачи от фазы окна не зависит).
// 
// Вы стартуете в узле 1 в момент времени 0. В любом узле можно ждать сколь угодно долго и затем отправиться по любому исходящему каналу. Требуется найти минимальный момент времени, в который можно оказаться в узле n. Если попасть в узел n невозможно, выведите -1.
// 
// Формат входных данных
// Первая строка: два целых числа n и m (2 ≤ n ≤ 100000, 1 ≤ m ≤ 200000).
// Следующие m строк: по шесть целых чисел u v w p s d, описывающих канал: 1 ≤ u, v ≤ n; 0 ≤ w ≤ 10^9; 1 ≤ p ≤ 10^9; 0 ≤ s; 0 ≤ d; s + d ≤ p.
// Если d = 0, канал никогда не открыт. Гарантируется, что все промежуточные времена и ответ не превосходят 10^15.
// 
// Формат результата
// Одно целое число — минимальное время прибытия в узел n, либо -1.
// 
// Пример 1
// Вход:
// 3 2
// 1 2 3 10 0 5
// 2 3 4 10 6 2
// Выход:
// 10
// Разбор: в момент 0 канал 1->2 открыт (0 mod 10 = 0 ∈ [0, 5)), передача занимает 3, приходим в узел 2 в момент 3. Канал 2->3 открыт на [6, 8) каждого периода длины 10; при t = 3 фаза равна 3 < 6, поэтому ждём до 6, передача 4, прибываем в 10.
// 
// Пример 2
// Вход:
// 2 2
// 1 2 5 4 1 2
// 2 1 1 3 0 1
// Выход:
// 6
// Разбор: единственный способ попасть в узел 2 — канал 1->2, его окно [1, 3) периода 4. При t = 0 фаза 0, ждём до 1, передача 5, прибываем в 6. Обратный канал 2->1 ничего не улучшает.
// 
// Пример 3
// Вход:
// 3 1
// 1 2 1 1 0 1
// Выход:
// -1
// Разбор: из узла 1 достижим только узел 2, узел 3 недостижим.
// 
// Идея решения: посчитать для каждого ребра функцию «ближайший допустимый момент старта ≥ t» через остаток t mod p и применить алгоритм Дейкстры по времени прибытия. Он корректен благодаря свойству FIFO: чем позже мы оказались в узле, тем позже (не раньше) сможем оказаться в любом другом узле, значит самая ранняя метка узла является доминирующей. Сложность O(m log n).

// Канал — это объект ребра со смыслом полей:
// to — куда ведёт канал, w — время передачи,
// p — период окон доступа, s — смещение первого окна, d — длина окна.

// Минимальная двоичная куча для пар [время, узел].
class MinHeap {
  constructor() {
    this.data = [];
  }
  get size() {
    return this.data.length;
  }
  push(item) {
    const a = this.data;
    a.push(item);
    let i = a.length - 1;
    while (i > 0) {
      const parent = (i - 1) >> 1;
      if (a[parent][0] <= a[i][0]) break;
      [a[parent], a[i]] = [a[i], a[parent]];
      i = parent;
    }
  }
  pop() {
    const a = this.data;
    const top = a[0];
    const last = a.pop();
    if (a.length > 0) {
      a[0] = last;
      let i = 0;
      for (;;) {
        const l = 2 * i + 1;
        const r = l + 1;
        let best = i;
        if (l < a.length && a[l][0] < a[best][0]) best = l;
        if (r < a.length && a[r][0] < a[best][0]) best = r;
        if (best === i) break;
        [a[best], a[i]] = [a[i], a[best]];
        i = best;
      }
    }
    return top;
  }
}

// Ключевая операция: мы пришли в хвост ребра в момент t и можем подождать.
// Ближайший допустимый старт — это первый момент t' >= t, у которого
// остаток t' mod p попадает в окно [s, s + d). Возвращаем время прибытия в голову.
function arriveVia(t, edge) {
  const { w, p, s, d } = edge;
  const phase = t % p;          // текущая фаза внутри периода
  let start;
  if (phase < s) {
    start = t + (s - phase);    // окно ещё не открылось — ждём его начала
  } else if (phase - s < d) {
    start = t;                  // окно открыто прямо сейчас, едем без ожидания
  } else {
    start = t + (p - phase + s);// окно уже закрылось — ждём до следующего периода
  }
  return start + w;
}

// Дейкстра по времени прибытия. Корректность опирается на свойство FIFO:
// функция «ближайшее прибытие по ребру» монотонна по времени старта,
// поэтому более поздний приход в узел никогда не даёт преимущества
// и достаточно хранить одну метку — самое раннее прибытие.
function chronoNetworkRouting(n, rawEdges) {
  const adj = Array.from({ length: n + 1 }, () => []);
  for (const e of rawEdges) {
    const [u, v, w, p, s, d] = e;
    adj[u].push({ to: v, w, p, s, d });
  }

  const INF = Infinity;
  const dist = new Array(n + 1).fill(INF);
  const heap = new MinHeap();

  dist[1] = 0;
  heap.push([0, 1]);

  while (heap.size > 0) {
    const [time, node] = heap.pop();
    if (time > dist[node]) continue;  // устаревшая запись: метку уже улучшили
    if (node === n) return time;      // цель впервые извлечена — это оптимум

    for (const edge of adj[node]) {
      const arrival = arriveVia(time, edge);
      if (arrival < dist[edge.to]) {
        dist[edge.to] = arrival;
        heap.push([arrival, edge.to]);
      }
    }
  }

  return dist[n] === INF ? -1 : dist[n];
}
