// Задача: Onyxbloom Ripple Budgeting
// Сложность: medium
// Дата генерации: 2026-11-19

// Условие задачи
// В саду ониксовых цветов (Onyxbloom) полив идёт по дням. В день i саду требуется costs[i] единиц влаги. Если в некоторый день вылить p единиц воды, то часть этой влаги «перетекает» в последующие дни: к дню i+k из этого полива доходит p * r^k, где 0 ≤ r ≤ 1 — коэффициент затухания ряби (ripple).
// 
// Правила учёта простые:
// — влага, дошедшая из прошлых дней, идёт в счёт потребности текущего дня;
// — если её меньше, чем нужно, мы доливаем разницу (именно эти доливы и образуют суммарный расход);
// — если её больше, чем нужно, доливать не надо, а избыток не исчезает и продолжает затухать дальше с тем же коэффициентом r.
// 
// Нужно найти минимальный коэффициент затухания r, при котором суммарный объём вылитой за все дни воды не превышает бюджет B. Если уложиться в бюджет нельзя даже при r = 1 (рябь совсем не затухает), вернуть -1.
// 
// Полезные наблюдения:
// — при r = 0 рябь отсутствует, и суммарный расход равен сумме всех costs[i];
// — при r = 1 рябь не затухает и суммарный расход равен max(costs[i]);
// — расход монотонно не возрастает по r, поэтому ответ ищется бинарным поиском по r на отрезке [0, 1].
// 
// Формат входных данных: costs — массив неотрицательных целых чисел (потребности по дням, 0 ≤ costs[i] ≤ 10^9, длина до 10^5), budget — целое неотрицательное число.
// 
// Формат результата: число r из отрезка [0, 1] — минимальный подходящий коэффициент затухания, либо -1, если решения нет. Точность ответа — порядка 1e-9 (бинарный поиск выполняется 100 итераций).
// 
// Примеры:
// 1) costs = [4, 6, 2], budget = 7  →  0.75
//    Проверка при r = 0.75: день 0 — выливаем 4, к дню 1 доходит 3; день 1 — нужно 6, доливаем 3 (итого 7), к дню 2 доходит 4.5; день 2 — нужно 2, хватает. Итог ровно 7.
// 2) costs = [10, 10, 10], budget = 10  →  1
//    Только при r = 1 рябь полностью покрывает все дни, расход равен 10.
// 3) costs = [5, 5], budget = 4  →  -1
//    Даже при r = 1 расход равен max = 5, что больше бюджета.
// 4) costs = [1, 2, 3], budget = 100  →  0
//    Сумма всех потребностей 6 уже укладывается в бюджет, рябь не нужна.

/**
 * Задача Onyxbloom Ripple Budgeting.
 * Ищем минимальный коэффициент затухания ряби r из [0, 1],
 * при котором суммарный полив не превышает budget.
 * Если это невозможно (даже при r = 1), возвращаем -1.
 */
function onyxbloomRippleBudget(costs, budget) {
  // Пустой сад не требует воды вообще.
  if (costs.length === 0) return 0;

  // Считаем два крайних случая заранее: полный расход и расход при максимальной ряби.
  let sum = 0;
  let max = 0;
  for (const need of costs) {
    sum += need;
    if (need > max) max = need;
  }

  // Рябь только уменьшает расход, поэтому sum — это самый плохой вариант (r = 0).
  if (sum <= budget) return 0;

  // При r = 1 рябь не затухает и весь суммарный расход равен максимуму по дням.
  // Если даже он не влезает в бюджет, решения не существует.
  if (max > budget) return -1;

  // Считаем суммарный расход воды при заданном коэффициенте затухания r.
  // ripple — сколько влаги дошло до текущего дня из предыдущих поливов.
  const neededWater = (r) => {
    let total = 0;
    let ripple = 0;

    for (const need of costs) {
      // Влаги не хватает — доливаем разницу, и уровень влаги поднимается до need.
      if (need > ripple) {
        total += need - ripple;
        ripple = need;
      }
      // Избыток влаги не пропадает: он затухает к следующему дню с коэффициентом r.
      ripple *= r;
    }

    return total;
  };

  // Расход монотонно не возрастает по r, поэтому подходящие значения r
  // образуют хвост [r*, 1]. Бинарным поиском находим левую границу.
  let lo = 0;
  let hi = 1;

  for (let step = 0; step < 100; step++) {
    const mid = (lo + hi) / 2;
    if (neededWater(mid) <= budget) {
      hi = mid; // такой r подходит — пробуем меньший
    } else {
      lo = mid; // влаги не хватает — нужна более сильная рябь
    }
  }

  return hi;
}
