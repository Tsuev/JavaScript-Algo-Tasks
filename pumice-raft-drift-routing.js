// Задача: Pumice Raft Drift Routing
// Сложность: hard
// Дата генерации: 2026-10-21

// Условие задачи
// **Pumice Raft Drift Routing**
// 
// После извержения в океан попадают плавучие пемзовые плоты. Океан — это прямоугольная сетка N×M; часть клеток занята сушей ('#'), остальные — вода. Морские течения периодичны: заданы P карт течений, карта с номером k (0 ≤ k < P) действует в те моменты времени t, для которых t mod P = k.
// 
// В каждой водной клетке карта течений задаёт смещение на один шаг: '^' — на строку вверх, 'v' — на строку вниз, '<' — на столбец влево, '>' — на столбец вправо, '.' — стоячая вода (плот остаётся на месте). В клетках суши всегда записана '.' (течение там не важно).
// 
// Плот стартует в момент времени 0 в клетке (r, c) (нумерация строк и столбцов — с нуля). Пока плот находится на воде, каждую единицу времени он смещается на одну клетку по течению той карты, которая действует сейчас: находясь в воде в момент t, в момент t+1 он оказывается в клетке, куда указывает течение карты номер (t mod P). Если плот попал на клетку суши, он прибивается к берегу и останавливается. Если шаг уводит его за границу карты, плот уносит в открытый океан, и к суше он уже никогда не вернётся. Аналогично, если плот попадает в замкнутый круговорот, он будет дрейфовать по нему бесконечно.
// 
// Для каждого из Q независимых запросов «плот стартовал в клетке (r, c)» определите, через сколько шагов (единиц времени) он окажется на суше, или −1, если этого никогда не случится. Если стартовая клетка — суша, ответ 0.
// 
// **Формат ввода**
// 
// Все данные разделены пробелами и/или переводами строк.
// 
// 1. Первая строка: четыре целых числа N M P Q.
// 2. Следующие N строк по M символов: карта суши, '#' — суша, '.' — вода.
// 3. Далее P блоков по N строк по M символов: карты течений по порядку (сначала карта номер 0, затем 1, …, P−1). Символы: '.', '^', 'v', '<', '>'. В клетках суши стоит '.'.
// 4. Далее Q строк, в каждой два целых числа r и c — стартовая клетка (0 ≤ r < N, 0 ≤ c < M).
// 
// **Формат вывода**
// 
// Q строк: для каждого запроса — минимальное число шагов до попадания на сушу, либо −1, если плот никогда не прибьётся к берегу.
// 
// **Пример 1**
// 
// Вход:
// ```
// 3 3 1 5
// ...
// .#.
// ...
// >v.
// ...
// .<.
// 0 0
// 0 1
// 1 0
// 2 2
// 1 1
// ```
// 
// Выход:
// ```
// 2
// 1
// -1
// -1
// 0
// ```
// 
// Разбор: из (0,0) плот идёт вправо в (0,1), а оттуда вниз — прямо на сушу (1,1), итого 2 шага. Из (0,1) до суши один шаг. В клетках (1,0) и (2,2) стоячая вода, плот стоит на месте вечно → −1. Клетка (1,1) — суша, ответ 0.
// 
// **Пример 2**
// 
// Вход:
// ```
// 2 3 2 4
// ..#
// ..#
// >>.
// ...
// ...
// >>.
// 0 0
// 1 0
// 0 2
// 1 2
// ```
// 
// Выход:
// ```
// 3
// 4
// 0
// 0
// ```
// 
// Разбор: старт (0,0), карта 0: шаг вправо → (0,1) в момент 1. Карта 1 в (0,1) — штиль, стоим до момента 2. Карта 0 в (0,1) — шаг вправо → (0,2), это суша, момент 3. Для старта (1,0): карта 0 — штиль (момент 1), карта 1 — вправо → (1,1) (момент 2), карта 0 — штиль (момент 3), карта 1 — вправо → (1,2), суша, момент 4.
// 
// **Ограничения**
// 
// 1 ≤ N, M ≤ 300, 1 ≤ P ≤ 8, 1 ≤ Q ≤ 200 000. Требуемая сложность — O(N·M·P + Q).

/**
 * Pumice Raft Drift Routing
 *
 * Ключевая идея: состояние плота — это пара (клетка, фаза течения). Фаз всего P,
 * значит состояний N*M*P, и из каждого выходит ровно один переход. Получается
 * функциональный граф (каждая компонента — «дерево», растущее в цикл).
 * Добавим два виртуальных состояния: «прибило к суше» (расстояние 0) и
 * «унесло за карту» (расстояние -1, суши уже не будет). Тогда ответ — это
 * расстояние до состояния «суша» по рёбрам графа, либо -1, если путь упирается
 * в цикл (или в «унесло за карту»).
 *
 * Сложность: O(N*M*P + Q) по времени и O(N*M*P) по памяти.
 *
 * Пример вызова:
 *   solve("2 3 2 4\n..#\n..#\n>>.\n...\n...\n>>.\n0 0\n1 0\n0 2\n1 2\n")
 *   // => "3\n4\n0\n0"
 */
function solve(input) {
  // ---------- разбор входа ----------
  const tokens = input.trim().split(/\s+/).filter((t) => t.length > 0);
  let ptr = 0;

  const n = Number(tokens[ptr++]);
  const m = Number(tokens[ptr++]);
  const p = Number(tokens[ptr++]);
  const q = Number(tokens[ptr++]);

  const cells = n * m;

  // Карта суши: 1 — берег, 0 — вода.
  const land = new Uint8Array(cells);
  for (let r = 0; r < n; r++) {
    const row = tokens[ptr++];
    for (let c = 0; c < m; c++) {
      if (row.charCodeAt(c) === 35) land[r * m + c] = 1; // 35 — это '#'
    }
  }

  // Карты течений: код 0 — штиль, 1 — вверх, 2 — вниз, 3 — влево, 4 — вправо.
  const dir = new Uint8Array(p * cells);
  for (let phase = 0; phase < p; phase++) {
    const base = phase * cells;
    for (let r = 0; r < n; r++) {
      const row = tokens[ptr++];
      for (let c = 0; c < m; c++) {
        const ch = row[c];
        let code = 0;
        if (ch === '^') code = 1;
        else if (ch === 'v') code = 2;
        else if (ch === '<') code = 3;
        else if (ch === '>') code = 4;
        dir[base + r * m + c] = code;
      }
    }
  }

  const DR = [0, -1, 1, 0, 0];
  const DC = [0, 0, 0, -1, 1];

  // ---------- граф состояний ----------
  // Состояние с номером cell * p + phase — плот стоит в клетке cell,
  // и сейчас действует карта течений номер phase.
  const waterStates = cells * p;
  const TERM = waterStates;     // «плот прибило к суше» — поглощающее состояние
  const VOID = waterStates + 1; // «плот унесло за карту» — суши уже не будет
  const total = waterStates + 2;

  // dist[i]: -2 — ещё не посчитано, -1 — суши не достичь, d >= 0 — осталось d шагов.
  const dist = new Int32Array(total).fill(-2);
  dist[TERM] = 0;
  dist[VOID] = -1;

  // Единственный переход из состояния.
  function succ(state) {
    const cell = (state / p) | 0;
    const phase = state - cell * p;
    const r = (cell / m) | 0;
    const c = cell - r * m;
    const code = dir[phase * cells + cell];
    const nr = r + DR[code];
    const nc = c + DC[code];

    // Уплыл за границу карты — к суше уже не вернётся.
    if (nr < 0 || nr >= n || nc < 0 || nc >= m) return VOID;

    const nextCell = nr * m + nc;
    // Шаг на сушу — финиш.
    if (land[nextCell]) return TERM;

    // Иначе просто сменилась фаза течения.
    return nextCell * p + ((phase + 1) % p);
  }

  const onPath = new Int32Array(total).fill(-1);
  const stack = new Int32Array(total);

  // Обход функционального графа без рекурсии: идём вперёд, пока не упрёмся
  // в уже посчитанное состояние, в сушу за карту или в цикл, а затем
  // раскручиваем накопленный путь назад, прибавляя по единице на каждый шаг.
  for (let start = 0; start < waterStates; start++) {
    if (dist[start] !== -2) continue;
    if (land[(start / p) | 0]) continue; // состояний «плот на суше» не бывает

    let sp = 0;
    let cur = start;

    while (dist[cur] === -2) {
      if (onPath[cur] !== -1) {
        // Нашли цикл: из него до суши не добраться, значит -1 для всех,
        // кто в этот цикл рано или поздно придёт.
        for (let i = 0; i < sp; i++) {
          dist[stack[i]] = -1;
          onPath[stack[i]] = -1;
        }
        sp = 0;
        break;
      }
      onPath[cur] = sp;
      stack[sp++] = cur;
      cur = succ(cur);
    }

    if (sp > 0) {
      let d = dist[cur];
      for (let i = sp - 1; i >= 0; i--) {
        // -1 «заразно»: из недостижимой суши никогда не получится 0 шагов.
        if (d !== -1) d += 1;
        dist[stack[i]] = d;
        onPath[stack[i]] = -1;
      }
    }
  }

  // ---------- ответы на запросы ----------
  const out = [];
  for (let i = 0; i < q; i++) {
    const r = Number(tokens[ptr++]);
    const c = Number(tokens[ptr++]);
    const cell = r * m + c;

    if (land[cell]) {
      out.push('0'); // плот уже на берегу
    } else {
      // В момент 0 действует карта течений номер 0, то есть фаза 0.
      out.push(String(dist[cell * p]));
    }
  }

  return out.join('\n');
}
