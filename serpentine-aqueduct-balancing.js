// Задача: Serpentine Aqueduct Balancing
// Сложность: hard
// Дата генерации: 2026-10-31

// Условие задачи
// Акведук «Змеевик» — это замкнутая кольцевая система из n резервуаров, соединённых n трубами. Резервуары пронумерованы 0, 1, ..., n-1 по кольцу (акведук змеевидно спускается по склону и замыкается сам на себя). Труба i соединяет резервуар i с резервуаром (i+1) mod n и пропускает воду в обе стороны; перекачка одной единицы воды по трубе i стоит w[i] монет.
// 
// Сейчас в резервуаре i находится a[i] единиц воды, а по проекту в нём должно оказаться ровно b[i] единиц. Воду можно перекачивать по трубам в любых направлениях и в любых (в том числе дробных) количествах, суммарные потери отсутствуют.
// 
// Найдите минимальную суммарную стоимость перекачки, после которой в каждом резервуаре окажется ровно b[i] единиц воды. Если это невозможно (общее количество воды в системе не совпадает с требуемым), верните -1.
// 
// Формат входных данных:
// Даны три массива одинаковой длины n (1 ≤ n ≤ 10^4):
//   • a — текущее количество воды в резервуарах, 0 ≤ a[i] ≤ 10^3;
//   • b — требуемое количество воды в резервуарах, 0 ≤ b[i] ≤ 10^3;
//   • w — стоимость перекачки единицы воды по трубе, 1 ≤ w[i] ≤ 10^3.
// 
// Формат результата:
// Одно целое число — минимальная стоимость (гарантируется, что ответ не превосходит 10^14 и точно представим в Number), либо -1, если сумма элементов a не равна сумме элементов b.
// 
// Примеры:
// 1) a = [4, 0, 0, 0], b = [1, 1, 1, 1], w = [1, 1, 1, 1] → 4
//    (лишние 3 единицы из резервуара 0 развозим по кольцу: 1 → резервуар 1 за 1, 1 → резервуар 3 за 1, 1 → резервуар 2 за 2; итого 4).
// 2) a = [3, 0], b = [0, 3], w = [1, 5] → 3
//    (выгоднее гнать всю воду по дешёвой трубе 0, а не по дорогой трубе 1).
// 3) a = [1, 2, 3], b = [3, 2, 1], w = [2, 2, 2] → 4
//    (нужно перенести 2 единицы от резервуара 2 к резервуару 0 напрямую по трубе 2: 2 × 2 = 4).
// 4) a = [1, 1], b = [1, 2], w = [1, 1] → -1
//    (в системе 2 единицы воды, а требуется 3 — баланс невозможен).

/**
 * Serpentine Aqueduct Balancing.
 *
 * Возвращает минимальную стоимость приведения кольцевого акведука
 * к требуемому распределению воды или -1, если баланс невозможен.
 *
 * @param {number[]} a текущее количество воды в резервуарах
 * @param {number[]} b требуемое количество воды в резервуарах
 * @param {number[]} w стоимость перекачки единицы воды по каждой трубе
 * @returns {number} минимальная стоимость или -1
 */
function balanceSerpentine(a, b, w) {
  const n = a.length;

  // Вода не создаётся и не исчезает: если суммы не совпали, решение невозможно.
  let totalA = 0;
  let totalB = 0;
  for (let i = 0; i < n; i++) {
    totalA += a[i];
    totalB += b[i];
  }
  if (totalA !== totalB) return -1;

  // Кольцо из одного резервуара уже сбалансировано (суммы совпали).
  if (n <= 1) return 0;

  // Обозначим через f_i чистое количество воды, текущее по трубе i
  // в направлении i -> (i+1) mod n (отрицательное значение — поток в обратную сторону).
  //
  // Баланс резервуара i: сколько втекло минус сколько вытекло = b[i] - a[i],
  // то есть f_{i-1} - f_i = b[i] - a[i], откуда
  //     f_i = f_{i-1} + (a[i] - b[i]).
  //
  // Сеть замкнута, поэтому f_{-1} = f_{n-1} = c — свободный параметр (циркуляция по кольцу).
  // Значит f_i = c + prefix[i], где prefix[i] = сумма (a[j] - b[j]) для j <= i.
  // Заметим, что prefix[n-1] = 0, так что равенство f_{-1} = f_{n-1} выполняется автоматически.
  const prefix = new Array(n);
  let running = 0;
  for (let i = 0; i < n; i++) {
    running += a[i] - b[i];
    prefix[i] = running;
  }

  // Стоимость = сумма по трубам w[i] * |f_i| = сумма w[i] * |c + prefix[i]|.
  // Если положить u_i = -prefix[i], получаем сумму w[i] * |c - u_i|.
  // Это взвешенная сумма модулей, её минимум достигается во взвешенной медиане
  // точек u_i с весами w[i]. Поэтому перебираем точки в порядке возрастания
  // и берём первую, на которой накопленный вес достигает половины общего.
  const points = new Array(n);
  let totalWeight = 0;
  for (let i = 0; i < n; i++) {
    points[i] = { value: -prefix[i], weight: w[i] };
    totalWeight += w[i];
  }
  points.sort((p, q) => p.value - q.value);

  let accumulated = 0;
  let optimalCirculation = points[n - 1].value; // страховка на случай странных весов
  for (const point of points) {
    accumulated += point.weight;
    if (2 * accumulated >= totalWeight) {
      optimalCirculation = point.value;
      break;
    }
  }

  // Считаем итоговую стоимость при найденной оптимальной циркуляции c.
  let cost = 0;
  for (let i = 0; i < n; i++) {
    const flow = optimalCirculation + prefix[i]; // сколько реально течёт по трубе i
    cost += w[i] * Math.abs(flow);
  }

  return cost;
}
