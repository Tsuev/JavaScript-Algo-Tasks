// Задача: Cinnabar Shard Fusion
// Сложность: hard
// Дата генерации: 2026-10-10

// Условие задачи
// У вас есть n осколков киновари, выложенных в ряд. Каждый осколок i имеет энергию a_i. Вы можете слить два соседних осколка. Если их энергии равны x и y, то новый осколок получает энергию x+y, а стоимость операции равна x+y. Требуется слить все осколки в один, минимизировав суммарную стоимость. Найдите минимальную возможную суммарную стоимость.
// 
// Формат входных данных:
// В первой строке записано целое число n (1 ≤ n ≤ 3000). Во второй строке записаны n целых чисел a_i (1 ≤ a_i ≤ 10^6).
// 
// Формат выходных данных:
// Выведите одно целое число — минимальную суммарную стоимость.
// 
// Пример 1:
// Вход:
// 3
// 1 2 3
// Выход:
// 9
// 
// Пример 2:
// Вход:
// 3
// 1 2 4
// Выход:
// 10
// 
// Пример 3:
// Вход:
// 3
// 5 5 5
// Выход:
// 25

function minFusionCost(energies) {
  const n = energies.length;
  if (n <= 1) return 0;

  // Префиксные суммы для быстрого получения суммы на отрезке [l, r]
  const pref = new Float64Array(n + 1);
  for (let i = 0; i < n; i++) {
    pref[i + 1] = pref[i] + energies[i];
  }

  // dp[l][r] — минимальная стоимость слияния отрезка l..r в один осколок.
  // opt[l][r] — оптимальный индекс разбиения для этого отрезка.
  // Используем одномерные массивы для экономии памяти: индекс l * n + r.
  const dp = new Float64Array(n * n);
  const opt = new Int32Array(n * n);

  // База: отрезок из одного осколка уже слит, стоимость 0.
  for (let i = 0; i < n; i++) {
    dp[i * n + i] = 0;
    opt[i * n + i] = i;
  }

  // Перебираем длины отрезков от 2 до n.
  for (let len = 2; len <= n; len++) {
    for (let l = 0; l + len <= n; l++) {
      const r = l + len - 1;
      const sum = pref[r + 1] - pref[l];

      // Границы для k по оптимизации Кнута.
      const startK = opt[l * n + (r - 1)];
      let endK = opt[(l + 1) * n + r];
      // k не может быть больше r - 1.
      if (endK > r - 1) endK = r - 1;

      let best = Infinity;
      let bestK = startK;

      for (let k = startK; k <= endK; k++) {
        const cost = dp[l * n + k] + dp[(k + 1) * n + r];
        if (cost < best) {
          best = cost;
          bestK = k;
        }
      }

      dp[l * n + r] = best + sum;
      opt[l * n + r] = bestK;
    }
  }

  return dp[0 * n + (n - 1)];
}
