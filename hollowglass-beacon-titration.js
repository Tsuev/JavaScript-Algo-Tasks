// Задача: Hollowglass Beacon Titration
// Сложность: medium
// Дата генерации: 2026-11-21

// Условие задачи
// ## Условие
// 
// В лаборатории на столе выстроены в ряд `n` полых стеклянных маяков (hollowglass beacons). Маяк `i` считается настроенным, когда в нём находится ровно `a[i]` капель раствора. Изначально все маяки пусты.
// 
// Титрование проводится раундами. За один раунд лаборант выбирает произвольный непустой отрезок маяков `[l, r]` и добавляет ровно по одной капле в каждый маяк этого отрезка. Один раунд занимает одну единицу времени, и других способов добавлять капли нет. Разумеется, «переливать» и «отливать» раствор нельзя: количество капель в маяке может только расти.
// 
// Нужно найти минимальное количество раундов, за которое можно добиться, чтобы в каждом маяке `i` оказалось ровно `a[i]` капель.
// 
// **Формат входных данных**
// 
// Массив (список) целых неотрицательных чисел `a` длины `n`, где `1 ≤ n ≤ 200000` и `0 ≤ a[i] ≤ 10^9`.
// 
// **Формат результата**
// 
// Одно целое число — минимальное число раундов. Ответ не превосходит `2·10^14`, поэтому спокойно помещается в обычное число JavaScript (точность до `2^53`).
// 
// **Примеры**
// 
// 1) `a = [1, 2, 3]` → `3`.
//    Раунды: `[0,2]`, затем `[1,2]`, затем `[2,2]`. Итог: `1, 2, 3` капли.
// 
// 2) `a = [3, 1, 2]` → `4`.
//    Раунды: `[0,2]` → `[1,1,1]`; `[0,0]` → `[2,1,1]`; `[0,0]` → `[3,1,1]`; `[2,2]` → `[3,1,2]`.
//    Меньше нельзя: маяк 0 требует трёх раундов, и отдельно нужен раунд для маяка 2, который не влезает в те же отрезки.
// 
// 3) `a = [0, 0, 0]` → `0`.
// 
// 4) `a = [5, 0, 5]` → `10`.
//    Отрезок, проходящий через пустой маяк, бесполезен: он добавляет каплю туда, где она не нужна, поэтому маяки 0 и 2 приходится наполнять по отдельности.
// 
// 5) `a = [2, 5, 1]` → `5`.
//    Раунды: два раза `[0,1]`, три раза `[1,1]` (или любая другая разумная раскладка) — суммарно `2 + 3 + 0 = 5`.
// 
// **Идея решения (кратко)**
// 
// Смотрим на «профиль» массива `a`. Каждый раунд — это горизонтальный отрезок на этом профиле. При переходе от `i-1` к `i`:
// 
// * если уровень вырос (`a[i] > a[i-1]`), то ровно `a[i] - a[i-1]` новых отрезков обязаны начаться именно в позиции `i` — эти раунды уже ничем не заменить;
// * если уровень упал или не изменился, «лишние» отрезки просто заканчиваются, и это не стоит ничего дополнительно.
// 
// Отсюда ответ: `a[0] + Σ max(0, a[i] - a[i-1])` для `i = 1..n-1`.

/**
 * Hollowglass Beacon Titration.
 *
 * Задача: за один раунд можно выбрать любой непустой отрезок маяков
 * и добавить по одной капле в каждый маяк отрезка. Нужно получить
 * ровно a[i] капель в маяке i, сделав минимум раундов.
 *
 * Ответ: a[0] + сумма по i от 1 до n-1 от max(0, a[i] - a[i-1]).
 *
 * Почему так:
 *  - каждый раунд — это горизонтальный отрезок на «профиле» массива a;
 *  - если при переходе i-1 -> i уровень вырос, то ровно (a[i] - a[i-1])
 *    новых отрезков обязаны начинаться именно в i (иначе маяк i не добрать),
 *    и эти раунды неизбежны;
 *  - если уровень упал или не изменился, лишние отрезки просто заканчиваются,
 *    и это не добавляет новых раундов;
 *  - первый маяк требует a[0] отрезков, начинающихся с него.
 *  То есть нижняя оценка достигается, значит формула — точный ответ.
 *
 * Сложность: O(n) по времени, O(1) дополнительной памяти.
 */
function hollowglassBeaconTitration(a) {
  if (!Array.isArray(a) || a.length === 0) return 0;

  // Все капли первого маяка набираются только отрезками, начинающимися в нём.
  let rounds = a[0];

  for (let i = 1; i < a.length; i++) {
    const rise = a[i] - a[i - 1];

    // Уровень вырос — нужно открыть rise новых отрезков именно здесь.
    // Если уровень упал или остался прежним, начинать ничего не надо: rise <= 0.
    if (rise > 0) {
      rounds += rise;
    }
  }

  return rounds;
}

/*
 * Проверочные примеры (запускать отдельно, без вывода в консоль):
 *   hollowglassBeaconTitration([1, 2, 3]);      // 3
 *   hollowglassBeaconTitration([3, 1, 2]);      // 4
 *   hollowglassBeaconTitration([0, 0, 0]);      // 0
 *   hollowglassBeaconTitration([5, 0, 5]);      // 10
 *   hollowglassBeaconTitration([2, 5, 1]);      // 5
 */

export { hollowglassBeaconTitration };
