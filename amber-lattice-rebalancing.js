// Условие задачи
// Задача: Amber Lattice Rebalancing (Перебалансировка янтарной решётки)
// 
// Дан прямоугольный участок размера n×m. В клетке (i, j) находится a[i][j] единиц янтаря (целое число; отрицательные значения тоже допустимы как абстрактные величины).
// 
// За одну операцию можно выбрать любую строку или любой столбец и прибавить 1 либо вычесть 1 из всех клеток выбранной линии. Например: «строка i плюс один» или «столбец j минус один». Стоимость операции — 1.
// 
// Требуется сделать так, чтобы во всех n·m клетках оказалось одинаковое количество янтаря. Какое именно одинаковое значение получится — не важно. Нужно минимизировать число операций.
// 
// Если уравнять все клетки невозможно, выведите -1.
// 
// Формат входных данных:
// В первой строке два целых числа n и m (1 ≤ n, m ≤ 1000).
// В следующих n строках по m целых чисел a[i][j] (−10^9 ≤ a[i][j] ≤ 10^9).
// 
// Формат результата:
// Одно целое число — минимальное количество операций или -1, если уравнять клетки нельзя.
// 
// Пример 1:
// Вход:
// 2 2
// 1 2
// 2 3
// Выход:
// 2
// Пояснение: уменьшим вторую строку на 1, затем увеличим первый столбец на 1 — получим все двойки за 2 операции.
// 
// Пример 2:
// Вход:
// 2 2
// 1 2
// 3 5
// Выход:
// -1
// Пояснение: величина a[i][j] − a[i][0] − a[0][j] + a[0][0] является инвариантом; здесь она равна 1, поэтому выровнять клетки нельзя.
// 
// Пример 3:
// Вход:
// 2 2
// 0 1
// 2 3
// Выход:
// 3
// Пояснение: например, вычтем 2 из второй строки и 1 из второго столбца — получим нули за 3 операции.
// 
// Пример 4:
// Вход:
// 2 2
// 5 5
// 5 5
// Выход:
// 0
// Пояснение: все клетки уже равны.

// Минимальная сумма |x - v| по всем значениям массива достигается на медиане.
function medianCost(values) {
  const sorted = [...values].sort((x, y) => x - y);
  const median = sorted[Math.floor(sorted.length / 2)];
  let cost = 0;
  for (const v of values) cost += Math.abs(v - median);
  return cost;
}

function solve(n, m, a) {
  // Инвариант: сдвиг целой строки или целого столбца на константу не меняет
  // величину a[i][j] - a[i][0] - a[0][j] + a[0][0]. Если она где-то не ноль,
  // уравнять клетки невозможно.
  for (let i = 0; i < n; i++) {
    for (let j = 0; j < m; j++) {
      if (a[i][j] !== a[i][0] + a[0][j] - a[0][0]) return -1;
    }
  }

  // Если инвариант выполнен, матрица раскладывается в сумму
  // a[i][j] = p[i] + q[j], где p[i] = a[i][0], q[j] = a[0][j] - a[0][0].
  const p = new Array(n);
  for (let i = 0; i < n; i++) p[i] = a[i][0];
  const q = new Array(m);
  for (let j = 0; j < m; j++) q[j] = a[0][j] - a[0][0];

  // Пусть к строке i прибавили R[i], а к столбцу j прибавили C[j].
  // Значение в клетке после операций: (p[i] + R[i]) + (q[j] + C[j]).
  // Чтобы все клетки стали равны, нужно p[i] + R[i] = alpha для всех i
  // и q[j] + C[j] = beta для всех j. Тогда R[i] = alpha - p[i],
  // C[j] = beta - q[j], а общее число операций равно sum|R[i]| + sum|C[j]|.
  // Alpha и beta независимы, поэтому минимум распадается на две отдельные
  // задачи о медиане: по строкам и по столбцам.
  return medianCost(p) + medianCost(q);
}
