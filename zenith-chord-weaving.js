// Условие задачи
// ## Zenith Chord Weaving
// 
// На окружности отмечены `M` точек, пронумерованных по часовой стрелке числами `0, 1, ..., M-1`. Мы хотим «сплести» из них узор: провести несколько хорд (каждая хорда соединяет две разные точки), причём каждая точка может быть концом не более одной хорды, а сами хорды не должны пересекаться внутри круга.
// 
// Две хорды `(a,b)` и `(c,d)` (где `a<b`, `c<d`) пересекаются, если их концы чередуются вдоль окружности, то есть выполнено `a < c < b < d` или `c < a < d < b`. Хорды, имеющие общий конец, пересекающимися не считаются, но в этой задаче мы и так запрещаем точке быть концом двух хорд.
// 
// Не всякую хорду разрешено проводить. Задан список допустимых хорд, у каждой есть свой вес (целое число, возможно отрицательное). Нужно выбрать такое множество попарно непересекающихся допустимых хорд, у которого сумма весов максимальна. Хорды с одинаковыми концами в списке могут повторяться — тогда берётся вариант с наибольшим весом.
// 
// ### Формат входных данных
// 
// Реализуй функцию `maxNonCrossingWeight(pointsCount, chords)`:
// 
// - `pointsCount` — целое число `M` (`0 <= M <= 500`), количество точек на окружности.
// - `chords` — массив троек `[a, b, w]`, где `0 <= a, b < M`, `a != b`, а `w` — целый вес хорды между точками `a` и `b`.
// 
// ### Формат результата
// 
// Функция возвращает одно целое число — максимальную суммарную стоимость набора попарно непересекающихся допустимых хорд. Если ни одну хорду провести нельзя (или точек меньше двух), ответ равен `0`.
// 
// ### Пример
// 
// Вход:
// 
// ```
// pointsCount = 4
// chords = [
//   [0, 1, 1], [2, 3, 1], [1, 2, 1], [0, 3, 1],
//   [0, 2, 5], [1, 3, 5]
// ]
// ```
// 
// Разберём варианты. Хорда `(0,2)` весит `5`, но тогда точки `1` и `3` свободны, а хорда `(1,3)` пересекает `(0,2)` (концы чередуются `0<1<2<3`), поэтому взять обе нельзя — итого `5`. Набор `(0,1)` и `(2,3)` не пересекается, но даёт лишь `1+1=2`. Одиночные хорды `(0,3)` и `(1,2)` дают `1`. Максимум достигается на `(0,2)`, ответ `5`.
// 
// Выход:
// 
// ```
// 5
// ```
// 
// ### Ограничения
// 
// - Время работы — `O(M^3)`, память — `O(M^2)`.
// - Веса помещаются в стандартный целочисленный диапазон JavaScript.

function maxNonCrossingWeight(pointsCount, chords) {
  const M = pointsCount;
  if (M < 2) return 0;

  // Вес допустимой хорды храним в таблице weight[lo][hi] для lo < hi.
  // null означает, что такой хорды в списке нет и проводить её нельзя.
  const weight = Array.from({ length: M }, () => new Array(M).fill(null));
  for (const [a, b, w] of chords) {
    const lo = Math.min(a, b);
    const hi = Math.max(a, b);
    if (lo === hi) continue; // хорда не может замыкаться в одну точку
    // При дубликатах оставляем самый выгодный вариант.
    if (weight[lo][hi] === null || weight[lo][hi] < w) {
      weight[lo][hi] = w;
    }
  }

  // dp[i][j] — максимальная суммарная стоимость непересекающихся хорд,
  // целиком лежащих на дуге из точек i, i+1, ..., j.
  //
  // Ключевая идея: рассматриваем крайнюю точку i отрезка [i..j].
  // Либо она свободна, либо соединена с некоторой точкой k. Тогда любая
  // хорда, выходящая из точек внутри (i,k), не может дотянуться наружу,
  // иначе она пересечёт хорду (i,k). Значит дуга распадается на две
  // независимые части: (i+1..k-1) и (k+1..j).
  const dp = Array.from({ length: M }, () => new Array(M).fill(0));
  const get = (i, j) => (i > j ? 0 : dp[i][j]);

  for (let len = 1; len <= M; len++) {
    for (let i = 0; i + len - 1 < M; i++) {
      const j = i + len - 1;

      // Вариант 1: точка i остаётся свободной.
      let best = get(i + 1, j);

      // Вариант 2: соединяем i с какой-нибудь точкой k правее.
      for (let k = i + 1; k <= j; k++) {
        const w = weight[i][k];
        if (w === null) continue;
        const candidate = w + get(i + 1, k - 1) + get(k + 1, j);
        if (candidate > best) best = candidate;
      }

      dp[i][j] = best;
    }
  }

  return dp[0][M - 1];
}
