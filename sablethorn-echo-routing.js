// Задача: Sablethorn Echo Routing
// Сложность: medium
// Дата генерации: 2026-11-10

// Условие задачи
// Долина Саблторн покрыта сетью из n ретрансляционных башен, соединённых двусторонними коридорами. По коридорам пускают эхо: оно стартует на башне s и должно дойти до башни t.
// 
// Каждый коридор задаётся временем прохождения w и типом:
// • 0 — обычный коридор;
// • 1 — резонансный: проходя по нему, эхо усиливается.
// 
// Усиление не бесплатно: если эхо пройдёт два резонансных коридора подряд, возникнет перегрузка и эхо погибнет. Значит, в допустимом маршруте не может быть двух резонансных коридоров подряд (на первый коридор маршрута ограничение не распространяется).
// 
// Нужно найти минимальное суммарное время, за которое эхо доберётся из s в t по допустимому маршруту, или вернуть -1, если такого маршрута нет. Если s = t, ответ 0.
// 
// Формат входных данных:
// первая строка — четыре целых числа n, m, s, t (число башен, число коридоров, старт, цель);
// следующие m строк — по четыре целых числа u, v, w, type: коридор между башнями u и v, время прохождения w, тип type ∈ {0, 1}.
// 
// Формат результата: одно целое число — минимальное время маршрута или -1.
// 
// Ограничения: 1 ≤ n ≤ 2·10^5, 0 ≤ m ≤ 2·10^5, 1 ≤ w ≤ 10^9, 1 ≤ s, t ≤ n. Граф не обязан быть связным, возможны кратные рёбра.
// 
// Пример 1:
// Вход:
// 4 4 1 4
// 1 2 1 1
// 2 3 1 1
// 1 3 5 0
// 3 4 2 0
// Выход:
// 7
// Пояснение: маршрут 1→2→3 запрещён (два резонансных коридора подряд), поэтому идём 1→3 (время 5) →4 (время 2), суммарно 7.
// 
// Пример 2:
// Вход:
// 3 1 1 3
// 1 2 4 0
// Выход:
// -1
// Пояснение: башня 3 недостижима из башни 1.

// Двоичная min-куча: пары (расстояние, состояние) лежат в двух параллельных массивах.
class MinHeap {
  constructor() {
    this.dist = [];   // значения расстояний
    this.state = [];  // соответствующие им состояния
  }

  get size() {
    return this.dist.length;
  }

  push(dist, state) {
    const d = this.dist, s = this.state;
    let i = d.length;
    d.push(dist);
    s.push(state);
    // всплываем вверх, пока родитель больше текущего элемента
    while (i > 0) {
      const p = (i - 1) >> 1;
      if (d[p] <= d[i]) break;
      [d[p], d[i]] = [d[i], d[p]];
      [s[p], s[i]] = [s[i], s[p]];
      i = p;
    }
  }

  pop() {
    const d = this.dist, s = this.state;
    const topDist = d[0], topState = s[0];
    const lastDist = d.pop(), lastState = s.pop();
    if (d.length > 0) {
      d[0] = lastDist;
      s[0] = lastState;
      let i = 0;
      const n = d.length;
      // погружаем корень вниз, выбирая меньшего из детей
      for (;;) {
        const l = 2 * i + 1, r = 2 * i + 2;
        let m = i;
        if (l < n && d[l] < d[m]) m = l;
        if (r < n && d[r] < d[m]) m = r;
        if (m === i) break;
        [d[m], d[i]] = [d[i], d[m]];
        [s[m], s[i]] = [s[i], s[m]];
        i = m;
      }
    }
    return [topDist, topState];
  }
}

/**
 * Sablethorn Echo Routing.
 *
 * @param {number} n        количество башен (нумерация во входных данных с единицы)
 * @param {Array<[number, number, number, number]>} edges
 *        список коридоров [u, v, w, type], где type: 0 — обычный, 1 — резонансный
 * @param {number} s        стартовая башня
 * @param {number} t        целевая башня
 * @returns {number} минимальное время маршрута или -1, если дойти нельзя
 */
function sablethornEchoRouting(n, edges, s, t) {
  // Внутри работаем с индексами с нуля, а входные данные нумеруются с единицы.
  s -= 1;
  t -= 1;

  const adj = Array.from({ length: n }, () => []);
  for (const e of edges) {
    const u = e[0] - 1, v = e[1] - 1, w = e[2], type = e[3];
    adj[u].push([v, w, type]);
    adj[v].push([u, w, type]); // коридоры двусторонние
  }

  // Ключевая идея: кроме башни нам важно, был ли предыдущий коридор резонансным,
  // ведь именно от этого зависит, можно ли идти по следующему резонансному коридору.
  // Кодируем состояние как (башня * 2 + флаг «предыдущий коридор резонансный»).
  // Дальше это обычный Дейкстра по 2n состояниям.
  const INF = Infinity;
  const dist = new Array(2 * n).fill(INF);

  const startState = s * 2; // предыдущего коридора нет — считаем флаг нулевым
  dist[startState] = 0;

  const heap = new MinHeap();
  heap.push(0, startState);

  while (heap.size > 0) {
    const [d, state] = heap.pop();
    if (d > dist[state]) continue; // устаревшая запись, уже нашли короче

    const u = state >> 1;         // текущая башня
    const prevResonant = state & 1;
    if (u === t) return d;        // в Дейкстре это и есть минимальное время до цели

    for (const [v, w, type] of adj[u]) {
      // Два резонансных коридора подряд перегружают эхо — такой переход запрещён
      if (prevResonant === 1 && type === 1) continue;

      const nextState = (v << 1) | type;
      const nd = d + w;
      if (nd < dist[nextState]) {
        dist[nextState] = nd;  // нашли более быстрый способ попасть в это состояние
        heap.push(nd, nextState);
      }
    }
  }

  return -1; // эхо так и не смогло добраться до цели
}
