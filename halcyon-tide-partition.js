// Условие задачи
// Halcyon Tide Partition
// 
// Океанологи изучают «тихий прилив» (halcyon tide). За сутки они сделали n последовательных измерений высоты воды — массив a[1..n] неотрицательных целых чисел. Чтобы обработать запись, её нужно разрезать на несколько непрерывных частей (каждая часть — непустой отрезок подряд идущих измерений) так, чтобы сумма высот внутри каждой части попадала в диапазон [L, R] включительно.
// 
// Посчитайте, сколькими способами это можно сделать. Два способа считаются различными, если различается набор границ между частями. Ответ выведите по модулю 10^9+7.
// 
// Формат входных данных
// Первая строка содержит три целых числа n, L, R (1 ≤ n ≤ 200000, 0 ≤ L ≤ R ≤ 2·10^14).
// Вторая строка содержит n целых чисел a[i] (0 ≤ a[i] ≤ 10^9) — высоты прилива.
// 
// Формат результата
// Одно целое число — количество подходящих разбиений по модулю 10^9+7.
// 
// Пример 1
// Вход:
// 4 2 3
// 2 1 1 2
// Выход:
// 2
// Пояснение: подходят два разбиения — [2][1,1][2] (суммы 2, 2, 2) и [2,1][1,2] (суммы 3 и 3).
// 
// Пример 2
// Вход:
// 3 1 1
// 1 1 1
// Выход:
// 1
// Пояснение: единственное разбиение [1][1][1].
// 
// Пример 3
// Вход:
// 2 5 5
// 2 2
// Выход:
// 0
// Пояснение: сумма всех элементов равна 4 < 5, поэтому ни одна часть не может иметь сумму 5.

const MOD = 1_000_000_007;

/**
 * Считает число способов разбить массив a на непрерывные непустые части
 * так, чтобы сумма каждой части лежала в отрезке [L, R] включительно.
 *
 * @param {number[]} a — высоты прилива (неотрицательные числа)
 * @param {number} L — нижняя граница суммы части
 * @param {number} R — верхняя граница суммы части
 * @returns {number} количество разбиений по модулю 1e9+7
 */
function halcyonTidePartition(a, L, R) {
  const n = a.length;

  // Префиксные суммы: pref[i] = a[0] + a[1] + ... + a[i-1], pref[0] = 0.
  const pref = new Array(n + 1);
  pref[0] = 0;
  for (let i = 0; i < n; i++) {
    pref[i + 1] = pref[i] + a[i];
  }

  // dp[i] — число способов разбить первые i измерений (префикс длины i).
  const dp = new Array(n + 1).fill(0);
  dp[0] = 1; // пустой префикс имеет ровно одно (пустое) разбиение

  /*
   * Переход: последняя часть — это отрезок (j, i], её сумма равна
   * pref[i] - pref[j]. Он допустим, когда L <= pref[i] - pref[j] <= R,
   * то есть pref[j] принадлежит отрезку [pref[i] - R, pref[i] - L].
   * Значит dp[i] = сумма dp[j] по всем таким j < i.
   *
   * Так как все a[i] >= 0, префиксные суммы не убывают, поэтому множество
   * подходящих j — это непрерывный отрезок индексов. При росте i обе
   * границы (pref[i] - R и pref[i] - L) только не убывают, значит окно
   * подходящих j можно двигать двумя указателями и поддерживать сумму dp
   * внутри него за O(1). Итоговая сложность — O(n) по времени и O(n) памяти.
   */
  let lo = 0;        // левая граница окна j, включительно
  let hi = 0;        // правая граница окна j, не включительно: окно = [lo, hi)
  let windowSum = 0; // сумма dp[j] по текущему окну

  for (let i = 1; i <= n; i++) {
    // Расширяем окно справа: добавляем все j, для которых pref[j] <= pref[i] - L.
    // Условие hi < i не позволяет взять j == i, ведь часть обязана быть непустой.
    while (hi < i && pref[hi] <= pref[i] - L) {
      windowSum = (windowSum + dp[hi]) % MOD;
      hi++;
    }
    // Сужаем окно слева: убираем все j, для которых pref[j] < pref[i] - R.
    while (lo < hi && pref[lo] < pref[i] - R) {
      windowSum = (windowSum - dp[lo] + MOD) % MOD;
      lo++;
    }
    dp[i] = windowSum;
  }

  return dp[n];
}
