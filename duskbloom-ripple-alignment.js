// Задача: Duskbloom Ripple Alignment
// Сложность: medium
// Дата генерации: 2026-11-13

// Условие задачи
// ## Условие
// 
// В саду Сумерек `n` цветков душноцвета растут по кругу. У цветка с номером `i` (`0 ≤ i < n`) высота `heights[i]`.
// 
// Волна (ripple) может начаться у любого цветка и распространяться по часовой стрелке, каждый раз переходя к соседнему цветку (после последнего снова идёт первый). Волна характеризуется целым шагом `d ≥ 1` и называется **выровненной** на участке, если каждый следующий цветок участка выше предыдущего ровно на `d`.
// 
// Формально: участок из `L` цветков, начинающийся у цветка `s` и идущий по часовой стрелке, выровнен, если существует такое целое `d ≥ 1`, что для всех `t` от `0` до `L − 2` выполнено
// 
// ```
// heights[(s + t + 1) mod n] − heights[(s + t) mod n] = d
// ```
// 
// Цветки внутри участка не повторяются, так как `1 ≤ L ≤ n`. Участок из одного цветка считается выровненным всегда.
// 
// Найдите максимально возможное значение `L` среди всех начальных позиций `s` и всех шагов `d`.
// 
// ## Формат входных данных
// 
// Функция принимает один аргумент — массив целых чисел `heights` (высоты цветков по кругу).
// 
// Ограничения: `1 ≤ n ≤ 5000`, `|heights[i]| ≤ 10^9`.
// 
// ## Формат результата
// 
// Целое число — максимальная длина выровненного участка, `1 ≤ answer ≤ n`.
// 
// ## Примеры
// 
// Пример 1:
// ```
// heights = [7, 9, 3, 5]
// ответ: 4
// ```
// Участок из индексов `2, 3, 0, 1` даёт высоты `3, 5, 7, 9` — шаг `2`, длина `4` (участок замыкается через край круга).
// 
// Пример 2:
// ```
// heights = [1, 2, 3, 2, 4]
// ответ: 3
// ```
// Участок `1, 2, 3` (индексы `0, 1, 2`) имеет шаг `1` и длину `3`; более длинного выровненного участка нет.
// 
// Пример 3:
// ```
// heights = [5, 5, 5]
// ответ: 1
// ```
// Ни один переход не является подъёмом, поэтому подходящего `d ≥ 1` не существует и остаётся только одиночный цветок.

function maxRippleAlignment(heights) {
  const n = heights.length;
  if (n <= 1) return n;

  // Перепады высот по часовой стрелке: diffs[i] = высота следующего минус высота текущего.
  // Последний перепад замыкает круг и возвращает нас к нулевому цветку.
  const diffs = new Array(n);
  for (let i = 0; i < n; i++) {
    diffs[i] = heights[(i + 1) % n] - heights[i];
  }

  // Волна поднимается, поэтому интересны только положительные шаги.
  // Различных шагов не больше n, значит полный перебор даёт O(n^2), что при n ≤ 5000 вполне достаточно.
  const steps = new Set();
  for (const d of diffs) {
    if (d >= 1) steps.add(d);
  }

  // Одинокий цветок — всегда корректный участок, поэтому минимум равен 1.
  let best = 1;

  for (const d of steps) {
    // Ищем самый длинный блок подряд идущих переходов, равных выбранному шагу d.
    // Блок считается по кругу, поэтому нельзя просто пройти массив слева направо.
    let firstBad = -1;
    for (let i = 0; i < n; i++) {
      if (diffs[i] !== d) {
        firstBad = i;
        break;
      }
    }

    let bestRun;
    if (firstBad === -1) {
      // Весь круг состоит из нужных переходов.
      bestRun = n;
    } else {
      // Начинаем обход сразу после «плохого» перехода: тогда искомый блок
      // гарантированно не окажется разорванным границей массива.
      bestRun = 0;
      let cur = 0;
      for (let k = 1; k <= n; k++) {
        const i = (firstBad + k) % n;
        if (diffs[i] === d) {
          cur++;
          if (cur > bestRun) bestRun = cur;
        } else {
          cur = 0;
        }
      }
    }

    // k подходящих переходов соединяют k + 1 цветок, но цветков в круге всего n.
    const len = Math.min(bestRun + 1, n);
    if (len > best) best = len;
  }

  return best;
}
