// Задача: Karst Sinkhole Routing
// Сложность: medium
// Дата генерации: 2026-10-12

// Условие задачи
// В карстовом массиве есть прямоугольная сетка n×m. Каждая клетка описывает поверхность: -1 — карстовый провал (непроходим), 0 — прочная порода, положительное число d — воронка глубины d (пройти можно, но это риск). Путешественник стартует в клетке (0,0) и должен попасть в клетку (n-1,m-1), двигаясь за один шаг вверх, вниз, влево или вправо. Риск маршрута — максимальная глубина воронки среди всех клеток маршрута (старт и финиш тоже учитываются; если воронок нет, риск 0). Найдите минимально возможный риск. Если пути не существует, верните -1.
// 
// Формат входа: функция получает grid — двумерный массив n×m целых чисел. Ограничения: 1 ≤ n,m ≤ 1000, значения клеток от -1 до 10^9.
// 
// Формат результата: одно целое число — минимальный риск или -1.
// 
// Пример 1:
// grid = [
//   [0, 1, 5],
//   [2, 4, 1],
//   [3, 0, 0]
// ]
// Ответ: 3
// Пояснение: путь (0,0)→(1,0)→(2,0)→(2,1)→(2,2) имеет максимальную глубину 3. Любой путь через верхнюю часть даёт максимум 5.
// 
// Пример 2:
// grid = [
//   [0, 2, 1, 1, 1],
//   [1, -1, -1, -1, 2],
//   [1, 1, 1, -1, 3],
//   [5, 5, 5, -1, 0]
// ]
// Ответ: 3
// Пояснение: из-за стены провалов приходится идти по верхней строке и спускаться по правому столбцу; максимальная глубина на этом пути равна 3.
// 
// Пример 3:
// grid = [
//   [0, -1],
//   [-1, 0]
// ]
// Ответ: -1
// Пояснение: старт и финиш изолированы провалами.

function minMaxSinkholeDepth(grid) {
  const n = grid.length;
  if (n === 0) return -1;
  const m = grid[0].length;
  if (m === 0) return -1;

  // Если старт или финиш — провал, путь невозможен.
  if (grid[0][0] === -1 || grid[n - 1][m - 1] === -1) return -1;

  // Собираем все допустимые глубины, чтобы потом искать ответ бинарным поиском.
  const depths = new Set();
  for (let i = 0; i < n; i++) {
    for (let j = 0; j < m; j++) {
      if (grid[i][j] >= 0) depths.add(grid[i][j]);
    }
  }
  const values = [...depths].sort((a, b) => a - b);

  // Проверяем достижимость финиша, если разрешено ходить по клеткам с глубиной не больше limit.
  const canReach = (limit) => {
    if (grid[0][0] > limit) return false;

    const visited = Array.from({ length: n }, () => new Array(m).fill(false));
    const queue = [[0, 0]];
    visited[0][0] = true;

    const dirs = [[1, 0], [-1, 0], [0, 1], [0, -1]];

    for (let head = 0; head < queue.length; head++) {
      const [x, y] = queue[head];

      if (x === n - 1 && y === m - 1) return true;

      for (const [dx, dy] of dirs) {
        const nx = x + dx;
        const ny = y + dy;

        if (nx < 0 || nx >= n || ny < 0 || ny >= m) continue;
        if (visited[nx][ny]) continue;

        const depth = grid[nx][ny];
        if (depth === -1 || depth > limit) continue;

        visited[nx][ny] = true;
        queue.push([nx, ny]);
      }
    }

    return false;
  };

  // Если даже максимальная глубина не позволяет дойти, пути нет.
  if (!canReach(values[values.length - 1])) return -1;

  // Бинарный поиск по возрастанию: ищем минимальную глубину, при которой путь существует.
  let left = 0;
  let right = values.length - 1;

  while (left < right) {
    const mid = (left + right) >> 1;
    if (canReach(values[mid])) {
      right = mid;
    } else {
      left = mid + 1;
    }
  }

  return values[left];
}
