// Задача: Thornwake Lattice Pruning
// Сложность: hard
// Дата генерации: 2026-11-14

// Условие задачи
// Thornwake Lattice Pruning
// 
// На участке-решётке размера n × m в каждой клетке (i, j) сидит колючка. Чтобы выкорчевать колючку из клетки (i, j), нужно потратить c[i][j] единиц сил (c[i][j] ≥ 0). Если после выкорчёвывания две оставшиеся колючки окажутся в соседних клетках (имеющих общую сторону), они переплетутся и «проснутся», чего допускать нельзя.
// 
// Нужно выбрать набор клеток, из которых колючки будут выкорчеваны, так, чтобы после этого никакие две оставшиеся колючки не были соседними по стороне, а суммарная стоимость выкорчёвывания была минимальной.
// 
// Иными словами, для каждой пары соседних по стороне клеток хотя бы одна из двух колючек должна быть выкорчевана. Требуется минимизировать суммарную стоимость удалённых колючек.
// 
// Формат входных данных:
// - первая строка содержит два целых числа n и m (1 ≤ n, m ≤ 200) — размеры решётки;
// - далее идут n строк по m целых чисел каждая: c[i][j] (0 ≤ c[i][j] ≤ 10^9) — стоимость выкорчёвывания колючки в клетке (i, j).
// 
// Формат результата:
// - одно целое число — минимальная суммарная стоимость выкорчёванных колючек.
// 
// Примеры:
// 
// Вход 1:
// 2 2
// 1 2
// 3 4
// Выход 1: 5
// Пояснение: можно выкорчевать клетки (0,0) и (1,1) — сумма 1 + 4 = 5; либо клетки (0,1) и (1,0) — сумма 2 + 3 = 5. Меньше не получится.
// 
// Вход 2:
// 1 3
// 2 9 2
// Выход 2: 4
// Пояснение: выкорчевать центральную колючку стоит 9, а выкорчевать обе крайние — 2 + 2 = 4. Второй вариант дешевле.
// 
// Вход 3:
// 1 1
// 7
// Выход 3: 0
// Пояснение: соседей нет, можно ничего не выкорчёвывать.
// 
// Ключевая идея: решётка — двудольный граф (красим клетки в шахматном порядке), а задача есть поиск минимального по весу вершинного покрова двудольного графа, который сводится к минимальному разрезу (max-flow).

// Задача сводится к минимальному по весу вершинному покрову двудольного графа.
// Раскрашиваем клетки в шахматном порядке: чёрные и белые.
// Каждое ребро (соседство по стороне) соединяет чёрную и белую клетки.
// Нужно удалить вершины минимальной суммарной стоимости так, чтобы каждое
// ребро было покрыто. По теореме Кёнига (взвешенный вариант) это значение
// равно величине минимального разреза в сети:
//   источник -> чёрные клетки (пропускная способность = стоимость клетки),
//   белые клетки -> сток (пропускная способность = стоимость клетки),
//   чёрная клетка -> соседняя белая (бесконечная пропускная способность).
// Минимальный разрез считаем алгоритмом Диница.

function thornwakeLatticePruning(n, m, grid) {
  const V = n * m + 2;          // все клетки + исток + сток
  const S = n * m;              // номер истока
  const T = n * m + 1;          // номер стока
  const INF = Number.MAX_SAFE_INTEGER; // «бесконечность» для рёбер соседства

  // Граф храним в виде связных списков на массивах.
  const head = new Int32Array(V).fill(-1);
  const to = [];
  const cap = [];
  const nxt = [];

  // Добавляем прямое ребро пропускной способности c и обратное (остаточное) 0.
  const addEdge = (u, v, c) => {
    to.push(v); cap.push(c); nxt.push(head[u]); head[u] = to.length - 1;
    to.push(u); cap.push(0); nxt.push(head[v]); head[v] = to.length - 1;
  };

  const id = (i, j) => i * m + j;

  // Рёбра истока и стока по цвету клетки.
  for (let i = 0; i < n; i++) {
    for (let j = 0; j < m; j++) {
      if ((i + j) % 2 === 0) addEdge(S, id(i, j), grid[i][j]);
      else addEdge(id(i, j), T, grid[i][j]);
    }
  }

  // Рёбра соседства: только из чёрных клеток в белые, бесконечной ёмкости.
  const di = [1, -1, 0, 0];
  const dj = [0, 0, 1, -1];
  for (let i = 0; i < n; i++) {
    for (let j = 0; j < m; j++) {
      if ((i + j) % 2 !== 0) continue;
      for (let d = 0; d < 4; d++) {
        const ni = i + di[d], nj = j + dj[d];
        if (ni >= 0 && ni < n && nj >= 0 && nj < m) {
          addEdge(id(i, j), id(ni, nj), INF);
        }
      }
    }
  }

  // Массивы для алгоритма Диница.
  const level = new Int32Array(V);
  const it = new Int32Array(V);       // текущие дуги (current arc)
  const queue = new Int32Array(V);
  const nodeStack = new Int32Array(V + 1);
  const edgeStack = new Int32Array(V + 1);

  // Построение слоистой сети обходом в ширину по остаточным рёбрам.
  const bfs = () => {
    level.fill(-1);
    let qh = 0, qt = 0;
    queue[qt++] = S;
    level[S] = 0;
    while (qh < qt) {
      const u = queue[qh++];
      for (let e = head[u]; e !== -1; e = nxt[e]) {
        if (cap[e] > 0 && level[to[e]] === -1) {
          level[to[e]] = level[u] + 1;
          queue[qt++] = to[e];
        }
      }
    }
    return level[T] !== -1;
  };

  // Итеративный поиск одного дополняющего пути в слоистой сети.
  // Возвращает проталкиваемый поток (0, если пути нет).
  // Итеративность важна: глубина рекурсии могла бы быть очень большой.
  const augment = () => {
    let sp = 0;               // указатель стека вершин пути
    nodeStack[0] = S;
    edgeStack[0] = -1;
    while (sp >= 0) {
      const u = nodeStack[sp];
      if (u === T) {
        // Нашли путь — проталкиваем минимум по его рёбрам.
        let f = INF;
        for (let k = 1; k <= sp; k++) f = Math.min(f, cap[edgeStack[k]]);
        for (let k = 1; k <= sp; k++) {
          cap[edgeStack[k]] -= f;
          cap[edgeStack[k] ^ 1] += f; // обратное ребро
        }
        return f;
      }
      // Продвигаем текущую дугу, пока она не станет допустимой.
      let e = it[u];
      while (e !== -1 && !(cap[e] > 0 && level[to[e]] === level[u] + 1)) e = nxt[e];
      it[u] = e;
      if (e === -1) {
        level[u] = -1; // вершина тупиковая в этом слое — отсекаем
        sp--;
      } else {
        sp++;
        nodeStack[sp] = to[e];
        edgeStack[sp] = e;
      }
    }
    return 0;
  };

  // Основной цикл Диница: строим слои и выжимаем блокирующий поток.
  let maxflow = 0;
  while (bfs()) {
    it.set(head); // сбрасываем текущие дуги на начало фазы
    while (true) {
      const f = augment();
      if (f === 0) break;
      maxflow += f;
    }
  }

  // По теореме о минимальном разрезе это и есть минимальный вес покрова.
  return maxflow;
}
