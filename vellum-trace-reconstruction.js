// Задача: Vellum Trace Reconstruction
// Сложность: medium
// Дата генерации: 2026-10-20

// Условие задачи
// Древний манускрипт («веллум») содержал строку s из строчных латинских букв. До нас дошли m «следов»: каждый след — это копия исходной строки, из которой удалили ровно один символ (у разных следов могли быть удалены разные символы; следы могут повторяться). Порядок оставшихся символов, разумеется, сохраняется.
// 
// По набору следов восстановите исходный текст; если подходящих вариантов несколько, выберите лексикографически наименьший.
// 
// Формально: пусть L — длина самого длинного из следов. Требуется найти лексикографически наименьшую строку s длины ровно L+1 такую, что каждый след является подпоследовательностью s. Гарантируется, что хотя бы одна такая строка существует.
// 
// Входные данные: функция принимает массив строк traces.
//   1 ≤ traces.length ≤ 100;
//   каждая строка состоит только из символов 'a'..'z';
//   длина каждого следа не превосходит 100 (след может быть пустой строкой).
// 
// Результат: строка s — лексикографически наименьший возможный исходный текст.
// 
// Примеры:
// 1) traces = ["bc","ac","ab"] → "abc". Все три следа являются подпоследовательностями "abc", длина 3 минимально возможна, и меньше "abc" подходящей строки нет.
// 2) traces = ["a","b"] → "ab". Подходят и "ab", и "ba"; берём меньшую.
// 3) traces = ["a"] → "aa". Подходят все строки длины 2, содержащие "a"; лексикографически первая из них — "aa".
// 4) traces = [""] → "a". Исходная строка состояла из одного символа; минимальный вариант — 'a'.
// 
// Идея решения: любая подходящая строка длины L+1 обязана содержать самый длинный след как подпоследовательность, поэтому она получается из него вставкой ровно одного символа. Перебираем все позиции вставки и все 26 букв, проверяем каждый след на «подпоследовательность» жадно за O(L) и оставляем лексикографически наименьший годный вариант. Сложность O(26·L²·m), что при указанных ограничениях легко укладывается в лимит.

/**
 * Восстановление исходной строки по набору «следов».
 * Каждый след — исходная строка с удалённым ровно одним символом.
 * Возвращается лексикографически наименьший подходящий вариант.
 *
 * @param {string[]} traces
 * @returns {string}
 */
function reconstructVellum(traces) {
  if (!traces || traces.length === 0) return '';

  // Берём самый длинный след за основу: любой подходящий ответ длиной L+1
  // обязан содержать его как подпоследовательность, а значит получается
  // из него вставкой ровно одного символа. Так мы резко сужаем перебор.
  let base = traces[0];
  for (const t of traces) {
    if (t.length > base.length) base = t;
  }

  // Жадная проверка: является ли a подпоследовательностью b.
  const isSubsequence = (a, b) => {
    let i = 0;
    for (let j = 0; j < b.length && i < a.length; j++) {
      if (a[i] === b[j]) i++;
    }
    return i === a.length;
  };

  let best = null;

  // Перебираем позицию вставки (от начала до конца включительно)
  // и сам вставляемый символ.
  for (let pos = 0; pos <= base.length; pos++) {
    const left = base.slice(0, pos);
    const right = base.slice(pos);

    for (let code = 97; code <= 122; code++) {
      const candidate = left + String.fromCharCode(code) + right;

      // Нам нужен лексикографически наименьший ответ, поэтому кандидаты,
      // которые не лучше уже найденного, можно даже не проверять.
      if (best !== null && candidate >= best) continue;

      if (traces.every((t) => isSubsequence(t, candidate))) {
        best = candidate;
      }
    }
  }

  // По условию подходящая строка существует, поэтому best не останется null.
  return best ?? '';
}
