// Задача: Chromatic Cascade Routing
// Сложность: hard
// Дата генерации: 2026-09-13

// Условие задачи
// Chromatic Cascade Routing
// 
// В сети из n узлов (нумерация 0..n-1) настроена каскадная маршрутизация. Каждый узел окрашен в один из k цветов (цвета занумерованы 0..k-1). Между узлами проложены односторонние каналы; граф каналов гарантированно ацикличен (DAG).
// 
// Каскадный маршрут — это такая последовательность различных по позиции узлов v1 → v2 → … → vt, что:
//   1) для каждого i от 1 до t-1 существует канал vi → vi+1;
//   2) все цвета узлов v1, v2, …, vt попарно различны.
// Иными словами, маршрут «переливается» всё новыми цветами и не может вернуться к уже использованному цвету.
// 
// Нужно найти максимально возможную длину (число узлов t) каскадного маршрута. Маршрут из одного узла всегда допустим, поэтому при n ≥ 1 ответ не меньше 1.
// 
// Формат входных данных (аргументы функции):
//   • n — целое число узлов, 1 ≤ n ≤ 300;
//   • k — целое число цветов, 1 ≤ k ≤ 15;
//   • colors — массив длины n, colors[i] ∈ [0, k-1] — цвет узла i;
//   • edges — массив пар [u, v], 0 ≤ u,v < n, задающий ориентированные каналы u → v. Граф ацикличен, 0 ≤ |edges| ≤ 3000.
// 
// Формат результата: одно целое число — максимальная длина каскадного маршрута (максимальное число узлов).
// 
// Примеры:
//   1) n = 5, k = 4, colors = [0,1,2,3,0], edges = [[0,1],[1,2],[2,3],[3,4]]. Ответ 4.
//      Маршрут 0→1→2→3 имеет цвета 0,1,2,3 — все различны. Продлить до узла 4 нельзя: его цвет 0 уже использован.
//   2) n = 5, k = 2, colors = [0,1,0,1,0], edges = [[0,1],[1,2],[2,3],[3,4]]. Ответ 2.
//      Самый длинный путь в графе 0→1→2→3→4 переиспользует цвета. Любой каскадный маршрут здесь — это одно ребро (0→1, 1→2, 2→3 или 3→4), то есть длина 2.
//   3) n = 3, k = 3, colors = [0,1,2], edges = [[0,1],[1,2],[0,2]]. Ответ 3.
//      Маршрут 0→1→2 собирает все три цвета.

/**
 * Chromatic Cascade Routing.
 *
 * Ищем самый длинный путь в ориентированном ациклическом графе, у которого
 * все цвета вершин попарно различны (так называемый «радужный» путь).
 *
 * Хитрость в том, что число цветов k маленькое — поэтому удобно вести динамику
 * по битовой маске использованных цветов.
 *
 *   dp[mask][v] — максимальная длина пути, который заканчивается в вершине v
 *                 и использует ровно множество цветов mask
 *                 (бит c установлен в mask, если цвет c присутствует на пути).
 *
 * Состояние осмысленно только когда mask содержит цвет вершины v.
 *
 *   База:    mask === (1 << colors[v])  =>  dp = 1 (путь из одной вершины).
 *   Переход: dp[mask][v] = 1 + max dp[mask ^ (1 << colors[v])][u]
 *                         по всем предшественникам u вершины v.
 *
 * Никаких циклов в графе нет, а подмаска mask ^ (1 << colors[v]) всегда численно
 * меньше mask, поэтому достаточно просто перебирать mask по возрастанию.
 *
 * Время работы O(2^k * (n + m)), память O(2^k * n).
 */
function chromaticCascadeRouting(n, k, colors, edges) {
  if (n === 0) return 0;

  // parents[v] — все вершины u, из которых идёт ребро u -> v.
  // Переход в динамике идёт «назад по ребру», так что удобно хранить именно предшественников.
  const parents = Array.from({ length: n }, () => []);
  for (const [u, v] of edges) {
    parents[v].push(u);
  }

  const masks = 1 << k;

  // dp выложен одним плоским массивом: dp[mask * n + v].
  // -1 означает «пути не существует».
  const NEG = -1;
  const dp = new Int32Array(masks * n).fill(NEG);

  let best = 0;

  for (let mask = 1; mask < masks; mask++) {
    const base = mask * n;              // начало «строки» этой маски
    for (let v = 0; v < n; v++) {
      const bit = 1 << colors[v];

      // Путь с набором цветов mask не может содержать вершину v, если её цвет не входит в mask.
      if ((mask & bit) === 0) continue;

      if (mask === bit) {
        // Путь состоит из единственной вершины.
        dp[base + v] = 1;
        if (best < 1) best = 1;
        continue;
      }

      // Временно убираем цвет вершины v и смотрим, откуда можно было прийти.
      const prevBase = (mask ^ bit) * n;
      let local = NEG;
      for (const u of parents[v]) {
        const val = dp[prevBase + u];
        if (val > local) local = val;
      }

      if (local !== NEG) {
        dp[base + v] = local + 1;
        if (local + 1 > best) best = local + 1;
      }
    }
  }

  return best;
}
