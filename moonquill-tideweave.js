// Условие задачи
// «Луна-переписчик» (Moonquill) ведёт хронику приливов. За n часов она записала уровни воды: a[0], a[1], …, a[n−1] (целые числа, могут быть и отрицательными).
// 
// Запись нужно «свить» (tideweave) в несколько нитей. Нить — это подпоследовательность хроники: часть часов, взятых в исходном порядке (не обязательно подряд), в которой уровень воды не убывает. Каждый час должен попасть ровно в одну нить. Требуется найти минимальное количество нитей, на которые можно разбить всю хронику.
// 
// Формат входных данных:
// — в первой строке целое число n (1 ≤ n ≤ 100000) — количество часов;
// — во второй строке n целых чисел a[i] (−10^9 ≤ a[i] ≤ 10^9) — уровни воды по часам.
// 
// Формат результата:
// — одно целое число: минимальное число неубывающих нитей, покрывающих все n часов.
// 
// Пример 1:
// Вход:
// 5
// 3 1 2 5 4
// Выход:
// 2
// Пояснение: подходят нити [3, 5] (часы 0 и 3) и [1, 2, 4] (часы 1, 2, 4). Одной нитью не обойтись, так как 3 > 1.
// 
// Пример 2:
// Вход:
// 4
// 4 3 2 1
// Выход:
// 4
// Пояснение: уровни строго убывают, поэтому любые два часа в одной нити нарушат неубывание — каждый час образует отдельную нить.
// 
// Пример 3:
// Вход:
// 3
// 1 2 3
// Выход:
// 1
// Пояснение: вся хроника уже не убывает — достаточно одной нити.
// 
// Пример 4:
// Вход:
// 6
// 2 2 1 3 1 2
// Выход:
// 2
// Пояснение: нити [2, 2, 3] (часы 0, 1, 3) и [1, 1, 2] (часы 2, 4, 5).
// 
// Подсказка к решению: по теореме Дилуорта для последовательностей минимальное число неубывающих подпоследовательностей, покрывающих все элементы, равно длине самой длинной строго убывающей подпоследовательности. Эту длину можно найти за O(n log n) методом «терпеливой сортировки» с двоичным поиском.

/**
 * Минимальное число неубывающих нитей, на которые разбивается хроника приливов.
 * @param {number[]} levels — уровни воды по часам в исходном порядке (n = levels.length)
 * @returns {number}
 */
function minStrands(levels) {
  // Ключевой факт (теорема Дилуорта в форме для последовательностей):
  // минимальное число неубывающих подпоследовательностей, покрывающих все элементы,
  // равно длине самой длинной строго убывающей подпоследовательности.
  // Поэтому вместо явного раскладывания по нитям достаточно посчитать эту длину.

  // Удобный трюк: строго убывающая подпоследовательность исходного массива —
  // это строго возрастающая подпоследовательность массива с противоположными знаками.
  // tails[k] = наименьший возможный последний элемент строго возрастающей
  // подпоследовательности длины k + 1; массив tails всегда отсортирован по возрастанию.
  const tails = [];

  for (const level of levels) {
    const x = -level;

    // Двоичный поиск (lowerBound): первый индекс i, для которого tails[i] >= x.
    let lo = 0;
    let hi = tails.length;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      if (tails[mid] >= x) hi = mid;
      else lo = mid + 1;
    }

    // Если подходящего хвоста нет — подпоследовательность удлиняется,
    // иначе заменяем хвост на меньший: от этого её шансы продолжиться только растут.
    if (lo === tails.length) tails.push(x);
    else tails[lo] = x;
  }

  // Длина массива tails — это длина самой длинной строго возрастающей
  // подпоследовательности инвертированных уровней, то есть самой длинной
  // строго убывающей подпоследовательности исходной хроники. Это и есть ответ.
  return tails.length;
}
