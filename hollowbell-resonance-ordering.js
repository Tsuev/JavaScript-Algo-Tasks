// Условие задачи
// Hollowbell Resonance Ordering
// 
// У нас есть n полых колоколов, каждый характеризуется резонансной частотой — положительным целым числом. Мы хотим расставить колокола по кругу так, чтобы суммарный резонанс был максимальным. Резонанс между двумя соседними колоколами равен произведению их частот. Суммарный резонанс — это сумма резонансов по всем соседним парам в круге (каждый колокол имеет двух соседей, за исключением n=2, где они соседствуют дважды). Требуется найти максимально возможный суммарный резонанс.
// 
// Формат входных данных: В первой строке дано целое число n (2 ≤ n ≤ 100000). Во второй строке даны n целых чисел a_i (1 ≤ a_i ≤ 10^6) — резонансные частоты колоколов.
// 
// Формат выходных данных: Выведите одно целое число — максимальный суммарный резонанс.
// 
// Пример 1:
// Вход:
// 4
// 1 2 3 4
// Выход:
// 25
// Пояснение: Оптимальный порядок: 1, 2, 4, 3 (или 1, 3, 4, 2). Суммарный резонанс = 1*2 + 2*4 + 4*3 + 3*1 = 2 + 8 + 12 + 3 = 25.
// 
// Пример 2:
// Вход:
// 5
// 1 2 3 4 5
// Выход:
// 48
// Пояснение: Оптимальный порядок: 1, 3, 5, 4, 2. Сумма = 1*3 + 3*5 + 5*4 + 4*2 + 2*1 = 3 + 15 + 20 + 8 + 2 = 48.

/**
 * Возвращает максимальный суммарный резонанс при расстановке колоколов по кругу.
 * @param {number} n - количество колоколов.
 * @param {number[]} arr - массив резонансных частот.
 * @returns {string} - максимальный суммарный резонанс в виде строки (для больших чисел).
 */
function maxResonance(n, arr) {
    // Сортируем частоты по возрастанию.
    const a = [...arr].sort((x, y) => x - y);
    
    // Строим оптимальный порядок обхода по кругу.
    // Сначала идут элементы с чётными индексами (0, 2, 4, ...) в порядке возрастания,
    // затем элементы с нечётными индексами в порядке убывания.
    const order = [];
    for (let i = 0; i < n; i += 2) {
        order.push(a[i]);
    }
    // Начальный индекс для нечётных элементов: если n нечётно, то n-2, иначе n-1.
    const startOdd = (n % 2 === 1) ? n - 2 : n - 1;
    for (let i = startOdd; i >= 1; i -= 2) {
        order.push(a[i]);
    }
    
    // Считаем суммарный резонанс.
    // Используем BigInt, так как произведение и сумма могут превышать 2^53.
    let total = 0n;
    for (let i = 0; i < n; i++) {
        const j = (i + 1) % n;
        total += BigInt(order[i]) * BigInt(order[j]);
    }
    
    return total.toString();
}
