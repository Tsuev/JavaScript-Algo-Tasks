// Задача: Driftglass Partition
// Сложность: hard
// Дата генерации: 2026-10-23

// Условие задачи
// В мастерской собрали n осколков дрейфгласа (морского стекла), выложенных в один ряд. У i-го осколка масса weights[i] (целое число, 0 ≤ weights[i] ≤ 1000).
// 
// Осколки нужно переплавить, выполнив ровно k плавок. За одну плавку можно взять только непрерывный блок ещё не переплавленных осколков, идущих подряд (переставлять или пропускать осколки нельзя). Значит, весь ряд разрезается на ровно k непустых последовательных кусков.
// 
// Энергия одной плавки равна квадрату суммарной массы осколков в этом куске. Нужно минимизировать суммарную энергию всех k плавок.
// 
// Формат: реализуйте функцию driftglassPartition(weights, k).
// - weights — массив целых неотрицательных чисел длины n (1 ≤ n ≤ 2000);
// - k — целое число, количество блоков.
// 
// Результат: минимальная возможная суммарная энергия. Если разбить ряд на k непустых кусков невозможно (k < 1 или k > n), верните -1.
// 
// Примеры:
// 1) weights = [1, 2, 3], k = 2 → 18
//    (варианты: [1][2,3] = 1 + 25 = 26; [1,2][3] = 9 + 9 = 18 — минимум 18)
// 2) weights = [1, 2, 3], k = 3 → 14
//    (по одному осколку на плавку: 1 + 4 + 9 = 14)
// 3) weights = [1, 2, 3], k = 1 → 36
//    (весь ряд целиком: (1+2+3)^2 = 36)
// 4) weights = [3, 1, 1], k = 2 → 13
//    ([3][1,1] = 9 + 4 = 13 против [3,1][1] = 16 + 1 = 17)
// 5) weights = [1, 2, 3], k = 4 → -1
//    (из 3 осколков нельзя получить 4 непустых куска)

// Структура для трюка с выпуклой оболочкой (Convex Hull Trick).
// Хранит набор прямых y = m*x + b и умеет быстро находить минимум по x.
class LowerHull {
  constructor() {
    // Наклоны будем добавлять в порядке невозрастания, поэтому массив
    // наклонов окажется строго убывающим — это ключ к бинарному поиску.
    this.ms = [];
    this.bs = [];
  }

  get size() {
    return this.ms.length;
  }

  // Добавляет прямую y = m*x + b.
  add(m, b) {
    const ms = this.ms;
    const bs = this.bs;

    // При одинаковых наклонах для минимума выгоднее меньший свободный член.
    while (ms.length > 0 && ms[ms.length - 1] === m) {
      if (bs[bs.length - 1] <= b) return; // новая прямая нигде не лучше
      ms.pop();
      bs.pop();
    }

    // Убираем с конца прямые, которые перестали быть частью нижней огибающей.
    // Средняя прямая (m2,b2) лишняя, если пересечение (m1,b1)-(m2,b2) не левее
    // пересечения (m2,b2)-новой прямой.
    while (ms.length >= 2) {
      const m1 = ms[ms.length - 2], b1 = bs[bs.length - 2];
      const m2 = ms[ms.length - 1], b2 = bs[bs.length - 1];
      if ((b2 - b1) * (m2 - m) >= (b - b2) * (m1 - m2)) {
        ms.pop();
        bs.pop();
      } else {
        break;
      }
    }

    ms.push(m);
    bs.push(b);
  }

  // Минимум m*x + b по всем прямым. Значения по индексам образуют «долину»,
  // поэтому минимум ищется бинарным поиском.
  query(x) {
    const ms = this.ms;
    const bs = this.bs;
    let lo = 0;
    let hi = ms.length - 1;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      const left = ms[mid] * x + bs[mid];
      const right = ms[mid + 1] * x + bs[mid + 1];
      if (left <= right) hi = mid;
      else lo = mid + 1;
    }
    return ms[lo] * x + bs[lo];
  }
}

function driftglassPartition(weights, k) {
  const n = weights.length;
  if (k < 1 || k > n) return -1;

  // Префиксные суммы: сумма масс первых i осколков.
  const S = new Array(n + 1).fill(0);
  for (let i = 0; i < n; i++) S[i + 1] = S[i] + weights[i];

  const INF = Infinity;

  // dpPrev[i] — минимальная энергия разбиения первых i осколков на (t-1) блок.
  // Ноль блоков возможен только для пустого префикса.
  let dpPrev = new Array(n + 1).fill(INF);
  dpPrev[0] = 0;

  for (let t = 1; t <= k; t++) {
    const dp = new Array(n + 1).fill(INF);
    const hull = new LowerHull();

    for (let i = 1; i <= n; i++) {
      // Перед запросом для префикса i добавляем точку разреза j = i-1,
      // чтобы к моменту запроса были доступны все j < i.
      const j = i - 1;
      if (dpPrev[j] !== INF) {
        // Раскрываем (S[i] - S[j])^2 = S[i]^2 - 2*S[i]*S[j] + S[j]^2.
        // Для фиксированного i это прямая по x = S[i]: наклон -2*S[j],
        // свободный член dpPrev[j] + S[j]^2. Множитель S[i]^2 вынесен наружу.
        hull.add(-2 * S[j], dpPrev[j] + S[j] * S[j]);
      }

      if (hull.size > 0) {
        dp[i] = S[i] * S[i] + hull.query(S[i]);
      }
    }

    dpPrev = dp;
  }

  return dpPrev[n];
}
