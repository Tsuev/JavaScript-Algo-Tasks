// Задача: Starlight Weave
// Сложность: hard
// Дата генерации: 2026-10-08

// Условие задачи
// # Starlight Weave
// 
// В далёкой галактике есть N звёзд, расположенных на окружности и пронумерованных от 0 до N-1 по часовой стрелке. Между любыми двумя звёздами i и j можно протянуть нить силы W[i][j]. Нить можно протягивать только между двумя разными звёздами, и никакие две нити не должны пересекаться внутри круга. Кроме того, каждая звезда может быть соединена не более чем с одной другой звездой. Требуется выбрать набор нитей, максимизирующий суммарную силу.
// 
// ## Формат входных данных
// Первая строка содержит целое число N (2 ≤ N ≤ 400). Далее следуют N строк, каждая содержит N целых чисел, разделённых пробелами. Число в i-й строке и j-м столбце равно W[i][j]. Гарантируется, что W[i][j] = W[j][i], W[i][i] = 0, и все W[i][j] — целые неотрицательные числа, не превышающие 10^9.
// 
// ## Формат выходных данных
// Одно целое число — максимальная суммарная сила выбранных нитей.
// 
// ## Пример
// Вход:
// 4
// 0 10 5 8
// 10 0 3 2
// 5 3 0 7
// 8 2 7 0
// 
// Выход:
// 17
// 
// Пояснение: Оптимально соединить звёзды 0 и 1 (сила 10) и звёзды 2 и 3 (сила 7). Суммарная сила 17. Нить 0-3 и 1-2 дают 8+3=11, нить 0-2 и 1-3 пересекаются, поэтому недопустимы.

/**
 * Решение задачи "Starlight Weave".
 * @param {string} input - входные данные в виде строки.
 * @returns {number} - максимальная суммарная сила нитей.
 */
function solve(input) {
  // Парсим вход
  const lines = input.trim().split('\n');
  const N = parseInt(lines[0], 10);
  const W = [];
  for (let i = 0; i < N; i++) {
    W.push(lines[i + 1].trim().split(/\s+/).map(Number));
  }

  // Удваиваем количество звёзд, чтобы разорвать круг
  const M = 2 * N;
  // dp[i][j] — максимальная сила для отрезка от i до j (включительно) на удвоенном массиве
  // Используем плоский массив для скорости: индекс = i * M + j
  const dp = new Array(M * M).fill(0);
  const idx = (i, j) => i * M + j;

  // Перебираем длину отрезка
  for (let len = 2; len <= N; len++) {
    for (let i = 0; i + len <= M; i++) {
      const j = i + len - 1;
      // Вариант 1: звезда i остаётся без нити
      let best = dp[idx(i + 1, j)];
      // Вариант 2: звезда i соединяется с k
      for (let k = i + 1; k <= j; k++) {
        const left = (i + 1 <= k - 1) ? dp[idx(i + 1, k - 1)] : 0;
        const right = (k + 1 <= j) ? dp[idx(k + 1, j)] : 0;
        const val = W[i % N][k % N] + left + right;
        if (val > best) best = val;
      }
      dp[idx(i, j)] = best;
    }
  }

  // Ответ — максимум по всем разрезам круга (интервалам длины N)
  let ans = 0;
  for (let i = 0; i < N; i++) {
    const val = dp[idx(i, i + N - 1)];
    if (val > ans) ans = val;
  }
  return ans;
}
