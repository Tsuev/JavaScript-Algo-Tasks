// Условие задачи
// Ночью над солончаковым болотом вспыхивают светлячки. Про каждого светлячка известно, что он светится непрерывно в течение промежутка времени от start_i до end_i. Наблюдатель ведёт журнал (ledger): сессией называется максимальный непрерывный промежуток времени, в течение которого светится хотя бы один светлячок. Если два промежутка пересекаются или хотя бы соприкасаются (конец одного не меньше начала другого), они относятся к одной сессии.
// 
// Требуется определить: сколько всего сессий, каково суммарное время свечения (длина объединения всех промежутков) и какова длительность самой долгой сессии.
// 
// Формат ввода:
// - первая строка — целое n (1 ≤ n ≤ 100000) — количество светлячков;
// - далее n строк, в каждой по два целых числа start_i и end_i (0 ≤ start_i < end_i ≤ 10^9) — промежуток свечения очередного светлячка.
// 
// Формат результата:
// Одна строка с тремя целыми числами через пробел: количество сессий, суммарное время свечения, длительность самой долгой сессии.
// 
// Пример:
// Ввод:
// 4
// 1 4
// 2 5
// 7 9
// 8 10
// Вывод:
// 2 7 4
// 
// Пояснение к примеру: промежутки [1,4] и [2,5] сливаются в [1,5] длиной 4, а [7,9] и [8,10] — в [7,10] длиной 3. Получаем 2 сессии, суммарное время свечения 7, самая долгая сессия длиной 4.
// 
// Граничный случай: [1,3] и [3,5] считаются одной сессией, потому что соприкасаются; её длина равна (5−1) = 4.

function fireflyLedger(intervals) {
  // Без светлячков журнал пуст.
  if (intervals.length === 0) {
    return { sessions: 0, totalGlow: 0, longest: 0 };
  }

  // Сортируем по левой границе: так все отрезки, которые могут
  // слиться в одну сессию, окажутся рядом.
  const sorted = [...intervals].sort((a, b) => a[0] - b[0] || a[1] - b[1]);

  let sessions = 0;   // сколько непрерывных сессий уже закрыли
  let totalGlow = 0;  // суммарное время свечения
  let longest = 0;    // длительность самой долгой сессии

  let curStart = sorted[0][0];
  let curEnd = sorted[0][1];

  for (let i = 1; i < sorted.length; i++) {
    const [s, e] = sorted[i];
    if (s <= curEnd) {
      // Отрезок пересекается или касается текущей сессии — продлеваем её.
      if (e > curEnd) curEnd = e;
    } else {
      // Между отрезками есть разрыв: фиксируем закрытую сессию.
      const len = curEnd - curStart;
      sessions++;
      totalGlow += len;
      if (len > longest) longest = len;
      curStart = s;
      curEnd = e;
    }
  }

  // Последнюю сессию закрываем отдельно, уже после цикла.
  const lastLen = curEnd - curStart;
  sessions++;
  totalGlow += lastLen;
  if (lastLen > longest) longest = lastLen;

  return { sessions, totalGlow, longest };
}
