// Задача: Tidal Lantern Relay
// Сложность: hard
// Дата генерации: 2026-09-22

// Условие задачи
// Вы находитесь на острове 1 и должны доставить фонарь на остров N. Всего есть N островов и M мостов. Каждый мост соединяет два острова и может быть пройден только тогда, когда уровень прилива не меньше определённого значения. Уровень прилива меняется периодически с периодом T. В момент времени t (t >= 0) уровень прилива равен tide[t mod T]. Вы можете перейти мост в момент времени t, если tide[t mod T] >= требуемый уровень для этого моста. Переход по мосту занимает ровно 1 единицу времени. Вы можете ждать на острове любое количество времени. Вы начинаете на острове 1 в момент времени 0. Найдите минимальное время, в которое вы сможете оказаться на острове N. Если это невозможно, верните -1.
// 
// Формат входных данных:
// - Первая строка: N M T
// - Вторая строка: T целых чисел tide[0..T-1]
// - Следующие M строк: u v h (острова нумеруются с 1, мост между u и v, требует уровень прилива >= h)
// 
// Формат выходных данных:
// - Одно число — минимальное время прибытия на остров N, или -1.
// 
// Пример:
// Вход:
// 3 2 4
// 1 2 1 3
// 1 2 1
// 2 3 2
// 
// Выход:
// 2
// 
// Пояснение к примеру:
// В момент 0 уровень прилива 1. Переходим мост 1-2 (требует 1), оказываемся на острове 2 в момент 1. В момент 1 уровень прилива 2. Переходим мост 2-3 (требует 2), оказываемся на острове 3 в момент 2. Ответ 2.
// 
// Ограничения:
// 1 <= N <= 1000
// 1 <= M <= 5000
// 1 <= T <= 1000
// 0 <= tide[i] <= 10^9
// 1 <= h <= 10^9

/**
 * Задача Tidal Lantern Relay.
 * 
 * @param {number} N - количество островов
 * @param {number} M - количество мостов
 * @param {number} T - период прилива
 * @param {number[]} tide - массив уровней прилива длины T
 * @param {number[][]} edges - список мостов [u, v, h]
 * @returns {number} - минимальное время прибытия на остров N или -1
 */
function solve(N, M, T, tide, edges) {
    // Список смежности: для каждого острова храним пары (сосед, требуемый уровень прилива)
    const adj = Array.from({ length: N + 1 }, () => []);
    for (const [u, v, h] of edges) {
        adj[u].push({ to: v, h });
        adj[v].push({ to: u, h });
    }

    // visited[остров][время по модулю T] — были ли мы в этом состоянии
    const visited = Array.from({ length: N + 1 }, () => new Array(T).fill(false));
    
    // Очередь для BFS: [остров, время по модулю T, реальное время]
    const queue = [];
    let head = 0;
    
    // Стартуем с острова 1 в момент времени 0
    queue.push([1, 0, 0]);
    visited[1][0] = true;

    while (head < queue.length) {
        const [u, tMod, time] = queue[head++];

        // Если достигли цели, возвращаем время
        if (u === N) {
            return time;
        }

        const nextTMod = (tMod + 1) % T;

        // 1) Ожидание на острове: остаёмся на u, время увеличивается на 1
        if (!visited[u][nextTMod]) {
            visited[u][nextTMod] = true;
            queue.push([u, nextTMod, time + 1]);
        }

        // 2) Переход по мостам: если текущий уровень прилива достаточен
        const currentTide = tide[tMod];
        for (const { to, h } of adj[u]) {
            if (currentTide >= h && !visited[to][nextTMod]) {
                visited[to][nextTMod] = true;
                queue.push([to, nextTMod, time + 1]);
            }
        }
    }

    // Если цель недостижима
    return -1;
}
