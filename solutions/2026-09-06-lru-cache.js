// Задача: LRU Cache
// Сложность: hard
// Дата генерации: 2026-09-06

// Условие задачи
// Необходимо реализовать структуру данных для кэша с политикой вытеснения LRU (Least Recently Used).
// 
// Кэш имеет ограниченную ёмкость. Нужно реализовать класс LRUCache:
// 
// - LRUCache(capacity) — создаёт кэш ёмкости capacity.
// - int get(int key) — возвращает значение ключа если он присутствует в кэше, иначе -1.
// - void put(int key, int value) — обновляет значение ключа, если он существует; если нет — добавляет пару. При вставке, если количество ключей превышает ёмкость, удаляется наименее недавно использованный ключ.
// 
// Все операции должны выполняться за O(1) в среднем.
// 
// Формат входных данных:
// На вход подаётся массив команд commands и массив аргументов args, где commands[i] — название метода, args[i] — массив параметров. Для конструктора команда — "LRUCache" и args[i] содержит один элемент capacity. Для get — args[i] содержит один ключ. Для put — args[i] содержит два элемента: ключ и значение. Результатом является массив, в котором на месте вызова конструктора стоит null, на месте put — null, на месте get — значение или -1.
// 
// Пример:
// 
// commands = ["LRUCache", "put", "put", "get", "put", "get", "put", "get", "get", "get"]
// args = [[2], [1, 1], [2, 2], [1], [3, 3], [2], [4, 4], [1], [3], [4]]
// Выход: [null, null, null, 1, null, -1, null, -1, 3, 4]
// 
// Пояснение:
// LRUCache cache = new LRUCache(2);
// cache.put(1, 1);
// cache.put(2, 2);
// cache.get(1);    // возвращает 1
// cache.put(3, 3); // удаляется ключ 2
// cache.get(2);    // возвращает -1 (не найден)
// cache.put(4, 4); // удаляется ключ 1
// cache.get(1);    // возвращает -1
// cache.get(3);    // возвращает 3
// cache.get(4);    // возвращает 4
// 
// Ограничения:
// - 1 ≤ capacity ≤ 3000
// - количество вызовов методов до 2 * 10^5
// - ключи и значения — целые числа

class LRUCache {
    constructor(capacity) {
        this.capacity = capacity;
        this.map = new Map(); // В Map ключи упорядочены по времени добавления, поэтому самый левый — самый старый.
    }

    get(key) {
        if (!this.map.has(key)) {
            return -1;
        }
        // Перемещаем ключ в конец, чтобы отметить его как недавно использованный.
        const value = this.map.get(key);
        this.map.delete(key);
        this.map.set(key, value);
        return value;
    }

    put(key, value) {
        // Если ключ уже есть — удаляем старую запись.
        if (this.map.has(key)) {
            this.map.delete(key);
        }
        this.map.set(key, value);
        // Если размер превысил ёмкость — удаляем самый давний ключ.
        if (this.map.size > this.capacity) {
            const oldestKey = this.map.keys().next().value;
            this.map.delete(oldestKey);
        }
    }
}
