// Задача: Tesseract Traversal
// Сложность: hard
// Дата генерации: 2026-09-28

// Условие задачи
// Гиперкуб размерности n — это граф, вершины которого соответствуют всем n-битным строкам, а рёбра соединяют вершины, различающиеся ровно в одном бите. Тетракт — это гиперкуб размерности 4.
// 
// Вам даны:
// - n (1 ≤ n ≤ 4) — размерность гиперкуба;
// - start — стартовая вершина, строка длины n из символов '0' и '1';
// - end — конечная вершина, строка длины n из символов '0' и '1';
// - blocked — массив запрещённых вершин (строк длины n). Эти вершины нельзя посещать.
// 
// Требуется найти количество гамильтоновых путей из start в end, которые проходят через все разрешённые вершины ровно по одному разу. Гамильтонов путь — это путь, начинающийся в start, заканчивающийся в end и посещающий каждую разрешённую вершину ровно один раз. Если start или end запрещены, ответ 0.
// 
// Формат входных данных:
// Функция принимает:
// - n: целое число (1 ≤ n ≤ 4)
// - start: строка длины n
// - end: строка длины n
// - blocked: массив строк длины n (может быть пустым)
// 
// Формат результата:
// Целое число — количество гамильтоновых путей.
// 
// Пример 1:
// n = 2, start = "00", end = "01", blocked = []
// В гиперкубе Q2 (квадрат) вершины: 00, 01, 10, 11. Рёбра: 00-01, 00-10, 01-11, 10-11.
// Гамильтоновы пути из 00 в 01: 00 -> 10 -> 11 -> 01. Ответ: 1.
// 
// Пример 2:
// n = 2, start = "00", end = "11", blocked = []
// Гамильтоновых путей из 00 в 11 нет, так как путь должен иметь нечётную длину (3 ребра), а вершины 00 и 11 имеют одинаковую чётность. Ответ: 0.
// 
// Пример 3:
// n = 2, start = "00", end = "11", blocked = ["01"]
// Разрешённые вершины: 00, 10, 11. Гамильтонов путь: 00 -> 10 -> 11. Ответ: 1.

function tesseractTraversal(n, start, end, blocked) {
  // Преобразуем битовые строки в целые числа (индексы вершин от 0 до 2^n - 1)
  const startIdx = parseInt(start, 2);
  const endIdx = parseInt(end, 2);
  const totalVertices = 1 << n; // всего вершин в гиперкубе

  // Массив разрешённых вершин: true, если вершину можно посещать
  const allowed = new Array(totalVertices).fill(true);
  for (const b of blocked) {
    allowed[parseInt(b, 2)] = false;
  }

  // Если старт или финиш запрещены, путей нет
  if (!allowed[startIdx] || !allowed[endIdx]) {
    return 0;
  }

  // Собираем маску всех разрешённых вершин
  let fullMask = 0;
  for (let v = 0; v < totalVertices; v++) {
    if (allowed[v]) fullMask |= (1 << v);
  }

  // dp[mask][v] — количество способов посетить множество вершин mask, закончив в v
  // Размер mask: от 0 до (1 << totalVertices) - 1
  const maxMask = 1 << totalVertices;
  const dp = Array.from({ length: maxMask }, () => new Array(totalVertices).fill(0));

  // Начинаем с start: посещена только стартовая вершина
  dp[1 << startIdx][startIdx] = 1;

  // Перебираем все маски
  for (let mask = 1; mask < maxMask; mask++) {
    // Стартовая вершина обязательно должна быть в маске
    if ((mask & (1 << startIdx)) === 0) continue;

    // Перебираем последнюю вершину пути
    for (let v = 0; v < totalVertices; v++) {
      if (!(mask & (1 << v))) continue; // v не входит в маску
      const ways = dp[mask][v];
      if (ways === 0) continue;

      // Перебираем соседей v — вершины, отличающиеся ровно одним битом
      for (let bit = 0; bit < n; bit++) {
        const u = v ^ (1 << bit);
        // Сосед должен быть разрешён и ещё не посещён
        if (allowed[u] && !(mask & (1 << u))) {
          const newMask = mask | (1 << u);
          dp[newMask][u] += ways;
        }
      }
    }
  }

  // Ответ — число путей, посетивших все разрешённые вершины и закончившихся в end
  return dp[fullMask][endIdx];
}
