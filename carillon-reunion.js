// Задача: Carillon Reunion
// Сложность: medium
// Дата генерации: 2026-09-29

// Условие задачи
// В старинном городе Кэррильон есть n колоколен, и каждая звонит по своему расписанию. Колокол номер i впервые звонит в момент времени a_i (секунд после полудня), а затем звонит строго периодически — каждые p_i секунд, то есть в моменты a_i, a_i + p_i, a_i + 2p_i, …
// 
// Мэрия готовит праздник и хочет выбрать момент t ≥ 0, когда звонят все n колоколов одновременно («созвучие»). Найдите самый ранний такой момент.
// 
// ВХОДНЫЕ ДАННЫЕ.
// Первая строка — целое число n (1 ≤ n ≤ 1000). Следующие n строк содержат по два целых числа a_i и p_i (0 ≤ a_i ≤ 10^9, 1 ≤ p_i ≤ 10^9) — время первого звонка и период i-го колокола.
// 
// В терминах функции решение принимает массив bells длины n, где bells[i] = [a_i, p_i].
// 
// ВЫХОДНЫЕ ДАННЫЕ.
// Одно число — самый ранний момент t ≥ 0, в который звонят все колокола, либо −1, если такого момента не существует. Ответ может быть очень большим (больше 2^63), поэтому его нужно возвращать десятичной строкой и считать с длинной арифметикой (BigInt).
// 
// ПРИМЕР 1.
// Вход:
// 3
// 0 2
// 1 3
// 0 5
// Ответ: 10.
// Первый колокол звонит в 0,2,4,6,8,10; второй — в 1,4,7,10; третий — в 0,5,10. Раньше момента 10 все три вместе не звонят.
// 
// ПРИМЕР 2.
// Вход:
// 2
// 0 4
// 1 6
// Ответ: -1.
// Первый колокол звонит только в чётные моменты, второй — в моменты вида 1 + 6k, то есть нечётные. Одновременно они не зазвонят никогда.
// 
// ПРИМЕР 3.
// Вход:
// 2
// 100 7
// 0 3
// Ответ: 114.
// Условия t ≡ 2 (mod 7) и t ≡ 0 (mod 3) дают t ≡ 9 (mod 21), но 9 слишком рано: первый колокол к этому времени ещё ни разу не звонил. Ближайшее подходящее время, не меньшее 100, — это 114.

/*
 * Задача сводится к системе сравнений:
 *   t ≡ a_i (mod p_i)   для всех i
 * Ранний момент t — это наименьшее неотрицательное решение системы,
 * которое вдобавок не меньше max(a_i) (каждый колокол должен успеть прозвенеть).
 *
 * Систему сравнений с не взаимно простыми модулями решаем
 * обобщённой китайской теоремой об остатках: постепенно объединяем
 * пары (t ≡ R (mod M)) и (t ≡ A (mod P)). Если на очередном шаге
 * gcd(M, P) не делит (A - R), решения нет вовсе.
 * Все вычисления — в BigInt: модули перемножаются и ответ может быть огромным.
 */
function carillonReunion(bells) {
  // Обычный НОД для BigInt.
  const gcd = (a, b) => {
    while (b !== 0n) {
      const r = a % b;
      a = b;
      b = r;
    }
    return a;
  };

  // Расширенный алгоритм Евклида: возвращает [g, x, y], где a*x + b*y = g.
  const egcd = (a, b) => {
    if (b === 0n) return [a, 1n, 0n];
    const [g, x, y] = egcd(b, a % b);
    return [g, y, x - (a / b) * y];
  };

  // Неотрицательный остаток: в JS знак % следует за делимым, а нам нужен 0..m-1.
  const mod = (x, m) => ((x % m) + m) % m;

  let R = 0n; // текущее решение: t ≡ R (mod M)
  let M = 1n; // текущий модуль
  let T = 0n; // самый поздний первый звонок среди колоколов

  for (const [a, p] of bells) {
    const A = BigInt(a);
    const P = BigInt(p);
    if (A > T) T = A;

    // Объединяем t ≡ R (mod M) и t ≡ A (mod P).
    const g = gcd(M, P);
    const diff = A - R;

    // Система несовместна — одновременного звона не случится никогда.
    if (mod(diff, g) !== 0n) return '-1';

    // Из M*k ≡ diff (mod P) получаем (M/g)*k ≡ diff/g (mod P/g).
    // Модуль P/g взаимно прост с M/g, значит обратный элемент существует.
    const Mp = M / g;
    const Pp = P / g;
    const dp = mod(diff / g, Pp);
    const inverse = mod(egcd(mod(Mp, Pp), Pp)[1], Pp);
    const k = mod(dp * inverse, Pp);

    R = R + M * k;
    M = M * Pp; // новое значение — это lcm(M, P) = M * (P / g)
  }

  // R — наименьшее неотрицательное решение системы, но каждый колокол
  // обязан прозвенеть хотя бы раз, поэтому поднимаем ответ до T шагами по M.
  if (R < T) {
    const steps = (T - R + M - 1n) / M; // округление вверх
    R += steps * M;
  }

  return R.toString();
}
