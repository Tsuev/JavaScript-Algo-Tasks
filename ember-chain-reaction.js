// Задача: Ember Chain Reaction
// Сложность: hard
// Дата генерации: 2026-09-21

// Условие задачи
// **Ember Chain Reaction (Цепная реакция угольков)**
// 
// Вдоль прямой линии выложены n угольков, пронумерованных от 1 до n. Уголёк с номером i обладает силой a[i]: как только он загорается, он мгновенно поджигает каждый уголёк j, для которого |i − j| ≤ a[i] (все угольки в радиусе a[i], включая себя). Загоревшиеся угольки, в свою очередь, поджигают соседей по тому же правилу — возникает цепная реакция.
// 
// Некоторые угольки разрешено поджечь вручную. Ручное поджигание уголька i стоит c[i] монет. Требуется, чтобы в итоге горели все n угольков; минимизируйте суммарную стоимость ручных поджиганий (угольки, загоревшиеся от реакции, бесплатны).
// 
// **Входные данные**
// - Первая строка: целое число n (1 ≤ n ≤ 3000).
// - Вторая строка: n целых чисел a[1..n] (0 ≤ a[i] ≤ n) — силы угольков.
// - Третья строка: n целых чисел c[1..n] (1 ≤ c[i] ≤ 10^9) — стоимости ручного поджигания.
// 
// **Результат**
// Одно число — минимальная суммарная стоимость. Ответ существует всегда: можно поджечь вручную каждый уголёк.
// 
// **Пример 1**
// Вход:
// 5
// 1 0 2 0 0
// 3 10 4 5 1
// Выход:
// 4
// Пояснение: поджигаем вручную уголёк 3 за 4 монеты. Его радиус 2, поэтому он поджигает угольки 1, 2, 4 и 5. Все горят. Дешевле не получится: уголёк 3 (позиция 3) накрывается только своим же интервалом [1, 5], значит его радиус обязателен, а стоит он 4.
// 
// **Пример 2**
// Вход:
// 4
// 0 3 0 0
// 1 5 1 1
// Выход:
// 5
// Пояснение: уголёк 2 имеет силу 3 и поджигает сразу всё (расстояние до 1 и до 4 равно 2 ≤ 3). Но накрыть сам уголёк 2 может только он сам — у остальных сила 0, поэтому без его ручного поджигания за 5 монет не обойтись.
// 
// **Формат решения**
// Функция minIgnitionCost(n, a, c), где a и c — массивы длины n (0-индексация соответствует уголькам 1..n), возвращающая минимальную суммарную стоимость.

/**
 * Ember Chain Reaction.
 *
 * n угольков стоят в ряд. Уголёк i, загоревшись, поджигает все угольки
 * в радиусе a[i], а те — дальше (цепная реакция). Ручное поджигание
 * уголька i стоит c[i]. Нужно сжечь все угольки за минимальные деньги.
 *
 * Идея решения:
 *   1) Для каждого i находим отрезок [left[i], right[i]] угольков, которые
 *      сгорят, если вручную поджечь только i. Ключевое наблюдение: множество
 *      горящих угольков всегда непрерывно, поэтому это именно интервал.
 *      Обход в ширину по «прямым» радиусам; суммарно O(n^2) в худшем случае.
 *   2) Задача превращается в минимальное по стоимости покрытие отрезка [1..n]
 *      интервалами [left[i], right[i]] с ценой c[i]. Обычное ДП по префиксу,
 *      ускоренное кучей: O(n log n).
 */
function minIgnitionCost(n, a, c) {
  // ---------- Шаг 1: границы цепной реакции для каждого уголька ----------

  // Прямое поджигание уголька j (1-индексация) накрывает отрезок [lf[j], rg[j]].
  const lf = new Int32Array(n + 2);
  const rg = new Int32Array(n + 2);
  for (let j = 1; j <= n; j++) {
    lf[j] = Math.max(1, j - a[j - 1]);
    rg[j] = Math.min(n, j + a[j - 1]);
  }

  const left = new Int32Array(n + 1);
  const right = new Int32Array(n + 1);
  // Метка version вместо очистки: seen[x] === version значит «x уже в очереди».
  const seen = new Int32Array(n + 1);
  const queue = new Int32Array(n + 1);
  let version = 0;

  for (let i = 1; i <= n; i++) {
    version++;
    let head = 0, tail = 0;
    queue[tail++] = i;
    seen[i] = version;
    let lo = i, hi = i;

    // Множество горящих угольков непрерывно: добавляя к уже горящему отрезку
    // прямой радиус нового уголька, мы снова получаем отрезок. Поэтому храним
    // только две границы и расширяем их, пока это возможно.
    while (head < tail) {
      const j = queue[head++];
      if (lf[j] < lo) {
        // Новые позиции слева достижимы напрямую из j, добавляем их в очередь.
        for (let t = lf[j]; t < lo; t++) {
          if (seen[t] !== version) { seen[t] = version; queue[tail++] = t; }
        }
        lo = lf[j];
      }
      if (rg[j] > hi) {
        for (let t = hi + 1; t <= rg[j]; t++) {
          if (seen[t] !== version) { seen[t] = version; queue[tail++] = t; }
        }
        hi = rg[j];
      }
    }
    left[i] = lo;
    right[i] = hi;
  }

  // ---------- Шаг 2: минимальное по стоимости покрытие [1..n] ----------

  // Группируем интервалы по их левой границе: интервал становится кандидатом,
  // когда мы доходим сканированием до его начала.
  const byStart = Array.from({ length: n + 2 }, () => []);
  for (let i = 1; i <= n; i++) byStart[left[i]].push(i);

  // Мини-куча из пар (стоимость, правая граница), реализованная двумя
  // параллельными массивами — компактнее и быстрее, чем массив объектов.
  const hCost = [];
  const hEnd = [];

  function push(cost, end) {
    let i = hCost.length;
    hCost.push(cost);
    hEnd.push(end);
    while (i > 0) {
      const p = (i - 1) >> 1;
      if (hCost[p] <= hCost[i]) break;
      const tc = hCost[p]; hCost[p] = hCost[i]; hCost[i] = tc;
      const te = hEnd[p]; hEnd[p] = hEnd[i]; hEnd[i] = te;
      i = p;
    }
  }

  function popMin() {
    const last = hCost.length - 1;
    hCost[0] = hCost[last];
    hEnd[0] = hEnd[last];
    hCost.pop();
    hEnd.pop();
    let i = 0;
    const size = hCost.length;
    while (true) {
      const l = 2 * i + 1, r = 2 * i + 2;
      let best = i;
      if (l < size && hCost[l] < hCost[best]) best = l;
      if (r < size && hCost[r] < hCost[best]) best = r;
      if (best === i) break;
      const tc = hCost[best]; hCost[best] = hCost[i]; hCost[i] = tc;
      const te = hEnd[best]; hEnd[best] = hEnd[i]; hEnd[i] = te;
      i = best;
    }
  }

  const INF = Infinity;
  // dp[r] — минимум денег, при котором гарантированно горят угольки 1..r.
  // Если позицию r накрывает интервал i (left[i] <= r <= right[i]), то вариант
  // такой: заплатить c[i] и отдельно оплатить префикс 1..left[i]-1.
  const dp = new Array(n + 1).fill(INF);
  dp[0] = 0;

  for (let r = 1; r <= n; r++) {
    // Интервалы, начинающиеся в r, становятся доступными кандидатами.
    for (const i of byStart[r]) push(c[i - 1] + dp[left[i] - 1], right[i]);
    // Ленивое удаление: выкидываем тех, кто закончился левее текущей позиции.
    while (hCost.length > 0 && hEnd[0] < r) popMin();
    // Наверху кучи — самый дешёвый способ накрыть позицию r.
    dp[r] = hCost.length > 0 ? hCost[0] : INF;
  }

  // Каждый уголёк накрывает сам себя, поэтому dp[n] всегда конечно.
  return dp[n];
}
