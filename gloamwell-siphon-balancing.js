// Условие задачи
// ## Gloamwell Siphon Balancing
// 
// Вокруг колодца Глоамвелл по кругу стоят `n` сифонов, качающих глоум (тьму). В сифоне с номером `i` сейчас находится `a[i]` единиц глоума (нумерация с 0, соседними считаются сифоны `i-1` и `i+1` по модулю `n`, то есть первый и последний сифоны тоже соседи).
// 
// За одну операцию разрешается перелить **одну** единицу глоума из любого сифона в любой соседний с ним по кругу. Требуется за минимальное число операций сделать так, чтобы во всех сифонах стало одинаковое количество глоума. Если это невозможно (общий объём глоума не делится нацело на число сифонов), верните `-1`.
// 
// **Входные данные.** Массив целых неотрицательных чисел `a` длины `n` — текущее количество глоума в сифонах. Ограничения: `1 <= n <= 2*10^5`, `0 <= a[i] <= 10^9`.
// 
// **Выходные данные.** Одно целое число — минимальное количество операций переливания или `-1`, если уравнять сифоны нельзя.
// 
// **Примеры.**
// 
// 1. `a = [1, 3]` → `1`. В среднем должно быть по 2 единицы; переливаем одну единицу из второго сифона в первый (они соседи).
// 2. `a = [1, 2, 3]` → `1`. Нужно по 2 единицы; первый и третий сифоны соседи по кругу, поэтому одной операцией переносим единицу из третьего в первый.
// 3. `a = [4, 0, 0, 0]` → `4`. Нужно по 1 единице. Из первого сифона одна единица уходит соседу слева (1 операция), одна — соседу справа (1 операция), а одна должна дойти до дальнего сифона за 2 операции. Итого `1 + 1 + 2 = 4`.
// 4. `a = [0, 3]` → `-1`: сумма равна 3, на два сифона поровну не делится.
// 5. `a = [2, 2, 2]` → `0`.
// 
// Идея решения: считаем «перекосы» — накопленные отклонения от среднего. Каждое ребро круга должно пропустить через себя ровно этот перекос (со знаком), а стоимость — сумма модулей этих потоков. Особенность круга в том, что через замыкающее ребро тоже может что-то течь, поэтому все перекосы можно сдвинуть на одну и ту же величину `x`; сумма `|s[i] - x|` минимальна, когда `x` — медиана массива перекосов.

function balanceSiphons(a) {
  const n = a.length;
  if (n === 0) return 0;

  const total = a.reduce((sum, v) => sum + v, 0);

  // Уровень во всех сифонах должен быть целым: разлить «дробную» единицу нельзя.
  if (total % n !== 0) return -1;
  const avg = total / n;

  // s[i] — накопленный перекос на границе между сифоном i и i+1.
  // Ровно столько глоума (с учётом знака) обязано протечь через это ребро,
  // иначе баланс слева от границы не сойдётся.
  const s = new Array(n);
  let acc = 0;
  for (let i = 0; i < n; i++) {
    acc += a[i] - avg;
    s[i] = acc;
  }
  // Последний перекос всегда 0: суммарное отклонение по всем сифонам равно нулю.

  // Отличие круга от прямой: через замыкающее ребро тоже может течь поток.
  // Если пустить через него x единиц, стоимость станет суммой |s[i] - x|,
  // а такая сумма минимальна, когда x — медиана массива перекосов.
  const sorted = [...s].sort((x, y) => x - y);
  const median = sorted[n >> 1];

  let moves = 0;
  for (const v of s) moves += Math.abs(v - median);

  return moves;
}
