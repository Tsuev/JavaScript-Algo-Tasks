// Задача: Cinderfall Crossing
// Сложность: medium
// Дата генерации: 2026-10-18

// Условие задачи
// «Синдерфолл Кроссинг»
// 
// Через реку расплавленной лавы перекинуто n камней. Левый берег — это старт, правый — финиш. Пронумеруем камни слева направо числами 1..n, левый берег считаем позицией 0, правый берег — позицией n+1.
// 
// У каждого камня i есть свой «жар» h[i]. Стоять на камне больно: каждая остановка на камне i добавляет h[i] к суммарному урону. Берега безопасны, урон за них равен 0.
// 
// Прыгать можно только вправо и не дальше чем на k позиций за один прыжок: находясь в позиции p, можно прыгнуть в любую позицию q, для которой p < q ≤ p + k. Прыгать назад нельзя.
// 
// Нужно добраться с левого берега (позиция 0) на правый (позиция n+1), минимизировав суммарный урон от камней, на которые приходится приземляться.
// 
// Формат входных данных:
// — в первой строке два целых числа: n (количество камней) и k (максимальная длина прыжка), 1 ≤ n ≤ 10^6, 1 ≤ k ≤ 10^9;
// — во второй строке n целых чисел h[1], h[2], ..., h[n] — жар каждого камня, 0 ≤ h[i] ≤ 10^9.
// 
// Формат результата:
// — одно целое число: минимально возможный суммарный урон.
// 
// Пример 1:
// Вход:
// 5 3
// 3 1 4 1 5
// Выход:
// 2
// Пояснение: прыжки 0 → 2 → 4 → 6 дают урон h[2] + h[4] = 1 + 1 = 2, и каждое расстояние не больше 3.
// 
// Пример 2:
// Вход:
// 3 5
// 4 4 4
// Выход:
// 0
// Пояснение: расстояние от берега до берега равно 4, а k = 5, поэтому можно перепрыгнуть реку одним прыжком и не касаться камней.
// 
// Пример 3:
// Вход:
// 4 1
// 2 7 3 9
// Выход:
// 21
// Пояснение: при k = 1 прыгать можно только на соседний камень, поэтому придётся наступить на все: 2 + 7 + 3 + 9 = 21.

/**
 * Минимальный суммарный урон при переправе с левого берега на правый.
 *
 * Идея: пусть dp[i] — минимальный урон, если последней точкой остановки
 * была позиция i (0 — левый берег, 1..n — камни, n+1 — правый берег).
 * Тогда dp[i] = (урон за приземление в i) + min(dp[j]) по всем j из окна
 * [i - k, i - 1]. Минимум в скользящем окне поддерживаем монотонной очередью,
 * поэтому весь проход занимает O(n).
 *
 * @param {number} n количество камней
 * @param {number} k максимальная длина прыжка
 * @param {number[]} heat массив жары камней (heat[0] — камень 1)
 * @returns {number} минимальный суммарный урон
 */
function minHeatToCross(n, k, heat) {
  // dp[0] = 0 — на левом берегу мы уже стоим бесплатно.
  const dp = new Array(n + 2).fill(0);

  // Монотонная очередь индексов: значения dp по ней строго возрастают,
  // значит голова очереди всегда даёт лучший (минимальный) вариант в окне.
  const dq = new Array(n + 2);
  let head = 0;
  let tail = 0;
  dq[tail++] = 0;

  for (let i = 1; i <= n + 1; i++) {
    // Убираем из окна точки, до которых уже не дотянуться прыжком длины k.
    while (head < tail && dq[head] < i - k) head++;

    // Урон за приземление: камень греет, а берега безопасны.
    const landCost = i <= n ? heat[i - 1] : 0;
    dp[i] = dp[dq[head]] + landCost;

    // Поддерживаем монотонность: более дорогие варианты позади нас
    // уже никогда не пригодятся, пока в очереди есть этот, более дешёвый.
    while (head < tail && dp[dq[tail - 1]] >= dp[i]) tail--;
    dq[tail++] = i;
  }

  return dp[n + 1];
}
