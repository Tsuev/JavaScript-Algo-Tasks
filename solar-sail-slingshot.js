// Задача: Solar Sail Slingshot
// Сложность: medium
// Дата генерации: 2026-09-24

// Условие задачи
// Космический корабль с солнечным парусом летит через звёздную систему. На его пути ровно n планет, пронумерованных в порядке встречи: 1, 2, ..., n. Перед первой планетой скорость корабля равна v0.
// 
// Пролетая планету i, корабль выполняет ровно один из трёх вариантов:
//   • солнечный парус — скорость увеличивается на s[i];
//   • гравитационный манёвр («праща») — скорость умножается на k[i];
//   • пропуск планеты — скорость не меняется.
// 
// Ограничения:
//   1. Гравитационный манёвр нельзя выполнять на двух подряд идущих планетах. Если на планете i была праща, то на планете i+1 разрешён только парус или пропуск; на планете i+2 праща снова разрешена.
//   2. Скорость никогда не может превысить C: если манёвр даёт больше, скорость становится ровно C. Например, при v0 = 10, C = 25 и k = 5 праща даёт 25, а не 50.
// 
// Найдите максимально возможную скорость корабля после того, как он пролетит все n планет.
// 
// Формат входных данных (аргументы функции):
//   solve(n, v0, C, s, k)
//     n  — число планет, 0 <= n <= 200000;
//     v0 — начальная скорость, 0 <= v0 <= 10^9;
//     C  — предельная скорость, 1 <= C <= 10^9;
//     s  — массив длины n, 0 <= s[i] <= 10^9;
//     k  — массив длины n, 1 <= k[i] <= 10^9.
// 
// Формат результата: одно целое число — максимальная скорость после всех планет.
// 
// Пример 1
//   Вход: n = 5, v0 = 2, C = 1000, s = [3, 10, 0, 5, 7], k = [2, 1, 4, 3, 2]
//   Выход: 130
//   Пояснение: 2 --(+3)--> 5 --(+10)--> 15 --(x4)--> 60 --(+5)--> 65 --(x2)--> 130. Пращи стоят не подряд.
// 
// Пример 2
//   Вход: n = 3, v0 = 5, C = 50, s = [0, 0, 0], k = [3, 3, 3]
//   Выход: 45
//   Пояснение: две пращи подряд запрещены, поэтому берём пращу только на 1-й и 3-й планетах: 5 --(x3)--> 15 --(пропуск)--> 15 --(x3)--> 45.
// 
// Пример 3
//   Вход: n = 1, v0 = 10, C = 25, s = [1], k = [5]
//   Выход: 25
//   Пояснение: парус дал бы 11, праща дала бы 50, но предел C = 25.

/**
 * Solar Sail Slingshot — динамика по планетам за O(n) времени и O(1) памяти.
 *
 * Для каждой планеты храним два числа:
 *   A — лучшая скорость, если на этой планете гравитационного манёвра НЕ было
 *       (был солнечный парус или планету пропустили);
 *   B — лучшая скорость, если на этой планете гравитационный манёвр БЫЛ.
 *
 * Почему можно помнить только максимум внутри каждого состояния: любое действие
 * (прибавить s[i], умножить на k[i], ограничить сверху C) — монотонная функция
 * от текущей скорости. Большая скорость никогда не приводит к худшему результату
 * в будущем, поэтому медленные варианты одного и того же состояния можно выбрасывать.
 *
 * Запрет «двух пращей подряд» учитывается тем, что состояние B на планете i
 * получается только из состояния A на планете i-1.
 */
function solve(n, v0, C, s, k) {
  // Перед первой планетой пращи ещё не было — это состояние A.
  let A = v0 < C ? v0 : C;
  // Состояние «праща была на планете 0» недостижимо; -1 играет роль минус бесконечности.
  let B = -1;

  for (let i = 0; i < n; i++) {
    // Скорость, с которой корабль подлетает к планете i.
    const incoming = A > B ? A : B;

    // Вариант 1: солнечный парус. Отдельно рассматривать пропуск планеты не нужно:
    // s[i] >= 0, значит парус даёт скорость не меньше, а дальнейшие операции монотонны.
    let nextA = incoming + s[i];
    if (nextA > C) nextA = C;

    // Вариант 2: гравитационная праща. Она разрешена, только если на предыдущей
    // планете пращи не было, то есть переходим именно из состояния A.
    // Произведение A * k[i] может превысить 2^53, но тогда оно заведомо больше C <= 10^9,
    // поэтому сравнение с C и обрезка до C всё равно дают правильный результат.
    let nextB = A * k[i];
    if (nextB > C) nextB = C;

    A = nextA;
    B = nextB;
  }

  // Победитель — лучшее из двух состояний на последней планете.
  return A > B ? A : B;
}
