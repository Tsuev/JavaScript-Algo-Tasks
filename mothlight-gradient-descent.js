// Задача: Mothlight Gradient Descent
// Сложность: hard
// Дата генерации: 2026-10-07

// Условие задачи
// Ночная поляна разбита на n строк и m столбцов. В клетке (i, j) горит огонёк яркости v[i][j]; все яркости в поле попарно различны.
// 
// Мотылёк садится в некоторую клетку и дальше ведёт себя как градиентный подъём по яркости. На каждом шаге он смотрит на восемь соседних клеток (по стороне и по диагонали, не выходя за границы поля) и, если среди них есть клетка строго ярче той, где он сидит, перелетает в самую яркую из них. Если строго ярче нет ни одной — мотылёк успокаивается и остаётся в этой клетке навсегда.
// 
// Все яркости различны, поэтому самая яркая соседняя клетка определена однозначно, а яркость при каждом перелёте строго возрастает — значит, мотылёк никогда не зациклится и всегда куда-нибудь да сядет.
// 
// Для каждого из q стартов определите, в какой клетке мотылёк в итоге остановится и сколько перелётов он сделает.
// 
// Формат ввода
// Первая строка: два целых числа n и m (1 ≤ n, m ≤ 1000, n·m ≤ 10^6).
// Следующие n строк: по m целых чисел — яркости v[i][j] (1 ≤ v[i][j] ≤ 10^9, все значения различны).
// Следующая строка: целое число q (1 ≤ q ≤ 2·10^5).
// Следующие q строк: по два целых числа r и c — стартовая клетка (нумерация строк и столбцов с единицы).
// 
// Формат вывода
// q строк, в каждой три целых числа: строка и столбец клетки остановки, затем количество перелётов.
// 
// Пример 1
// Ввод:
// 3 3
// 1 2 3
// 4 5 6
// 7 8 9
// 3
// 1 1
// 2 2
// 3 3
// 
// Вывод:
// 3 3 2
// 3 3 1
// 3 3 0
// 
// Пример 2
// Ввод:
// 4 4
// 5 4 3 2
// 6 20 1 11
// 7 8 9 10
// 12 13 14 15
// 5
// 1 1
// 3 4
// 4 2
// 1 3
// 4 1
// 
// Вывод:
// 2 2 1
// 4 4 1
// 4 4 2
// 2 2 1
// 4 4 3
// 
// Пояснение ко второму примеру. В поле есть две точки притяжения: клетка (2, 2) с яркостью 20 и клетка (4, 4) с яркостью 15. Из (1, 1) самая яркая соседняя клетка — (2, 2), там мотылёк и останавливается за один перелёт. Из (4, 1) мотылёк летит по цепочке (4, 1) → (4, 2) → (4, 3) → (4, 4): три перелёта, потому что каждая следующая клетка цепочки ярче предыдущей.
// 
// Ограничения подобраны так, что наивная симуляция пути для каждого запроса не проходит: клеток может быть порядка 10^6, а запросов — 2·10^5.

/**
 * Mothlight Gradient Descent.
 *
 * Поле n x m, в каждой клетке горит огонёк уникальной яркости.
 * Мотылёк из клетки перелетает в самую яркую из восьми соседних клеток,
 * если она ярче текущей; иначе он остаётся там навсегда.
 * Для каждого старта нужно найти клетку остановки и число перелётов.
 *
 * Ключевая идея: яркость при каждом перелёте строго растёт, поэтому путь конечен.
 * Обрабатываем клетки в порядке убывания яркости — тогда к моменту обработки клетки c
 * клетка, в которую мотылёк из неё прыгнет, уже обработана, и её ответ уже известен.
 * Итого O(nm log nm + q) вместо наивного O(q * nm).
 */
function mothlightGradientDescent(n, m, grid, queries) {
  const nm = n * m;

  // Плоский массив яркостей: быстрее и экономнее, чем массив массивов.
  const light = new Int32Array(nm);
  for (let i = 0; i < n; i++) {
    const row = grid[i];
    for (let j = 0; j < m; j++) {
      light[i * m + j] = row[j];
    }
  }

  // Порядок обхода: от самой яркой клетки к самой тусклой.
  const order = new Uint32Array(nm);
  for (let k = 0; k < nm; k++) order[k] = k;
  order.sort((a, b) => (light[a] > light[b] ? -1 : light[a] < light[b] ? 1 : 0));

  const sinkRow = new Int32Array(nm); // строка клетки остановки
  const sinkCol = new Int32Array(nm); // столбец клетки остановки
  const flights = new Int32Array(nm); // сколько перелётов до остановки

  // Смещения для восьми направлений: по стороне и по диагонали.
  const dr = [-1, -1, -1, 0, 0, 1, 1, 1];
  const dc = [-1, 0, 1, -1, 1, -1, 0, 1];

  for (let k = 0; k < nm; k++) {
    const cell = order[k];
    const row = (cell / m) | 0;
    const col = cell - row * m;

    // Ищем самого яркого соседа, который строго ярче текущей клетки.
    let best = -1;
    let bestLight = -1;
    for (let d = 0; d < 8; d++) {
      const nr = row + dr[d];
      const nc = col + dc[d];
      if (nr < 0 || nr >= n || nc < 0 || nc >= m) continue;
      const cand = nr * m + nc;
      const val = light[cand];
      if (val > light[cell] && val > bestLight) {
        bestLight = val;
        best = cand;
      }
    }

    if (best === -1) {
      // Соседей ярче нет — мотылёк садится прямо здесь.
      sinkRow[cell] = row;
      sinkCol[cell] = col;
      flights[cell] = 0;
    } else {
      // Прыжок в уже обработанную, более яркую клетку: переиспользуем её ответ.
      sinkRow[cell] = sinkRow[best];
      sinkCol[cell] = sinkCol[best];
      flights[cell] = flights[best] + 1;
    }
  }

  // Отвечаем на запросы; во входных данных координаты считаются с единицы.
  const answer = new Array(queries.length);
  for (let t = 0; t < queries.length; t++) {
    const r = queries[t][0];
    const c = queries[t][1];
    const cell = (r - 1) * m + (c - 1);
    answer[t] = [sinkRow[cell] + 1, sinkCol[cell] + 1, flights[cell]];
  }
  return answer;
}
