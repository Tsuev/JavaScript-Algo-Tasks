// Условие задачи
// Коралловый риф цветёт волнами. Каждый день исследователи записывают высоту главного коралла — получается массив целых чисел h длины n (1 ≤ n ≤ 2·10^5, |h[i]| ≤ 10^9).
// 
// Непрерывный отрезок дней [l, r], длина которого не меньше 3, называется кадэнсом цветения, если внутри него есть такой день m (l < m < r), что высоты строго возрастают до дня m и строго убывают после него:
//   h[l] < h[l+1] < ... < h[m] > h[m+1] > ... > h[r].
// День m называется вершиной кадэнса.
// 
// Нужно посчитать, сколько всего различных кадэнсов цветения встречается в записи.
// 
// Формат входа: функция получает один аргумент — массив целых чисел h (все элементы — корректные числа JavaScript).
// Формат результата: одно целое число — количество отрезков-кадэнсов. Ответ может превосходить 2^31, но всегда помещается в обычное число JavaScript (не более ~10^10 при n = 2·10^5).
// 
// Примеры:
// h = [1, 2, 3, 2, 1]  →  4
//   подходят отрезки: [1,2,3,2], [1,2,3,2,1], [2,3,2], [2,3,2,1] (у всех вершина в индексе 2).
// h = [1, 2, 3, 4]  →  0
//   массив только возрастает, вершины внутри нет.
// h = [5, 1, 4, 2, 3]  →  1
//   единственный кадэнс — [1, 4, 2] с вершиной в значении 4.
// h = [2, 2, 2]  →  0
//   равенства запрещены: строгость нарушена.
// 
// Ограничения: решение должно работать за O(n) по времени и O(n) по памяти.

// Считаем количество отрезков, которые строго возрастают до внутренней вершины
// и строго убывают после неё.
//
// Ключевая идея: из-за строгости неравенств у каждого кадэнса вершина
// определена однозначно. Значит, можно для каждой позиции i посчитать, сколько
// есть кадэнсов именно с вершиной в i, и сложить — двойного счёта не будет.
function countCoralCadences(heights) {
  const n = heights.length;
  if (n < 3) return 0; // кадэнсу нужны хотя бы два склона и вершина между ними

  // up[i]   — на сколько шагов подряд можно уйти влево от i, сохраняя строгий рост.
  // down[i] — на сколько шагов подряд можно уйти вправо от i, сохраняя строгое убывание.
  const up = new Array(n).fill(0);
  const down = new Array(n).fill(0);

  for (let i = 1; i < n; i++) {
    if (heights[i] > heights[i - 1]) up[i] = up[i - 1] + 1;
  }

  for (let i = n - 2; i >= 0; i--) {
    if (heights[i] > heights[i + 1]) down[i] = down[i + 1] + 1;
  }

  // Если i — вершина, то левый конец кадэнса можно выбрать up[i] способами,
  // а правый — down[i] способами. Все такие комбинации дают разные отрезки.
  let total = 0;
  for (let i = 0; i < n; i++) {
    total += up[i] * down[i];
  }

  return total;
}

