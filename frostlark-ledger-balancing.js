// Задача: Frostlark Ledger Balancing
// Сложность: medium
// Дата генерации: 2026-11-06

// Условие задачи
// **Frostlark Ledger Balancing**
// 
// Фростларк ведёт бухгалтерскую книгу. В книге ровно n записей, i-я запись задаёт изменение баланса d_i: положительное число — поступление, отрицательное — списание, ноль — пустая запись. Баланс стартует с нуля, и записи рассматриваются строго в том порядке, в котором они записаны.
// 
// Главное правило книги: после проведения каждой записи баланс обязан быть неотрицательным. Если очередная запись нарушила бы это правило (или клерк заранее понимает, что она приведёт к нарушению), её можно **отложить**: отложенная запись не проводится вовсе и на баланс не влияет. Откладывать можно любые записи, в том числе заранее, до момента нарушения.
// 
// Нужно провести как можно больше записей, то есть найти **минимальное количество записей, которые придётся отложить**, чтобы все остальные записи прошли в исходном порядке и баланс ни разу не стал отрицательным.
// 
// **Формат входных данных**
// 
// Массив целых чисел `changes` длины n — изменения баланса в порядке записей.
// Ограничения: 0 ≤ n ≤ 200000, |d_i| ≤ 10^9.
// 
// **Формат результата**
// 
// Одно целое число — минимальное количество отложенных записей. Ответ существует всегда: в худшем случае можно отложить все списания, и все оставшиеся записи будут только увеличивать баланс.
// 
// **Примеры**
// 
// 1) `[3, -6, 2, -3, 4]` → `1`
//    Откладываем `-6`. Остаются балансы: 3 → 5 → 2 → 6, ни разу не отрицательный. Ноль отложенных не подходит: после `3` идёт `-6` и баланс становится −3.
// 
// 2) `[-1, -1, -1, 5]` → `3`
//    Первые три записи — списания при нулевом балансе, все три приходится отложить; затем проводится `5`.
// 
// 3) `[5, -1, -1, -1, -1, -1, -1]` → `1`
//    Баланс идёт 5, 4, 3, 2, 1, 0 и на последней записи станет −1; достаточно отложить одно (любое) списание.
// 
// 4) `[1, 2, 3]` → `0`
//    Все записи — поступления, откладывать ничего не нужно.
// 
// **Идея решения**
// 
// Идём по записям слева направо и держим баланс так, будто все просмотренные записи проведены. Все встреченные списания складываем в максимум-кучу (по модулю). Как только баланс стал отрицательным, откладываем самое крупное списание из уже просмотренных — оно даёт наибольший прирост баланса за одну отложенную запись, поэтому жадный выбор оптимален. После одного такого «возврата» баланс гарантированно становится неотрицательным. Сложность O(n log n).

// Двоичная куча-максимум: наверху всегда самый большой модуль списания.
class MaxHeap {
  constructor() {
    this.items = [];
  }

  get size() {
    return this.items.length;
  }

  push(value) {
    this.items.push(value);
    let i = this.items.length - 1;
    // Поднимаем новый элемент вверх, пока он больше своего родителя.
    while (i > 0) {
      const parent = (i - 1) >> 1;
      if (this.items[parent] >= this.items[i]) break;
      [this.items[parent], this.items[i]] = [this.items[i], this.items[parent]];
      i = parent;
    }
  }

  pop() {
    if (this.items.length === 0) return 0;
    const top = this.items[0];
    const last = this.items.pop();

    if (this.items.length > 0) {
      this.items[0] = last;
      let i = 0;
      const n = this.items.length;
      // Опускаем корень вниз, меняясь местами с большим из детей.
      while (true) {
        const left = 2 * i + 1;
        const right = 2 * i + 2;
        let best = i;
        if (left < n && this.items[left] > this.items[best]) best = left;
        if (right < n && this.items[right] > this.items[best]) best = right;
        if (best === i) break;
        [this.items[i], this.items[best]] = [this.items[best], this.items[i]];
        i = best;
      }
    }

    return top;
  }
}

/**
 * Возвращает минимальное число записей, которые нужно отложить,
 * чтобы баланс никогда не становился отрицательным.
 *
 * @param {number[]} changes изменения баланса в порядке записей
 * @returns {number} минимальное количество отложенных записей
 */
function frostlarkLedgerBalancing(changes) {
  const heap = new MaxHeap();
  let balance = 0;   // баланс, если провести все ещё не отложенные записи
  let deferred = 0;  // сколько записей уже отложено

  for (const change of changes) {
    balance += change;

    // Откладывать имеет смысл только списания: поступления балансу помогают,
    // поэтому в кучу попадают лишь модули отрицательных записей.
    if (change < 0) heap.push(-change);

    if (balance < 0) {
      // Баланс ушёл в минус. Откладываем самое крупное списание среди уже
      // просмотренных: один «возврат» даёт максимальный прирост баланса,
      // поэтому при жадном выборе число отложенных записей минимально.
      // Одного возврата всегда хватает: если баланс до записи был B >= 0,
      // то текущее списание по модулю больше B, а значит и максимум в куче
      // (он не меньше этого модуля) поднимает баланс обратно до >= 0.
      balance += heap.pop();
      deferred++;
    }
  }

  return deferred;
}
