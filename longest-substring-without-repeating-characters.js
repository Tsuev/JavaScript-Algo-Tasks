// Задача: Longest Substring Without Repeating Characters
// Сложность: medium
// Дата генерации: 2026-09-07

// Условие задачи
// Дана строка s. Найдите длину самой длинной подстроки без повторяющихся символов. Подстрока — это непрерывная последовательность символов в строке. Необходимо вернуть целое число — максимальную длину такой подстроки.
// 
// Формат входных данных: одна строка s, состоящая из символов ASCII, длина строки от 0 до 5 * 10^4.
// 
// Формат результата: одно целое число — ответ на задачу.
// 
// Примеры:
// 1) Вход: s = "abcabcbb" → Выход: 3 (подстрока "abc" длиной 3).
// 2) Вход: s = "bbbbb" → Выход: 1 (подстрока "b").
// 3) Вход: s = "pwwkew" → Выход: 3 (подстрока "wke" — это подстрока длиной 3, ответ не "pwke", так как это подпоследовательность, а не подстрока).
// 4) Вход: s = "" → Выход: 0.
// 
// Ограничения: длина строки не превышает 50 000, строка может содержать любые печатные символы.

/**
 * Решение задачи "Longest Substring Without Repeating Characters"
 * Используем метод скользящего окна с множеством (Set) для хранения
 * уникальных символов в текущем окне.
 *
 * Алгоритм:
 * 1. Двигаем правый указатель `right` по строке.
 * 2. Если символ уже есть в Set, то сдвигаем левый указатель `left`
 *    до тех пор, пока дубликат не будет удалён из окна.
 * 3. Добавляем текущий символ в Set и обновляем максимальную длину.
 * Время работы: O(n), память: O(min(n, размер алфавита)).
 */
function lengthOfLongestSubstring(s) {
    // Множество символов, которые сейчас находятся в окне
    const seen = new Set();
    let left = 0;          // левая граница окна
    let maxLength = 0;     // результирующая максимальная длина

    // Проходим по строке правым указателем
    for (let right = 0; right < s.length; right++) {
        const currentChar = s[right];

        // Если символ уже есть в окне, сдвигаем левую границу
        // до тех пор, пока не удалим его из Set (вместе с лишними слева символами)
        while (seen.has(currentChar)) {
            seen.delete(s[left]);
            left++;
        }

        // Добавляем текущий символ в окно
        seen.add(currentChar);

        // Обновляем максимальную длину (размер окна = right - left + 1)
        maxLength = Math.max(maxLength, right - left + 1);
    }

    return maxLength;
}
