// Задача: Ferrofluid Lattice Fusion
// Сложность: hard
// Дата генерации: 2026-10-07

// Условие задачи
// На одномерной решётке выстроены n капель феррожидкости. У капли i (1 ≤ i ≤ n) известен объём v_i — целое положительное число.
// 
// Разрешена операция слияния: выбираются две соседние группы капель (то есть группы, занимающие соседние отрезки исходной решётки), после чего они объединяются в одну группу. Объём новой группы равен сумме объёмов сливаемых групп, а затраченная энергия равна объёму получившейся группы. Слияние можно проводить многократно, пока все капли не образуют одну группу.
// 
// Требуется найти минимальную суммарную энергию, необходимую для того, чтобы слить все капли в одну.
// 
// Формат входных данных:
// В первой строке записано целое число n (1 ≤ n ≤ 2000).
// Во второй строке записаны n целых чисел v_1, v_2, ..., v_n (1 ≤ v_i ≤ 10^9).
// 
// Формат выходных данных:
// Выведите одно целое число — минимальную суммарную энергию.
// 
// Пример 1:
// Вход:
// 3
// 1 2 3
// Выход:
// 9
// 
// Пояснение: сначала сливаем капли 1 и 2, получаем группу объёма 3 и тратим 3. Затем сливаем эту группу с каплей 3, получаем объём 6 и тратим 6. Итого 3 + 6 = 9.
// 
// Пример 2:
// Вход:
// 4
// 1 1 1 1
// Выход:
// 8
// 
// Пояснение: сливаем попарно (1+1) и (1+1), тратим по 2, затем сливаем две группы объёма 2, тратим 4. Итого 2 + 2 + 4 = 8.
// 
// Ограничения: ответ может быть большим, но при заданных ограничениях он не превосходит 4·10^15 и гарантированно помещается в 64-битное целое. В JavaScript можно использовать тип Number без потери точности.

function minFusionEnergy(volumes) {
  const n = volumes.length;
  if (n <= 1) return 0;

  // Префиксные суммы для быстрого получения суммарного объёма отрезка.
  const pref = new Float64Array(n + 1);
  for (let i = 0; i < n; i++) {
    pref[i + 1] = pref[i] + volumes[i];
  }
  const segmentSum = (l, r) => pref[r + 1] - pref[l];

  // dp[l][r] — минимальная энергия слияния капель отрезка [l, r] в одну.
  // opt[l][r] — оптимальная точка разбиения k (сливаем [l, k] и [k+1, r]).
  // Используем одномерные массивы размера n * n для экономии памяти.
  const totalCells = n * n;
  const dp = new Float64Array(totalCells);
  const opt = new Int32Array(totalCells);

  // База: одна капля уже «слита», энергия равна 0.
  for (let i = 0; i < n; i++) {
    dp[i * n + i] = 0;
    opt[i * n + i] = i;
  }

  // Перебираем длину отрезка.
  for (let len = 2; len <= n; len++) {
    for (let l = 0; l + len - 1 < n; l++) {
      const r = l + len - 1;
      const idx = l * n + r;
      let best = Infinity;
      let bestK = -1;

      // Оптимизация Кнута: оптимальная точка разбиения лежит между
      // opt[l][r-1] и opt[l+1][r]. Это уменьшает сложность до O(n^2).
      const start = opt[l * n + (r - 1)];
      const end = Math.min(opt[(l + 1) * n + r], r - 1);
      const totalVolume = segmentSum(l, r);

      for (let k = start; k <= end; k++) {
        const cost =
          dp[l * n + k] +
          dp[(k + 1) * n + r] +
          totalVolume;
        if (cost < best) {
          best = cost;
          bestK = k;
        }
      }

      dp[idx] = best;
      opt[idx] = bestK;
    }
  }

  // Ответ — энергия слияния всего отрезка [0, n-1].
  return dp[0 * n + (n - 1)];
}
