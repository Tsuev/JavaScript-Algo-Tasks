// Задача: Glacier Flow Gates
// Сложность: hard
// Дата генерации: 2026-09-21

// Условие задачи
// ## Glacier Flow Gates
// 
// В горах есть ледниковая сеть из `n` станций наблюдения. Станция `1` стоит у вершины, а все остальные соединены с ней так, что получается дерево с корнем в станции `1`: для каждой станции `i` (2 ≤ i ≤ n) задан её родитель `p[i]`, и вода стекает по каналу от `i` к `p[i]`. На канале между станцией `i` и её родителем стоят **ворота**.
// 
// Изначально все ворота открыты, и вода свободно перетекает по всей сети. Когда ворота закрываются (замерзают), они больше никогда не открываются.
// 
// На станции `i` накопилось `v[i]` единиц талой воды.
// 
// Далее происходит `q` событий в хронологическом порядке. Каждое событие — одна из двух строк:
// 
// * `- x` — ворота на канале между станцией `x` (гарантируется 2 ≤ x ≤ n) и её родителем замерзают. Гарантируется, что эти ворота ещё открыты (то есть событие `- x` встречается для одного и того же `x` не более одного раза).
// * `? x` — нужно узнать характеристики связной компоненты, которой принадлежит станция `x` **в этот момент**.
// 
// Для каждого события `? x` выведите через пробел два числа: суммарный объём воды во всех станциях этой компоненты и количество станций в ней.
// 
// ### Формат входных данных
// 
// ```
// n q
// p[2] p[3] ... p[n]
// v[1] v[2] ... v[n]
// событие_1
// ...
// событие_q
// ```
// 
// Вторая строка содержит `n-1` целых чисел (родители станций 2..n), третья — `n` целых чисел (объёмы воды). Каждое из следующих `q` событий — либо `- x`, либо `? x`.
// 
// ### Формат результата
// 
// Для каждого события `? x` — одна строка с двумя целыми числами: суммарный объём воды в компоненте и число станций в ней. Порядок строк соответствует хронологическому порядку запросов.
// 
// ### Пример
// 
// Вход:
// ```
// 5 7
// 1 1 2 2
// 3 5 2 4 1
// ? 4
// - 2
// ? 4
// - 4
// ? 4
// ? 3
// ? 1
// ```
// 
// Выход:
// ```
// 15 5
// 10 3
// 4 1
// 5 2
// 5 2
// ```
// 
// Пояснение к примеру. Дерево: 1 — 2, 1 — 3, 2 — 4, 2 — 5. Воды: 3, 5, 2, 4, 1.
// 
// * `? 4` при всех открытых воротах — вся сеть: 3+5+2+4+1 = 15, станций 5.
// * `- 2` — замерзают ворота между 2 и 1. Остались компоненты {1,3} и {2,4,5}.
// * `? 4` — компонента {2,4,5}: 5+4+1 = 10, станций 3.
// * `- 4` — замерзают ворота между 4 и 2. Компоненты: {1,3}, {2,5}, {4}.
// * `? 4` — компонента {4}: 4, станций 1.
// * `? 3` — компонента {1,3}: 3+2 = 5, станций 2.
// * `? 1` — та же компонента {1,3}: 5 и 2.
// 
// ### Ограничения
// 
// * 1 ≤ n ≤ 2·10^5, 1 ≤ q ≤ 2·10^5;
// * 0 ≤ v[i] ≤ 10^9 (суммарный объём гарантированно не превосходит 2·10^14, то есть помещается в обычное число двойной точности);
// * гарантируется, что входные рёбра действительно образуют дерево с корнем 1 и что каждое событие `- x` корректно (ворота открыты в этот момент).

/**
 * Задача «Glacier Flow Gates».
 *
 * Главная идея — рассматривать события в ОБРАТНОМ времени.
 * Ворота умеют только закрываться, значит при проходе «вперёд» рёбра
 * дерева только исчезают, а СНМ (система непересекающихся множеств) умеет
 * только объединять — удалять рёбра в ней нельзя.
 * Зато если читать события с конца, ворота будут только открываться,
 * то есть рёбра только добавляться, — а это ровно то, что умеет СНМ.
 *
 * Алгоритм:
 *   1. Запоминаем, какие ворота в итоге окажутся закрытыми.
 *   2. Собираем СНМ в состоянии «после всех событий»: объединяем все рёбра,
 *      которые к финалу остались открытыми.
 *   3. Идём по событиям с конца к началу. Текущее состояние СНМ всегда
 *      совпадает с состоянием сети сразу после события i — поэтому запросы
 *      можно отвечать прямо на месте. Встретив заморозку, «откатываем» её,
 *      объединяя компоненты станции и её родителя.
 *   4. Ответы записаны в обратном порядке — переворачиваем их.
 *
 * Сложность: O((n + q) * α(n)) по времени и O(n + q) по памяти,
 * то есть практически линейно.
 */
function solveGlacierFlow(input) {
  // ---------- разбор входных данных ----------
  const tokens = input.split(/\s+/).filter((t) => t.length > 0);
  let pos = 0;

  const n = Number(tokens[pos++]);
  const q = Number(tokens[pos++]);

  const parent = new Int32Array(n + 1);
  for (let i = 2; i <= n; i++) parent[i] = Number(tokens[pos++]);

  const water = new Float64Array(n + 1);
  for (let i = 1; i <= n; i++) water[i] = Number(tokens[pos++]);

  const FREEZE = 0;
  const QUERY = 1;
  const evType = new Uint8Array(q);
  const evNode = new Int32Array(q);
  for (let i = 0; i < q; i++) {
    const t = tokens[pos++];
    evNode[i] = Number(tokens[pos++]);
    evType[i] = t === '?' ? QUERY : FREEZE;
  }

  // ---------- 1. какие ворота в итоге закрыты ----------
  const frozen = new Uint8Array(n + 1);
  for (let i = 0; i < q; i++) {
    if (evType[i] === FREEZE) frozen[evNode[i]] = 1;
  }

  // ---------- 2. СНМ ----------
  // Для каждой компоненты держим суммарный объём воды и число станций:
  // обе величины легко пересчитываются при объединении множеств.
  const dsu = new Int32Array(n + 1);
  const size = new Int32Array(n + 1); // размер для union by size
  const sum = new Float64Array(n + 1); // сумма v[i] в компоненте
  const cnt = new Int32Array(n + 1);   // число станций в компоненте

  for (let i = 1; i <= n; i++) {
    dsu[i] = i;
    size[i] = 1;
    sum[i] = water[i];
    cnt[i] = 1;
  }

  // Поиск корня с сжатием путей (итеративно, без рекурсии — глубина до 2·10^5).
  const find = (x) => {
    let root = x;
    while (dsu[root] !== root) root = dsu[root];
    while (dsu[x] !== root) {
      const next = dsu[x];
      dsu[x] = root;
      x = next;
    }
    return root;
  };

  const unite = (a, b) => {
    let ra = find(a);
    let rb = find(b);
    if (ra === rb) return;
    if (size[ra] < size[rb]) {
      const t = ra;
      ra = rb;
      rb = t;
    }
    dsu[rb] = ra;
    size[ra] += size[rb];
    sum[ra] += sum[rb];
    cnt[ra] += cnt[rb];
  };

  // Стартовое состояние — момент ПОСЛЕ последнего события: открыты только те
  // ворота, которые ни разу не замерзали.
  for (let v = 2; v <= n; v++) {
    if (!frozen[v]) unite(v, parent[v]);
  }

  // ---------- 3. обратный проход по событиям ----------
  const answers = [];
  for (let i = q - 1; i >= 0; i--) {
    const v = evNode[i];
    if (evType[i] === QUERY) {
      // СНМ сейчас описывает сеть ровно на момент запроса.
      const r = find(v);
      answers.push(sum[r] + ' ' + cnt[r]);
    } else {
      // Откатываем заморозку: ворота снова открываются, компоненты сливаются.
      unite(v, parent[v]);
    }
  }

  // ---------- 4. ответы восстановлены в обратном порядке ----------
  answers.reverse();
  return answers.join('\n');
}

