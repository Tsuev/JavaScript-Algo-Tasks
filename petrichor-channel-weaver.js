// Задача: Petrichor Channel Weaver
// Сложность: medium
// Дата генерации: 2026-10-05

// Условие задачи
// После дождя над горным хребтом остаётся сеть каналов, по которым вода ищет себе путь вниз. Нужно определить, где соберётся больше всего воды.
// 
// Дано:
// • heights — массив целых чисел длины n: высота каждой ячейки хребта (индексы 0..n-1);
// • clouds — список туч, каждая задана тройкой [l, r, v]: туча проливает v единиц воды в каждую ячейку с l по r включительно.
// 
// Сначала вода просто падает в ячейки. Затем происходит сток по правилам:
// 1. Ячейки обрабатываются в порядке убывания высоты.
// 2. Ячейка отдаёт всю свою воду соседу (слева i-1 или справа i+1) с наименьшей высотой — но только если эта высота строго меньше высоты самой ячейки. Если наименьшую высоту имеют оба соседа, выбирается сосед с меньшим индексом (левый).
// 3. Если оба соседа не ниже текущей ячейки (или соседа нет), ячейка становится впадиной: вода в ней остаётся.
// 4. Поскольку вода всегда течёт строго вниз, она никогда не поднимается обратно, и порядок «от высоких к низким» гарантирует, что вся вода, способная притечь в ячейку, уже притекла к моменту её обработки.
// 
// Формат результата: объект { index, depth } — самая левая ячейка с максимальным количеством оставшейся воды и это количество. Если ячеек с максимумом несколько, берётся наименьший индекс.
// 
// Функция решения: weaveChannels(heights, clouds) -> { index, depth }
// 
// Пример 1
// heights = [3, 1, 4, 1, 5], clouds = [[0, 4, 2]]
// После дождя воды всюду по 2. Ячейка 4 (h=5) отдаёт воду ячейке 3; ячейка 2 (h=4) — ячейке 1; ячейка 0 (h=3) — ячейке 1. Ячейки 1 и 3 — впадины.
// Итоговое распределение воды: [0, 6, 0, 4, 0].
// Результат: { index: 1, depth: 6 }
// 
// Пример 2
// heights = [5, 2, 5, 2, 5], clouds = [[0, 2, 3], [2, 4, 3]]
// Начальная вода: [3, 3, 6, 3, 3]. Вода со всех трёх вершин высоты 5 стекает вниз: в ячейку 1 (слева) и в ячейку 3.
// Итоговое распределение: [0, 12, 0, 6, 0].
// Результат: { index: 1, depth: 12 }
// 
// Пример 3
// heights = [7], clouds = [[0, 0, 5]]
// У единственной ячейки нет соседей — она впадина.
// Результат: { index: 0, depth: 5 }
// 
// Ограничения: 1 ≤ n ≤ 200000, 0 ≤ m ≤ 200000 (m — число туч), 0 ≤ heights[i] ≤ 1e9, 1 ≤ v ≤ 1e9. Ответ не превосходит 2e14 и спокойно помещается в обычное число JavaScript. Ожидаемая сложность: O(n log n + m) по времени и O(n) по памяти.

/**
 * Petrichor Channel Weaver.
 * heights — высоты ячеек хребта, clouds — тучи вида [l, r, v].
 * Возвращает { index, depth }: самую левую ячейку с максимумом воды и сам максимум.
 */
function weaveChannels(heights, clouds) {
  const n = heights.length;
  if (n === 0) return { index: -1, depth: 0 };

  // 1) Сколько воды выпало в каждую ячейку.
  // Тучи заданы отрезками, поэтому считаем разностным массивом: O(n + m).
  const diff = new Array(n + 1).fill(0);
  for (const cloud of clouds) {
    const l = cloud[0];
    const r = cloud[1];
    const v = cloud[2];
    diff[l] += v;
    diff[r + 1] -= v;
  }

  const water = new Array(n).fill(0);
  let fallen = 0;
  for (let i = 0; i < n; i++) {
    fallen += diff[i];
    water[i] = fallen;
  }

  // 2) Ключевая идея: вода всегда утекает строго вниз, поэтому граф стока
  // ациклический. Обрабатывая ячейки от высоких к низким, мы гарантируем,
  // что вся вода, способная притечь в ячейку, уже притекла до её обработки.
  const order = new Array(n);
  for (let i = 0; i < n; i++) order[i] = i;
  order.sort((a, b) => heights[b] - heights[a] || a - b);

  for (const u of order) {
    // Ищем соседа с наименьшей высотой. Левый сосед становится кандидатом
    // сразу, а правый вытесняет его только при строго меньшей высоте —
    // так при равенстве высот побеждает левый, как и требуется в условии.
    let target = -1;
    if (u - 1 >= 0) target = u - 1;
    if (u + 1 < n && (target === -1 || heights[u + 1] < heights[target])) {
      target = u + 1;
    }

    // Переливаем воду, только если сосед строго ниже; иначе ячейка — впадина,
    // и вода остаётся в ней навсегда.
    if (target !== -1 && heights[target] < heights[u]) {
      water[target] += water[u];
      water[u] = 0;
    }
  }

  // 3) Самая левая ячейка с максимальным количеством оставшейся воды.
  // Строгое сравнение сохраняет первый индекс при равенстве значений.
  let best = 0;
  for (let i = 1; i < n; i++) {
    if (water[i] > water[best]) best = i;
  }

  return { index: best, depth: water[best] };
}
