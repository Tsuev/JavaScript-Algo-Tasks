// Задача: Bioluminescent Drift Resonance
// Сложность: hard
// Дата генерации: 2026-10-09

// Условие задачи
// Bioluminescent Drift Resonance
// 
// В океанической впадине дрейфуют n колоний светящегося планктона. Колонии связаны дрейфовыми каналами так, что граф связей образует дерево (ровно n-1 канал, граф связен). Колония с номером i светится с интенсивностью a[i] (целое неотрицательное число).
// 
// Две различные колонии u и v находятся в резонансе, если побитовый XOR интенсивностей всех колоний, лежащих на единственном простом пути между u и v (сами u и v входят в путь), равен нулю.
// 
// Определите количество неупорядоченных пар различных колоний, находящихся в резонансе.
// 
// Формат входных данных:
// - первая строка: целое число n (1 <= n <= 2*10^5);
// - вторая строка: n целых чисел a[1..n] (0 <= a[i] < 2^30);
// - следующие n-1 строк: по два числа u, v (1 <= u, v <= n, u != v) - дрейфовый канал между колониями u и v.
// Гарантируется, что каналы образуют дерево.
// 
// Формат результата:
// Одно целое число - количество резонирующих пар. Ответ не превосходит n*(n-1)/2 <= 2*10^10 и точно представим обычным числом JavaScript.
// 
// Пример 1:
// Вход:
// 3
// 1 1 0
// 1 2
// 2 3
// Выход:
// 2
// Пояснение: пара (1,2): 1 XOR 1 = 0; пара (1,3): 1 XOR 1 XOR 0 = 0; пара (2,3): 1 XOR 0 = 1 - не резонирует.
// 
// Пример 2:
// Вход:
// 4
// 7 7 0 0
// 1 2
// 1 3
// 3 4
// Выход:
// 4
// Пояснение: подходят пары (1,2), (2,3), (2,4), (3,4).
// 
// Пример 3:
// Вход:
// 1
// 5
// Выход:
// 0
// Пояснение: пары должны состоять из двух различных колоний, поэтому одна колония резонанса не даёт.
// 
// Ожидаемая сложность: O(n log n) по времени и O(n) по памяти.

// Задача: Bioluminescent Drift Resonance (hard).
// Считаем число пар различных колоний (u, v), у которых XOR значений на пути u..v равен 0.
//
// Ключевая идея. Пусть pre[x] = XOR значений всех колоний на пути от корня до x включительно.
// Тогда для пары (u, v) с LCA = w верно:
//     XOR(u..v) = pre[u] XOR pre[v] XOR a[w]
// (общие предки выше w взаимно уничтожаются, а значение w входит в оба pre и его надо вернуть).
// Значит условие резонанса равносильно  pre[u] XOR pre[v] = a[w].
//
// Поэтому обрабатываем вершины снизу вверх: для каждой вершины w держим мультимножество
// значений pre[] её поддерева и считаем пары, у которых LCA ровно w: это пары между
// разными детьми плюс пары (w, потомок). Слияние маленьких мультимножеств в большое
// (small-to-large, он же DSU on tree) даёт суммарно O(n log n).

function solve(n, intensities, edges) {
  const a = intensities;
  if (n <= 1) return 0;

  // Список смежности; на входе вершины 1-индексированы, внутри работаем с 0-индексами.
  const adj = Array.from({ length: n }, () => []);
  for (const [x, y] of edges) {
    const u = x - 1;
    const v = y - 1;
    adj[u].push(v);
    adj[v].push(u);
  }

  // Итеративный DFS из корня 0: рекурсия глубиной 2e5 переполнила бы стек.
  const parent = new Int32Array(n).fill(-1);
  const pre = new Array(n).fill(0);
  const order = [];                 // порядок обхода: родитель всегда раньше своих детей
  const seen = new Uint8Array(n);
  pre[0] = a[0];
  seen[0] = 1;
  const stack = [0];
  while (stack.length > 0) {
    const u = stack.pop();
    order.push(u);
    for (const v of adj[u]) {
      if (seen[v] === 0) {
        seen[v] = 1;
        parent[v] = u;
        pre[v] = pre[u] ^ a[v];
        stack.push(v);
      }
    }
  }

  // Списки детей каждой вершины.
  const children = Array.from({ length: n }, () => []);
  for (let v = 0; v < n; v++) {
    if (parent[v] !== -1) children[parent[v]].push(v);
  }

  // maps[v] - Map: значение pre -> сколько вершин поддерева v имеют такое pre.
  const maps = new Array(n).fill(null);
  let answer = 0;

  // Идём в обратном порядке обхода: к моменту обработки w все её дети уже готовы.
  for (let idx = order.length - 1; idx >= 0; idx--) {
    const w = order[idx];

    // Сама вершина w - это отдельное мультимножество из одного элемента.
    const own = new Map([[pre[w], 1]]);
    let big = own;
    for (const c of children[w]) {
      const m = maps[c];
      if (m.size > big.size) big = m;   // самое большое поддерево выбираем базой
    }

    if (big !== own) {
      // Пары (w, потомок из большого поддерева): нужно pre[x] = pre[w] XOR a[w].
      const got = big.get(pre[w] ^ a[w]);
      if (got !== undefined) answer += got;
      big.set(pre[w], (big.get(pre[w]) || 0) + 1);
    }

    // Все остальные детские мультимножества по очереди приклеиваем к базе.
    for (const c of children[w]) {
      const m = maps[c];
      if (m === big) continue;          // база уже учтена

      // 1) Пары между m и уже накопленным big: нужно pre[x] XOR pre[y] = a[w],
      //    то есть pre[y] = pre[x] XOR a[w]. Для каждого значения из m берём счётчик.
      for (const [val, cnt] of m) {
        const got = big.get(val ^ a[w]);
        if (got !== undefined) answer += cnt * got;
      }
      // 2) Сливаем m в big.
      for (const [val, cnt] of m) {
        big.set(val, (big.get(val) || 0) + cnt);
      }
      maps[c] = null;                   // освобождаем ссылку, чтобы GC забрал мелочь
    }

    maps[w] = big;
  }

  return answer;
}

// Примеры запуска (без вывода в консоль, просто как эталонные вызовы):
// solve(3, [1, 1, 0], [[1, 2], [2, 3]])           -> 2
// solve(4, [7, 7, 0, 0], [[1, 2], [1, 3], [3, 4]]) -> 4
// solve(1, [5], [])                                -> 0
