// Задача: Zephyr Interference
// Сложность: medium
// Дата генерации: 2026-10-02

// Условие задачи
// ## Zephyr Interference
// 
// В долине Зефир дуют `n` лёгких ветров. Каждый зефир с номером `i` действует на всех целых точках отрезка `[l_i, r_i]` и приносит вклад `a_i`. Вклад может быть отрицательным: тогда зефир не усиливает, а гасит общий поток (интерференция).
// 
// В целой точке `x` суммарная сила ветра равна сумме вкладов всех зефиров, чьи отрезки содержат `x`:
// 
// `F(x) = сумма a_i по всем i, где l_i <= x <= r_i`
// 
// Нужно найти максимальную суммарную силу ветра и **наименьшую** целую точку, в которой она достигается. Рассматриваются только точки, накрытые хотя бы одним зефиром (если все вклады отрицательны, ответ тоже будет отрицательным).
// 
// ### Формат входных данных
// 
// - Первая строка — целое число `n` (`1 <= n <= 200000`).
// - Следующие `n` строк — по три целых числа `l_i`, `r_i`, `a_i` (`-10^9 <= l_i <= r_i <= 10^9`, `|a_i| <= 10^9`).
// 
// ### Формат результата
// 
// Два целых числа через пробел: максимальная суммарная сила и наименьшая целая точка, где она достигается.
// 
// ### Пример 1
// 
// Вход:
// ```
// 3
// 1 5 3
// 2 4 -1
// 4 6 2
// ```
// 
// Выход:
// ```
// 5 5
// ```
// 
// Пояснение: при `x = 5` работают первый (`+3`) и третий (`+2`) зефиры, второй уже закончился. Итого `5` — это максимум.
// 
// ### Пример 2
// 
// Вход:
// ```
// 2
// 1 2 -5
// 3 4 -3
// ```
// 
// Выход:
// ```
// -3 3
// ```
// 
// Пояснение: все вклады отрицательны, поэтому максимум — наименее «затушенная» точка, то есть `x = 3` со силой `-3`.
// 
// ### Пример 3
// 
// Вход:
// ```
// 3
// 1 3 4
// 2 5 4
// 4 6 4
// ```
// 
// Выход:
// ```
// 8 2
// ```
// 
// Пояснение: в точке `x = 2` работают первые два зефира, давая `4 + 4 = 8`.
// 
// ### Ограничения по эффективности
// 
// Решение должно работать за `O(n log n)` по времени и `O(n)` по памяти: полный перебор координат невозможен, так как они достигают `10^9`.

/**
 * Zephyr Interference
 *
 * Идея: сила ветра меняется только в отдельных точках — там, где
 * начинается (l) или заканчивается (r) отрезок зефира. Значит, достаточно
 * построить «события» и пройтись по ним слева направо, поддерживая текущую
 * суммарную силу методом заметающей прямой (sweep line).
 *
 * Чтобы не разбираться с閉 открытыми/закрытыми концами, конец отрезка
 * моделируем событием в точке r + 1: до этой точки зефир ещё действует,
 * начиная с неё — уже нет.
 *
 * Асимптотика: O(n log n) времени (сортировка событий) и O(n) памяти.
 *
 * Вход: массив троек [l, r, a].
 * Выход: { power, point } — максимум силы и наименьшая точка, где он достигнут.
 * Разбор входного текста в задачу не входит: сюда приходит уже разобранный массив.
 */
function zephyrInterference(zephyrs) {
  // Собираем события: [координата, на сколько меняется сила ветра].
  const events = [];
  for (const [l, r, a] of zephyrs) {
    events.push([l, a]);       // зефир включается в точке l
    events.push([r + 1, -a]);  // и выключается сразу после r, то есть в r + 1
  }

  // Сортируем события по координате — это и есть заметающая прямая.
  events.sort((p, q) => p[0] - q[0]);

  let current = 0;        // суммарная сила в текущей позиции
  let best = -Infinity;   // лучшая найденная сила
  let bestPoint = 0;      // наименьшая точка, где она достигнута

  let i = 0;
  while (i < events.length) {
    const x = events[i][0];

    // Применяем сразу ВСЕ события в координате x: важно, чтобы ответ
    // в самой точке x уже учитывал и включения, и выключения.
    while (i < events.length && events[i][0] === x) {
      current += events[i][1];
      i++;
    }

    // Последняя координата — после неё зефиров нет, эту пустую область
    // рассматривать нельзя (иначе при всех отрицательных вкладах ответ стал бы 0).
    if (i === events.length) break;

    // Между x и следующим событием сила постоянна, поэтому сравниваем один раз.
    // Строгое неравенство сохраняет самую левую точку среди оптимальных.
    if (current > best) {
      best = current;
      bestPoint = x;
    }
  }

  return { power: best, point: bestPoint };
}
