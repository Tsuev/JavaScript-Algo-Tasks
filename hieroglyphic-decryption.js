// Условие задачи
// В древнем храме нашли строку из иероглифов, которые выглядят как цифры от 0 до 9, но некоторые иероглифы стерлись, и их можно принять за любую цифру. Известно, что каждый иероглиф или пара иероглифов кодируют одну букву: число от 1 до 26 соответствует букве от A до Z. Ноль не может быть началом числа (числа не имеют ведущих нулей, кроме самого числа 0, но 0 не входит в диапазон 1..26). Требуется определить, сколькими способами можно расшифровать строку в последовательность букв. Так как ответ может быть большим, выведите его по модулю 1 000 000 007.
// 
// Входные данные: одна строка S (1 ≤ |S| ≤ 100 000), состоящая из символов '0'-'9' и '?'. Символ '?' обозначает стертый иероглиф, который может быть любой цифрой от 0 до 9.
// 
// Выходные данные: одно целое число — количество способов расшифровки строки по модулю 1 000 000 007.
// 
// Примеры:
// 1) S = "12" -> 2 (варианты: "1" "2" = AB, "12" = L)
// 2) S = "1?" -> 19
// 3) S = "??" -> 98
// 4) S = "0" -> 0

/**
 * Расшифровывает строку из иероглифов (цифры и '?') в количество способов
 * представить её как последовательность чисел от 1 до 26.
 * @param {string} s — входная строка
 * @returns {number} — количество способов по модулю 1e9+7
 */
function decryptHieroglyphs(s) {
  const MOD = 1_000_000_007;
  const n = s.length;
  // dp[i] — количество способов расшифровать первые i символов строки
  const dp = new Array(n + 1).fill(0);
  dp[0] = 1; // пустая строка — один способ

  for (let i = 1; i <= n; i++) {
    const ch = s[i - 1];

    // Вариант 1: текущий символ — однозначное число (1..9)
    let ways1 = 0;
    if (ch === '?') {
      ways1 = 9; // '?' может быть любой цифрой от 1 до 9
    } else if (ch !== '0') {
      ways1 = 1; // конкретная цифра от 1 до 9
    }
    if (ways1 > 0) {
      dp[i] = (dp[i] + dp[i - 1] * ways1) % MOD;
    }

    // Вариант 2: текущий и предыдущий символы образуют двузначное число (10..26)
    if (i >= 2) {
      const prev = s[i - 2];
      let ways2 = 0;

      if (prev !== '?' && ch !== '?') {
        // Оба символа известны — проверяем, попадает ли число в диапазон 10..26
        const num = parseInt(prev + ch, 10);
        if (num >= 10 && num <= 26) {
          ways2 = 1;
        }
      } else if (prev === '?' && ch === '?') {
        // Оба неизвестны: первая цифра 1 (10-19, 10 вариантов) или 2 (20-26, 7 вариантов)
        ways2 = 17;
      } else if (prev === '?') {
        // Известен только второй символ
        const digit2 = parseInt(ch, 10);
        // Первая цифра может быть 1 (тогда число 10..19, всегда подходит)
        // или 2 (тогда число 20..29, подходит только если digit2 <= 6)
        if (digit2 <= 9) ways2 += 1; // первая цифра 1
        if (digit2 <= 6) ways2 += 1; // первая цифра 2
      } else {
        // Известен только первый символ (prev), второй — '?'
        const digit1 = parseInt(prev, 10);
        if (digit1 === 1) {
          ways2 = 10; // вторая цифра 0..9 -> 10..19
        } else if (digit1 === 2) {
          ways2 = 7; // вторая цифра 0..6 -> 20..26
        }
      }

      if (ways2 > 0) {
        dp[i] = (dp[i] + dp[i - 2] * ways2) % MOD;
      }
    }
  }

  return dp[n];
}
