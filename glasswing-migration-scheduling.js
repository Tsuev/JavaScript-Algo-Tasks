// Задача: Glasswing Migration Scheduling
// Сложность: medium
// Дата генерации: 2026-10-28

// Условие задачи
// Стекляннокрылые бабочки (Glasswing) мигрируют через луг, где растут цветы. Каждая бабочка прилетает в момент времени l_i и улетает в момент r_i, и на всё это время ей нужен отдельный цветок для отдыха. Цветок считается занятым на полуинтервале [l_i, r_i): в момент r_i бабочка уже улетела, и другая бабочка может сесть на этот цветок ровно в момент r_i. В любой момент времени на одном цветке отдыхает не более одной бабочки, но один и тот же цветок можно использовать повторно для разных бабочек в непересекающиеся интервалы.
// 
// Нужно найти минимальное количество цветков k, которого достаточно, чтобы все n бабочек смогли отдохнуть, и выдать распределение бабочек по цветкам.
// 
// Формат входных данных:
// - первая строка: целое число n (1 ≤ n ≤ 2·10^5);
// - следующие n строк: по два целых числа l_i и r_i (0 ≤ l_i < r_i ≤ 10^9) — время прилёта и отлёта i-й бабочки.
// 
// Формат результата:
// - первая строка: минимальное число цветков k;
// - вторая строка: n целых чисел p_i (1 ≤ p_i ≤ k), где p_i — номер цветка, назначенного i-й бабочке (нумерация в порядке входа). Подходит любое корректное распределение при минимальном k: интервалы бабочек, получивших один и тот же цветок, не должны пересекаться.
// 
// Пример 1:
// Вход:
// 3
// 1 4
// 2 5
// 5 7
// Выход:
// 2
// 1 2 1
// Пояснение: первая бабочка занимает цветок 1 на [1,4), вторая — цветок 2 на [2,5). Третья прилетает в момент 5, когда вторая уже улетела, поэтому садится на цветок 1. В момент времени 4 заняты 2 цветка, поэтому меньшим числом не обойтись.
// 
// Пример 2:
// Вход:
// 3
// 1 3
// 2 4
// 3 5
// Выход:
// 2
// 1 2 1
// Пояснение: первая бабочка улетает ровно в момент 3, когда прилетает третья, поэтому они могут делить цветок 1.
// 
// Пример 3:
// Вход:
// 4
// 1 5
// 2 6
// 3 7
// 4 8
// Выход:
// 4
// 1 2 3 4
// Пояснение: в момент времени 4 все четыре интервала пересекаются, поэтому нужно 4 цветка.
// 
// Пример 4:
// Вход:
// 4
// 1 10
// 2 3
// 4 5
// 6 7
// Выход:
// 2
// 1 2 2 2
// Пояснение: первая бабочка занимает цветок 1 на всё время [1,10), а три коротких интервала не пересекаются между собой и могут по очереди использовать цветок 2.

// Минимальное число цветков и распределение бабочек по цветкам.
// Бабочка занимает цветок на полуинтервале [start, end):
// в момент start она садится, а в момент end цветок уже свободен.

class MinHeap {
  constructor(compare) {
    this.compare = compare;
    this.items = [];
  }

  get size() {
    return this.items.length;
  }

  peek() {
    return this.items[0];
  }

  push(value) {
    const a = this.items;
    a.push(value);
    let i = a.length - 1;
    // Поднимаем элемент вверх, пока он меньше родителя.
    while (i > 0) {
      const parent = (i - 1) >> 1;
      if (this.compare(a[i], a[parent]) < 0) {
        [a[i], a[parent]] = [a[parent], a[i]];
        i = parent;
      } else {
        break;
      }
    }
  }

  pop() {
    const a = this.items;
    const top = a[0];
    const last = a.pop();
    if (a.length > 0) {
      a[0] = last;
      let i = 0;
      const n = a.length;
      // Опускаем новый корень вниз, меняясь с меньшим из детей.
      while (true) {
        const left = 2 * i + 1;
        const right = 2 * i + 2;
        let smallest = i;
        if (left < n && this.compare(a[left], a[smallest]) < 0) smallest = left;
        if (right < n && this.compare(a[right], a[smallest]) < 0) smallest = right;
        if (smallest === i) break;
        [a[i], a[smallest]] = [a[smallest], a[i]];
        i = smallest;
      }
    }
    return top;
  }
}

// Основное решение: жадный проход по времени прилёта.
// Возвращает объект { flowers: k, assignment: [p_0, ..., p_{n-1}] }.
// При выводе сначала печатается k, затем assignment через пробел.
function solve(n, intervals) {
  // Обходим бабочек в порядке возрастания времени прилёта — так события «сесть» идут по времени.
  const order = Array.from({ length: n }, (_, i) => i)
    .sort((a, b) => intervals[a][0] - intervals[b][0] || intervals[a][1] - intervals[b][1]);

  // busy хранит занятые цветки, упорядоченные по времени освобождения.
  const busy = new MinHeap((a, b) => a.end - b.end || a.id - b.id);
  // free хранит освободившиеся цветки; берём наименьший номер, чтобы ответ был предсказуемым.
  const free = new MinHeap((a, b) => a - b);

  const assignment = new Array(n).fill(0);
  let flowers = 0;

  for (const i of order) {
    const [start, end] = intervals[i];

    // К моменту start все цветки с временем освобождения <= start уже свободны.
    // Полуинтервал [l, r) даёт именно нестрогое условие end <= start.
    while (busy.size > 0 && busy.peek().end <= start) {
      free.push(busy.pop().id);
    }

    let flowerId;
    if (free.size > 0) {
      // Есть свободный цветок — переиспользуем его.
      flowerId = free.pop();
    } else {
      // Все цветки заняты, значит в этот момент пересекается максимум интервалов.
      // Заводим новый цветок: меньше цветков не хватит по принципу максимальной нагрузки.
      flowers += 1;
      flowerId = flowers;
    }

    assignment[i] = flowerId;
    busy.push({ end, id: flowerId });
  }

  return { flowers, assignment };
}
