// Условие задачи
// Фрактальная калибровка маяков
// 
// Вдоль плоскости расставлены маяки по фрактальному правилу. Обозначим через R_n множество маяков уровня n.
// 
//   R_0 = { (0, 0) } — один маяк в начале координат.
// 
// Каждый следующий уровень получается применением трёх преобразований подобия к предыдущему множеству:
//   A(x, y) = (x/2,       y/2)
//   B(x, y) = (x/2 + 1/2, y/2)
//   C(x, y) = (x/2 + 1/4, y/2 + 1/2)
// 
//   R_n = A(R_{n-1}) ∪ B(R_{n-1}) ∪ C(R_{n-1}).
// 
// Легко видеть, что |R_n| = 3^n, а при n → ∞ это множество стремится к треугольнику Серпинского.
// 
// Корабль-калибратор стоит в точке Q = (qx, qy). Каждый маяк даёт вклад, равный квадрату расстояния до корабля, поэтому суммарная принятая энергия равна
// 
//   E = Σ_{P ∈ R_n} ( (P.x − qx)^2 + (P.y − qy)^2 ).
// 
// Все координаты маяков — двоично-рациональные числа, значит E — рациональное число со знаменателем 2^(2n+2). Требуется найти E по модулю M = 1 000 000 007 (простое число). Формально: если E = a / b в несократимой форме, выведите a · b^(−1) mod M (b не делится на M, так как M нечётно).
// 
// Формат входных данных:
//   Три целых числа: n, qx, qy.
//   Ограничения: 0 ≤ n ≤ 10^18, |qx| ≤ 10^9, |qy| ≤ 10^9.
// 
// Формат результата:
//   Одно целое число — значение E mod 1 000 000 007 в диапазоне [0, M).
// 
// Примеры:
//   1) n = 1, qx = 0, qy = 0  →  62500001        (E = 9/16)
//   2) n = 0, qx = 3, qy = 4  →  25              (маяк один, в начале координат)
//   3) n = 2, qx = 0, qy = 0  →  296875005       (E = 187/64)
// 
// Пояснение к примеру 1: на уровне 1 есть три маяка (0,0), (1/2,0), (1/4,1/2); сумма квадратов расстояний до начала координат равна 0 + 1/4 + (1/16 + 1/4) = 9/16.

// ============================================================
// Fractal Beacon Calibration
// ------------------------------------------------------------
// Уровень n строится тремя подобиями:
//   A(x,y) = (x/2,       y/2)
//   B(x,y) = (x/2 + 1/2, y/2)
//   C(x,y) = (x/2 + 1/4, y/2 + 1/2)
// Каждый маяк кодируется словом d_1 d_2 ... d_n, d_j ∈ {0,1,2}:
//   P = ( Σ u_{d_j} · 2^(-j),  Σ v_{d_j} · 2^(-j) ),
// где u = (0, 1/2, 1/4), v = (0, 0, 1/2).
//
// Умножим обе координаты на 2^(n+1) — получим целые числа
//   U_k = Σ u_{d_j} · 2^(n-j),   V_k = Σ v_{d_j} · 2^(n-j),
// где теперь u = (0, 2, 1), v = (0, 0, 2).
//
// Тогда E = N / 2^(2n+2), где
//   N = Σ (U_k − qx·2^(n+1))^2 + (V_k − qy·2^(n+1))^2.
// Все суммы по 3^n словам берём по замкнутым формулам:
//   Σ u = 3, Σ u^2 = 5, Σ v = 2, Σ v^2 = 4.
// ============================================================

const MOD = 1000000007n;

// Быстрое возведение в степень по модулю.
function modPow(base, exp, mod) {
  let result = 1n;
  base %= mod;
  while (exp > 0n) {
    if (exp & 1n) result = (result * base) % mod;
    base = (base * base) % mod;
    exp >>= 1n;
  }
  return result;
}

// Обратный элемент по простому модулю (малая теорема Ферма).
const modInverse = (a) => modPow(a, MOD - 2n, MOD);

/**
 * Основная функция: суммарная энергия всех маяков уровня n
 * относительно точки (qx, qy), взятая по модулю 1e9+7.
 *
 * @param {bigint|number|string} n  уровень фрактала (0 ≤ n ≤ 10^18)
 * @param {bigint|number|string} qx абсцисса корабля
 * @param {bigint|number|string} qy ордината корабля
 * @returns {number} E mod 1 000 000 007
 */
function calibrate(n, qx, qy) {
  n = BigInt(n);
  qx = ((BigInt(qx) % MOD) + MOD) % MOD;
  qy = ((BigInt(qy) % MOD) + MOD) % MOD;

  const inv3 = modInverse(3n);
  const inv9 = (inv3 * inv3) % MOD;

  const pow2 = modPow(2n, n, MOD);       // 2^n
  const pow4 = (pow2 * pow2) % MOD;      // 4^n
  const pow3 = modPow(3n, n, MOD);       // 3^n
  const pow3m1 = (pow3 * inv3) % MOD;    // 3^(n-1)
  const pow3m2 = (pow3 * inv9) % MOD;    // 3^(n-2)

  const p2minus1 = (pow2 - 1n + MOD) % MOD;                 // 2^n - 1
  const geom4 = ((pow4 - 1n + MOD) % MOD) * inv3 % MOD;     // (4^n - 1) / 3
  const sqHalf = (p2minus1 * p2minus1) % MOD;               // (2^n - 1)^2
  // Σ_{j≠j'} 2^(2n-j-j') = (2^n-1)^2 - (4^n-1)/3
  const offDiag = (sqHalf - geom4 + MOD) % MOD;

  // Суммы U_k и V_k по всем 3^n словам (только диагональные слагаемые).
  const sumU = (3n * pow3m1 % MOD) * p2minus1 % MOD;        // A_u = 3
  const sumV = (2n * pow3m1 % MOD) * p2minus1 % MOD;        // A_v = 2

  // Суммы квадратов: диагональ (B) + недиагональная часть (A^2).
  const sumU2 = (
    pow3m1 * 5n % MOD * geom4 % MOD +        // 3^(n-1) * B_u * geom4, B_u = 5
    pow3m2 * 9n % MOD * offDiag % MOD        // 3^(n-2) * A_u^2 * offDiag, A_u^2 = 9
  ) % MOD;
  const sumV2 = (
    pow3m1 * 4n % MOD * geom4 % MOD +        // 3^(n-1) * B_v * geom4, B_v = 4
    pow3m2 * 4n % MOD * offDiag % MOD        // 3^(n-2) * A_v^2 * offDiag, A_v^2 = 4
  ) % MOD;

  // Масштаб, переводящий координаты маяков в целые: 2^(n+1).
  const scale = (pow2 * 2n) % MOD;
  const qxS = (qx * scale) % MOD;
  const qyS = (qy * scale) % MOD;

  // N = Σ (U − qxS)^2 + Σ (V − qyS)^2 — раскрываем квадраты.
  let total = (sumU2 + sumV2) % MOD;
  total = (total - 2n * qxS % MOD * sumU % MOD + MOD) % MOD;
  total = (total - 2n * qyS % MOD * sumV % MOD + MOD) % MOD;
  total = (total + pow3 * ((qxS * qxS + qyS * qyS) % MOD)) % MOD; // 3^n * qxS^2 + ...

  // Делим на (2^(n+1))^2, то есть умножаем на обратный квадрат.
  const invScale = modInverse(scale);
  const answer = total * invScale % MOD * invScale % MOD;

  return Number(answer); // результат меньше 1e9+7, безопасно для Number
}

