// Условие задачи
// Условие задачи.
// В лесу Оукенвейл сок движется по дереву к центральному дуплу. Дерево состоит из n узлов, пронумерованных от 0 до n-1. Узел 0 — это дупло, то есть корень. Каждое из n-1 рёбер соединяет два узла и имеет целую пропускную способность c: суммарно по этому ребру может пройти не более c единиц сока. В узле i образуется supply[i] единиц сока. Сок может течь только по направлению к корню: из узла в его родителя в дереве с корнем 0. Если доступного сока больше, чем пропускает ребро, излишек не проходит дальше и не учитывается. Нужно найти максимальное количество сока, которое может оказаться в корне. Сок, изначально находящийся в корне, тоже считается находящимся в корне.
// 
// Входные данные — параметры функции maxSap(n, edges, supply):
// - n — целое число узлов, 1 ≤ n ≤ 200000;
// - edges — массив из n-1 троек [u, v, c], где 0 ≤ u, v < n, а c — целая пропускная способность ребра, 0 ≤ c ≤ 10^9. Гарантируется, что рёбра образуют дерево;
// - supply — массив длины n, где supply[i] — целое количество сока, образовавшегося в узле i, 0 ≤ supply[i] ≤ 10^9.
// 
// Результат: целое число — максимальное количество сока, которое может собраться в корне. Все ответы не превосходят 2·10^14, поэтому безопасно помещаются в обычный Number.
// 
// Пример 1.
// maxSap(5, [[0,1,3], [0,2,5], [1,3,10], [1,4,10]], [0,0,0,4,6]) вернёт 3.
// Объяснение: из узлов 3 и 4 в узел 1 приходит 4 + 6 = 10 единиц сока, но ребро 1-0 пропускает только 3 единицы. Ответ 3.
// 
// Пример 2.
// maxSap(6, [[0,1,5], [1,2,2], [1,3,10], [0,4,100], [4,5,1]], [0,0,4,1,0,50]) вернёт 4.
// Объяснение: узел 2 даёт 4, но ребро 1-2 пропускает 2; узел 3 даёт 1, ребро 1-3 пропускает 10. В узел 1 приходит 3, в корень через ребро 1-0 проходит 3. Узел 5 даёт 50, но ребро 4-5 пропускает 1; эта единица доходит до корня через ребро 4-0. Итого 3 + 1 = 4.
// 
// Пример 3.
// maxSap(1, [], [7]) вернёт 7.

function maxSap(n, edges, supply) {
  // Строим дерево в виде списка смежности.
  const graph = Array.from({ length: n }, () => []);
  for (const [u, v, cap] of edges) {
    graph[u].push([v, cap]);
    graph[v].push([u, cap]);
  }

  // Обходим дерево от корня 0 и запоминаем родителя и ёмкость ребра к нему.
  const parent = new Array(n).fill(-1);
  const parentCap = new Array(n).fill(0);
  const order = [0];
  parent[0] = 0;

  for (let i = 0; i < order.length; i++) {
    const u = order[i];
    for (const [v, cap] of graph[u]) {
      if (parent[v] !== -1) continue;
      parent[v] = u;
      parentCap[v] = cap;
      order.push(v);
    }
  }

  // available[i] — сколько сока может собраться в поддереве i и подойти к выходу из i.
  const available = supply.slice();

  // Идём от листьев к корню. Через ребро v-parent[v] пройдёт не больше его ёмкости.
  for (let i = order.length - 1; i > 0; i--) {
    const v = order[i];
    const flow = Math.min(available[v], parentCap[v]);
    available[parent[v]] += flow;
  }

  // В корне уже учтён его собственный сок и весь сок, который смог дойти.
  return available[0];
}
