// Задача: Merge Intervals
// Сложность: medium
// Дата генерации: 2026-09-06

// Условие задачи
// Дан массив интервалов, каждый из которых представлен парой целых чисел [start, end] (start ≤ end). Требуется объединить все пересекающиеся интервалы и вернуть массив непересекающихся интервалов, которые покрывают все исходные интервалы. Два интервала считаются пересекающимися, если у них есть хотя бы одна общая точка (в том числе когда границы совпадают: [1,4] и [4,5] считаются пересекающимися).
// 
// Формат входных данных:
// Первая строка содержит целое число n (1 ≤ n ≤ 10^5) — количество интервалов. Каждая из следующих n строк содержит два целых числа li и ri (li ≤ ri, -10^9 ≤ li ≤ ri ≤ 10^9).
// 
// Формат выходных данных:
// Выведите объединённые интервалы по одному на строку через пробел, в порядке возрастания левой границы.
// 
// Пример 1:
// Вход:
// 4
// 1 3
// 2 6
// 8 10
// 15 18
// Выход:
// 1 6
// 8 10
// 15 18
// 
// Пример 2:
// Вход:
// 2
// 1 4
// 4 5
// Выход:
// 1 5

function merge(intervals) {
  // Если интервалов нет, сразу возвращаем пустой массив
  if (!intervals.length) {
    return [];
  }

  // Сортируем интервалы по левой границе, чтобы можно было последовательно схлопывать пересечения
  intervals.sort((a, b) => a[0] - b[0]);

  // Первый интервал всегда войдёт в результат как отдельный либо будет расширен далее
  const result = [intervals[0]];

  // Проходим по оставшимся интервалам
  for (let i = 1; i < intervals.length; i++) {
    const [start, end] = intervals[i];
    const last = result[result.length - 1];

    if (start <= last[1]) {
      // Интервалы пересекаются (начало текущего не позже конца предыдущего)
      // Расширяем конец объединённого интервала, если текущий заканчивается дальше
      last[1] = Math.max(last[1], end);
    } else {
      // Нет пересечения — добавляем текущий интервал как отдельный
      result.push([start, end]);
    }
  }

  return result;
}
