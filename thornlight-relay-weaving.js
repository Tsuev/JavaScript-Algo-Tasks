// Условие задачи
// ## Thornlight Relay Weaving (Плетение тернового света)
// 
// Вдоль Терновой дороги в ряд стоят `n` реликвий-фонарей тернового света. У фонаря с номером `i` есть заряд `a[i]` — целое неотрицательное число.
// 
// Мастер-плетельщик умеет соединять **только соседние** фонари: если рядом стоят фонари с зарядами `x` и `y`, их можно сплести в один фонарь с зарядом `x + y`. За каждое такое сплетение мастер платит ровно столько, каков заряд получившегося фонаря, то есть `x + y`.
// 
// Нужно сплести все фонари в один (после `n − 1` сплетений) и заплатить как можно меньше. Найдите минимальную суммарную плату.
// 
// ### Формат входных данных
// 
// В первой строке — целое число `n` (`1 ≤ n ≤ 300`) — количество фонарей.
// Во второй строке — `n` целых чисел `a[i]` (`0 ≤ a[i] ≤ 10^6`) — заряды фонарей в порядке вдоль дороги.
// 
// Суммарный заряд не превосходит `3 · 10^8`, а искомая плата может доходить до `~9 · 10^10`, поэтому ответ не помещается в 32-битное целое — используйте 64-битные числа (в JavaScript достаточно обычного `Number`, точного до `2^53`).
// 
// ### Формат результата
// 
// Одно целое число — минимальная суммарная плата за плетение всех фонарей в один. Если фонарь всего один, плата равна `0`.
// 
// ### Пример 1
// 
// Вход:
// ```
// 4
// 4 1 2 3
// ```
// Выход:
// ```
// 19
// ```
// Пояснение: сплетаем `1` и `2` → `3` (платим 3), получаем `[4, 3, 3]`; сплетаем `3` и `3` → `6` (платим 6), получаем `[4, 6]`; сплетаем `4` и `6` → `10` (платим 10). Итого `3 + 6 + 10 = 19`. Порядок `4+1` в начале дал бы 20, поэтому он хуже.
// 
// ### Пример 2
// 
// Вход:
// ```
// 1
// 7
// ```
// Выход:
// ```
// 0
// ```
// 
// ### Пример 3
// 
// Вход:
// ```
// 3
// 5 5 5
// ```
// Выход:
// ```
// 25
// ```
// Пояснение: `5+5=10` (платим 10), затем `10+5=15` (платим 15). Итого 25.

/**
 * Плетение тернового света: минимальная суммарная плата за объединение
 * всех фонарей в один, если объединять разрешено только соседние.
 *
 * Идея — классическое «слияние камней» на отрезке.
 * dp[l][r] — минимальная плата, чтобы сплести фонари с l-го по r-й в один.
 * Последним ходом этот единственный фонарь получается слиянием двух соседних
 * кусков [l..k] и [k+1..r], поэтому
 *     dp[l][r] = сумма(l..r) + min по k ( dp[l][k] + dp[k+1][r] ).
 * Сумма на отрезке считается за O(1) по префиксным суммам,
 * итоговая сложность — O(n^3) по времени и O(n^2) по памяти.
 *
 * @param {number[]} relays заряды фонарей в порядке вдоль дороги
 * @returns {number} минимальная суммарная плата
 */
function minWeaveCost(relays) {
  const n = relays.length;
  if (n <= 1) return 0; // плести нечего — платить не за что

  // Префиксные суммы, чтобы брать заряд любого отрезка за один шаг.
  const prefix = new Float64Array(n + 1);
  for (let i = 0; i < n; i++) prefix[i + 1] = prefix[i] + relays[i];

  // dp[l][r] — минимальная плата сплести отрезок [l..r].
  // Float64Array заполнен нулями, а для отрезка длины 1 плата и правда 0:
  // DP по длинам перебирает только len >= 2.
  const dp = Array.from({ length: n }, () => new Float64Array(n));

  // Идём по возрастанию длины отрезка: короткие ответы нужны раньше длинных.
  for (let len = 2; len <= n; len++) {
    for (let l = 0; l + len - 1 < n; l++) {
      const r = l + len - 1;

      // Перебираем место последнего слияния: слева [l..k], справа [k+1..r].
      let bestSplit = Infinity;
      for (let k = l; k < r; k++) {
        const cost = dp[l][k] + dp[k + 1][r];
        if (cost < bestSplit) bestSplit = cost;
      }

      // Плюс плата за сам последний ход — заряд получившегося фонаря,
      // то есть сумма всех зарядов отрезка [l..r].
      dp[l][r] = bestSplit + (prefix[r + 1] - prefix[l]);
    }
  }

  return dp[0][n - 1];
}
