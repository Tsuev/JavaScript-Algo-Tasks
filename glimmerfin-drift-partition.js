// Задача: Glimmerfin Drift Partition
// Сложность: medium
// Дата генерации: 2026-11-07

// Условие задачи
// **Условие.** Косяк глимерфинов дрейфует по течению реки: рыбы плывут строго друг за другом, и у каждой есть яркость свечения — целое неотрицательное число. Исследователь хочет разделить косяк на ровно `k` последовательных групп-стай: каждая стая — это несколько подряд идущих рыб, все рыбы распределены, порядок сохраняется, стаи не перемешиваются и не пустуют. Свечение стаи — сумма яркостей входящих в неё рыб. Нужно сделать так, чтобы самая яркая стая светила как можно слабее, то есть минимизировать максимум свечения по стаям.
// 
// Требуется найти это минимально возможное значение максимума и предъявить одно подходящее разбиение.
// 
// **Входные данные.** Функция `solution(glow, k)`, где:
// - `glow` — массив неотрицательных целых чисел, `0 <= glow[i] <= 10^9`, длина `n` от 1 до 10^5;
// - `k` — целое число, `1 <= k <= n`.
// 
// **Результат.** Объект `{ maxGlow, shoals }`:
// - `maxGlow` — минимально достижимое максимальное свечение стаи;
// - `shoals` — массив ровно из `k` пар `[start, end]` (индексы 0-based, включительно), которые идут подряд, покрывают весь массив без пропусков и перекрытий и задают стаи в порядке следования.
// 
// **Пример 1.** `solution([1, 2, 3, 4, 5], 2)` → `{ maxGlow: 9, shoals: [[0, 2], [3, 4]] }`. Свечения стай: 1+2+3 = 6 и 4+5 = 9, максимум 9; меньше нельзя, так как сумма 15 при двух стаях даёт максимум не меньше 8, а 8 не достигается.
// 
// **Пример 2.** `solution([7, 2, 5, 10, 8], 2)` → `{ maxGlow: 18, shoals: [[0, 2], [3, 4]] }`. Свечения: 7+2+5 = 14 и 10+8 = 18. Любое другое разрезание даёт максимум не меньше 18.
// 
// **Пример 3.** `solution([3, 1, 2], 3)` → `{ maxGlow: 3, shoals: [[0, 0], [1, 1], [2, 2]] }`.
// 
// **Пример 4.** `solution([0, 0, 0], 2)` → `{ maxGlow: 0, shoals: [[0, 1], [2, 2]] }`.
// 
// **Идея решения.** Ответ монотонен по величине лимита: если при лимите `L` хватает `k` стай, то при большем лимите тоже хватает. Поэтому минимальный лимит ищется бинарным поиском на отрезке от максимума `glow` до суммы всех яркостей, а проверка «хватает ли `k` стай» делается жадно за O(n). После нахождения лимита разбиение восстанавливается ещё одним жадным проходом. Итоговая сложность O(n log S), где S — сумма яркостей.

function solution(glow, k) {
  const n = glow.length;
  if (k < 1 || k > n) throw new RangeError('k должно лежать в диапазоне от 1 до n');

  // Границы бинарного поиска: снизу — самая яркая рыба (стая не может быть пустой),
  // сверху — весь косяк одной стаей.
  let low = 0;
  let high = 0;
  for (const g of glow) {
    if (g > low) low = g;
    high += g;
  }

  // Жадно считаем минимальное число стай, которого хватит при ограничении limit:
  // набираем рыбу в текущую стаю, пока сумма не превысит limit.
  const shoalsNeeded = (limit) => {
    let count = 1;
    let sum = 0;
    for (const g of glow) {
      if (sum + g > limit) {
        count += 1;
        sum = g;
      } else {
        sum += g;
      }
    }
    return count;
  };

  // Ищем минимальный лимит, при котором удаётся уложиться в k стай.
  while (low < high) {
    const mid = Math.floor((low + high) / 2);
    if (shoalsNeeded(mid) <= k) {
      high = mid;
    } else {
      low = mid + 1;
    }
  }
  const maxGlow = low;

  // Восстанавливаем само разбиение. Режем стаю, когда очередная рыба переполняет
  // лимит, либо когда оставшихся рыб ровно столько, сколько стай ещё нужно
  // сформировать, — иначе не наберём ровно k непустых стай.
  const shoals = [];
  let start = 0;
  let sum = 0;
  for (let i = 0; i < n; i += 1) {
    const left = n - i;                      // рыб от i до конца включительно
    const shoalsLeft = k - shoals.length;    // стай ещё нужно получить, включая текущую
    const mustSplitForCount = left === shoalsLeft - 1;
    if (i > start && (sum + glow[i] > maxGlow || mustSplitForCount)) {
      shoals.push([start, i - 1]);
      start = i;
      sum = glow[i];
    } else {
      sum += glow[i];
    }
  }
  shoals.push([start, n - 1]);

  return { maxGlow, shoals };
}
