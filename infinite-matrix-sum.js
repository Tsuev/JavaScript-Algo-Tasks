// Задача: Infinite Matrix Sum
// Сложность: medium
// Дата генерации: 2026-09-08

// Условие задачи
// Рассмотрим бесконечную матрицу A, строки и столбцы которой нумеруются с 1. Элемент в строке r и столбце c задаётся формулой:
// A[r][c] = ((r + c - 2) * (r + c - 1)) / 2 + r.
// Так заполняются натуральные числа по диагоналям: сначала (1,1)=1, затем (1,2)=2, (2,1)=3, затем (1,3)=4, (2,2)=5, (3,1)=6 и так далее.
// 
// Требуется по координатам прямоугольника от (r1, c1) до (r2, c2) включительно найти сумму всех элементов этого прямоугольника по модулю 1 000 000 007.
// 
// Формат входных данных: четыре целых числа r1, c1, r2, c2. Ограничения: 1 ≤ r1 ≤ r2 ≤ 10^9, 1 ≤ c1 ≤ c2 ≤ 10^9.
// Формат выходных данных: одно целое число — искомая сумма по модулю.
// 
// Пример 1:
// Вход: 1 1 2 2
// Выход: 11
// Пояснение: внутри прямоугольника элементы 1, 2, 3, 5, их сумма равна 11.
// 
// Пример 2:
// Вход: 1 1 1 3
// Выход: 7
// Пояснение: элементы 1, 2, 4, сумма равна 7.

const MOD = 1000000007n;

function prefixSum(inputN, inputM) {
    const n = BigInt(inputN);
    const m = BigInt(inputM);
    if (n === 0n || m === 0n) return 0n;

    // Сумма 1 + 2 + ... + x
    const S1 = (x) => x * (x + 1n) / 2n;
    // Сумма 1^2 + 2^2 + ... + x^2
    const S2 = (x) => x * (x + 1n) * (2n * x + 1n) / 6n;

    const s1n = S1(n);
    const s1m = S1(m);
    const s2n = S2(n);
    const s2m = S2(m);

    // Если раскрыть формулу элемента в многочлен и просуммировать по всем
    // x=1..n, y=1..m, получится следующее замкнутое выражение.
    // Все промежуточные вычисления делаем в BigInt, чтобы не терять точность.
    const numerator =
        m * s2n +
        n * s2m +
        2n * s1n * s1m -
        m * s1n -
        3n * n * s1m +
        2n * n * m;

    // Исходная сумма всегда целая, поэтому деление на 2 точное.
    return (numerator / 2n) % MOD;
}

/**
 * Основная функция: сумма в прямоугольнике с координатами (r1,c1) и (r2,c2).
 * Используется включение-исключение через префиксные суммы.
 */
function infiniteMatrixSum(r1, c1, r2, c2) {
    const R1 = BigInt(r1);
    const C1 = BigInt(c1);
    const R2 = BigInt(r2);
    const C2 = BigInt(c2);

    const value =
        prefixSum(R2, C2) -
        prefixSum(R1 - 1n, C2) -
        prefixSum(R2, C1 - 1n) +
        prefixSum(R1 - 1n, C1 - 1n);

    // Нормализуем отрицательный остаток и возвращаем обычное число
    return Number(((value % MOD) + MOD) % MOD);
}
