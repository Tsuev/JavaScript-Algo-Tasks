// Условие задачи
// Задача «Zircon Facet Balancing».
// 
// Ювелир обрабатывает циркон, у которого n граней расположены по кругу. У каждой грани i есть целочисленный показатель блеска w_i. Чтобы камень выглядел симметрично, его распиливают по кольцу на две непрерывные дуги (каждая дуга — это непрерывный кусок граней вдоль окружности, дуга не может быть пустой). Требуется так выбрать разрез, чтобы суммарный блеск двух дуг оказался как можно ближе друг к другу, и вывести минимально возможную абсолютную разницу этих суммарных блесков.
// 
// Формат входных данных:
// В первой строке задано целое число n (количество граней, n >= 2).
// Во второй строке заданы n целых чисел через пробел — блеск каждой грани в порядке обхода кольца.
// 
// Формат результата:
// Одно целое число — минимальная абсолютная разница между суммарным блеском двух дуг.
// 
// Пример 1:
// Вход: n = 4, блеск = [1, 2, 3, 4]
// Выход: 0
// Пояснение: дуга [2, 3] даёт блеск 5, дуга [4, 1] тоже даёт 5, разница 0.
// 
// Пример 2:
// Вход: n = 3, блеск = [10, 1, 1]
// Выход: 8
// Пояснение: лучший разрез — дуга [10] (10) против дуги [1, 1] (2), разница 8.
// 
// Пример 3:
// Вход: n = 5, блеск = [5, 1, 4, 2, 3]
// Выход: 1
// Пояснение: дуга [3, 5] даёт 8, оставшаяся дуга даёт 7, разница 1.

/**
 * Разбивает кольцо граней на две непрерывные дуги так,
 * чтобы разница их суммарного блеска была минимальной.
 *
 * @param {number} n количество граней (n >= 1)
 * @param {number[]} facets блеск каждой грани в порядке обхода кольца
 * @returns {number} минимальная абсолютная разница блеска двух дуг
 */
function balanceZircon(n, facets) {
  // Считаем общий блеск камня.
  let total = 0;
  for (const value of facets) total += value;

  // Из единственной грани кольцо на две непустые дуги не разрезать.
  if (n < 2) return total;

  // Удваиваем массив: тогда любую дугу вдоль кольца (в том числе «через край»)
  // можно рассматривать как обычный непрерывный отрезок удвоенного массива.
  const doubled = facets.concat(facets);

  // Разница двух дуг равна |total - 2 * sum|, где sum — блеск одной дуги.
  // Значит, нам нужен непрерывный отрезок, сумма которого ближе всего к total / 2.
  let best = Infinity;
  let left = 0;
  let sum = 0;

  for (let right = 0; right < 2 * n; right++) {
    sum += doubled[right];

    // Длина дуги не может превышать длину всего кольца.
    while (right - left + 1 > n) {
      sum -= doubled[left];
      left++;
    }

    // Сжимаем окно слева, пока сумма больше половины.
    // Каждое такое окно (sum > total / 2) — претендент на ответ.
    while (left < right && sum * 2 > total) {
      best = Math.min(best, sum * 2 - total);
      sum -= doubled[left];
      left++;
    }

    // Окно с суммой не больше половины тоже проверяем — часто именно оно и лучше.
    best = Math.min(best, Math.abs(total - 2 * sum));
  }

  return best;
}
