// Задача: Whale Fall Succession
// Сложность: medium
// Дата генерации: 2026-10-27

// Условие задачи
// На дне океана обнаружен упавший кит. Вокруг туши развивается сукцессия — последовательная смена видов. Учёные рассматривают n видов. Для каждого вида i известны дни l_i и r_i включительно, когда он может доминировать на туше, и ценность b_i — вклад вида в суммарную биомассу сообщества.
// 
// Нужно выбрать подмножество видов, которые сменяют друг друга корректно: если вид A выбран раньше вида B, то должно выполняться r_A < l_B. Иными словами, интервалы активности выбранных видов не должны пересекаться даже одним днём. Среди всех корректных последовательностей нужно найти такую, у которой суммарная ценность b_i максимальна. Разрешается не выбирать ни одного вида — тогда ответ равен 0.
// 
// Формат входных данных:
// В первой строке задано целое число n (1 <= n <= 200000) — количество видов.
// В следующих n строках записаны по три целых числа: l_i, r_i, b_i (1 <= l_i <= r_i <= 10^9, 0 <= b_i <= 10^9).
// 
// Формат результата:
// Выведите одно целое число — максимально возможную суммарную ценность выбранных видов.
// 
// Пример:
// Вход:
// 4
// 1 3 10
// 4 6 20
// 2 5 30
// 7 8 15
// 
// Выход:
// 45
// 
// Пояснение к примеру:
// Можно выбрать виды [1, 3] с ценностью 10, [4, 6] с ценностью 20 и [7, 8] с ценностью 15. Их интервалы не пересекаются, суммарная ценность равна 45. Другой оптимальный вариант — выбрать [2, 5] с ценностью 30 и [7, 8] с ценностью 15, тоже 45.

function whaleFallSuccession(n, stages) {
  const m = Math.min(n, stages.length);
  if (m === 0) return 0;

  // Каждый вид храним как объект, чтобы не путаться в индексах.
  const items = stages
    .slice(0, m)
    .map(([l, r, biomass]) => ({ l, r, biomass }))
    .sort((a, b) => a.r - b.r || a.l - b.l);

  // ends[k] — день окончания k-го вида после сортировки.
  const ends = items.map(item => item.r);
  const dp = new Array(m + 1).fill(0);

  for (let i = 1; i <= m; i++) {
    const current = items[i - 1];

    // Ищем количество видов среди первых i-1, которые заканчиваются
    // строго раньше начала текущего вида. Их можно поставить перед ним.
    let left = 0;
    let right = i - 1;
    while (left < right) {
      const mid = (left + right) >> 1;
      if (ends[mid] < current.l) {
        left = mid + 1;
      } else {
        right = mid;
      }
    }

    const bestBefore = dp[left];
    const takeCurrent = bestBefore + current.biomass;

    // Либо пропускаем текущий вид, либо добавляем его к лучшей
    // совместимой последовательности слева.
    dp[i] = Math.max(dp[i - 1], takeCurrent);
  }

  return dp[m];
}
