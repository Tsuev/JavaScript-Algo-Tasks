// Задача: Glassmoth Lantern Assignment
// Сложность: medium
// Дата генерации: 2026-11-04

// Условие задачи
// ## Glassmoth Lantern Assignment (Распределение стеклянных мотыльков по фонарям)
// 
// ### Легенда
// Ночью в стеклянном саду просыпаются `n` стеклянных мотыльков. Каждый мотылёк должен сесть ровно на один фонарь, и на одном фонаре может сидеть не больше одного мотылька. Мотыльки сидят в точках `x[1..n]` на аллее, а фонари висят в точках `y[1..m]` той же аллеи. Фонарей не меньше, чем мотыльков (`m >= n`), поэтому места хватит всем, но часть фонарей останется пустой.
// 
// Если мотылёк из точки `x[i]` садится на фонарь в точке `y[j]`, он пролетает расстояние `|x[i] - y[j]|`. Суммарный путь всех мотыльков — это стоимость назначения. Нужно назначить мотыльков на фонари так, чтобы суммарная стоимость была минимальной.
// 
// ### Формат входных данных
// В терминах функции решение принимает два аргумента:
// - `mothPositions` — массив из `n` целых чисел: координаты мотыльков;
// - `lanternPositions` — массив из `m` целых чисел: координаты фонарей, причём `1 <= n <= m`.
// 
// Координаты могут быть отрицательными и повторяться.
// 
// ### Формат результата
// Одно целое число — минимальная суммарная стоимость назначения.
// 
// ### Пример
// ```
// mothPositions    = [1, 5, 10]
// lanternPositions = [2, 3, 6, 12]
// ```
// Ответ: `4`.
// 
// Пояснение: отсортировав обе группы, получаем мотыльков `[1, 5, 10]` и фонари `[2, 3, 6, 12]`. Оптимально посадить `1 -> 2` (путь 1), `5 -> 6` (путь 1), `10 -> 12` (путь 2). Итого `1 + 1 + 2 = 4`. Фонарь `3` остаётся пустым.
// 
// ### Ограничения
// - `1 <= n <= m <= 2000`;
// - `|x[i]|, |y[j]| <= 10^9`;
// - ответ помещается в стандартное число JavaScript (сумма не превосходит `4 * 10^12`).
// 
// ### Идея решения
// Ключевое наблюдение: существует оптимальное назначение без «пересечений». Если два мотылька `a <= b` посажены на фонари `u > v`, то обмен местами не увеличивает сумму (свойство модуля на прямой). Значит, отсортировав мотыльков и фонари, можно искать назначение, сохраняющее порядок: `i`-й мотылёк садится на какой-то фонарь, идущий после фонаря `(i-1)`-го мотылька.
// 
// Отсюда динамическое программирование: `dp[i][j]` — минимум стоимости, если первых `i` мотыльков рассадили, используя только первые `j` фонарей. Переход:
// - `dp[i][j] = min(dp[i][j-1], dp[i-1][j-1] + |x[i] - y[j]|)` — либо `j`-й фонарь пустует, либо `i`-й мотылёк садится на него.
// 
// Ответ — `dp[n][m]`. Храним только предыдущую строку, поэтому память `O(m)`, время `O(n * m)`.

/**
 * Минимальная суммарная стоимость рассадки стеклянных мотыльков по фонарям.
 *
 * @param {number[]} mothPositions   координаты мотыльков (n штук)
 * @param {number[]} lanternPositions координаты фонарей (m штук, m >= n)
 * @returns {number} минимальная сумма пройденных расстояний
 */
function minTotalGlassmothDistance(mothPositions, lanternPositions) {
  // Сортировка не меняет ответ, но делает назначение «монотонным»:
  // в оптимальном решении порядок мотыльков совпадает с порядком фонарей,
  // поэтому пересекающиеся пары можно безопасно обменивать местами.
  const moths = [...mothPositions].sort((a, b) => a - b);
  const lanterns = [...lanternPositions].sort((a, b) => a - b);

  const n = moths.length;
  const m = lanterns.length;

  // Фонарей должно хватать на всех мотыльков.
  if (n > m) return Number.POSITIVE_INFINITY;

  // dp[j] — минимум стоимости, если первых i мотыльков уже рассадили,
  // используя только первые j фонарей. Для i = 0 стоимость всегда 0:
  // никого не посадили, сколько бы фонарей ни было доступно.
  let dp = new Array(m + 1).fill(0);

  for (let i = 1; i <= n; i++) {
    const moth = moths[i - 1];
    const next = new Array(m + 1).fill(Number.POSITIVE_INFINITY);

    for (let j = 1; j <= m; j++) {
      // Вариант 1: j-й фонарь остаётся пустым — просто наследуем лучший
      // результат для тех же i мотыльков на первых j-1 фонарях.
      const skipLantern = next[j - 1];

      // Вариант 2: сажаем i-го мотылька именно на j-й фонарь.
      // Тогда предыдущие i-1 мотыльков должны были занять первые j-1 фонарей.
      const useLantern = dp[j - 1] + Math.abs(moth - lanterns[j - 1]);

      next[j] = Math.min(skipLantern, useLantern);
    }

    // Переходим к следующему мотыльку, храня только одну строку таблицы.
    dp = next;
  }

  // После обработки всех мотыльков dp[m] — лучший вариант с любым
  // подмножеством из m фонарей, то есть глобальный оптимум.
  return dp[m];
}
