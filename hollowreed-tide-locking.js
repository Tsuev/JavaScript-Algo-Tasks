// Условие задачи
// Задача «Hollowreed Tide Locking»
// 
// На песчаном берегу в ряд стоят n полых тростников. Тростник с номером i имеет высоту h[i] (целое неотрицательное число, ширина каждого тростника считается равной 1, расстояния между ними нет).
// 
// Во время прилива вода поднимается и полностью затапливает берег, а когда прилив отступает, часть воды остаётся запертой в «жёлобах» между тростниками. Вода над позицией i держится только в том случае, если слева и справа от неё есть тростники выше неё: уровень воды над i равен min(самый высокий тростник слева, самый высокий тростник справа), а слой запертой воды равен max(0, уровень − h[i]). Над самыми высокими тростниками и по краям ряда вода не задерживается.
// 
// Нужно посчитать суммарный объём (площадь поперечного сечения) воды, запертой между тростниками после отлива.
// 
// Формат входных данных:
// — первая строка: целое число n — количество тростников (0 ≤ n ≤ 100000);
// — вторая строка: n целых чисел h[i] через пробел (0 ≤ h[i] ≤ 10^9); если n = 0, вторая строка пустая.
// 
// Формат результата:
// — одно целое число — суммарный объём запертой воды.
// 
// Требуемая сложность: O(n) по времени и O(1) по дополнительной памяти.
// 
// Пример 1:
// Вход:
// 12
// 0 1 0 2 1 0 1 3 2 1 2 1
// Выход:
// 6
// 
// Пример 2:
// Вход:
// 6
// 4 2 0 3 2 5
// Выход:
// 9
// 
// Пример 3:
// Вход:
// 3
// 5 1 5
// Выход:
// 4
// 
// Пример 4:
// Вход:
// 0
// 
// Выход:
// 0

/**
 * Hollowreed Tide Locking.
 *
 * После отлива над каждой позицией i остаётся слой воды, равный
 * max(0, min(maxLeft, maxRight) - h[i]), где maxLeft и maxRight —
 * самые высокие тростники слева и справа. Это обычная задача
 * о «запертой воде», только вместо столбиков — тростники.
 *
 * Решаем двумя указателями с краёв к центру: тот край, где текущий
 * максимум ниже, уже не сможет стать «стенкой» для противоположной
 * стороны, поэтому уровень воды над ним определяется однозначно.
 * Время O(n), дополнительная память O(1).
 */
function tideLocking(heights) {
  if (!Array.isArray(heights) || heights.length < 3) {
    // Меньше трёх тростников — жёлоб образовать некому, воде негде запереться.
    return 0;
  }

  let left = 0;
  let right = heights.length - 1;
  let maxLeft = 0;  // самый высокий тростник, встреченный слева
  let maxRight = 0; // самый высокий тростник, встреченный справа
  let locked = 0;   // накопленный объём запертой воды

  while (left < right) {
    if (heights[left] < heights[right]) {
      // Слева опора ниже: уровень воды над left задаёт maxLeft.
      if (heights[left] >= maxLeft) {
        maxLeft = heights[left]; // новый максимум — вода здесь не держится
      } else {
        locked += maxLeft - heights[left]; // разница и есть слой воды
      }
      left += 1;
    } else {
      // Симметричный случай: опора справа ниже, уровень задаёт maxRight.
      if (heights[right] >= maxRight) {
        maxRight = heights[right];
      } else {
        locked += maxRight - heights[right];
      }
      right -= 1;
    }
  }

  return locked;
}

// Экспорт основной функции решения: модуль можно подключить и вызвать tideLocking([...]).
export { tideLocking };
