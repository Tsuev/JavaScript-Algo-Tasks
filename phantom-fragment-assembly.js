// Задача: Phantom Fragment Assembly
// Сложность: hard
// Дата генерации: 2026-09-22

// Условие задачи
// Название: Phantom Fragment Assembly.
// 
// Учёные секвенировали небольшой участок ДНК и получили набор перекрывающихся фрагментов. Известно, что ровно один из этих фрагментов — «фантом»: он случайно попал в образец из другого организма и не является частью исходной последовательности. Все остальные фрагменты действительно вырезаны из одной и той же строки-генома.
// 
// Требуется найти фантом и определить минимально возможную длину генома, из которого могли получиться все остальные фрагменты.
// 
// Формально: даны N строк. Нужно выбрать одну строку-фантом и удалить её. Для оставшихся N−1 строк надо построить кратчайшую общую надстроку — строку, в которой каждая из оставшихся строк встречается как непрерывная подстрока. Среди всех вариантов удаления выбирается тот, при котором длина такой кратчайшей надстроки минимальна.
// 
// Гарантируется, что фантом определён однозначно: минимум длины достигается ровно при удалении одного конкретного фрагмента.
// 
// Входные данные:
// Первая строка содержит целое число N (2 ≤ N ≤ 10).
// Следующие N строк — фрагменты, состоящие из строчных латинских букв, длина каждого от 1 до 12 символов.
// 
// Выходные данные:
// Первая строка — фрагмент-фантом (тот, который нужно удалить).
// Вторая строка — минимальная длина кратчайшей общей надстроки оставшихся фрагментов.
// 
// Пример 1:
// Вход:
// 5
// acgt
// cgta
// gtac
// tttt
// tacg
// 
// Выход:
// tttt
// 7
// 
// Пояснение к примеру 1: после удаления «tttt» оставшиеся фрагменты acgt, cgta, gtac, tacg склеиваются в строку acgtacg длины 7 (соседние перекрываются по 3 символа). Любое другое удаление даёт более длинную надстроку.
// 
// Пример 2:
// Вход:
// 3
// ab
// bc
// xy
// 
// Выход:
// xy
// 3
// 
// Пояснение к примеру 2: без «xy» остаются «ab» и «bc», которые склеиваются в «abc» длины 3.

function solve(input) {
  // Разбираем вход: первая строка — число фрагментов, дальше идут сами фрагменты.
  const tokens = input.split('\n').map(s => s.trim()).filter(s => s !== '');
  const n = parseInt(tokens[0], 10);
  const fragments = tokens.slice(1, 1 + n);

  // Максимальное перекрытие двух строк: длина наибольшего суффикса a,
  // совпадающего с префиксом b. Это экономия символов при приставлении b справа к a.
  const overlap = (a, b) => {
    const lim = Math.min(a.length, b.length);
    for (let k = lim; k >= 1; k--) {
      if (a.endsWith(b.slice(0, k))) return k;
    }
    return 0;
  };

  // Длина кратчайшей общей надстроки для набора строк.
  const scsLength = (arr) => {
    // Строки, целиком содержащиеся в другой строке, никогда не удлиняют ответ,
    // поэтому их можно сразу выбросить (дубликаты оставляем ровно в одном экземпляре).
    const kept = arr.filter((s, i) =>
      !arr.some((t, j) =>
        j !== i && t.includes(s) && (t.length > s.length || j < i)
      )
    );
    const m = kept.length;
    if (m === 0) return 0; // вырожденный случай: собирать нечего

    // Предподсчитываем перекрытия между всеми парами оставшихся фрагментов.
    const ov = Array.from({ length: m }, () => new Array(m).fill(0));
    for (let i = 0; i < m; i++) {
      for (let j = 0; j < m; j++) {
        if (i !== j) ov[i][j] = overlap(kept[i], kept[j]);
      }
    }

    // Для фиксированного порядка фрагментов длина надстроки равна сумме их длин
    // минус сумма перекрытий соседних элементов. Поэтому достаточно перебрать порядок
    // (полный перебор с отсечением по уже найденному минимуму).
    const used = new Array(m).fill(false);
    let best = Infinity;

    const dfs = (last, cur, cnt) => {
      if (cur >= best) return;            // хуже найденного — дальше нет смысла идти
      if (cnt === m) { best = cur; return; }
      for (let i = 0; i < m; i++) {
        if (used[i]) continue;
        used[i] = true;
        if (last === -1) {
          dfs(i, kept[i].length, 1);
        } else {
          dfs(i, cur + kept[i].length - ov[last][i], cnt + 1);
        }
        used[i] = false;
      }
    };
    dfs(-1, 0, 0);
    return best;
  };

  // Перебираем, какой фрагмент объявить фантомом, и ищем минимальную длину сборки.
  // При равенстве длин берём лексикографически меньший фрагмент-фантом.
  let bestLen = Infinity;
  let phantom = null;
  for (let skip = 0; skip < n; skip++) {
    const rest = fragments.filter((_, i) => i !== skip);
    const len = scsLength(rest);
    if (phantom === null || len < bestLen ||
        (len === bestLen && fragments[skip] < phantom)) {
      bestLen = len;
      phantom = fragments[skip];
    }
  }

  return phantom + '\n' + bestLen;
}
