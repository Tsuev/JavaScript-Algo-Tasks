// Задача: Whisperfern Pollen Routing
// Сложность: medium
// Дата генерации: 2026-11-01

// Условие задачи
// В волшебной долине Висперферн n папоротников растут по кругу. Папоротники пронумерованы от 1 до n; соседними считаются i и i+1, а также n и 1. У папоротника i сейчас лежит a[i] пыльцевых зёрен, а к празднику нужно, чтобы у него было ровно b[i] зёрен. За один перенос можно взять одно зерно с любого папоротника и переместить его на соседний папоротник; стоимость такого переноса равна 1. Нужно найти минимальное суммарное число переносов, чтобы получить из распределения a распределение b, или вернуть -1, если это невозможно.
// 
// Формат входных данных: функция whisperfernPollenRouting(a, b) принимает два массива целых неотрицательных чисел. Если длины массивов различаются, это невозможно. Гарантируется, что 1 <= n <= 200000 и 0 <= a[i], b[i] <= 10000.
// 
// Формат результата: одно целое число — минимальное количество переносов, либо -1, если суммы пыльцы в массивах не совпадают или длины массивов различаются.
// 
// Пример 1:
// a = [0, 0, 3], b = [1, 1, 1]
// Ответ: 2
// Объяснение: одно зерно можно перенести с папоротника 3 на папоротник 1 по кругу, ещё одно — с 3 на 2; всего 2 переноса.
// 
// Пример 2:
// a = [2, 0, 0], b = [0, 0, 2]
// Ответ: 2
// Объяснение: два зерна переносятся с папоротника 1 на папоротник 3 по кругу, каждое за 1 перенос.
// 
// Пример 3:
// a = [1, 2], b = [2, 2]
// Ответ: -1
// Объяснение: суммарное количество пыльцы различается, поэтому получить нужное распределение нельзя.

function whisperfernPollenRouting(a, b) {
  // Если массивы разной длины, распределения заведомо несовместимы.
  if (a.length !== b.length) return -1;

  const n = a.length;

  // Без равенства общего количества пыльцы пересыпать её невозможно.
  let sumA = 0;
  let sumB = 0;
  for (let i = 0; i < n; i++) {
    sumA += a[i];
    sumB += b[i];
  }
  if (sumA !== sumB) return -1;

  // Считаем префиксные дисбалансы по кругу:
  // balance после i-го папоротника показывает, сколько пыльцы
  // должно пройти через разрез между i и i+1 при выбранном начале отсчёта.
  const prefix = [];
  let balance = 0;
  for (let i = 0; i < n; i++) {
    balance += a[i] - b[i];
    prefix.push(balance);
  }

  // На круге общий сдвиг всех потоков можно выбрать произвольно.
  // Чтобы минимизировать сумму |поток|, сдвиг нужно привязать к медиане
  // префиксных дисбалансов. Для чётного n подходит любой из двух средних.
  prefix.sort((x, y) => x - y);
  const median = prefix[Math.floor(n / 2)];

  // После выбора оптимального сдвига стоимость — сумма расстояний
  // префиксных дисбалансов до медианы.
  let moves = 0;
  for (const value of prefix) {
    moves += Math.abs(value - median);
  }

  return moves;
}
