// Задача: Tallowglass Tide Reconciliation
// Сложность: medium
// Дата генерации: 2026-11-13

// Условие задачи
// Хранители маяка ведут два независимых журнала всплесков прилива — по одному на каждый таллогласовый датчик (tallowglass). Журнал — это массив моментов времени в минутах от начала суток.
// 
// Два всплеска из разных журналов описывают один и тот же прилив, если разница их моментов не превышает d минут. Каждый всплеск можно использовать не более одного раза. Нужно согласовать (reconcile) журналы: найти максимальное число пар «свой–свой», вывести сами пары, а также моменты, оставшиеся без пары.
// 
// ВХОДНЫЕ ДАННЫЕ:
// функция reconcileTide(timesA, timesB, d), где
// — timesA, timesB — массивы целых чисел (минуты от полуночи), 0 ≤ длина ≤ 10^5, значения 0 ≤ t ≤ 10^9;
// — d — максимально допустимая разница моментов, 0 ≤ d ≤ 10^9.
// Массивы могут быть не отсортированы — исходный порядок не важен (в решении они сортируются).
// 
// РЕЗУЛЬТАТ: объект
// {
//   matchedCount: число согласованных пар,
//   pairs: массив пар [момент из A, момент из B], упорядоченный по возрастанию момента из A,
//   unmatchedA: моменты из timesA, не вошедшие ни в одну пару (по возрастанию),
//   unmatchedB: то же для timesB (по возрастанию)
// }
// 
// ПРАВИЛО ВЫБОРА ПАР (детерминированное): берём самый ранний ещё не использованный момент из A и самый ранний из B; если |a − b| ≤ d — образуем пару, иначе отбрасываем меньший из двух моментов (он уже не сможет ни с чем совпасть, ведь все оставшиеся моменты другого журнала ещё больше). Такая жадная стратегия даёт максимальное число пар.
// 
// ПРИМЕРЫ:
// 1) reconcileTide([0, 10, 20], [3, 12, 22], 5)
//    → { matchedCount: 3, pairs: [[0,3],[10,12],[20,22]], unmatchedA: [], unmatchedB: [] }
// 2) reconcileTide([0, 10], [6], 3)
//    → { matchedCount: 0, pairs: [], unmatchedA: [0, 10], unmatchedB: [6] }
// 3) reconcileTide([3, 2, 1], [3, 2], 0)
//    → { matchedCount: 2, pairs: [[2,2],[3,3]], unmatchedA: [1], unmatchedB: [] }
// 4) reconcileTide([], [5, 7], 10)
//    → { matchedCount: 0, pairs: [], unmatchedA: [], unmatchedB: [5, 7] }
// 
// СЛОЖНОСТЬ: O(n log n + m log m) по времени (сортировка) и O(n + m) дополнительной памяти.

function reconcileTide(timesA, timesB, d) {
  // Журналы могут прийти в произвольном порядке, поэтому работаем с отсортированными копиями.
  const a = [...timesA].sort((x, y) => x - y);
  const b = [...timesB].sort((x, y) => x - y);

  const pairs = [];
  const unmatchedA = [];
  const unmatchedB = [];

  let i = 0;
  let j = 0;

  // Идём двумя указателями по отсортированным журналам: на каждом шаге
  // сравниваем самые ранние ещё не использованные всплески.
  while (i < a.length && j < b.length) {
    const diff = a[i] - b[j];

    if (Math.abs(diff) <= d) {
      // Всплески достаточно близки — это один и тот же прилив, забираем оба момента.
      pairs.push([a[i], b[j]]);
      i += 1;
      j += 1;
    } else if (diff < 0) {
      // a[i] слишком ранний: все оставшиеся моменты B не меньше b[j],
      // значит этот всплеск уже ни с чем не сойдётся — отправляем его в одиночки.
      unmatchedA.push(a[i]);
      i += 1;
    } else {
      // Симметричная ситуация: b[j] слишком ранний для всех оставшихся моментов A.
      unmatchedB.push(b[j]);
      j += 1;
    }
  }

  // Невзятые хвосты журналов остаются без пар.
  while (i < a.length) unmatchedA.push(a[i++]);
  while (j < b.length) unmatchedB.push(b[j++]);

  return { matchedCount: pairs.length, pairs, unmatchedA, unmatchedB };
}

// Почему жадный проход по двум указателям максимален по числу пар:
// когда разница больше d, меньший из двух моментов нельзя спарить ни с одним
// из оставшихся (они только больше), поэтому потерять его безопасно.
// А когда разница допустима, брать пару «здесь и сейчас» выгодно: это оставляет
// более поздним моментам не меньше возможностей, чем если бы мы отложили пару.
