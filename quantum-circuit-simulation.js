// Задача: Quantum Circuit Simulation
// Сложность: hard
// Дата генерации: 2026-10-09

// Условие задачи
// Постановка задачи.
// 
// Квантовый регистр состоит из n кубитов, изначально все кубиты находятся в состоянии |0⟩, то есть вектор состояния равен |0...0⟩. Задана последовательность из m однокубитных и двухкубитных гейтов. Нужно промоделировать схему и вывести итоговый вектор состояния.
// 
// Нумерация базисных состояний.
// Базисное состояние |i⟩ (0 ≤ i < 2^n) определяется так: кубит с номером k (0 ≤ k < n) находится в |1⟩ тогда и только тогда, когда k-й бит числа i равен 1. Иначе говоря, кубит 0 — самый младший бит. Амплитуда состояния |i⟩ — это i-я компонента вектора состояния (комплексное число).
// 
// Матрицы гейтов (в базисе {|0⟩, |1⟩}):
//   H = (1/√2) * [[1, 1], [1, -1]]
//   X = [[0, 1], [1, 0]]
//   Y = [[0, -i], [i, 0]]
//   Z = [[1, 0], [0, -1]]
//   S = [[1, 0], [0, i]]
//   T = [[1, 0], [0, exp(i*pi/4)]]
//   Rx(t) = [[cos(t/2), -i*sin(t/2)], [-i*sin(t/2), cos(t/2)]]
//   Ry(t) = [[cos(t/2), -sin(t/2)], [sin(t/2), cos(t/2)]]
//   Rz(t) = [[exp(-i*t/2), 0], [0, exp(i*t/2)]]
//   CNOT c t — контролируемое X: если кубит c равен |1⟩, состояние кубита t меняется на противоположное (в индексе базисного состояния это значит, что при установленном бите c бит t инвертируется, иначе ничего не происходит).
//   CZ c t — фаза -1, если оба кубика c и t находятся в |1⟩, и фаза 1 в остальных случаях.
//   SWAP a b — обмен состояниями кубиков a и b (в индексе это перестановка битов a и b).
// 
// Формат входных данных.
// Первая строка содержит два целых числа n и m. В следующих m строках записаны гейты, по одному в строке:
//   H q, X q, Y q, Z q, S q, T q — однокубитные гейты (q — номер кубита);
//   Rx t q, Ry t q, Rz t q — повороты (t — вещественный угол в радианах);
//   CNOT c t, CZ c t — двухкубитные гейты;
//   SWAP a b — обмен кубиков.
// Как обычно, несколько пробелов между токенами допустимы.
// 
// Ограничения.
//   1 ≤ n ≤ 16
//   0 ≤ m ≤ 2000
//   0 ≤ q, c, t, a, b < n, причём c ≠ t и a ≠ b для двухкубитных гейтов
//   |t| ≤ 10 для поворотов
// 
// Формат результата.
// Выведите 2^n строк. В строке с номером i (нумерация с нуля) через пробел записаны действительная и мнимая части амплитуды базисного состояния |i⟩. Ответ проверяется с точностью 10^(-6); рекомендуется печатать шесть знаков после десятичной точки.
// 
// Пример 1.
// Вход:
// 2 3
// H 0
// CNOT 0 1
// H 1
// Выход:
// 0.500000 0.000000
// 0.500000 0.000000
// 0.500000 0.000000
// -0.500000 0.000000
// Пояснение: строки соответствуют |00⟩, |01⟩ (кубит 0 в |1⟩), |10⟩, |11⟩. Получается известное состояние Белла (|00⟩ + |01⟩ + |10⟩ − |11⟩)/2.
// 
// Пример 2.
// Вход:
// 1 1
// Rx 3.14159265358979 0
// Выход:
// 0.000000 0.000000
// 0.000000 -1.000000
// Пояснение: Rx(pi) = -i*X, поэтому |0⟩ переходит в -i|1⟩.
// 
// Пример 3.
// Вход:
// 2 2
// H 1
// SWAP 0 1
// Выход:
// 0.707107 0.000000
// 0.000000 0.000000
// 0.707107 0.000000
// 0.000000 0.000000
// Пояснение: после H на кубите 1 состояние (|00⟩ + |10⟩)/√2, обмен битов переводит его в (|00⟩ + |01⟩)/√2.

/**
 * Симуляция квантовой схемы над n кубитами.
 *
 * Вектор состояния хранится явно: два массива длины 2^n (вещественные
 * и мнимые части амплитуд). Индекс i соответствует базисному состоянию
 * |i>, где k-й бит числа i показывает состояние кубита k (кубит 0 — младший).
 *
 * Любой однокубитный гейт связывает только пары индексов, различающихся
 * битом q, поэтому применяется за один проход по массиву. CNOT, CZ и SWAP —
 * это перестановка/смена знака амплитуд по индексам, тоже один проход.
 * Итоговая сложность O(m * 2^n), памяти O(2^n).
 */
function solve(input) {
  const lines = input.split('\n').map(s => s.trim()).filter(s => s.length > 0);
  const [n, m] = lines[0].split(/\s+/).map(Number);
  const size = 1 << n;

  // Состояние: отдельно вещественная и мнимая части амплитуд.
  const re = new Float64Array(size);
  const im = new Float64Array(size);
  re[0] = 1; // стартуем из |0...0>

  // Матрица однокубитного гейта [a, b, c, d]; каждый элемент — пара [Re, Im].
  const SQ2 = Math.SQRT1_2;
  function matrix(name, th) {
    const c = Math.cos(th / 2), s = Math.sin(th / 2);
    switch (name) {
      case 'H':  return [[SQ2, 0], [SQ2, 0], [SQ2, 0], [-SQ2, 0]];
      case 'X':  return [[0, 0], [1, 0], [1, 0], [0, 0]];
      case 'Y':  return [[0, 0], [0, -1], [0, 1], [0, 0]];
      case 'Z':  return [[1, 0], [0, 0], [0, 0], [-1, 0]];
      case 'S':  return [[1, 0], [0, 0], [0, 0], [0, 1]];
      case 'T':  return [[1, 0], [0, 0], [0, 0], [Math.cos(Math.PI / 4), Math.sin(Math.PI / 4)]];
      case 'Rx': return [[c, 0], [0, -s], [0, -s], [c, 0]];
      case 'Ry': return [[c, 0], [-s, 0], [s, 0], [c, 0]];
      case 'Rz': return [[c, -s], [0, 0], [0, 0], [c, s]];
      default:   return [[1, 0], [0, 0], [0, 0], [1, 0]]; // единичная, на всякий случай
    }
  }

  // Применяем однокубитный гейт к кубиту q.
  function applySingle(q, M) {
    const [a, b, c, d] = M;
    const mask = 1 << q;
    for (let i = 0; i < size; i++) {
      if (i & mask) continue;      // обрабатываем только пару (i, i|mask)
      const j = i | mask;
      // сначала читаем обе амплитуды, потом записываем — так in-place безопасно
      const xr = re[i], xi = im[i];
      const yr = re[j], yi = im[j];
      // i-я амплитуда: a*x + b*y
      re[i] = a[0] * xr - a[1] * xi + b[0] * yr - b[1] * yi;
      im[i] = a[0] * xi + a[1] * xr + b[0] * yi + b[1] * yr;
      // j-я амплитуда: c*x + d*y
      re[j] = c[0] * xr - c[1] * xi + d[0] * yr - d[1] * yi;
      im[j] = c[0] * xi + c[1] * xr + d[0] * yi + d[1] * yr;
    }
  }

  // Обмен амплитуд двух индексов.
  function swapAmplitudes(i, j) {
    const r = re[i]; re[i] = re[j]; re[j] = r;
    const t = im[i]; im[i] = im[j]; im[j] = t;
  }

  for (let k = 1; k <= m; k++) {
    const parts = lines[k].split(/\s+/);
    const name = parts[0];

    if (name === 'CNOT') {
      const mc = 1 << Number(parts[1]);
      const mt = 1 << Number(parts[2]);
      for (let i = 0; i < size; i++) {
        // управляющий бит установлен, целевой — нет: обмен с индексом, где целевой установлен
        if ((i & mc) && !(i & mt)) swapAmplitudes(i, i | mt);
      }
    } else if (name === 'CZ') {
      const mc = 1 << Number(parts[1]);
      const mt = 1 << Number(parts[2]);
      for (let i = 0; i < size; i++) {
        // фаза -1 ровно у состояний |...1...1...>
        if ((i & mc) && (i & mt)) { re[i] = -re[i]; im[i] = -im[i]; }
      }
    } else if (name === 'SWAP') {
      const ma = 1 << Number(parts[1]);
      const mb = 1 << Number(parts[2]);
      if (ma !== mb) {
        for (let i = 0; i < size; i++) {
          // обмениваем только пары (бит a = 1, бит b = 0) <-> (бит a = 0, бит b = 1)
          if ((i & ma) && !(i & mb)) swapAmplitudes(i, i ^ ma ^ mb);
        }
      }
    } else {
      let th = 0, q;
      if (name === 'Rx' || name === 'Ry' || name === 'Rz') {
        th = Number(parts[1]);
        q = Number(parts[2]);
      } else {
        q = Number(parts[1]);
      }
      applySingle(q, matrix(name, th));
    }
  }

  // Печать амплитуд; отдельно избавляемся от некрасивого «-0.000000».
  const fmt = v => {
    const s = v.toFixed(6);
    return s === '-0.000000' ? '0.000000' : s;
  };
  const out = [];
  for (let i = 0; i < size; i++) out.push(fmt(re[i]) + ' ' + fmt(im[i]));
  return out.join('\n');
}
