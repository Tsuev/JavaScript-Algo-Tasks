// Задача: Void Bridge Balancing
// Сложность: hard
// Дата генерации: 2026-09-22

// Условие задачи
// **Void Bridge Balancing**
// 
// Через бесконечную пропасть (void) переброшен мост, состоящий из n секций, стоящих в ряд и жёстко соединённых друг с другом. Секция с номером i (1 ≤ i ≤ n) несёт постоянную вертикальную нагрузку a_i — целое неотрицательное число (a_i ≥ 0).
// 
// Чтобы мост не провис, под стыками между соседними секциями ставят опоры. Если поставить ровно k−1 опору, мост распадается на ровно k непустых непрерывных блоков секций (порядок секций сохраняется, каждый блок — это несколько подряд идущих секций).
// 
// Напряжение одного блока равно квадрату суммарной нагрузки входящих в него секций. Например, блок из секций i..j имеет напряжение (a_i + a_{i+1} + ... + a_j)².
// 
// Суммарное напряжение моста — это сумма напряжений всех его блоков.
// 
// Определите минимально возможное суммарное напряжение моста при расстановке ровно k−1 опоры, то есть при разбиении массива на ровно k непустых отрезков подряд идущих элементов.
// 
// **Формат входных данных**
// 
// Первая строка содержит два целых числа n и k (1 ≤ k ≤ n ≤ 2000).
// Вторая строка содержит n целых чисел a_1, a_2, ..., a_n (0 ≤ a_i ≤ 10^4) — нагрузки секций слева направо.
// 
// **Формат выходных данных**
// 
// Выведите одно целое число — минимальное суммарное напряжение моста. Гарантируется, что ответ не превосходит 4·10^14 и точно представим 64-битным целым.
// 
// **Пример 1**
// 
// Вход:
// 5 2
// 1 2 3 4 5
// 
// Выход:
// 117
// 
// Пояснение: единственная опора ставится между 3-й и 4-й секциями, получаются блоки [1,2,3] и [4,5]. Напряжение равно 6² + 9² = 36 + 81 = 117.
// 
// **Пример 2**
// 
// Вход:
// 3 3
// 2 3 4
// 
// Выход:
// 29
// 
// Пояснение: опора под каждым стыком, напряжение равно 2² + 3² + 4² = 4 + 9 + 16 = 29.
// 
// **Пример 3**
// 
// Вход:
// 4 1
// 1 1 1 1
// 
// Выход:
// 16
// 
// Пояснение: опор нет, весь мост — один блок, напряжение равно 4² = 16.
// 
// **Пример 4**
// 
// Вход:
// 1 1
// 7
// 
// Выход:
// 49

/**
 * Void Bridge Balancing
 *
 * Мост состоит из n секций с нагрузками a[0..n-1]. Нужно поставить ровно k-1 опору,
 * то есть разрезать массив на ровно k непустых непрерывных отрезков, и минимизировать
 * сумму квадратов сумм отрезков.
 *
 * Идея:
 *   dp[t][i] — минимальное напряжение для первых i секций, разбитых ровно на t блоков.
 *   dp[t][i] = min по j < i от ( dp[t-1][j] + (S[i] - S[j])^2 ),
 *   где S — массив префиксных сумм нагрузок.
 *
 * Прямое вычисление требует O(k * n^2), что при n = k = 2000 слишком много.
 * Зато функция стоимости w(j, i) = (S[i] - S[j])^2 удовлетворяет неравенству
 * четырёхугольника: при S[j1] <= S[j2] <= S[i1] <= S[i2] выполняется
 *   w(j1,i1) + w(j2,i2) <= w(j1,i2) + w(j2,i1)
 * (достаточно раскрыть скобки; неотрицательность a_i как раз и даёт монотонность S).
 * Из этого следует монотонность оптимального разреза: opt[i] <= opt[i+1].
 * А значит, к каждому слою DP применима оптимизация «разделяй и властвуй»,
 * дающая O(k * n log n).
 *
 * @param {number} n — количество секций (1 <= n <= 2000)
 * @param {number} k — итоговое количество блоков, опор ставится k-1 (1 <= k <= n)
 * @param {number[]} a — нагрузки секций слева направо
 * @returns {number} минимальное суммарное напряжение моста
 */
function voidBridgeBalancing(n, k, a) {
  // S[i] — суммарная нагрузка первых i секций; напряжение отрезка (j, i]
  // равно (S[i] - S[j])^2.
  const S = new Array(n + 1).fill(0);
  for (let i = 1; i <= n; i++) S[i] = S[i - 1] + a[i - 1];

  // prev — это dp[t-1][*]. Нулевой слой: 0 блоков можно собрать только из 0 секций.
  let prev = new Array(n + 1).fill(Infinity);
  prev[0] = 0;

  for (let t = 1; t <= k; t++) {
    const cur = new Array(n + 1).fill(Infinity);

    // Считаем dp[t][i] для всех i из [il, ir], зная, что оптимальный разрез
    // находится в диапазоне [jl, jr].
    const divideAndConquer = (il, ir, jl, jr) => {
      if (il > ir) return;
      const im = (il + ir) >> 1;

      // Для середины перебираем разрез j: он не меньше t-1 (иначе не хватит секций
      // на предыдущие t-1 блоков) и не больше im-1 (последний блок не пустой).
      const lastJ = Math.min(jr, im - 1);
      let bestValue = Infinity;
      let bestJ = jl;
      for (let j = jl; j <= lastJ; j++) {
        const d = S[im] - S[j];
        const value = prev[j] + d * d;
        if (value < bestValue) {
          bestValue = value;
          bestJ = j;
        }
      }
      cur[im] = bestValue;

      // Из монотонности разреза: слева от im оптимальный j не больше bestJ,
      // справа — не меньше bestJ.
      divideAndConquer(il, im - 1, jl, bestJ);
      divideAndConquer(im + 1, ir, bestJ, jr);
    };

    // Первый осмысленный индекс — t: чтобы получить t непустых блоков, нужно
    // минимум t секций. Первый допустимый разрез — t-1.
    divideAndConquer(t, n, t - 1, n - 1);
    prev = cur;
  }

  return prev[n];
}
