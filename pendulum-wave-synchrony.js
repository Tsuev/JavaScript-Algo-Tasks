// Условие задачи
// Задача: Pendulum Wave Synchrony (сложность medium).
// 
// В классической демонстрации «волна маятников» на общей раме подвешено n маятников с разными периодами. Наблюдение ведётся в течение времени T (величина T фиксирована для эксперимента, но в ответ она не входит).
// 
// Маятник с номером i за время T проходит крайнее (максимальное) отклонение ровно a_i раз, не считая стартового момента t = 0. Значит, он оказывается в крайнем отклонении в моменты времени
// 
//   t = k · (T / a_i),  k = 1, 2, …, a_i.
// 
// Назовём момент времени t ∈ (0, T] моментом синхронизации, если в этот момент хотя бы два маятника одновременно находятся в крайнем отклонении.
// 
// Требуется посчитать количество моментов синхронизации на интервале (0, T].
// 
// Формат ввода
// Первая строка: целое число n (1 ≤ n ≤ 2·10^5) — количество маятников.
// Вторая строка: n целых чисел a_1, a_2, …, a_n (1 ≤ a_i ≤ 10^6).
// 
// Формат вывода
// Одно целое число — количество моментов синхронизации в интервале (0, T].
// 
// Пример 1
// Ввод:
// 2
// 2 3
// Вывод:
// 1
// 
// Пример 2
// Ввод:
// 3
// 6 10 15
// Вывод:
// 8
// 
// Пример 3
// Ввод:
// 1
// 5
// Вывод:
// 0
// 
// Пояснение к примерам
// Пример 1. Первый маятник в крайнем положении при t/T = 1/2 и 1; второй — при t/T = 1/3, 2/3 и 1. Общая точка в (0, 1] только одна: t = T.
// Пример 2. Общие моменты: 1/5, 2/5, 3/5, 4/5, 1/3, 2/3, 1/2 и 1 — всего 8.
// Пример 3. Маятник всего один, пары нет, поэтому моментов синхронизации нет.
// 
// Полезно помнить: ответ не зависит от конкретного T, потому что все моменты удобно измерять в долях x = t / T.

/**
 * Задача «Pendulum Wave Synchrony».
 *
 * Маятник i проходит крайнее отклонение в моменты t = k * (T / a_i), k = 1..a_i.
 * Перейдём к безразмерному времени x = t / T. Тогда маятник i находится
 * в крайнем положении ровно в тех точках x ∈ (0, 1], которые можно записать
 * несократимой дробью p / q, у которой знаменатель q делит a_i.
 *
 * Значит, если на q делятся «номера» сразу нескольких маятников, то КАЖДЫЙ
 * момент вида p / q (0 < p <= q) является моментом синхронизации: в нём
 * в крайнем положении оказываются все такие маятники.
 *
 * Для каждого q >= 2 внутри интервала (0, 1) лежит ровно phi(q) несократимых
 * дробей p / q (phi — функция Эйлера), а сама точка x = 1 (то есть t = T)
 * подходит всегда, когда маятников хотя бы два — они одновременно вернулись
 * в исходное крайнее положение.
 *
 * Итог: ответ = 1 + сумма phi(q) по всем q >= 2, на которые делятся
 * значения a_i хотя бы двух маятников.
 *
 * Сложность O(M log M) по времени и O(M) по памяти, где M = max(a_i).
 *
 * @param {number[]} a — массив a_1..a_n (число крайних отклонений за время T)
 * @returns {number} количество моментов синхронизации в интервале (0, T]
 */
function countSynchronyMoments(a) {
  const n = a.length;
  if (n < 2) return 0; // одному маятнику не с кем совпадать

  let maxA = 1;
  for (const v of a) if (v > maxA) maxA = v;

  // freq[v] — сколько маятников имеют ровно v крайних отклонений за время T.
  const freq = new Int32Array(maxA + 1);
  for (const v of a) freq[v]++;

  // divisibleBy[q] — сколько маятников окажутся в крайнем положении
  // в точках вида p/q, то есть сколько чисел a_i делятся на q.
  const divisibleBy = new Int32Array(maxA + 1);
  for (let q = 1; q <= maxA; q++) {
    let sum = 0;
    for (let m = q; m <= maxA; m += q) sum += freq[m];
    divisibleBy[q] = sum;
  }

  // Функция Эйлера phi[q] = число p из [1..q-1], взаимно простых с q:
  // ровно столько несократимых дробей p/q лежит внутри (0, 1).
  // Считаем решетом: вычитаем долю чисел, кратных каждому простому делителю.
  const phi = new Int32Array(maxA + 1);
  for (let i = 0; i <= maxA; i++) phi[i] = i;
  for (let i = 2; i <= maxA; i++) {
    if (phi[i] === i) { // i — простое число
      for (let j = i; j <= maxA; j += i) phi[j] -= phi[j] / i;
    }
  }

  // Момент t = T (x = 1) подходит всегда: все маятники вернулись в крайнее положение.
  let total = 1;
  for (let q = 2; q <= maxA; q++) {
    if (divisibleBy[q] >= 2) total += phi[q];
  }
  return total;
}
