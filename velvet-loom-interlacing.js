// Задача: Velvet Loom Interlacing
// Сложность: hard
// Дата генерации: 2026-10-03

// Условие задачи
// Бархатный станок «Velvet Loom» заправлен n нитями основы, закреплёнными в один ряд сверху и снизу. Позиции пронумерованы слева направо числами 1..n; верхняя и нижняя позиция с одним и тем же номером считаются одной «колонкой».
// 
// За одно переплетение ткач может взять любые две соседние нити (стоящие на позициях i и i+1) и поменять их местами: 1 ≤ i < n. За всю программу ткач выполняет ровно L переплетений; пары можно выбирать произвольно и повторять сколько угодно раз.
// 
// После этого нижние концы нитей соединяются с верхними «в лоб»: нить из i-й колонки снизу пришивается к нити из i-й колонки сверху, то есть полотно замыкается в трубку. Замкнутое полотно распадается на несколько независимых замкнутых нитей (петель ворса).
// 
// Программа переплетения называется удачной, если после замыкания получилась ровно одна замкнутая нить. Посчитайте количество различных удачных программ длины L по модулю 1 000 000 007.
// 
// Формат входных данных: два целых числа n и L — количество нитей основы и количество выполненных переплетений (2 ≤ n ≤ 6, 0 ≤ L ≤ 10^4).
// 
// Формат выходных данных: одно целое число — количество удачных программ длины L по модулю 10^9+7.
// 
// Примеры:
// n = 2, L = 1  →  1
// n = 3, L = 2  →  2
// n = 3, L = 0  →  0
// n = 4, L = 3  →  6
// 
// Пояснение к первому примеру: доступно ровно одно переплетение — поменять местами нити 1 и 2; после замыкания концов обе нити образуют одну непрерывную петлю.
// Пояснение ко второму примеру: удачны программы (1, 2) и (2, 1): сначала переплести нити на позициях 1 и 2, затем на позициях 2 и 3 — или наоборот. Программы (1, 1), (2, 2) дают две петли.

const MOD = 1_000_000_007;

// Ключевой факт о замыкании косы: если после всех переплетений нить,
// стоящая на позиции i, пришла из исходной колонки p[i], то число замкнутых
// нитей в полотне равно числу циклов подстановки p.
// Одно переплетение соседних нитей i и i+1 — это просто обмен p[i] и p[i+1],
// поэтому состояние станка полностью описывается массивом p длины n.
//
// Так как n ≤ 6, различных состояний не больше 6! = 720, поэтому можно
// честно перебрать все программы динамикой по числу сделанных переплетений:
// время O(n! · n · L), память O(n!).

function countVelvetLoops(n, L) {
  // --- 1. Перечисляем все n! перестановок и раздаём им номера ---
  const perms = [];
  const permIndex = new Map();
  const stack = [];
  const used = new Array(n).fill(false);

  (function generate() {
    if (stack.length === n) {
      permIndex.set(stack.join(','), perms.length);
      perms.push(stack.slice());
      return;
    }
    for (let v = 0; v < n; v++) {
      if (used[v]) continue;
      used[v] = true;
      stack.push(v);
      generate();
      stack.pop();
      used[v] = false;
    }
  })();

  const total = perms.length; // n!
  const moves = n - 1;        // сколько различных переплетений доступно

  // --- 2. Предсчитываем таблицу переходов между состояниями ---
  const afterMove = new Int32Array(total * moves);
  for (let s = 0; s < total; s++) {
    const p = perms[s];
    for (let i = 0; i < moves; i++) {
      const q = p.slice();
      const t = q[i];
      q[i] = q[i + 1];
      q[i + 1] = t; // нити на позициях i и i+1 поменялись местами
      afterMove[s * moves + i] = permIndex.get(q.join(','));
    }
  }

  // --- 3. Динамика: dp[s] — сколько программ приводят станок в состояние s ---
  let dp = new Float64Array(total);
  dp[0] = 1; // первой сгенерирована перестановка-тождество, её номер 0

  for (let step = 0; step < L; step++) {
    const next = new Float64Array(total);
    for (let s = 0; s < total; s++) {
      const ways = dp[s];
      if (ways === 0) continue;
      const base = s * moves;
      for (let i = 0; i < moves; i++) {
        const to = afterMove[base + i];
        const sum = next[to] + ways;
        next[to] = sum >= MOD ? sum - MOD : sum; // значения < MOD, хватает одного вычитания
      }
    }
    dp = next;
  }

  // --- 4. Складываем варианты, у которых ровно один цикл (одна замкнутая нить) ---
  let answer = 0;
  for (let s = 0; s < total; s++) {
    if (dp[s] === 0) continue;
    if (isSingleCycle(perms[s])) answer = (answer + dp[s]) % MOD;
  }
  return answer;
}

// Проверяем, что подстановка p (p[i] — из какой колонки пришла нить на позиции i)
// состоит ровно из одного цикла.
function isSingleCycle(p) {
  const n = p.length;
  const seen = new Array(n).fill(false);
  let cycles = 0;

  for (let i = 0; i < n; i++) {
    if (seen[i]) continue;
    cycles++;
    if (cycles > 1) return false; // второй цикл — уже не то, выходим сразу
    let j = i;
    while (!seen[j]) {
      seen[j] = true;
      j = p[j];
    }
  }

  return cycles === 1;
}

// Примеры вызова:
// countVelvetLoops(2, 1) === 1
// countVelvetLoops(3, 2) === 2
// countVelvetLoops(3, 0) === 0
// countVelvetLoops(4, 3) === 6
