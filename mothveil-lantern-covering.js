// Задача: Mothveil Lantern Covering
// Сложность: hard
// Дата генерации: 2026-11-08

// Условие задачи
// Mothveil Lantern Covering
// 
// По кольцевой тропе длины C расставлены фонари. Фонарь с номером i стоит в точке p_i (целое, 0 <= p_i < C) и освещает дугу радиуса r_i в обе стороны от себя, то есть все точки кольца, дуговое расстояние от которых до p_i не превосходит r_i. Иными словами, фонарь освещает дугу [p_i - r_i, p_i + r_i] по модулю C.
// 
// Мотыльковая вуаль накрыла всю тропу, и нужно осветить её целиком, зажигая как можно меньше фонарей. Требуется определить минимальное количество фонарей, которые нужно включить, чтобы каждая точка кольца была освещена хотя бы одним включённым фонарём. Если осветить кольцо целиком невозможно, вернуть -1. Концы освещённых дуг считаются освещёнными (дуги замкнуты), точки касания дуг тоже дают покрытие.
// 
// Формат входных данных (аргументы функции):
//   minLanterns(C, lanterns)
//     C        — целое число, длина кольца (1 <= C <= 1e9);
//     lanterns — массив из n пар [p_i, r_i] (0 <= p_i < C, 0 <= r_i <= 1e9), 0 <= n <= 2e5.
// 
// Формат результата:
//   целое число — минимальное число фонарей, либо -1, если покрыть кольцо нельзя.
// 
// Ограничения и ожидаемая сложность:
//   n <= 2 * 10^5, поэтому решение должно работать за O(n log n) и не перебирать подмножества фонарей.
// 
// Примеры:
//   1) C = 10, lanterns = [[0,3],[4,2],[7,3]]
//      Фонари освещают [7,13] (= [7,10) + [0,3]), [2,6] и [4,10].
//      Двух фонарей не хватает (в любой паре остаётся дырка), а все три покрывают кольцо.
//      Ответ: 3.
// 
//   2) C = 10, lanterns = [[0,1],[2,1],[4,1],[6,1],[8,1]]
//      Каждый фонарь светит на отрезок длины 2: [9,11], [1,3], [3,5], [5,7], [7,9].
//      Вместе они покрывают всё кольцо, и без любого из них появляется разрыв.
//      Ответ: 5.
// 
//   3) C = 10, lanterns = [[0,1],[5,1]]
//      Освещены только [9,11] и [4,6], остаются тёмные участки (1,4) и (6,9).
//      Ответ: -1.
// 
//   4) C = 12, lanterns = [[3,7]]
//      Один фонарь освещает дугу длины 14 >= 12, то есть всё кольцо.
//      Ответ: 1.
// 
//   5) C = 10, lanterns = []
//      Ответ: -1.

/**
 * Mothveil Lantern Covering.
 *
 * Идея решения.
 * 1) Разворачиваем кольцо в отрезок, дублируя все дуги со сдвигом на C.
 *    Тогда «покрыть кольцо» = «покрыть отрезок [s, s + C]» для некоторого
 *    начала s, совпадающего с началом какой-то дуги.
 * 2) Для каждой дуги заранее считаем jump[i] — самую «дальнюю» дугу, которую
 *    выгодно взять следующей (она начинается не позже конца текущей и имеет
 *    максимально правый конец). Это классический жадный шаг.
 * 3) Чтобы не проходить цепочку jump целиком для каждого старта, строим
 *    двоичный подъём (binary lifting) и за O(log n) узнаём, сколько прыжков
 *    нужно, чтобы дотянуться до s + C.
 *
 * Итоговая сложность: O(n log n) по времени, O(n log n) по памяти.
 *
 * Использование: minLanterns(C, [[p0, r0], [p1, r1], ...]) -> число или -1.
 */
function minLanterns(C, lanterns) {
  const n = lanterns.length;
  if (n === 0) return -1;

  // Переводим каждую лампу в дугу [s, s + 2r] на развёрнутой прямой.
  const base = [];
  for (const [pos, r] of lanterns) {
    // Один фонарь, освещающий дугу длины не меньше длины кольца, решает всё.
    if (2 * r >= C) return 1;
    const s = ((pos - r) % C + C) % C; // начало дуги в [0, C)
    base.push([s, s + 2 * r]);
  }

  // Дублируем окружность: вторая копия каждой дуги сдвинута на C.
  const all = [];
  for (const [s, e] of base) {
    all.push([s, e]);
    all.push([s + C, e + C]);
  }
  // Сортируем по началу; при равных началах — сначала более длинная дуга.
  all.sort((a, b) => a[0] - b[0] || b[1] - a[1]);

  const m = all.length;
  const starts = all.map((a) => a[0]);
  const ends = all.map((a) => a[1]);

  // prefixBest[i] — индекс дуги с самым правым концом среди all[0..i].
  const prefixBest = new Array(m);
  let best = 0;
  for (let i = 0; i < m; i++) {
    if (ends[i] > ends[best]) best = i;
    prefixBest[i] = best;
  }

  // jump[i] — оптимальный следующий шаг: среди дуг, начинающихся не позже
  // конца ends[i], берём ту, что тянется правее всех.
  const jump = new Array(m);
  for (let i = 0; i < m; i++) {
    // Бинарный поиск самого правого индекса с starts[idx] <= ends[i].
    let lo = 0;
    let hi = m - 1;
    let rightmost = 0;
    while (lo <= hi) {
      const mid = (lo + hi) >> 1;
      if (starts[mid] <= ends[i]) {
        rightmost = mid;
        lo = mid + 1;
      } else {
        hi = mid - 1;
      }
    }
    jump[i] = prefixBest[rightmost];
  }

  // Двоичный подъём: up[k][i] — куда попадём из i за 2^k прыжков.
  const LOG = Math.max(1, Math.ceil(Math.log2(m)) + 1);
  const up = [jump];
  for (let k = 1; k < LOG; k++) {
    const prev = up[k - 1];
    const cur = new Array(m);
    for (let i = 0; i < m; i++) cur[i] = prev[prev[i]];
    up.push(cur);
  }

  let answer = Infinity;

  // Пробуем каждую дугу в роли «первой» в цепочке покрытия.
  // Достаточно первых копий, у которых начало меньше C.
  for (let i = 0; i < m; i++) {
    if (starts[i] >= C) continue;
    const target = starts[i] + C; // правый край отрезка, который надо покрыть
    if (ends[i] >= target) {
      answer = Math.min(answer, 1);
      continue;
    }

    let cur = i;
    let used = 1; // дуга i уже взята

    // Максимально «прыгаем» вперёд, пока не дошли до target.
    for (let k = LOG - 1; k >= 0; k--) {
      const nx = up[k][cur];
      if (ends[nx] < target) {
        cur = nx;
        used += 1 << k;
      }
    }

    // Одного прыжка из текущей позиции должно хватить до target,
    // иначе покрыть кольцо с таким стартом нельзя (цепочка застряла).
    if (ends[jump[cur]] >= target) {
      answer = Math.min(answer, used + 1);
    }
  }

  return answer === Infinity ? -1 : answer;
}
