// Задача: Obsidian Shard Mosaic
// Сложность: hard
// Дата генерации: 2026-09-20

// Условие задачи
// Осколки обсидиана имеют форму L-тримино (уголок из трёх единичных квадратов, как квадрат 2x2 без одного угла). Их можно поворачивать на 90, 180, 270 градусов, но нельзя отражать. У вас есть прямоугольная мозаичная доска размером N x M. Некоторые клетки повреждены (обозначены '#') и не могут быть покрыты. Все остальные клетки ('.') должны быть полностью покрыты осколками без наложений и пропусков. Посчитайте количество различных способов замостить доску. Так как ответ может быть большим, выведите его по модулю 1 000 000 007.
// 
// Формат входных данных:
// Первая строка содержит два целых числа N и M (1 <= N <= 100, 1 <= M <= 8).
// Следующие N строк содержат по M символов: '.' — целая клетка, '#' — повреждённая клетка.
// 
// Формат выходных данных:
// Одно целое число — количество замощений по модулю 1 000 000 007.
// 
// Пример:
// Вход:
// 2 3
// ...
// ...
// Выход:
// 2
// 
// Пояснение к примеру:
// Доску 2x3 можно замостить двумя способами.

/**
 * Основная функция решения задачи "Obsidian Shard Mosaic".
 * @param {number} N - количество строк
 * @param {number} M - количество столбцов
 * @param {string[]} grid - массив строк с символами '.' и '#'
 * @returns {number} количество замощений по модулю 1e9+7
 */
function countMosaicTilings(N, M, grid) {
  const MOD = 1000000007n;

  // dp: отображение маски (какие клетки текущей строки уже закрыты осколками из предыдущей строки)
  // в количество способов достичь такого состояния.
  let dp = new Map();
  dp.set(0, 1n);

  for (let i = 0; i < N; i++) {
    const nextDp = new Map();
    const rowBlocked = grid[i];
    const nextRowBlocked = i + 1 < N ? grid[i + 1] : null;

    for (const [inMask, count] of dp) {
      if (i === N - 1) {
        // Последняя строка: не можем класть новые осколки, только проверяем, что все целые клетки уже закрыты.
        let valid = true;
        for (let c = 0; c < M; c++) {
          if (rowBlocked[c] === '.' && (inMask & (1 << c)) === 0) {
            valid = false;
            break;
          }
          // Повреждённые клетки не должны быть закрыты.
          if (rowBlocked[c] === '#' && (inMask & (1 << c)) !== 0) {
            valid = false;
            break;
          }
        }
        if (valid) {
          const newCount = (nextDp.get(0) || 0n) + count;
          nextDp.set(0, newCount % MOD);
        }
      } else {
        // Обрабатываем строку i. Нужно заполнить все пустые клетки, начиная с первой.
        // DFS по столбцам. curMask — маска закрытых клеток в строке i,
        // nextMask — маска закрытых клеток в строке i+1 (которые мы закрываем сейчас).
        const outCounts = new Map(); // outMask -> количество способов

        function dfs(c, curMask, nextMask) {
          // Ищем первую пустую (не закрытую и не повреждённую) клетку в строке i.
          while (c < M && (rowBlocked[c] === '#' || (curMask & (1 << c)) !== 0)) {
            c++;
          }
          if (c === M) {
            // Вся строка заполнена, запоминаем получившуюся маску для следующей строки.
            outCounts.set(nextMask, (outCounts.get(nextMask) || 0n) + 1n);
            return;
          }

          // Пытаемся поставить L-тримино так, чтобы его самая верхняя-левая клетка была (i, c).
          // Всего 4 возможных ориентации.

          // 1. Вправо и вниз: (i,c), (i,c+1), (i+1,c)
          if (c + 1 < M && rowBlocked[c + 1] === '.' && nextRowBlocked[c] === '.' &&
              (curMask & (1 << (c + 1))) === 0 && (nextMask & (1 << c)) === 0) {
            dfs(c + 1, curMask | (1 << c) | (1 << (c + 1)), nextMask | (1 << c));
          }

          // 2. Вправо и вниз-вправо: (i,c), (i,c+1), (i+1,c+1)
          if (c + 1 < M && rowBlocked[c + 1] === '.' && nextRowBlocked[c + 1] === '.' &&
              (curMask & (1 << (c + 1))) === 0 && (nextMask & (1 << (c + 1))) === 0) {
            dfs(c + 1, curMask | (1 << c) | (1 << (c + 1)), nextMask | (1 << (c + 1)));
          }

          // 3. Вниз и вниз-вправо: (i,c), (i+1,c), (i+1,c+1)
          if (c + 1 < M && nextRowBlocked[c] === '.' && nextRowBlocked[c + 1] === '.' &&
              (nextMask & (1 << c)) === 0 && (nextMask & (1 << (c + 1))) === 0) {
            dfs(c + 1, curMask | (1 << c), nextMask | (1 << c) | (1 << (c + 1)));
          }

          // 4. Вниз и вниз-влево: (i,c), (i+1,c-1), (i+1,c)
          if (c - 1 >= 0 && nextRowBlocked[c - 1] === '.' && nextRowBlocked[c] === '.' &&
              (nextMask & (1 << (c - 1))) === 0 && (nextMask & (1 << c)) === 0) {
            dfs(c + 1, curMask | (1 << c), nextMask | (1 << (c - 1)) | (1 << c));
          }
        }

        dfs(0, inMask, 0);

        // Добавляем найденные способы в nextDp с учётом количества путей до inMask.
        for (const [outMask, ways] of outCounts) {
          const add = (count * ways) % MOD;
          const newCount = (nextDp.get(outMask) || 0n) + add;
          nextDp.set(outMask, newCount % MOD);
        }
      }
    }
    dp = nextDp;
  }

  // После обработки всех строк единственное допустимое состояние — outMask = 0.
  const result = dp.get(0) || 0n;
  return Number(result % MOD);
}
