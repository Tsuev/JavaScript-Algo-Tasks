// Задача: Mosslight Spore Relay
// Сложность: medium
// Дата генерации: 2026-10-19

// Условие задачи
// Моховая колония «Мшистый свет» передаёт споры по пещере. Пещера задана прямоугольной картой из R строк и C столбцов; каждый символ карты — это:
// 
// - '#' — моховая колония (источник спор),
// - '.' — пустой воздух, по которому споры могут распространяться,
// - 'X' — каменная стена, споры сквозь неё не проходят.
// 
// В момент времени 0 споры находятся во всех клетках мха одновременно. Каждую следующую секунду каждая заражённая клетка передаёт споры во все соседние по стороне клетки (вверх, вниз, влево, вправо), если те не являются стеной и ещё не заражены. Мох считается заражённым с самого начала.
// 
// Требуется узнать два числа:
// 
// 1) время в секундах, за которое заразится последняя достижимая клетка воздуха, то есть максимум времени заражения по всем клеткам '.' (если ни одна клетка воздуха не заразилась, время равно 0);
// 2) количество клеток воздуха, до которых споры так и не добрались.
// 
// Формат входа: функция solveSporeRelay(grid) принимает grid — массив строк одинаковой длины, состоящих из символов '#', '.' и 'X'.
// 
// Формат результата: массив из двух чисел [time, unreachable], где time — максимальное время заражения среди клеток воздуха (0, если таких заражений не было), unreachable — число незаражённых клеток воздуха.
// 
// Ограничения: 0 <= R, C <= 1000, R*C <= 10^6. Ожидаемая сложность — O(R*C).
// 
// Пример 1.
// Вход:
// grid = [
//   '.....',
//   '..#..',
//   '.....',
//   '.X...',
//   '.....']
// Выход: [5, 0]
// Пояснение: единственная колония стоит в центре; дальний левый нижний угол она заражает на 5-й секунде, все клетки воздуха достижимы.
// 
// Пример 2.
// Вход:
// grid = ['#X.', 'X.X', '.X#']
// Выход: [0, 3]
// Пояснение: все три клетки воздуха полностью отрезаны стенами, поэтому ни одна не заражается, а время остаётся нулевым.
// 
// Пример 3.
// Вход:
// grid = ['.#.']
// Выход: [1, 0]
// Пояснение: две клетки воздуха примыкают к мху и заражаются за одну секунду.
// 
// Пример 4.
// Вход:
// grid = []
// Выход: [0, 0]

// Задача Mosslight Spore Relay.
// Споры стартуют сразу из всех клеток мха, поэтому это классический
// multi-source BFS: кладём в очередь все источники с временем 0 и
// распространяем волну по слоям — каждая клетка получает время на 1 больше.

function solveSporeRelay(grid) {
  const rows = grid.length;
  const cols = rows > 0 ? grid[0].length : 0;

  // dist[r][c] — секунда, на которой клетка заразилась, либо -1, если ещё нет.
  const dist = Array.from({ length: rows }, () => new Array(cols).fill(-1));
  const queue = [];
  let airTotal = 0;

  // Инициализация: любая колония мха — источник, её время равно нулю.
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) {
      const ch = grid[r][c];
      if (ch === '#') {
        dist[r][c] = 0;
        queue.push([r, c]);
      } else if (ch === '.') {
        airTotal++;
      }
    }
  }

  const dr = [-1, 1, 0, 0];
  const dc = [0, 0, -1, 1];
  let head = 0;          // указатель на начало очереди вместо shift() — так быстрее
  let lastTime = 0;      // максимальное время заражения среди клеток воздуха
  let airReached = 0;    // сколько клеток воздуха удалось заразить

  while (head < queue.length) {
    const [r, c] = queue[head++];
    const nextTime = dist[r][c] + 1;

    for (let k = 0; k < 4; k++) {
      const nr = r + dr[k];
      const nc = c + dc[k];

      if (nr < 0 || nr >= rows || nc < 0 || nc >= cols) continue; // вышли за карту
      if (grid[nr][nc] === 'X') continue;                          // стена не пропускает споры
      if (dist[nr][nc] !== -1) continue;                           // клетка уже заражена раньше или одновременно

      dist[nr][nc] = nextTime;

      // Время интересует только по воздуху: клетки мха были заражены изначально.
      if (grid[nr][nc] === '.') {
        airReached++;
        if (nextTime > lastTime) lastTime = nextTime;
      }

      queue.push([nr, nc]);
    }
  }

  // Всё, что не посчиталось достижимым, — это отрезанный стенами воздух.
  const unreachable = airTotal - airReached;
  return [lastTime, unreachable];
}
