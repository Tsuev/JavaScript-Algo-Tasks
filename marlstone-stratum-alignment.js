// Условие задачи
// Задача: Marlstone Stratum Alignment (выравнивание мергелевых слоёв).
// 
// Мергель залегает горизонтальными слоями. Геологи пробурили две скважины и получили два вертикальных разреза — последовательности толщин слоёв (в метрах) сверху вниз. Разрезы не совпадают: часть слоёв в одной скважине отсутствует из-за размыва или несогласия, поэтому при сопоставлении нужно вставлять пропуски.
// 
// Требуется выровнять две последовательности: каждый слой можно либо сопоставить ровно одному слою другой последовательности (порядок слоёв сохраняется), либо оставить без пары. Непрерывный блок из k подряд идущих слоёв одной последовательности, не имеющих пары в другой, называется пропуском (несогласием).
// 
// Стоимость выравнивания складывается из:
// - сопоставление слоёв толщиной x и y стоит |x − y|;
// - пропуск из k слоёв стоит gapOpen + k · gapExtend (gapOpen — плата за открытие несогласия, gapExtend — плата за каждый пропущенный слой).
// 
// Нужно найти минимально возможную суммарную стоимость.
// 
// Формат входа:
// solve(a, b, gapOpen, gapExtend)
// - a — массив толщин слоёв первой скважины (целые положительные числа, длина n ≥ 0);
// - b — массив толщин слоёв второй скважины (целые положительные числа, длина m ≥ 0);
// - gapOpen, gapExtend — неотрицательные целые числа.
// 
// Формат результата:
// одно число — минимальная стоимость выравнивания.
// 
// Примеры:
// 1) solve([10, 5], [9], 2, 1) = 4. Пояснение: сопоставляем 10↔9 (стоимость 1), слой 5 оставляем без пары (пропуск длины 1: 2+1=3). Итого 1+3=4.
// 2) solve([5], [50], 2, 1) = 6. Пояснение: сопоставление стоило бы |5−50|=45, а два пропуска по одному слою — (2+1)+(2+1)=6. Выбираем 6.
// 3) solve([4, 4, 4], [4], 3, 1) = 5. Пояснение: сопоставляем один слой 4↔4 (0), остальные два слоя образуют один пропуск длины 2: 3+2·1=5.

function solve(a, b, gapOpen, gapExtend) {
  const n = a.length;
  const m = b.length;
  const INF = Infinity;

  // Три состояния динамики для выравнивания с аффинным штрафом за пропуск:
  // M[i][j] — первые i слоёв a и первые j слоёв b уже выровнены, и последняя пара — это сопоставление a[i-1] с b[j-1].
  // X[i][j] — то же, но последний слой a[i-1] остался без пары (пропуск в b).
  // Y[i][j] — то же, но последний слой b[j-1] остался без пары (пропуск в a).
  const M = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(INF));
  const X = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(INF));
  const Y = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(INF));

  M[0][0] = 0; // пустые префиксы выровнены бесплатно

  for (let i = 0; i <= n; i++) {
    for (let j = 0; j <= m; j++) {
      if (i === 0 && j === 0) continue;

      // Вариант 1: сопоставить слои a[i-1] и b[j-1], заплатив за разницу толщин.
      if (i > 0 && j > 0) {
        const prev = Math.min(M[i - 1][j - 1], X[i - 1][j - 1], Y[i - 1][j - 1]);
        if (prev !== INF) {
          M[i][j] = prev + Math.abs(a[i - 1] - b[j - 1]);
        }
      }

      // Вариант 2: слой a[i-1] без пары (пропуск в b).
      // Пропуск можно либо открыть заново (платим gapOpen + gapExtend), либо продлить (платим только gapExtend).
      if (i > 0) {
        let best = INF;
        const openFrom = Math.min(M[i - 1][j], Y[i - 1][j]);
        if (openFrom !== INF) best = Math.min(best, openFrom + gapOpen + gapExtend);
        if (X[i - 1][j] !== INF) best = Math.min(best, X[i - 1][j] + gapExtend);
        X[i][j] = best;
      }

      // Вариант 3: слой b[j-1] без пары (пропуск в a) — симметрично варианту 2.
      if (j > 0) {
        let best = INF;
        const openFrom = Math.min(M[i][j - 1], X[i][j - 1]);
        if (openFrom !== INF) best = Math.min(best, openFrom + gapOpen + gapExtend);
        if (Y[i][j - 1] !== INF) best = Math.min(best, Y[i][j - 1] + gapExtend);
        Y[i][j] = best;
      }
    }
  }

  // Выравнивание может закончиться любым из трёх состояний — берём минимум.
  return Math.min(M[n][m], X[n][m], Y[n][m]);
}
