// Условие задачи
// Задача: Glimmerreed Channel Arbitration.
// 
// Во Флеймриде натянуты k светящихся каналов связи. По ним надо передать как можно больше пакетов сигнала. Пакет i занимает канал в течение промежутка [l_i, r_i) — с момента l_i включительно до r_i не включительно. В каждый момент один канал передаёт максимум один пакет. Два пакета a и b могут идти по одному каналу без конфликта тогда и только тогда, когда их промежутки не перекрываются, то есть r_a <= l_b или r_b <= l_a (промежутки полуоткрытые, поэтому касание в точке допустимо).
// 
// Нужно выбрать максимальное число пакетов, которые можно распределить по k каналам так, чтобы на каждом канале выбранные пакеты попарно не перекрывались.
// 
// Формат ввода:
// - первая строка: два целых числа n и k (1 <= n <= 200000, 1 <= k <= 200000) — число пакетов и каналов;
// - следующие n строк: по два целых числа l_i и r_i (0 <= l_i < r_i <= 10^9) — промежуток передачи пакета.
// 
// Формат вывода:
// - одно целое число — максимальное количество пакетов, которые можно обслужить на k каналах.
// 
// Пример 1:
// Ввод:
// 3 1
// 1 4
// 2 3
// 4 7
// Вывод:
// 2
// Пояснение: при одном канале нельзя взять и [1,4), и [2,3) — они пересекаются. Оптимально взять [1,4) и [4,7) (касание в точке 4 разрешено), либо [2,3) и [4,7). Итого 2.
// 
// Пример 2:
// Ввод:
// 4 2
// 1 5
// 2 3
// 3 4
// 4 6
// Вывод:
// 4
// Пояснение: на первый канал кладём [1,5), на второй — цепочку [2,3), [3,4), [4,6) (соседние касаются в точках 3 и 4, это разрешено). Значит все 4 пакета помещаются.
// 
// Идея решения: сортируем пакеты по левому концу и заметаем время слева направо. Держим множество уже выбранных, ещё активных пакетов. Если в некоторый момент одновременно активны больше k выбранных пакетов, надо выбросить пакет с самым поздним правым концом — он освободит канал позже всех, поэтому такая жадность оптимальна. Для скорости нужны две кучи по правым концам: min — чтобы убирать завершившиеся пакеты, max — чтобы мгновенно находить худший пакет. Сложность O(n log n).

// Куча на массиве. Компаратор cmp(x, y) < 0 означает, что x стоит «выше» y (ближе к вершине).
class Heap {
  constructor(cmp) { this.a = []; this.cmp = cmp; }
  size() { return this.a.length; }
  peek() { return this.a[0]; }
  push(x) {
    const a = this.a;
    a.push(x);
    let i = a.length - 1;
    while (i > 0) {
      const p = (i - 1) >> 1;
      if (this.cmp(a[i], a[p]) < 0) { const t = a[i]; a[i] = a[p]; a[p] = t; i = p; }
      else break;
    }
  }
  pop() {
    const a = this.a;
    const top = a[0];
    const last = a.pop();
    if (a.length > 0) {
      a[0] = last;
      let i = 0;
      const n = a.length;
      while (true) {
        let best = i;
        const l = 2 * i + 1, r = 2 * i + 2;
        if (l < n && this.cmp(a[l], a[best]) < 0) best = l;
        if (r < n && this.cmp(a[r], a[best]) < 0) best = r;
        if (best === i) break;
        const t = a[i]; a[i] = a[best]; a[best] = t; i = best;
      }
    }
    return top;
  }
}

// Возвращает максимальное число пакетов, которые можно передать на k каналах.
// intervals — массив пар [l, r], промежуток считается полуоткрытым [l, r).
function maxTransmitted(n, k, intervals) {
  if (k <= 0 || n === 0) return 0;

  // Сортируем по левому концу: так мы «заметаем» время слева направо.
  const sorted = intervals.slice().sort((x, y) => x[0] - y[0] || x[1] - y[1]);

  // max-куча по правым концам: быстро находим пакет, который освободит канал позже всех.
  const maxHeap = new Heap((x, y) => y - x);
  // min-куча по правым концам: быстро находим пакеты, которые уже завершились.
  const minHeap = new Heap((x, y) => x - y);

  // Ленивое удаление: сколько раз значение надо «пропустить» при выборке из кучи.
  const skipMax = new Map();
  const skipMin = new Map();

  const cleanMax = () => {
    while (maxHeap.size() > 0) {
      const v = maxHeap.peek();
      const c = skipMax.get(v) || 0;
      if (c > 0) { skipMax.set(v, c - 1); maxHeap.pop(); } else break;
    }
  };
  const cleanMin = () => {
    while (minHeap.size() > 0) {
      const v = minHeap.peek();
      const c = skipMin.get(v) || 0;
      if (c > 0) { skipMin.set(v, c - 1); minHeap.pop(); } else break;
    }
  };

  let total = 0;   // сколько пакетов выбрано в итоге (это и есть ответ)
  let active = 0;  // сколько выбранных пакетов ещё занимают канал прямо сейчас

  for (const [l, r] of sorted) {
    // Снимаем с учёта пакеты, завершившиеся до начала текущего (правый конец <= l).
    while (true) {
      cleanMin();
      if (minHeap.size() === 0) break;
      const v = minHeap.peek();
      if (v <= l) {
        minHeap.pop();
        active--;
        // Пакет остаётся выбранным, но из max-кучи его надо будет пропустить.
        skipMax.set(v, (skipMax.get(v) || 0) + 1);
      } else break;
    }

    // Берём текущий пакет.
    maxHeap.push(r);
    minHeap.push(r);
    total++;
    active++;

    // Если одновременно занято больше k каналов — выбрасываем пакет с самым поздним концом.
    // Именно он дольше всех держит канал, поэтому освобождать надо его.
    if (active > k) {
      cleanMax();
      const dropped = maxHeap.pop();
      active--;
      total--;
      // И из min-кучи этот пакет тоже надо будет пропустить.
      skipMin.set(dropped, (skipMin.get(dropped) || 0) + 1);
    }
  }

  return total;
}
