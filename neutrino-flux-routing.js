// Условие задачи
// **Neutrino Flux Routing**
// 
// В глубоководной обсерватории установлено N нейтринных детекторов (модулей), пронумерованных от 1 до N. Модули соединены M направленными каналами: канал a → b способен пропускать не более c нейтрино в секунду. Нейтрино рождаются в модуле 1 и должны быть зарегистрированы в модуле N.
// 
// Каждый промежуточный модуль i (все, кроме 1 и N) может безопасно пропустить через себя не более cap[i] нейтрино в секунду — при большей нагрузке он выходит из строя. Исток (модуль 1) и сток (модуль N) ограничений на собственную нагрузку не имеют.
// 
// Требуется найти максимальный суммарный поток нейтрино из модуля 1 в модуль N, при котором не нарушается ни пропускная способность каналов, ни вместимость модулей. Формально: максимизировать величину потока по направленным рёбрам при сохранении баланса в промежуточных вершинах, ограничении 0 ≤ f(ребро) ≤ c(ребро) и при дополнительном условии, что суммарный поток через каждую промежуточную вершину не превосходит cap[i].
// 
// **Формат ввода**
// 
// - Первая строка: два целых числа N и M — количество модулей и каналов.
// - Вторая строка: N целых чисел cap[1..N] — предельная нагрузка каждого модуля (для модулей 1 и N значение можно игнорировать).
// - Далее M строк: `a b c` — направленный канал из модуля a в модуль b с пропускной способностью c. Гарантируется a ≠ b.
// 
// **Формат вывода**
// 
// Одно целое число — максимально возможный поток нейтрино из модуля 1 в модуль N.
// 
// **Пример 1**
// 
// Ввод:
// ```
// 4 5
// 100 3 4 100
// 1 2 10
// 1 3 10
// 2 4 10
// 3 4 10
// 2 3 1
// ```
// Вывод:
// ```
// 7
// ```
// Пояснение: единственные каналы, ведущие в сток 4, — это 2 → 4 и 3 → 4, поэтому весь поток обязан пройти через модули 2 и 3. Их вместимости равны 3 и 4, значит, суммарный поток не может превзойти 3 + 4 = 7, и это значение достижимо.
// 
// **Пример 2**
// 
// Ввод:
// ```
// 5 6
// 100 100 2 3 100
// 1 2 5
// 2 3 5
// 2 4 5
// 3 5 5
// 4 5 5
// 1 5 1
// ```
// Вывод:
// ```
// 6
// ```
// Пояснение: один нейтрино идёт напрямую по каналу 1 → 5 (пропускная способность 1), ещё пять — через модуль 2, где поток делится на две ветви: 2 единицы через модуль 3 (вместимость 2) и 3 единицы через модуль 4 (вместимость 3). Итого 1 + 5 = 6.
// 
// **Ограничения**
// 
// 2 ≤ N ≤ 1000, 0 ≤ M ≤ 5000, 0 ≤ c ≤ 10^9, 0 ≤ cap[i] ≤ 10^9. Гарантируется, что весь поток умещается в 64-битный диапазон.

/**
 * Neutrino Flux Routing
 *
 * Это задача о максимальном потоке с ограничениями сразу двух типов:
 *  - на пропускную способность рёбер (каналов);
 *  - на суммарный поток через вершину (вместимость модуля).
 *
 * Ключевая идея — свести вершинные ограничения к рёберным.
 * Каждую вершину i «расщепляем» на два узла in(i) и out(i):
 *   in(i)  = 2*i
 *   out(i) = 2*i + 1
 * и соединяем их ребром in(i) -> out(i). Пропускная способность этого
 * ребра равна вместимости модуля (для истока и стока — бесконечности).
 * Тогда любой путь 1 -> ... -> N вынужден проходить через эти рёбра,
 * и ограничение на модуль превращается в обычное ограничение на ребро.
 *
 * После сведения остаётся классический максимальный поток,
 * который считаем алгоритмом Диница (быстрый на практике).
 */

class Dinic {
  constructor(size) {
    this.size = size;
    // Список смежности: graph[u] — массив рёбер вида {to, cap, rev},
    // где rev — индекс обратного ребра в graph[to].
    this.graph = Array.from({ length: size }, () => []);
    this.level = new Int32Array(size);
    this.iter = new Int32Array(size);
  }

  // Добавляем ребро u -> v с пропускной способностью cap
  // и сразу обратное ребро v -> u с нулевой пропускной способностью.
  addEdge(u, v, cap) {
    this.graph[u].push({ to: v, cap, rev: this.graph[v].length });
    this.graph[v].push({ to: u, cap: 0, rev: this.graph[u].length - 1 });
  }

  // BFS строит слоистую сеть: расстояние по числу рёбер от истока.
  bfs(s, t) {
    this.level.fill(-1);
    const queue = [s];
    this.level[s] = 0;
    for (let head = 0; head < queue.length; head++) {
      const u = queue[head];
      for (const e of this.graph[u]) {
        if (e.cap > 0 && this.level[e.to] === -1) {
          this.level[e.to] = this.level[u] + 1;
          queue.push(e.to);
        }
      }
    }
    return this.level[t] !== -1;
  }

  // DFS ищет дополняющий путь в слоистой сети и проталкивает поток.
  // Параметр pushed — сколько ещё можно протолкнуть по текущему пути.
  dfs(u, t, pushed) {
    if (u === t) return pushed;
    for (; this.iter[u] < this.graph[u].length; this.iter[u]++) {
      const e = this.graph[u][this.iter[u]];
      // Идём только по рёбрам, увеличивающим слой (условие Диница).
      if (e.cap > 0 && this.level[e.to] === this.level[u] + 1) {
        const delta = this.dfs(e.to, t, Math.min(pushed, e.cap));
        if (delta > 0) {
          e.cap -= delta;
          this.graph[e.to][e.rev].cap += delta;
          return delta;
        }
      }
    }
    return 0;
  }

  maxFlow(s, t) {
    let flow = 0;
    // Каждая фаза BFS + блокирующий поток (набор DFS) увеличивает поток.
    while (this.bfs(s, t)) {
      this.iter.fill(0);
      let pushed;
      while ((pushed = this.dfs(s, t, Infinity)) > 0) {
        flow += pushed;
      }
    }
    return flow;
  }
}

/**
 * Основная функция решения.
 *
 * @param {number} n            количество модулей (1..n)
 * @param {number[][]} channels список каналов: [a, b, c] (a, b — 1-based)
 * @param {number[]} moduleCap  moduleCap[i] — вместимость модуля i+1 (0-based индексация)
 * @returns {number} максимальный поток из модуля 1 в модуль n
 */
function maxNeutrinoFlux(n, channels, moduleCap) {
  // В новой сети 2*n вершин: по паре in/out на каждый модуль.
  const dinic = new Dinic(2 * n);

  // Сумма всех пропускных способностей заведомо больше любого потока,
  // поэтому её можно использовать как «бесконечность» без риска переполнения.
  const totalCapacity = channels.reduce((sum, ch) => sum + ch[2], 0);
  const INF = totalCapacity + 1;

  // Рёбра, отвечающие за вместимость самих модулей.
  // У истока и стока ограничения нет, поэтому кладём INF.
  for (let i = 0; i < n; i++) {
    const isTerminal = i === 0 || i === n - 1;
    dinic.addEdge(2 * i, 2 * i + 1, isTerminal ? INF : moduleCap[i]);
  }

  // Каналы: выходим из out-узла модуля a, входим в in-узел модуля b.
  for (const [a, b, c] of channels) {
    const from = 2 * (a - 1) + 1; // out(a)
    const to = 2 * (b - 1);       // in(b)
    dinic.addEdge(from, to, c);
  }

  // Исток — out(модуль 1), сток — in(модуль n).
  const source = 1;
  const sink = 2 * (n - 1);

  return dinic.maxFlow(source, sink);
}
