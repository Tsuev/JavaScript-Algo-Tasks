// Условие задачи
// В улье «Кварцевый» есть n камер, соединённых n−1 туннелями так, что между любыми двумя камерами существует ровно один путь (то есть камеры образуют дерево). В i-й камере лежит a_i кристаллов кварца. За одну операцию можно перенести один кристалл по одному туннелю в соседнюю камеру. Требуется сделать так, чтобы во всех камерах стало одинаковое количество кристаллов. Гарантируется, что суммарное количество кристаллов делится на n. Найдите минимальное количество операций.
// 
// Формат входных данных:
// В первой строке — целое число n (1 ≤ n ≤ 100000).
// Во второй строке — n целых чисел a_i (0 ≤ a_i ≤ 10^9).
// В следующих n−1 строках — по два целых числа u и v (1 ≤ u, v ≤ n, u ≠ v) — туннель между камерами u и v.
// 
// Формат результата:
// Одно целое число — минимальное количество операций.
// 
// Пример 1:
// Вход:
// 4
// 1 0 5 2
// 1 2
// 1 3
// 1 4
// Выход:
// 5
// 
// Пример 2:
// Вход:
// 5
// 4 0 0 0 1
// 1 2
// 2 3
// 3 4
// 4 5
// Выход:
// 6
// 
// Пояснение к примеру 1. Сумма кристаллов равна 8, значит в каждой камере должно оказаться по 2. Из камеры 3 нужно вынести 3 лишних кристалла, в камеру 2 нужно принести 2. Итого 5 переносов по туннелям.
// 
// Пояснение к примеру 2. В улье-цепочке из 5 камер суммарно 4 + 0 + 0 + 0 + 1 = 5 кристаллов, цель — по 1 в каждой. Кристаллы из первой камеры последовательно сдвигаются к пустым камерам: 1 перенос до камеры 2, 2 переноса до камеры 3, 3 переноса до камеры 4. В сумме 1 + 2 + 3 = 6 операций.

// Основная функция: n — число камер, a — массив кристаллов (0-индексация),
// edges — список туннелей [u, v] в 0-индексации.
function balanceHive(n, a, edges) {
  // Строим список смежности улья-дерева.
  const adj = Array.from({ length: n }, () => []);
  for (const [u, v] of edges) {
    adj[u].push(v);
    adj[v].push(u);
  }

  const total = a.reduce((s, x) => s + x, 0);
  const target = total / n; // столько кристаллов должно быть в каждой камере

  // Итеративный обход в глубину, чтобы не переполнить стек на больших n.
  // parent[v] — родитель вершины v в дереве, корень — 0.
  const parent = new Array(n).fill(-1);
  const order = []; // порядок обхода: родитель всегда раньше потомка
  const stack = [0];
  parent[0] = 0;
  while (stack.length > 0) {
    const v = stack.pop();
    order.push(v);
    for (const to of adj[v]) {
      if (parent[to] === -1) {
        parent[to] = v;
        stack.push(to);
      }
    }
  }

  // sum[v] — сколько кристаллов сейчас в поддереве v,
  // size[v] — сколько камер в поддереве v.
  const sum = a.slice();
  const size = new Array(n).fill(1);
  let moves = 0;

  // Идём по вершинам в обратном порядке обхода: сначала листья, потом родители.
  for (let i = order.length - 1; i > 0; i--) {
    const v = order[i];
    const p = parent[v];

    // Через ребро v–p должно пройти ровно столько кристаллов,
    // на сколько текущая сумма в поддереве v отличается от целевой.
    // Модуль означает: кристаллы могут идти в любую сторону.
    moves += Math.abs(sum[v] - target * size[v]);

    // Присоединяем поддерево v к родителю.
    sum[p] += sum[v];
    size[p] += size[v];
  }

  return moves;
}
