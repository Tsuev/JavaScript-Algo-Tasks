// Условие задачи
// Дана строка s, состоящая только из символов '(', ')', '{', '}', '[', ']'. Проверьте, является ли она корректной скобочной последовательностью. Строка корректна, если каждая открывающая скобка закрывается соответствующей закрывающей скобкой того же типа и при этом соблюдается правильный порядок вложенности.
// 
// Формат входных данных: одна строка s, длина от 1 до 10^4, содержащая только указанные шесть символов.
// 
// Формат выходных данных (возвращаемое значение): булевое значение true — если последовательность корректна, false — иначе.
// 
// Примеры:
// 1) s = '()' → true
// 2) s = '()[]{}' → true
// 3) s = '(]' → false
// 4) s = '([)]' → false
// 5) s = '{[]}' → true

const isValid = function(s) {
    // стек для хранения ожидаемых закрывающих скобок
    const stack = [];
    // соответствие открывающей скобки её закрывающей паре
    const pairs = {
        '(': ')',
        '{': '}',
        '[': ']'
    };

    for (let i = 0; i < s.length; i++) {
        const ch = s[i];
        if (pairs[ch]) {
            // встретили открывающую — запоминаем, какую закрывающую ждём
            stack.push(pairs[ch]);
        } else {
            // встретили закрывающую: она должна совпасть с последней ожидаемой
            if (stack.pop() !== ch) {
                return false;
            }
        }
    }

    // если в стеке ничего не осталось — все скобки корректно закрылись
    return stack.length === 0;
};
