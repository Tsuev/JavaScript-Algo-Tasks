// Задача: Lumen Well Overflow
// Сложность: medium
// Дата генерации: 2026-10-17

// Условие задачи
// ## Lumen Well Overflow
// 
// ### Условие
// Представь светящийся колодец, поперечное сечение которого задано массивом `walls` из `n` неотрицательных целых чисел. Значение `walls[i]` — высота твёрдой породы в столбце `i`. Между столбцами породы образуются впадины, в которых скапливается «светящаяся вода». В колодец сверху выливают `volume` единиц этой жидкости.
// 
// Края колодца открыты: как только уровень жидкости где-то превышает высоту ограничивающей породы (включая сами крайние столбцы), излишек стекает за границы и теряется.
// 
// Нужно определить два числа:
// - `trapped` — сколько жидкости останется удержанной внутри рельефа;
// - `overflow` — сколько жидкости выльется за края.
// 
// Удерживающая способность рельефа — это классическая задача о «собранной воде»: над каждым столбцом `i` может стоять слой воды высотой `min(maxLeft, maxRight) - walls[i]`, где `maxLeft` — максимум породы слева (включая сам столбец), `maxRight` — максимум справа (включая сам столбец). Сумма этих слоёв — полная ёмкость `capacity`.
// 
// Поскольку жидкость сначала заполняет колодец, а лишнее стекает:
// - `trapped = min(volume, capacity)`;
// - `overflow = max(0, volume - capacity)`.
// 
// ### Формат входных данных
// - `walls` — массив целых чисел `0 <= walls[i]`, длина `0 <= n`.
// - `volume` — целое неотрицательное число `volume >= 0`.
// 
// ### Формат результата
// Объект `{ trapped, overflow }` с двумя целыми числами.
// 
// ### Примеры
// - `walls = [0,1,0,2,1,0,1,3,2,1,2,1]`, `volume = 4` → `{ trapped: 4, overflow: 0 }` (ёмкость 6, вся жидкость помещается).
// - `walls = [0,1,0,2,1,0,1,3,2,1,2,1]`, `volume = 10` → `{ trapped: 6, overflow: 4 }` (ёмкость 6, излишек 4).
// - `walls = [3,0,3]`, `volume = 5` → `{ trapped: 3, overflow: 2 }`.
// - `walls = []`, `volume = 7` → `{ trapped: 0, overflow: 7 }` (рельефа нет, удерживать нечего).
// 
// ### Ограничения
// Решай за `O(n)` по времени и `O(1)` дополнительной памяти.

/**
 * Вычисляет, сколько светящейся жидкости удержится в колодце,
 * а сколько перельётся через край.
 *
 * Идея: сначала считаем полную ёмкость рельефа (сколько воды
 * он способен удержать), затем сравниваем её с влитым объёмом.
 * Ёмкость находим двумя указателями за один проход,
 * не создавая дополнительных массивов.
 */
export function lumenWellOverflow(walls, volume) {
  // На всякий случай приводим входы к безопасным значениям.
  const heights = Array.isArray(walls) ? walls : [];
  const n = heights.length;
  const poured = volume > 0 ? volume : 0;

  // Полная ёмкость рельефа.
  let capacity = 0;

  // Два указателя двигаются навстречу друг другу.
  // leftMax/rightMax хранят максимальную высоту породы,
  // встреченную слева и справа соответственно.
  let left = 0;
  let right = n - 1;
  let leftMax = 0;
  let rightMax = 0;

  while (left < right) {
    // Обрабатываем ту сторону, где порода ниже: именно она
    // ограничивает уровень воды в текущем столбце.
    if (heights[left] < heights[right]) {
      if (heights[left] >= leftMax) {
        // Новая «стенка» выше прежней — вода здесь не копится.
        leftMax = heights[left];
      } else {
        // Между leftMax и текущим столбцом помещается слой воды.
        capacity += leftMax - heights[left];
      }
      left++;
    } else {
      if (heights[right] >= rightMax) {
        rightMax = heights[right];
      } else {
        capacity += rightMax - heights[right];
      }
      right--;
    }
  }

  // Всё, что влезло, остаётся; остальное стекает за края.
  const trapped = Math.min(poured, capacity);
  const overflow = Math.max(0, poured - capacity);

  return { trapped, overflow };
}
