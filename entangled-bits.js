// Условие задачи
// Задача «Entangled Bits».
// 
// В лаборатории квантовых вычислений есть n кубитов, пронумерованных от 1 до n. Каждый кубит при измерении даёт значение 0 или 1. Никаких значений изначально не известно.
// 
// Учёные провели m экспериментов. Каждый эксперимент задаётся тройкой (l, r, c), где 1 ≤ l ≤ r ≤ n и c ∈ {0, 1}, и означает: если измерить все кубиты с номерами от l до r и сложить их значения по модулю 2 (взять XOR), получится ровно c. Иначе говоря,
// 
//     b_l ⊕ b_{l+1} ⊕ … ⊕ b_r = c,
// 
// где b_i — значение i-го кубита.
// 
// Нужно выяснить:
//   1) существует ли хотя бы один набор значений (b_1, …, b_n), при котором выполняются все m экспериментов;
//   2) если да, то сколько кубитов имеют однозначно определённое значение — таких, чьё значение одинаково во всех допустимых наборах.
// 
// Формат входных данных.
// Первая строка содержит два целых числа n и m — количество кубитов и экспериментов.
// Следующие m строк содержат по три целых числа l, r, c, описывающих очередной эксперимент.
// 
// Формат выходных данных.
// Выведите одно целое число:
//   • количество кубитов с однозначно определённым значением, если хотя бы один допустимый набор существует;
//   • -1, если допустимого набора значений не существует (эксперименты противоречат друг другу).
// 
// Ограничения: 1 ≤ n ≤ 2·10^5, 0 ≤ m ≤ 2·10^5, 1 ≤ l ≤ r ≤ n, c ∈ {0, 1}.
// 
// Пример 1.
// Вход:
// 3 2
// 1 1 1
// 3 3 0
// Выход:
// 2
// Пояснение: b_1 = 1, b_3 = 0, а b_2 свободен. Однозначно определены b_1 и b_3.
// 
// Пример 2.
// Вход:
// 4 3
// 1 2 0
// 3 4 0
// 1 1 1
// Выход:
// 2
// Пояснение: b_1 = b_2 = 1 (из b_1 ⊕ b_2 = 0 и b_1 = 1), а b_3 и b_4 связаны лишь равенством b_3 = b_4, но их абсолютные значения свободны. Определены только b_1 и b_2.
// 
// Пример 3.
// Вход:
// 2 3
// 1 2 1
// 1 1 1
// 2 2 1
// Выход:
// -1
// Пояснение: из первых двух условий b_1 = 1 и b_2 = 1, тогда b_1 ⊕ b_2 = 0, что противоречит третьему условию b_1 ⊕ b_2 = 1.
// 
// Пример 4.
// Вход:
// 5 0
// Выход:
// 0
// Пояснение: без экспериментов ни один кубит не определён.

/*
 * Задача «Entangled Bits».
 *
 * Ключевая идея — переход к префиксным XOR-суммам. Положим
 *     p_0 = 0,   p_i = b_1 XOR b_2 XOR ... XOR b_i   для i = 1..n.
 * Тогда значение бита выражается как b_i = p_i XOR p_{i-1}, а условие
 *     b_l XOR ... XOR b_r = c
 * превращается в обычное соотношение между двумя префиксами:
 *     p_r XOR p_{l-1} = c.
 *
 * Значит каждое запутывание — это ребро между вершинами множества
 * {0, 1, ..., n} с известным значением XOR между ними. Такие системы
 * удобно решать системой непересекающихся множеств с чётностью (weighted
 * DSU): внутри одного компонента все p_i связаны фиксированными XOR.
 *
 * У каждого компонента ровно одна «степень свободы»: все его значения
 * можно одновременно перевернуть. Исключение — компонент вершины 0: там
 * p_0 = 0 известно заранее, поэтому свободы нет.
 *
 * Бит b_i = p_i XOR p_{i-1} определён однозначно тогда и только тогда,
 * когда p_{i-1} и p_i лежат в одном компоненте DSU: тогда их XOR
 * зафиксирован. Если же они в разных компонентах, можно независимо
 * перевернуть один из компонентов и получить другое значение b_i.
 */

function solveEntangledBits(n, constraints) {
  // parent[v], size[v] и parity[v] = p[v] XOR p[parent[v]] описывают DSU.
  const parent = new Int32Array(n + 1);
  const size = new Int32Array(n + 1);
  const parity = new Int8Array(n + 1);
  for (let i = 0; i <= n; i++) {
    parent[i] = i;
    size[i] = 1;
    parity[i] = 0;
  }

  // Поиск корня со сжатием путей. Итеративная версия, чтобы избежать
  // переполнения стека при длинных цепочках. После вызова
  // parity[v] = p[v] XOR p[root].
  function find(v) {
    const chain = [];
    let x = v;
    while (parent[x] !== x) {
      chain.push(x);
      x = parent[x];
    }
    const root = x;
    // Идём от конца пути к началу, накапливая XOR до корня.
    let acc = 0;
    for (let i = chain.length - 1; i >= 0; i--) {
      const node = chain[i];
      acc ^= parity[node];
      parity[node] = acc;
      parent[node] = root;
    }
    return root;
  }

  // Добавляет ограничение p[a] XOR p[b] = c.
  // Возвращает false, если система стала противоречивой.
  function unite(a, b, c) {
    const ra = find(a);
    const rb = find(b);
    const pa = parity[a]; // p[a] XOR p[ra]
    const pb = parity[b]; // p[b] XOR p[rb]

    if (ra === rb) {
      // Компонент один: проверяем совместимость нового соотношения.
      return (pa ^ pb) === c;
    }

    // Нужно сшить компоненты так, чтобы выполнялось p[a] XOR p[b] = c.
    // Из соотношений выше получаем p[ra] XOR p[rb] = pa ^ pb ^ c.
    const rel = pa ^ pb ^ c;
    if (size[ra] < size[rb]) {
      parent[ra] = rb;
      parity[ra] = rel;
      size[rb] += size[ra];
    } else {
      parent[rb] = ra;
      parity[rb] = rel; // так как XOR симметричен
      size[ra] += size[rb];
    }
    return true;
  }

  // Применяем все эксперименты, переводя их в ограничения на префиксы.
  for (let k = 0; k < constraints.length; k++) {
    const l = constraints[k][0];
    const r = constraints[k][1];
    const c = constraints[k][2];
    if (!unite(l - 1, r, c)) {
      return -1; // противоречие — допустимых наборов нет
    }
  }

  // Считаем биты, для которых p_{i-1} и p_i попали в один компонент.
  let answer = 0;
  for (let i = 1; i <= n; i++) {
    if (find(i - 1) === find(i)) {
      answer++;
    }
  }
  return answer;
}

