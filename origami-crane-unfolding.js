// Задача: Origami Crane Unfolding
// Сложность: hard
// Дата генерации: 2026-10-17

// Условие задачи
// Из полоски бумаги, разбитой на n одинаковых клеток, складывают фигурку (журавлика). Клетки пронумерованы слева направо: 0, 1, ..., n−1; клетки i и i+1 соединены линией сгиба (фальцем).
// 
// Складывание идёт по шагам. Каждый шаг задаётся парой [c, side], где c — номер фальца между клетками c и c+1, а side говорит, какая половина перегибается через этот фальц:
//  • 'left' — левая половина (всё, что лежит слева от фальца) поднимается и перегибается вправо;
//  • 'right' — правая половина перегибается влево.
// 
// Бумага идеальная, нулевой толщины, поэтому любой сгиб физически возможен. Перегибаемая половина отражается относительно линии фальца и ложится СВЕРХУ на неподвижную; при перевороте порядок слоёв в каждой стопке перегибаемой половины меняется на противоположный (самый нижний слой становится самым верхним).
// 
// После всех сгибов нужно вывести строение получившейся плоской стопки: для каждой позиции слева направо — список номеров клеток, лежащих в этой позиции, снизу вверх.
// 
// Формат входа: solve(n, folds), где n — число клеток (1 ≤ n ≤ 2000), folds — массив пар [c, side] (0 ≤ c < n−1, side — строка 'left' или 'right'), не более 2000 сгибов.
// Формат выхода: массив стопок слева направо; каждая стопка — массив номеров клеток снизу вверх. Сумма длин всех стопок всегда равна n.
// 
// Гарантируется, что в момент сгиба клетки c и c+1 лежат в разных стопках (иначе сгиб невозможен). На всякий случай такой вырожденный сгиб решение просто игнорирует.
// 
// Пример 1: solve(4, [[1, 'right']]) = [[0,3],[1,2]].
// Пояснение: клетка 2 ложится на клетку 1, клетка 3 ложится на клетку 0.
// 
// Пример 2: solve(4, [[0, 'right']]) = [[3],[2],[0,1]].
// Пояснение: правая половина длиннее левой, поэтому она «вылезает» за край: клетка 1 накрывает клетку 0, а клетки 2 и 3 оказываются левее.
// 
// Пример 3: solve(4, [[1,'right'], [0,'left']]) = [[1,2,3,0]].
// Пояснение: после первого сгиба получились стопки [0,3] и [1,2]; вторая, левая стопка переворачивается и ложится сверху, поэтому самым верхним слоем оказывается клетка 0.
// 
// Пример 4: solve(1, []) = [[0]].

function solve(n, folds) {
  // Стопки упорядочены слева направо, внутри каждой — номера клеток снизу вверх.
  let stacks = Array.from({ length: n }, (_, i) => [i]);

  // Правая половина перегибается налево.
  // left — стопки слева от фальца (0..k), right — справа (k+1..), right[0] примыкает к фальцу.
  function foldRightOntoLeft(left, right) {
    const k = left.length - 1;
    const m = right.length;
    // Самый дальний от фальца стек right[m-1] уедет в позицию k-(m-1); она может оказаться отрицательной.
    const shift = Math.min(0, k - m + 1);
    const res = new Array(k - shift + 1);
    for (let t = 0; t <= k; t++) res[t - shift] = left[t].slice();
    for (let j = 0; j < m; j++) {
      // right[j] отстоит от фальца на j+1 клетку и попадает ровно на позицию k-j.
      const moved = right[j].slice().reverse(); // при перевороте слои меняются местами
      const idx = k - j - shift;
      res[idx] = res[idx].concat(moved);
    }
    return res;
  }

  // Левая половина перегибается направо.
  function foldLeftOntoRight(left, right) {
    const k = left.length - 1;
    const r = right.length;
    // Неподвижная часть займёт позиции k+1..k+r, подвижная — k+1..2k+1.
    const top = Math.max(k + r, 2 * k + 1);
    const base = k + 1;
    const res = Array.from({ length: top - base + 1 }, () => []);
    for (let t = 0; t < r; t++) res[t] = right[t].slice();
    for (let j = 0; j <= k; j++) {
      // left[k-j] отстоит от фальца на j+1 клетку и попадает в позицию k+1+j.
      const moved = left[k - j].slice().reverse();
      res[j] = res[j].concat(moved);
    }
    return res;
  }

  for (const [crease, side] of folds) {
    // Определяем, где сейчас лежит каждая клетка.
    const where = new Int32Array(n).fill(-1);
    for (let s = 0; s < stacks.length; s++) {
      for (const cell of stacks[s]) where[cell] = s;
    }
    const a = where[crease];
    const b = where[crease + 1];
    if (a === b) continue;         // фальц уже полностью сложен — сгибать нечего
    const k = Math.min(a, b);      // линия сгиба проходит между стопками k и k+1
    const left = stacks.slice(0, k + 1);
    const right = stacks.slice(k + 1);
    stacks = side === 'right' ? foldRightOntoLeft(left, right) : foldLeftOntoRight(left, right);
  }

  return stacks;
}

// solve(4, [[1, 'right']]) === [[0,3], [1,2]]
