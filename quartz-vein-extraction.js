// Задача: Quartz Vein Extraction
// Сложность: hard
// Дата генерации: 2026-09-13

// Условие задачи
// В шахте обнаружено N кварцевых жил. Для добычи каждой жилы i необходим набор инструментов, который задаётся списком номеров инструментов. Всего существует M типов инструментов, пронумерованных от 0 до M-1. У вас есть ровно по одному инструменту каждого типа. Вы можете добывать любое подмножество жил, но при этом никакие две выбранные жилы не должны требовать один и тот же инструмент. Каждая жила i приносит прибыль p_i. Найдите максимальную суммарную прибыль, которую можно получить.
// 
// Формат ввода:
// Первая строка содержит два целых числа N и M (1 ≤ N ≤ 100, 1 ≤ M ≤ 20).
// Далее идут N строк. Каждая строка описывает одну жилу: сначала целое число p_i (1 ≤ p_i ≤ 10^6), затем целое число k_i (0 ≤ k_i ≤ M) — количество требуемых инструментов, затем k_i различных целых чисел — номера инструментов (от 0 до M-1). Гарантируется, что инструменты в наборе не повторяются и их номера в пределах от 0 до M-1.
// 
// Формат вывода:
// Одно целое число — максимальная суммарная прибыль.
// 
// Пример:
// Ввод:
// 3 3
// 10 1 0
// 15 1 1
// 20 2 0 1
// 
// Вывод:
// 25
// 
// Пояснение: Можно добыть первую и вторую жилы, использовав инструменты 0 и 1 соответственно, суммарная прибыль 10+15=25. Третья жила требует оба инструмента, поэтому её нельзя добыть вместе с ними.

/**
 * Решение задачи "Quartz Vein Extraction".
 * 
 * Мы имеем N жил, каждая требует набор инструментов (до M типов). 
 * У нас есть по одному инструменту каждого типа. Нужно выбрать подмножество жил 
 * с попарно непересекающимися наборами инструментов, максимизируя суммарную прибыль.
 * 
 * Это классическая задача о рюкзаке с ограничением на пересечение множеств. 
 * Поскольку M <= 20, мы можем использовать динамическое программирование по битовой маске 
 * использованных инструментов. dp[mask] = максимальная прибыль, которую можно получить, 
 * используя ровно набор инструментов mask.
 * 
 * Перебираем жилы по одной и для каждой обновляем dp, рассматривая только уже достижимые маски.
 * Чтобы не использовать одну жилу дважды, новые маски добавляются в отдельный список и 
 * обрабатываются только на следующем шаге.
 * 
 * Временная сложность: O(N * 2^M), что при N <= 100 и M <= 20 составляет ~10^8 операций,
 * что приемлемо для JavaScript при оптимизированной реализации.
 */
function extractQuartz(N, M, veins) {
  // Преобразуем наборы инструментов в битовые маски
  const items = veins.map(v => {
    let mask = 0;
    for (const t of v.tools) {
      mask |= (1 << t);
    }
    return { profit: v.profit, mask };
  });

  const totalMasks = 1 << M;
  // dp[mask] = максимальная прибыль, достижимая с набором инструментов mask
  const dp = new Array(totalMasks).fill(-1);
  dp[0] = 0;

  // Список масок, которые уже достижимы. Изначально только пустой набор.
  const inReachable = new Uint8Array(totalMasks);
  inReachable[0] = 1;
  let reachable = [0];

  for (const item of items) {
    const nextReachable = [];
    for (const mask of reachable) {
      // Если инструменты жилы не пересекаются с уже использованными
      if ((mask & item.mask) === 0) {
        const newMask = mask | item.mask;
        const newProfit = dp[mask] + item.profit;
        if (newProfit > dp[newMask]) {
          dp[newMask] = newProfit;
          if (!inReachable[newMask]) {
            inReachable[newMask] = 1;
            nextReachable.push(newMask);
          }
        }
      }
    }
    // Добавляем новые достижимые маски к общему списку
    if (nextReachable.length > 0) {
      reachable = reachable.concat(nextReachable);
    }
  }

  // Ответ — максимум по всем достижимым маскам
  let maxProfit = 0;
  for (const mask of reachable) {
    if (dp[mask] > maxProfit) {
      maxProfit = dp[mask];
    }
  }
  return maxProfit;
}
