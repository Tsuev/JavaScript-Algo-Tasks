// Условие задачи
// Thornmere Beacon Batching
// 
// На побережье Торнмира стоит n сигнальных маяков. У каждого маяка есть целочисленный заряд c[i]. Раз в сутки дежурный запускает «сигнальную партию» — несколько маяков вспыхивают одновременно.
// 
// Правила формирования партий:
// 1) В одну партию можно включить не более K маяков (иначе перегружается реле).
// 2) Заряды маяков внутри одной партии не должны различаться больше чем на D, иначе вспышки гасят друг друга: max(партии) - min(партии) <= D.
// 3) Каждый маяк должен вспыхнуть ровно один раз (каждый маяк попадает ровно в одну партию).
// 
// Маяки можно распределять по партиям в любом порядке — важен только состав партии, а не порядок маяков на берегу.
// 
// Требуется разбить все маяки на минимальное возможное число партий.
// 
// Формат входных данных:
// - charges — массив из n целых чисел (0 <= n <= 200000), заряды маяков;
// - D — целое число (0 <= D <= 10^9), максимально допустимый разброс зарядов в партии;
// - K — целое число (1 <= K <= n при n > 0), максимальный размер партии.
// 
// Формат результата:
// - одно целое число — минимальное количество партий (0, если маяков нет).
// 
// Примеры:
// 1) charges = [1, 2, 11, 12, 21], D = 10, K = 3  ->  2
//    Пояснение: партии {1, 2, 11} (разброс 10, размер 3) и {12, 21} (разброс 9). Одной партией не обойтись: 21 - 1 = 20 > 10.
// 2) charges = [5, 5, 5, 5, 5], D = 0, K = 2  ->  3
// 3) charges = [3, 1, 2], D = 5, K = 1  ->  3
// 4) charges = [1, 100], D = 50, K = 2  ->  2
// 5) charges = [], D = 7, K = 4  ->  0

/**
 * Минимальное число сигнальных партий для всех маяков.
 *
 * @param {number[]} charges заряды маяков
 * @param {number} D максимально допустимый разброс зарядов внутри партии
 * @param {number} K максимальный размер партии
 * @returns {number} минимальное количество партий
 */
function minBatches(charges, D, K) {
  // Ключевая идея: ограничения зависят только от минимума и максимума партии,
  // поэтому партию выгодно собирать из подряд идущих зарядов после сортировки.
  // Любое «перемешивание» можно перестроить в такие последовательные группы,
  // не нарушив ни разброс, ни размер.
  const a = [...charges].sort((x, y) => x - y);

  let batches = 0;
  let i = 0;

  while (i < a.length) {
    // a[i] — самый слабый из ещё не разобранных маяков.
    // Он обязательно должен попасть в какую-то партию, и если ставить его
    // в текущую, то выгоднее добрать как можно больше соседей справа:
    // это никогда не ухудшит оставшийся суффикс (жадность по префиксу).
    let j = i;

    // Расширяем партию, пока не упрёмся в лимит размера K
    // или в предельный разброс зарядов D.
    while (
      j + 1 < a.length &&        // есть следующий маяк
      j + 1 - i < K &&           // размер партии после добавления не превысит K
      a[j + 1] - a[i] <= D       // разброс зарядов остаётся допустимым
    ) {
      j++;
    }

    // Всё, что вошло в партию, больше не рассматриваем.
    i = j + 1;
    batches++;
  }

  return batches;
}

