// Задача: Glintfall Reconvergence
// Сложность: hard
// Дата генерации: 2026-10-30

// Условие задачи
// **Glintfall Reconvergence**
// 
// В кристальном древе ровно n узлов, соединённых n−1 ребром так, что получается дерево. Узел 1 — корень. Каждому узлу v сопоставлено целое число w[v] — его сияние.
// 
// Блик — это частица света. Блик может стартовать в узле u и падать вниз по дереву до узла v тогда и только тогда, когда u является предком v (случай u = v разрешён: блик рождается и сразу гаснет в v). За время падения блик проходит через все узлы пути u → v включительно.
// 
// Резонанс блика равен наибольшему общему делителю сияний всех узлов, через которые он пролетел.
// 
// Схождение узла v — это сумма резонансов всех бликов, которые заканчивают падение именно в v, то есть бликов, стартовавших во всех предках v (включая сам v).
// 
// Для каждого узла найдите его схождение.
// 
// **Формат входных данных**
// 
// Первая строка — целое число n (1 ≤ n ≤ 200000).
// Вторая строка — n целых чисел w[1], w[2], …, w[n] (1 ≤ w[v] ≤ 10^9).
// Следующие n−1 строк — по два числа a, b (1 ≤ a, b ≤ n) — рёбра дерева. Гарантируется, что граф является деревом.
// 
// **Формат выходных данных**
// 
// Одна строка из n целых чисел через пробел — схождение узлов 1, 2, …, n. Ответы помещаются в 64-битный целый тип (максимум ~2·10^14).
// 
// **Пример**
// 
// Вход:
// 5
// 6 4 3 9 2
// 1 2
// 1 3
// 2 4
// 2 5
// 
// Выход:
// 6 6 6 11 6
// 
// **Пояснение к примеру**
// 
// Дерево: 1—2, 1—3, 2—4, 2—5. Сияния: w1=6, w2=4, w3=3, w4=9, w5=2.
// 
// - узел 1: единственный блик [1], gcd(6) = 6 → 6;
// - узел 2: [2] → 4, [1,2] → gcd(6,4) = 2, итого 4+2 = 6;
// - узел 3: [3] → 3, [1,3] → gcd(6,3) = 3, итого 3+3 = 6;
// - узел 4: [4] → 9, [2,4] → gcd(4,9) = 1, [1,2,4] → gcd(6,4,9) = 1, итого 9+1+1 = 11;
// - узел 5: [5] → 2, [2,5] → gcd(4,2) = 2, [1,2,5] → gcd(6,4,2) = 2, итого 2+2+2 = 6.
// 
// **Идея решения**
// 
// Ключевое наблюдение: для путей, заканчивающихся в узле v, различных значений gcd всего O(log max w). При движении от v вверх gcd может только уменьшаться, и каждое строгое уменьшение как минимум вдвое сокращает значение. Поэтому для текущего корневого пути храним сжатый список пар (значение gcd, сколько путей дают это значение) и при спуске к ребёнку пересчитываем список за O(log max w), склеивая одинаковые gcd подряд. Суммарная сложность O(n · log max w), память O(n + log max w · depth). Обход дерева итеративный, чтобы не переполнить стек вызовов на глубине 2·10^5.

// Glintfall Reconvergence
// Для каждого узла v нужно просуммировать gcd по всем путям вида «предок -> v».
// Ключевое наблюдение: различных значений gcd на таких путях всего O(log max(w)),
// потому что при подъёме вверх gcd может только уменьшаться, а каждое строгое
// уменьшение хотя бы вдвое сокращает значение. Значит, можно хранить сжатый
// список пар (gcd, сколько путей дают этот gcd) и пересчитывать его при спуске.
// Обход дерева итеративный — рекурсия не выдержит глубину до 2*10^5.

function solve(input) {
  // ---------- разбор входных данных ----------
  const tokens = input.split(/\s+/).filter(t => t.length > 0);
  let pos = 0;

  const n = Number(tokens[pos++]);

  const shine = new Array(n);
  for (let i = 0; i < n; i++) shine[i] = Number(tokens[pos++]);

  const adj = Array.from({ length: n }, () => []);
  for (let i = 0; i < n - 1; i++) {
    const a = Number(tokens[pos++]) - 1;
    const b = Number(tokens[pos++]) - 1;
    adj[a].push(b);
    adj[b].push(a);
  }

  // ---------- структуры для сжатого списка gcd ----------
  const parent = new Int32Array(n).fill(-1);
  const startIdx = new Int32Array(n); // где начинается список gcd узла в общем стеке
  const endIdx = new Int32Array(n);   // где он заканчивается (не включая)
  const answers = new Array(n);

  // Общий стек пар (значение gcd, количество) для текущего пути от корня.
  // Список узла v занимает отрезок [startIdx[v], endIdx[v]).
  const gcdVal = [];
  const gcdCnt = [];
  let sp = 0;

  // Заход в узел: строим его список gcd из списка родителя.
  const enter = (v) => {
    const base = sp;

    // Путь, состоящий только из самого v.
    gcdVal[sp] = shine[v];
    gcdCnt[sp] = 1;
    sp++;

    // Пути, начинающиеся выше: gcd(старый_gcd, shine[v]).
    // Список родителя упорядочен по невозрастанию gcd, поэтому одинаковые
    // результаты идут подряд и их можно склеивать прямо на месте.
    if (parent[v] !== -1) {
      const p = parent[v];
      for (let i = startIdx[p]; i < endIdx[p]; i++) {
        const g = gcd(gcdVal[i], shine[v]);
        if (g === gcdVal[sp - 1]) {
          gcdCnt[sp - 1] += gcdCnt[i];
        } else {
          gcdVal[sp] = g;
          gcdCnt[sp] = gcdCnt[i];
          sp++;
        }
      }
    }

    startIdx[v] = base;
    endIdx[v] = sp;

    // Ответ узла — сумма резонансов всех бликов, упавших в него.
    let total = 0;
    for (let i = base; i < sp; i++) total += gcdVal[i] * gcdCnt[i];
    answers[v] = total;
  };

  // ---------- итеративный DFS ----------
  const iter = new Int32Array(n); // сколько соседей уже просмотрено
  const stack = [0];
  enter(0);

  while (stack.length > 0) {
    const v = stack[stack.length - 1];
    const neighbours = adj[v];
    let descended = false;

    while (iter[v] < neighbours.length) {
      const u = neighbours[iter[v]++];
      if (u === parent[v]) continue; // обратное ребро к родителю
      parent[u] = v;
      enter(u);
      stack.push(u);
      descended = true;
      break;
    }

    if (!descended) {
      // Выходим из поддерева: освобождаем место в стеке gcd.
      // Список родителя при этом остаётся нетронутым.
      sp = startIdx[v];
      stack.pop();
    }
  }

  return answers.join(' ');
}

// НОД двух неотрицательных чисел.
function gcd(a, b) {
  while (b !== 0) {
    const t = a % b;
    a = b;
    b = t;
  }
  return a;
}
