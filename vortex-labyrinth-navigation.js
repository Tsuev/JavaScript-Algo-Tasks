// Сложность: hard
// Дата генерации: 2026-10-07

// Условие задачи
// **Vortex Labyrinth Navigation**
// 
// Лабиринт — это прямоугольная сетка N×M. Время в нём дискретно: за один ход игрок перемещается на одну клетку вверх, вниз, влево или вправо, не выходя за границы сетки.
// 
// Главная особенность лабиринта в том, что он «пульсирует». У каждой клетки есть четыре фазы (0, 1, 2 и 3), и в каждой фазе клетка либо проходима, либо является стеной. Фаза однозначно определяется временем: если сделано t ходов, активна фаза t mod 4. Игрок стартует в момент времени t = 0 (фаза 0) в клетке S и хочет оказаться в клетке T (в какой фазе — не важно).
// 
// Ход из клетки (x, y), сделанный в момент t (то есть в фазе f = t mod 4), возможен в соседнюю клетку (x', y'), если:
// 1. (x', y') находится внутри сетки;
// 2. в момент t + 1 (фаза (f + 1) mod 4) клетка (x', y') проходима, то есть не является стеной.
// 
// По лабиринту гуляют вихревые воронки. Некоторые клетки — входы вихрей, и для каждого входа задана клетка-цель. Войдя в такую клетку ходом, игрок немедленно (не расходуя дополнительных ходов) переносится в цель. Телепорт разрешён, только если цель в тот же момент времени проходима; если цель — стена, войти в вихрь нельзя (такой ход недоступен). Вихрь срабатывает ровно один раз за ход: если цель сама является входом вихря, повторного срабатывания не происходит. Вихрь не срабатывает в момент старта: если игрок начинает на входе вихря, тот активируется только когда игрок войдёт в него ходом.
// 
// Нужно найти минимальное число ходов, за которое можно добраться из S в T, или сообщить, что это невозможно.
// 
// **Формат ввода**
// - Первая строка: N M.
// - Следующие N строк: по M символов — шестнадцатеричная цифра 0..F для каждой клетки. Бит k (k = 0..3) этой цифры равен 1 тогда и только тогда, когда клетка является стеной в фазе k.
// - Строка: sr sc tr tc — координаты старта и цели, 0-индексация (сначала строка, потом столбец).
// - Строка: K — количество вихрей.
// - K строк: r1 c1 r2 c2 — вход вихря (r1, c1) и его цель (r2, c2). Все входы уникальны.
// 
// Ограничения: 1 ≤ N, M ≤ 500, 0 ≤ K ≤ N·M, все координаты внутри сетки. Гарантируется, что стартовая клетка проходима в фазе 0.
// 
// **Формат вывода**
// Одно целое число — минимальное число ходов или -1, если добраться невозможно.
// 
// **Пример 1 (вихрь)**
// Вход:
// 3 3
// 000
// 000
// 000
// 0 0 2 2
// 1
// 0 1 2 2
// Выход: 1
// Пояснение: игрок делает один ход в (0,1), вихрь мгновенно переносит его в (2,2).
// 
// **Пример 2 (фазы)**
// Вход:
// 3 3
// 020
// 000
// 00A
// 0 0 0 2
// 0
// Выход: 4
// Пояснение: клетка (0,1) — стена в фазе 1, поэтому первый ход вправо невозможен. Кратчайший обход — вниз, вокруг и обратно, ровно за 4 хода; прямой путь за 2 хода запрещён, а за 3 хода цель (0,2) оказывается стеной в фазе 3.
// 
// **Пример 3 (недостижимо)**
// Вход:
// 2 2
// 0F
// F0
// 1 1 0 0
// 0
// Выход: -1
// Пояснение: клетки с маской F — стены во всех фазах, они полностью отрезают старт от цели.

// Задача: минимальное число ходов в лабиринте с четырьмя циклическими фазами стен
// и телепортами-вихрями, которые срабатывают мгновенно внутри хода.
//
// Ключевая идея: короткий путь зависит не только от позиции, но и от фазы времени,
// поэтому ищем в расширенном графе состояний (строка, столбец, фаза).
// Любой ход (с телепортом или без) стоит ровно 1, ведь сам вход в вихрь — это ход,
// а перенос внутри хода бесплатен. Значит, достаточно обычного BFS по состояниям.

function solve(input) {
  const tok = input.trim().split(/\s+/).filter(Boolean);
  let p = 0;

  const N = parseInt(tok[p++], 10);
  const M = parseInt(tok[p++], 10);

  // mask[r][c] — битовая маска стен клетки: бит f = 1 означает стену в фазе f.
  const mask = new Array(N);
  for (let r = 0; r < N; r++) {
    const row = tok[p++];
    const line = new Int32Array(M);
    for (let c = 0; c < M; c++) line[c] = parseInt(row[c], 16);
    mask[r] = line;
  }

  const sr = parseInt(tok[p++], 10);
  const sc = parseInt(tok[p++], 10);
  const tr = parseInt(tok[p++], 10);
  const tc = parseInt(tok[p++], 10);

  const K = parseInt(tok[p++], 10);
  // Входы вихрей: ключ — клетка входа (r*M+c), значение — клетка-цель (тоже r*M+c).
  const vortex = new Map();
  for (let i = 0; i < K; i++) {
    const r1 = parseInt(tok[p++], 10), c1 = parseInt(tok[p++], 10);
    const r2 = parseInt(tok[p++], 10), c2 = parseInt(tok[p++], 10);
    vortex.set(r1 * M + c1, r2 * M + c2);
  }

  // Клетка проходима в фазе f, если соответствующий бит маски равен нулю.
  const open = (r, c, f) => ((mask[r][c] >> f) & 1) === 0;

  // Стартовая клетка гарантированно проходима в фазе 0, но проверим на всякий случай.
  if (!open(sr, sc, 0)) return -1;

  // Упаковываем состояние (r, c, f) в одно число: (r*M + c) * 4 + f.
  const id = (r, c, f) => (((r * M + c) << 2) | f);
  const PH = 4;
  const total = N * M * PH;

  const dist = new Int32Array(total).fill(-1);
  // Очередь для BFS: каждое состояние кладём максимум один раз, поэтому хватает total ячеек.
  const queue = new Int32Array(total);
  let qh = 0, qt = 0;

  const start = id(sr, sc, 0);
  dist[start] = 0;
  queue[qt++] = start;

  const DR = [-1, 1, 0, 0];
  const DC = [0, 0, -1, 1];

  while (qh < qt) {
    const state = queue[qh++];
    const f = state & 3;                 // текущая фаза
    const cell = state >> 2;             // r*M + c
    const r = Math.floor(cell / M);
    const c = cell - r * M;
    const d = dist[state];
    const nf = (f + 1) & 3;              // фаза после хода

    for (let k = 0; k < 4; k++) {
      const nr = r + DR[k], nc = c + DC[k];
      if (nr < 0 || nr >= N || nc < 0 || nc >= M) continue;

      // Клетка, в которую входим, должна быть проходима именно в новом моменте времени.
      if (!open(nr, nc, nf)) continue;

      // Если это вход вихря — игрок мгновенно оказывается в цели (в той же фазе).
      let fr = nr, fc = nc;
      const target = vortex.get(nr * M + nc);
      if (target !== undefined) {
        const ur = Math.floor(target / M);
        const uc = target - ur * M;
        // Нельзя «войти» в вихрь, который выбросит игрока в стену.
        if (!open(ur, uc, nf)) continue;
        fr = ur;
        fc = uc;
      }

      const nid = id(fr, fc, nf);
      if (dist[nid] === -1) {
        dist[nid] = d + 1;
        queue[qt++] = nid;
      }
    }
  }

  // Цель можно посетить в любой фазе — берём минимум по четырём состояниям.
  let best = -1;
  for (let f = 0; f < PH; f++) {
    const v = dist[id(tr, tc, f)];
    if (v !== -1 && (best === -1 || v < best)) best = v;
  }
  return best;
}

