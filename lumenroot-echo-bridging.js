// Условие задачи
// Лес Люменкорней (Lumenroot Echo Bridging)
// 
// В подземном саду растёт светящееся дерево: n узлов, соединённых n−1 коридорами так, что между любыми двумя узлами существует ровно один путь (то есть граф — дерево). У каждого узла i есть яркость a_i; она может быть отрицательной — такие узлы глушат свет.
// 
// Эхо между двумя узлами u и v — это сумма яркостей всех узлов на единственном пути из u в v, включая сами u и v. Мост можно натянуть между любыми двумя узлами, в том числе между узлом и им же (тогда эхо равно яркости этого узла).
// 
// Найдите максимально возможное эхо моста.
// 
// Формат входных данных:
// • первая строка — целое число n (1 ≤ n ≤ 2·10^5);
// • вторая строка — n целых чисел a_1, …, a_n (−10^9 ≤ a_i ≤ 10^9);
// • следующие n−1 строк — по два целых числа u и v (1 ≤ u, v ≤ n), задающих коридор между узлами u и v.
// 
// Формат результата:
// Одно целое число — максимальное эхо.
// 
// Пример 1:
// Вход:
// 5
// 3 -2 4 5 -1
// 1 2
// 1 3
// 2 4
// 2 5
// Выход:
// 10
// Пояснение: лучший мост — между узлами 3 и 4; путь 3 → 1 → 2 → 4 даёт 4 + 3 + (−2) + 5 = 10.
// 
// Пример 2:
// Вход:
// 3
// -5 -2 -9
// 1 2
// 2 3
// Выход:
// -2
// Пояснение: все пути состоят из отрицательных яркостей, поэтому выгоднее всего «мост» из узла 2 в себя.
// 
// Ограничения: 1 ≤ n ≤ 2·10^5, |a_i| ≤ 10^9. Ответ помещается в обычное число JavaScript (не превосходит 2·10^14).

function lumenrootEchoBridging(n, brightness, edges) {
  // Дерево неориентированное, поэтому строим списки смежности, а корень выберем произвольно — узел 0.
  const adj = Array.from({ length: n }, () => []);
  for (const [u, v] of edges) {
    adj[u].push(v);
    adj[v].push(u);
  }

  // Обход в глубину делаем итеративно: при n = 2·10^5 рекурсия может переполнить стек.
  // Попутно запоминаем родителя каждого узла и порядок обхода — он нужен для обратного прохода.
  const parent = new Array(n).fill(-1);
  const order = [];
  const stack = [0];
  parent[0] = -1;

  while (stack.length > 0) {
    const u = stack.pop();
    order.push(u);
    for (const v of adj[u]) {
      if (v === parent[u]) continue; // назад к родителю не идём, иначе обход зациклится
      parent[v] = u;
      stack.push(v);
    }
  }

  // down[u] — максимальная суммарная яркость пути, который начинается в u и уходит только вниз по дереву.
  // Идём по узлам в обратном порядке обхода: к моменту обработки u все его дети уже посчитаны.
  const down = new Array(n).fill(0);
  let best = -Infinity;

  for (let i = order.length - 1; i >= 0; i--) {
    const u = order[i];
    let top1 = 0; // лучший вклад среди детей; отрицательные вклады выгодно не брать вообще
    let top2 = 0; // второй по величине вклад — нужен, когда мост «перегибается» в узле u

    for (const v of adj[u]) {
      if (parent[v] !== u) continue; // интересуют только дети
      const d = down[v];
      if (d > top1) {
        top2 = top1;
        top1 = d;
      } else if (d > top2) {
        top2 = d;
      }
    }

    // Самый светлый путь вниз от u: сам узел плюс лучшая ветвь (если она вообще улучшает сумму).
    down[u] = brightness[u] + top1;

    // Любой путь в дереве имеет единственную «верхнюю» точку — узел u, где он распадается
    // на две ветви (или на одну, или ни на одну — тогда это просто сам узел u).
    const throughU = brightness[u] + top1 + top2;
    if (throughU > best) best = throughU;
  }

  return best;
}
