// Условие задачи
// В саду Тернового Цветения живёт колония ладей. Сад — это прямоугольная сетка из n строк и m столбцов (строки и столбцы нумеруются с 1). Ладьи садятся на клетки строго по одной, и каждая севшая ладья «раскрывает крылья»: она бьёт всю свою строку и весь свой столбец.
// 
// Две ладьи называются враждующими, если они стоят в одной строке или в одном столбце (на одну клетку садится не более одной ладьи, поэтому совпадение позиций исключено). После каждой посадки ладьи нужно определить, сколько всего враждующих пар ладей находится в саду в этот момент.
// 
// Формат входных данных:
// — первая строка содержит три целых числа n, m и k — размеры сада и количество ладей (1 ≤ n, m ≤ 10^9, 1 ≤ k ≤ 2·10^5);
// — следующие k строк содержат по два целых числа r и c — координаты очередной ладьи (1 ≤ r ≤ n, 1 ≤ c ≤ m).
// 
// Формат результата:
// — массив из k целых чисел: i-й элемент равен общему числу враждующих пар ладей после посадки первых i ладей.
// 
// Пример:
// n = 3, m = 3, ладьи: (1,1), (1,2), (2,1), (2,2).
// 
// Пошагово:
// 1) (1,1) — ладья одна, пар нет → 0.
// 2) (1,2) — стоит в одной строке с (1,1) → 1 пара → 1.
// 3) (2,1) — стоит в одном столбце с (1,1) → +1 пара → 2.
// 4) (2,2) — стоит в одной строке с (2,1) и в одном столбце с (1,2) → +2 пары → 4.
// 
// Ответ: [0, 1, 2, 4].
// 
// Решение должно работать за O(k) в среднем, поэтому нельзя хранить всю доску: размеры n и m могут быть очень большими, а ладей мало. Достаточно хранить для каждой занятой строки и каждого занятого столбца количество стоящих в них ладей.

/**
 * Считает число враждующих пар ладей после каждой посадки.
 *
 * Ключевая идея: число пар = сумма по всем строкам C(cntRow, 2)
 * плюс сумма по всем столбцам C(cntCol, 2).
 * Когда садится новая ладья, она образует пару с каждой ладьёй,
 * уже стоящей в её строке или в её столбце, поэтому прирост равен
 * cntRow[r] + cntCol[c]. Отсюда достаточно хранить только счётчики
 * для занятых строк и столбцов — их не больше, чем ладей.
 *
 * @param {number} n - число строк в саду
 * @param {number} m - число столбцов в саду
 * @param {Array<[number, number]>} rooks - координаты ладей в порядке посадки
 * @returns {number[]} число враждующих пар после каждой посадки
 */
function rookeryUnfurling(n, m, rooks) {
  // Счётчики ладей по строкам и столбцам. Используем Map,
  // потому что размеры сада могут быть огромными, а занятых линий мало.
  const rowCount = new Map();
  const colCount = new Map();

  const result = [];
  let attackingPairs = 0;

  for (const [r, c] of rooks) {
    const inRow = rowCount.get(r) ?? 0;
    const inCol = colCount.get(c) ?? 0;

    // Новая ладья бьётся со всеми ладьями своей строки и своего столбца.
    // Пересечение (она сама с собой) невозможно: клетка ещё пустая.
    attackingPairs += inRow + inCol;

    rowCount.set(r, inRow + 1);
    colCount.set(c, inCol + 1);

    result.push(attackingPairs);
  }

  return result;
}

