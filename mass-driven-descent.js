// Условие задачи
// Mass-Driven Descent
// 
// Сложность: hard
// 
// Профиль горного хребта задан массивом высот h1, h2, …, hn (целые числа). Края хребта заперты бесконечно высокими стенами, поэтому вода никогда не вытекает наружу.
// 
// В клетку с номером s выливают V единиц воды. Гарантируется, что s — локальный минимум рельефа, то есть hs строго меньше высоты каждого своего соседа (у крайних клеток сосед только один, у n = 1 соседей нет).
// 
// Вода стекает вниз, заполняет впадину вокруг s, а когда уровень доходит до ближайшего перевала — переливается через него в соседнюю впадину, и так далее, пока вода не успокоится. Общий объём воды ровно V, наружу ничего не уходит.
// 
// Формально всё описывается так:
// — вода на уровне L (то есть с водной поверхностью на высоте L) может стоять только в клетках высотой не более L, и распространяется по ним как по связному множеству. Обозначим C(L) — множество клеток, достижимых из s, если разрешено ходить только по клеткам высотой не более L. При L < hs множество пусто.
// — чтобы поднять воду во всех клетках зоны C(L) ровно до уровня L, нужен объём W(L) = сумма по всем i из C(L) величины (L − hi).
// — искомый уровень воды (наибольшая высота водной поверхности) — это минимальное L, при котором W(L) ≥ V.
// 
// Найдите этот уровень и выведите его в виде несократимой дроби p/q.
// 
// Входные данные функции: heights — массив из n высот, startIndex — номер клетки s (от 1 до n), volume — объём вылитой воды V.
// 
// Результат: пара целых чисел [p, q] (q > 0), задающая уровень воды p/q в несократимой форме; если уровень целый, то q = 1.
// 
// Ограничения: 1 ≤ n ≤ 2·10^5, 0 ≤ hi ≤ 10^9, 1 ≤ V ≤ 10^15.
// 
// Примеры:
// 1) heights = [3, 1, 2, 1, 3], s = 2, V = 2  →  [2, 1].
//    Впадина вокруг клетки 2 (высота 1) заполняется до уровня 2: одна единица воды поднимает уровень до высоты перевала (клетка 3 высотой 2), вторая единица перетекает в клетку 4 и стоит там на высоте 1. Водная поверхность нигде не выше 2.
// 2) heights = [3, 1, 2, 1, 3], s = 2, V = 4  →  [8, 3].
//    Здесь вода стоит в клетках 2, 3, 4 и поднимается до уровня 8/3: 3 · 8/3 − (1 + 2 + 1) = 4.
// 3) heights = [0, 3, 0, 3, 0], s = 1, V = 10  →  [16, 5].
//    Сначала впадина клетки 1 заполняется до перевала высотой 3 (3 единицы), 3 единицы уходят в впадину клетки 3, и ещё 1 единица перетекает в впадину клетки 5. Дальше уровень поднимается уже над всем хребтом: 5L − 6 = 10, откуда L = 16/5.
// 
// Требуется решение за O(n log n).

/**
 * Mass-Driven Descent.
 *
 * Идея решения.
 *
 * Будем поднимать воду «виртуально» и отслеживать, какие клетки уже находятся
 * в зоне затопления. Клетка попадает в зону ровно тогда, когда уровень воды
 * доходит до её высоты, то есть клетки активируются в порядке возрастания высот.
 *
 * Зона затопления — это в точности компонента связности клетки s среди уже
 * активированных клеток, поэтому её удобно поддерживать системой непересекающихся
 * множеств (СНМ): для каждой компоненты храним её размер и сумму высот клеток.
 * Тогда при уровне L в зоне из k клеток с суммой высот S нужен объём
 *      W(L) = L * k - S.
 *
 * Пока состав зоны не меняется, W растёт линейно от L. Состав зоны меняется
 * только в моменты, когда активируются новые клетки, поэтому достаточно
 * разобрать группы клеток одинаковой высоты в порядке возрастания. Если для
 * очередной высоты H выполнено
 *      W(H) = предыдущий объём + (H - предыдущий уровень) * (размер зоны) >= V,
 * то ответ находится внутри этого линейного участка; иначе вода ровно доходит
 * до перевала и уровень равен H (новые клетки подключаются мгновенно, «прыжком»
 * добавляя ёмкость соседним впадинам).
 *
 * Замечание про вход: гарантируется, что клетка s — локальный минимум, поэтому
 * в момент её активации зона состоит ровно из неё, и все формулы согласованы
 * с физикой разлива.
 */

// Приводим дробь num / den к несократимому виду (num >= 0, den > 0).
function reduceFraction(num, den) {
  let a = num, b = den;
  while (b !== 0) {
    const t = a % b;
    a = b;
    b = t;
  }
  const g = a;
  return [num / g, den / g];
}

/**
 * @param {number[]} heights   высоты клеток рельефа
 * @param {number}   startIndex номер клетки s (нумерация с 1)
 * @param {number}   volume     объём вылитой воды V
 * @returns {[number, number]}  уровень воды в виде несократимой дроби [p, q]
 */
function solve(heights, startIndex, volume) {
  const n = heights.length;
  const s = startIndex - 1; // внутри работаем с нумерацией с нуля

  // ---- Система непересекающихся множеств над активированными клетками ----
  const parent = new Array(n);
  const compCount = new Array(n); // сколько клеток в компоненте
  const compSum = new Array(n);   // сумма высот клеток компоненты
  for (let i = 0; i < n; i++) {
    parent[i] = i;
    compCount[i] = 1;
    compSum[i] = heights[i];
  }
  const active = new Array(n).fill(false);

  function find(x) {
    let root = x;
    while (parent[root] !== root) root = parent[root];
    while (parent[x] !== root) {
      const next = parent[x];
      parent[x] = root;
      x = next;
    }
    return root;
  }

  function union(a, b) {
    a = find(a);
    b = find(b);
    if (a === b) return;
    if (compCount[a] < compCount[b]) {
      const t = a; a = b; b = t;
    }
    parent[b] = a;
    compCount[a] += compCount[b];
    compSum[a] += compSum[b];
  }

  // Клетки в порядке неубывания высоты.
  const order = Array.from({ length: n }, (_, i) => i)
    .sort((a, b) => heights[a] - heights[b]);

  let sActive = false;            // активировалась ли клетка, в которую льют воду
  let prevLevel = 0;              // предыдущая рассмотренная высота
  let prevCapacity = 0;           // объём зоны, поднятой до prevLevel
  let prevCount = 0;              // размер зоны на прошлом шаге

  let i = 0;
  while (i < n) {
    const level = heights[order[i]];
    let j = i;
    while (j < n && heights[order[j]] === level) j++;

    // Клетки одинаковой высоты активируются одновременно: на этом уровне
    // вода может стоять в любой из них с нулевой глубиной.
    for (let t = i; t < j; t++) {
      const c = order[t];
      active[c] = true;
      if (c > 0 && active[c - 1]) union(c, c - 1);
      if (c + 1 < n && active[c + 1]) union(c, c + 1);
    }
    i = j;

    if (!sActive) {
      if (active[s]) sActive = true;
      else continue; // вода ещё не добралась до клетки s
    }

    const root = find(s);
    const count = compCount[root];
    const capacityHere = level * count - compSum[root];

    // Пока зона не менялась, ёмкость линейно растёт с уровнем.
    if (prevCount > 0) {
      const capacityBefore = prevCapacity + (level - prevLevel) * prevCount;
      if (volume <= capacityBefore) {
        // Ответ лежит внутри отрезка (prevLevel, level]:
        // prevCapacity + (L - prevLevel) * prevCount = volume.
        const num = prevLevel * prevCount + (volume - prevCapacity);
        return reduceFraction(num, prevCount);
      }
    }

    // Вода ровно дошла до перевала: уровень совпадает с высотой level
    // (новые впадины за перевалом мгновенно получают воду).
    if (volume <= capacityHere) return reduceFraction(level, 1);

    prevLevel = level;
    prevCapacity = capacityHere;
    prevCount = count;
  }

  // Вода перелилась через все перевалы — уровень поднимается уже над всем
  // рельефом, зона затопления больше не меняется.
  const num = prevLevel * prevCount + (volume - prevCapacity);
  return reduceFraction(num, prevCount);
}
