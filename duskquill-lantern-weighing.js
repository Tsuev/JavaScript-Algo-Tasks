// Задача: Duskquill Lantern Weighing
// Сложность: medium
// Дата генерации: 2026-11-18

// Условие задачи
// Название: Duskquill Lantern Weighing
// 
// В городе Duskquill на закате зажигают фонарики. У каждого фонарика есть целый вес w_i. У мастера есть эталонная гиря веса T, и он хочет проверить её на рычажных весах с двумя чашами.
// 
// Правила взвешивания:
// — гирю ставят на левую чашу;
// — каждый фонарик разрешено положить на левую чашу, на правую чашу или не использовать вовсе;
// — взвешивание удалось, если чаши уравновесились, то есть вес левой чаши стал равен весу правой.
// 
// Нужно определить, можно ли уравновесить весы.
// 
// Формально: существуют ли такие коэффициенты c_i ∈ {−1, 0, +1}, что Σ c_i·w_i = T, где c_i = +1 означает «фонарик на правой чаше», c_i = −1 — «на левой», c_i = 0 — «фонарик не используется». (Гиря веса T стоит слева, поэтому справа должно оказаться ровно на T больше.)
// 
// Формат входных данных:
// Первая строка: два целых числа n и T (1 ≤ n ≤ 200, 0 ≤ T ≤ 20000).
// Вторая строка: n целых чисел w_i (1 ≤ w_i ≤ 100) — веса фонариков.
// 
// Формат результата:
// Одна строка — YES, если уравновесить можно, и NO иначе.
// 
// Примеры:
// 1) Вход: 3 4 / 2 3 5 → Выход: YES
//    Пояснение: 5 и 2 на правую чашу, 3 на левую: 7 − 3 = 4.
// 2) Вход: 3 8 / 1 2 4 → Выход: NO
//    Пояснение: суммарный вес всех фонариков 7 меньше 8, гирю не уравновесить.
// 3) Вход: 3 3 / 1 2 4 → Выход: YES
//    Пояснение: 4 на правую, 1 на левую: 4 − 1 = 3 (фонарик веса 2 не используется).
// 4) Вход: 2 0 / 1 1 → Выход: YES
//    Пояснение: гиря веса 0 — достаточно не класть ни одного фонарика.

/**
 * Duskquill Lantern Weighing.
 *
 * Идея решения — динамическое программирование по достижимой разности
 * «правый вес минус левый вес». Каждый фонарик даёт три варианта:
 * +w (на правую чашу), −w (на левую чашу) или 0 (не используем).
 *
 * Разность всегда лежит в диапазоне [−S, S], где S — сумма всех весов,
 * поэтому храним булев массив размера 2S+1 со смещением offset = S.
 * Сложность O(n·S) по времени и O(S) по памяти.
 *
 * @param {number[]} weights веса фонариков (целые положительные числа)
 * @param {number} target вес гири T, стоящей на левой чаше
 * @returns {string} "YES", если уравновесить можно, иначе "NO"
 */
function canBalanceLanterns(weights, target) {
  const total = weights.reduce((acc, w) => acc + w, 0);

  // Если нужная разность по модулю больше суммарного веса — она недостижима.
  if (Math.abs(target) > total) return "NO";

  const offset = total;          // сдвиг, чтобы индексировать отрицательные разности
  const size = 2 * total + 1;    // диапазон возможных разностей [−total, total]

  // dp[s + offset] === 1, если разность s уже достижима частью фонариков.
  let dp = new Uint8Array(size);
  dp[offset] = 1;                // пустой набор фонариков даёт разность 0

  for (const w of weights) {
    // Для каждого фонарика строим новый слой: нельзя использовать один
    // и тот же фонарик дважды, поэтому массив пересобирается с нуля.
    const next = new Uint8Array(size);
    for (let s = -total; s <= total; s++) {
      if (dp[s + offset] === 0) continue;

      next[s + offset] = 1;                     // фонарик не используем
      if (s + w <= total) next[s + w + offset] = 1; // на правую чашу
      if (s - w >= -total) next[s - w + offset] = 1; // на левую чашу
    }
    dp = next;
  }

  // Нам нужна разность ровно T: справа на T больше, чем слева.
  return dp[target + offset] === 1 ? "YES" : "NO";
}

/**
 * Удобная обёртка под формат задачи: n, T и список весов.
 * При необходимости её можно вызвать из тестов напрямую.
 */
function solveLanternWeighing(n, target, weights) {
  return canBalanceLanterns(weights.slice(0, n), target);
}
