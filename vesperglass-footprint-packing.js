// minShelves([[1,4],[2,5],[3,6]]) === 3
// minShelves([[1,2],[2,3],[3,4]]) === 1
// minShelves([[1,5],[2,3],[4,6]]) === 2
// minShelves([])                    === 0
// minShelves([[7,9],[1,4],[2,8]])   === 2
