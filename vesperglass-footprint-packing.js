// Условие задачи
// Мастерская витражей «Веспергласс» готовит партию образцов — «следов». Каждый след занимает промежуток времени [l, r), причём промежуток полуоткрытый: момент r уже НЕ принадлежит следу (касание концами не считается пересечением). Все следы нужно разложить по полкам. На одной полке в один и тот же момент времени не могут находиться два следа, чьи промежутки пересекаются. Полок можно завести сколько угодно, но нужно минимизировать их количество.
// 
// Формально: дан набор n интервалов вида [l_i, r_i), где l_i < r_i — целые числа. Нужно найти минимальное число «полок» (дорожек) так, чтобы никакие два интервала, назначенные на одну полку, не пересекались. Известно, что минимальное число полок равно максимальному числу интервалов, одновременно накрывающих какую-либо точку числовой прямой.
// 
// Формат входных данных: функция принимает массив footprints, где каждый элемент — пара [l, r) (массив из двух целых чисел), 0 ≤ n ≤ 10^5, 0 ≤ l_i < r_i ≤ 10^9. Порядок интервалов произвольный.
// 
// Формат результата: одно целое число — минимальное количество полок. Для пустого набора ответ 0.
// 
// Примеры:
// 1) footprints = [[1,4],[2,5],[3,6]] → 3. В момент времени 3 все три следа активны одновременно, значит нужно минимум 3 полки, и трёх достаточно.
// 2) footprints = [[1,2],[2,3],[3,4]] → 1. Интервалы лишь касаются концами (момент r не входит), пересечений нет — все следы помещаются на одну полку.
// 3) footprints = [[1,5],[2,3],[4,6]] → 2. Максимум одновременно активны 2 следа.
// 4) footprints = [] → 0.
// 5) footprints = [[7,9],[1,4],[2,8]] → 2.

// Задача сводится к раскраске интервального графа: минимальное число
// «полок» (дорожек) совпадает с максимальным числом интервалов, которые
// одновременно накрывают какую-то точку. Поэтому достаточно найти этот
// пик методом заметающей прямой — без хранения самих назначений.

function minShelves(footprints) {
  const events = [];

  // Каждый интервал даёт два события: в точке l он «занимает» полку (+1),
  // в точке r — «освобождает» её (-1).
  for (const [start, end] of footprints) {
    events.push([start, 1]);
    events.push([end, -1]);
  }

  // Сортируем события по координате. При равной координате сначала
  // обрабатываем концы (-1), затем начала (+1): интервалы полуоткрытые
  // [l, r), поэтому касание в одной точке пересечением не считается.
  events.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

  let current = 0; // сколько следов активно прямо сейчас
  let peak = 0;    // максимум по всей прямой = нужное число полок

  for (const [, delta] of events) {
    current += delta;
    if (current > peak) peak = current;
  }

  return peak;
}

