// Задача: Cinderlace Ladder Weaving
// Сложность: medium
// Дата генерации: 2026-11-17

// Условие задачи
// Ладер из пепельного кружева — это полотно из двух горизонтальных реек (верхней и нижней) и n столбцов, то есть сетка 2×n. Часть клеток прожжена пеплом и ткать по ним нельзя, остальные клетки свободны.
// 
// Мастер плетёт кружево нитями-домино: каждая нить занимает ровно две соседние по стороне свободные клетки — либо две клетки одного столбца (вертикальная нить), либо две клетки одной рейки в соседних столбцах (горизонтальная нить). Нужно закрыть нитями все свободные клетки, нити не должны пересекаться и не должны заходить на прожжённые клетки.
// 
// Посчитайте количество различных способов это сделать по модулю 1 000 000 007. Способы различны, если различается множество использованных пар клеток.
// 
// Формат входных данных: два аргумента — строки top и bottom одинаковой длины n (1 ≤ n ≤ 200000), состоящие из символов '.' (свободная клетка) и '#' (прожжённая клетка). top[c] описывает верхнюю рейку столбца c, bottom[c] — нижнюю.
// 
// Формат результата: одно целое число — количество замощений по модулю 1 000 000 007. Если закрыть все свободные клетки невозможно, вернуть 0.
// 
// Пример 1: top = "...", bottom = "..." → 3 (все вертикальные; все горизонтальные; вертикаль слева плюс блок 2×2 горизонтальных; вертикаль справа плюс блок 2×2 горизонтальных).
// Пример 2: top = "....", bottom = ".##." → 1.
// Пример 3: top = "..", bottom = ".." → 2.

/**
 * Считает число способов замостить свободные клетки лестницы 2×n костями домино
 * (вертикальными и горизонтальными нитями) по модулю 1e9+7.
 *
 * Идея: идём по столбцам слева направо и держим маску из двух бит — какие клетки
 * текущего столбца уже заняты горизонтальными нитями, пришедшими слева.
 * Внутри столбца клетки заполняем сверху вниз небольшим перебором:
 * либо ставим вертикальную нить, либо тянем горизонтальную вправо.
 */
function countWeavings(top, bottom) {
  const MOD = 1_000_000_007;
  const n = top.length;

  // Маска прожжённых клеток каждого столбца: бит 0 — верхняя рейка, бит 1 — нижняя.
  const blocked = new Array(n).fill(0);
  for (let c = 0; c < n; c++) {
    if (top[c] === '#') blocked[c] |= 1;
    if (bottom[c] === '#') blocked[c] |= 2;
  }

  // dp[mask] — число способов разложить нити во всех столбцах левее текущего так,
  // что в текущем столбце уже заняты клетки из mask (это «хвосты» горизонтальных нитей).
  let dp = [1, 0, 0, 0];

  for (let c = 0; c < n; c++) {
    const ndp = [0, 0, 0, 0];

    for (let mask = 0; mask < 4; mask++) {
      if (dp[mask] === 0) continue;
      // Нить слева упёрлась в прожжённую клетку — такое состояние невозможно.
      if (mask & blocked[c]) continue;

      // cur — занятые клетки текущего столбца, nxt — нити, уходящие в следующий столбец.
      const fill = (r, cur, nxt) => {
        if (r === 2) {
          // Столбец разобран целиком, накапливаем переход.
          ndp[nxt] = (ndp[nxt] + dp[mask]) % MOD;
          return;
        }
        if ((cur >> r) & 1) { fill(r + 1, cur, nxt); return; }        // клетка уже занята
        if ((blocked[c] >> r) & 1) { fill(r + 1, cur, nxt); return; } // клетка прожжена

        // Вариант 1: вертикальная нить соединяет обе рейки этого столбца.
        if (r === 0 && !((cur >> 1) & 1) && !((blocked[c] >> 1) & 1)) {
          fill(2, cur | 3, nxt);
        }
        // Вариант 2: горизонтальная нить уходит в следующий столбец.
        if (c + 1 < n && !((blocked[c + 1] >> r) & 1)) {
          fill(r + 1, cur, nxt | (1 << r));
        }
      };

      fill(0, mask, 0);
    }

    dp = ndp;
  }

  // За пределы полотна нити выходить не могут, поэтому в конце допустима только маска 0.
  return dp[0] % MOD;
}
