// Условие задачи
// Условие задачи «Cerulean Winnowing Coil» (Лазурная провеивающая спираль).
// 
// Лазурная спираль — это бесконечный обход клеток целочисленной решётки. Клетка (0,0) получает номер 0. Далее спираль закручивается шагами: вправо длины 1, вниз длины 1, влево длины 2, вверх длины 2, вправо длины 3, вниз длины 3, и так далее (длины сторон растут 1,1,2,2,3,3,…). Каждая клетка ровно один раз получает очередной номер 0,1,2,… Координаты: r — номер строки (растёт вниз), c — номер столбца (растёт вправо). Первые клетки: (0,0)=0, (0,1)=1, (1,1)=2, (1,0)=3, (1,-1)=4, (0,-1)=5, (-1,-1)=6, (-1,0)=7, (-1,1)=8, (-1,2)=9, …
// 
// Заданы радиус R и n отмеченных клеток, у каждой координаты (r_i, c_i) и целое значение v_i. Все координаты попарно различны. Рассматриваются только отмеченные клетки, лежащие в квадрате max(|r|,|c|) <= R. Их нужно «провеять» в порядке возрастания спирального номера.
// 
// Провеивание: заводим порог t = -∞. Идём по выбранным клеткам в порядке спирали. Если значение v клетки строго больше t, то это зерно: прибавляем v к сумме зерна и обновляем t = v. Иначе это мякина: прибавляем v к сумме мякины (порог не меняется). Нужно вернуть обе суммы.
// 
// Формат данных: функция winnowCoil(R, cells), где
// - R — целое, 0 <= R <= 10^6;
// - cells — массив из n объектов { r, c, v }, где 0 <= n <= 2*10^5, |r|,|c| <= 10^6, |v| <= 10^9.
// 
// Результат: объект { grain, chaff } — суммы зерна и мякины (целые числа).
// 
// Пример:
// R = 2, cells = [
//   { r: 0, c: 0, v: 5 },
//   { r: 1, c: 1, v: 3 },
//   { r: 0, c: 1, v: 7 },
//   { r: -1, c: 1, v: 7 },
//   { r: 1, c: 0, v: 1 },
//   { r: 2, c: 2, v: 4 }
// ]
// Спиральные номера: 0, 2, 1, 8, 3, 12. Порядок: (0,0)=5 → зерно 5, t=5; (0,1)=7 → зерно 12, t=7; (1,1)=3 → мякина; (1,0)=1 → мякина; (-1,1)=7 → мякина (7 не > 7); (2,2)=4 → мякина.
// Ответ: { grain: 12, chaff: 15 }.

function winnowCoil(R, cells) {
  // Номер клетки в лазурной спирали за O(1).
  // Клетка лежит на кольце k = max(|r|, |c|).
  // Первая клетка кольца имеет номер (2k-1)^2, дальше идём по сторонам.
  function spiralIndex(r, c) {
    if (r === 0 && c === 0) return 0;
    const k = Math.max(Math.abs(r), Math.abs(c));
    const base = (2 * k - 1) * (2 * k - 1);
    let offset;
    if (r === -k) {
      // верхняя сторона, движение вправо
      offset = 7 * k - 1 + c;
    } else if (c === k) {
      // правая сторона, движение вниз
      offset = r + k - 1;
    } else if (r === k) {
      // нижняя сторона, движение влево
      offset = 3 * k - 1 - c;
    } else {
      // левая сторона, движение вверх
      offset = 5 * k - 1 - r;
    }
    return base + offset;
  }

  // Отбираем клетки внутри квадрата радиуса R и сразу считаем их номера.
  const items = [];
  for (const cell of cells) {
    if (Math.abs(cell.r) <= R && Math.abs(cell.c) <= R) {
      items.push({ idx: spiralIndex(cell.r, cell.c), v: cell.v });
    }
  }

  // Провеивать нужно в порядке возрастания спирального номера.
  items.sort((a, b) => a.idx - b.idx);

  let grain = 0;
  let chaff = 0;
  let threshold = -Infinity; // порог: последнее принятое «крупное» зерно

  for (let i = 0; i < items.length; i++) {
    const v = items[i].v;
    if (v > threshold) {
      grain += v;
      threshold = v;
    } else {
      chaff += v;
    }
  }

  return { grain, chaff };
}
