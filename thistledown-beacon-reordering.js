// Задача: Thistledown Beacon Reordering
// Сложность: medium
// Дата генерации: 2026-10-25

// Условие задачи
// Вдоль тропы растут n маяков одуванчика (thistledown beacons). У каждого маяка есть целочисленная сила сигнала. Маяки стоят в ряд, и садовник может переставлять их: за одну операцию разрешено поменять местами два соседних маяка. Нужно добиться, чтобы все маяки с какой-то одной выбранной силой сигнала стояли подряд единым непрерывным блоком (между ними не должно быть маяков другой силы). Выбрать можно любую силу, но она должна встречаться хотя бы дважды — иначе «блок» из одного элемента уже тривиально сплошной. Среди всех подходящих сил выберите ту, для которой потребуется минимум обменов соседних маяков. Если ни одна сила не встречается дважды, ответ равен 0.
// 
// Формат входных данных: массив целых чисел strengths длины n (1 ≤ n ≤ 200000) — силы сигналов маяков по порядку слева направо.
// Формат результата: одно целое число — минимальное количество обменов соседних элементов, необходимое, чтобы все маяки выбранной силы стали непрерывным блоком.
// 
// Примеры:
// strengths = [1,2,1,2,1] => 1 (собираем двойки: [1,2,2,1,1] за один обмен, это выгоднее, чем собирать единицы за 2 обмена).
// strengths = [3,1,2,1,3] => 1 (собираем единицы за один обмен, получаем [3,1,1,2,3]).
// strengths = [4,4,4] => 0 (все маяки и так стоят подряд).

function minBeaconSwaps(strengths) {
  const n = strengths.length;
  if (n < 2) return 0;

  // Группируем индексы маяков по их силе сигнала.
  const positions = new Map();
  for (let i = 0; i < n; i++) {
    const v = strengths[i];
    if (!positions.has(v)) positions.set(v, []);
    positions.get(v).push(i);
  }

  let best = Infinity;

  for (const pos of positions.values()) {
    const k = pos.length;
    if (k < 2) continue; // одинокий маяк уже образует «блок»

    // Для блока из k маяков минимальные обмены достигаются,
    // если собрать их вокруг медианы. Перейдём к координатам
    // b[i] = pos[i] - i: тогда требуется минимизировать сумму |b[i] - t|,
    // а её минимум достигается на медиане массива b.
    const b = new Array(k);
    for (let i = 0; i < k; i++) b[i] = pos[i] - i;
    // Массив b неубывающий, так как pos[i+1] >= pos[i] + 1.

    const median = b[k >> 1]; // при чётном k подходит любой из двух средних
    let cost = 0;
    for (let i = 0; i < k; i++) cost += Math.abs(b[i] - median);

    if (cost < best) best = cost;
  }

  return best === Infinity ? 0 : best;
}
