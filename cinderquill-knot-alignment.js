// Задача: Cinderquill Knot Alignment
// Сложность: medium
// Дата генерации: 2026-11-19

// Условие задачи
// Синдерквилл исследует две верёвки с узлами. На верёвке A узлы завязаны в позициях a[0..n-1], на верёвке B — в позициях b[0..m-1] (позиции — целые числа, в пределах одной верёвки все различны).
// 
// Верёвку B можно сдвинуть вдоль числовой оси на целое число d: каждый её узел b[j] окажется в позиции b[j] + d. Узлы i и j считаются совпавшими, если a[i] = b[j] + d, то есть d = a[i] - b[j].
// 
// Нужно найти такой сдвиг d, при котором число совпавших пар узлов максимально. Если подходящих сдвигов несколько, выбрать сдвиг с наименьшим значением d (обычное числовое сравнение).
// 
// Формат входных данных:
// - первая строка: два целых числа n и m (1 ≤ n, m ≤ 2000);
// - вторая строка: n целых чисел a[i] (−10^9 ≤ a[i] ≤ 10^9);
// - третья строка: m целых чисел b[j] (−10^9 ≤ b[j] ≤ 10^9).
// 
// Формат результата:
// Одна строка с двумя целыми числами: максимальное число совпавших пар и соответствующий ему наименьший сдвиг d.
// 
// Пример 1:
// Вход:
// 3 3
// 1 2 3
// 0 1 2
// Выход:
// 3 1
// Пояснение: при d = 1 узлы A (1, 2, 3) совпадают с B (0, 1, 2), сдвинутыми на 1: 0+1=1, 1+1=2, 2+1=3. Совпали все 3 пары.
// 
// Пример 2:
// Вход:
// 2 3
// 5 10
// 1 2 3
// Выход:
// 1 2
// Пояснение: любая пара даёт не более одного совпадения. Сдвиги-кандидаты: 4, 3, 2, 9, 8, 7. Максимум совпадений равен 1, а наименьший такой сдвиг — 2.

// Задача: найти сдвиг d, при котором две верёвки с узлами совпадают чаще всего.
// Ключевая идея: пара узлов (a[i], b[j]) совпадает ровно при сдвиге d = a[i] - b[j].
// Поэтому достаточно для всех пар посчитать частоты сдвигов и взять самый частый.
// Сложность: O(n·m) по времени и памяти — при n, m ≤ 2000 это быстро.
function alignKnots(a, b) {
  if (a.length === 0 || b.length === 0) {
    // Хотя бы одна верёвка без узлов — совпадений нет.
    return [0, 0];
  }

  // Считаем, сколько пар дают каждый возможный сдвиг.
  const counts = new Map();
  for (const x of a) {
    for (const y of b) {
      const d = x - y;
      counts.set(d, (counts.get(d) ?? 0) + 1);
    }
  }

  // Выбираем сдвиг с максимумом совпадений; при равенстве — меньший по значению.
  let bestCount = -1;
  let bestShift = 0;
  for (const [d, c] of counts) {
    if (c > bestCount || (c === bestCount && d < bestShift)) {
      bestCount = c;
      bestShift = d;
    }
  }

  // Возвращаем пару [максимум совпадений, наименьший подходящий сдвиг].
  return [bestCount, bestShift];
}
