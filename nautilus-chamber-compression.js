// Задача: Nautilus Chamber Compression
// Сложность: hard
// Дата генерации: 2026-10-10

// Условие задачи
// Раковину наутилуса можно описать квадратной матрицей A размера n×n, элементы которой — «толщины» её отсеков.
// 
// Чтобы получить одномерную развёртку раковины, нужно обойти матрицу по спирали по часовой стрелке: начать в левом верхнем углу, идти вправо до края, затем вниз, затем влево, затем вверх, каждый раз сужая рамку, пока не будут пройдены все n² клеток. Пусть S — получившаяся последовательность длины n².
// 
// Сжатие раковины — это разбиение S на минимальное число подряд идущих непустых отрезков (камер). Каждая камера должна быть строгой горой: для отрезка b[0..m-1] найдётся такой индекс p (0 ≤ p < m), что
// 
//   b[0] < b[1] < ... < b[p] > b[p+1] > ... > b[m-1],
// 
// то есть сначала значения строго возрастают, а затем строго убывают. Отрезок из одного элемента — всегда корректная камера. Два соседних равных элемента внутри одной камеры недопустимы (строгость нарушена).
// 
// Требуется найти минимальное возможное число камер.
// 
// Формат входных данных:
// В первой строке записано целое n (1 ≤ n ≤ 1000). Далее идут n строк по n целых чисел A[i][j] (|A[i][j]| ≤ 10^9).
// 
// Формат результата:
// Одно целое число — минимальное количество камер.
// 
// Пример 1:
// Ввод:
// 3
// 1 2 3
// 8 9 4
// 7 6 5
// Вывод: 1
// Пояснение: спираль — 1,2,3,4,5,6,7,8,9, она строго возрастает, поэтому вся раковина является одной камерой.
// 
// Пример 2:
// Ввод:
// 2
// 1 3
// 4 2
// Вывод: 2
// Пояснение: спираль — 1,3,2,4. Целиком горой она не является (после спуска 3→2 идёт подъём 2→4), но разбивается на две горы: [1,3] и [2,4].
// 
// Пример 3:
// Ввод:
// 3
// 5 1 2
// 4 9 3
// 3 8 7
// Вывод: 3
// Пояснение: спираль — 5,1,2,3,7,8,3,4,9. Минимальное разбиение: [5] | [1,2,3,7,8,3] | [4,9].
// 
// Ограничения и требования:
// – время работы O(n²), память O(n²);
// – решение должно поддерживать n до 1000 (то есть до 10^6 элементов в развёртке).

/**
 * Nautilus Chamber Compression.
 *
 * Матрица читается «по спирали» по часовой стрелке от левого верхнего угла —
 * получается последовательность S длины n*n. Её нужно разрезать на минимальное
 * число подряд идущих отрезков-камер, каждый из которых является строгой горой.
 */

// Чтение матрицы по спирали по часовой стрелке (вправо, вниз, влево, вверх, ...).
function spiralRead(matrix) {
  const n = matrix.length;
  const res = [];
  let top = 0;
  let bottom = n - 1;
  let left = 0;
  let right = n - 1;

  while (top <= bottom && left <= right) {
    for (let c = left; c <= right; c++) res.push(matrix[top][c]);       // верхняя строка →
    top++;
    for (let r = top; r <= bottom; r++) res.push(matrix[r][right]);     // правый столбец ↓
    right--;
    if (top <= bottom) {
      for (let c = right; c >= left; c--) res.push(matrix[bottom][c]);  // нижняя строка ←
      bottom--;
    }
    if (left <= right) {
      for (let r = bottom; r >= top; r--) res.push(matrix[r][left]);    // левый столбец ↑
      left++;
    }
  }
  return res;
}

/**
 * Минимальное число строгих гор, на которые разбивается массив a.
 *
 * dp[i] — минимум камер для префикса a[0..i]. Тогда
 *   dp[i] = 1 + min(dp[j-1]) по всем j, для которых отрезок a[j..i] — гора.
 *
 * Ключевое наблюдение: множество допустимых j всегда является непрерывным
 * отрезком [L[i]..i], причём L[i] не убывает с ростом i. Значит, минимум
 * dp[j-1] можно поддерживать скользящим окном с монотонной очередью — O(n).
 */
function minMountainPartition(a) {
  const n = a.length;
  if (n === 0) return 0;

  const dp = new Array(n).fill(0);
  const L = new Array(n).fill(0); // L[i] — минимальное начало горы, заканчивающейся в i

  // Монотонная очередь индексов m = j - 1 (значений dp). Индекс -1 обозначает
  // пустой префикс и имеет «стоимость» 0.
  const deque = [];
  let head = 0;

  let lastZero = -1;  // последняя позиция k, где a[k] === a[k+1]
  let lastMinus = -1; // последняя позиция k, где a[k] > a[k+1] (спуск)

  const valAt = (m) => (m < 0 ? 0 : dp[m]);

  for (let i = 0; i < n; i++) {
    if (i > 0) {
      const diff = a[i] - a[i - 1];
      let cand;
      if (diff === 0) {
        // Равные соседи не могут лежать в одной строгой горе — начинаем отрезок заново.
        cand = i;
      } else if (diff < 0) {
        // Спуск сам по себе не мешает горе, но в отрезке не должно быть равных соседей.
        cand = lastZero + 1;
      } else {
        // Подъём допустим, только если до него внутри отрезка не было спусков.
        cand = lastMinus + 1;
      }
      L[i] = Math.max(L[i - 1], cand); // L монотонна: подотрезок горы — тоже гора

      if (diff === 0) lastZero = i - 1;
      else if (diff < 0) lastMinus = i - 1;
    }

    // Добавляем в окно кандидата m = i - 1: последняя камера — один элемент a[i].
    const m = i - 1;
    const value = valAt(m);
    while (deque.length > head && valAt(deque[deque.length - 1]) >= value) deque.pop();
    deque.push(m);

    // Выбрасываем кандидатов, которые лежат левее допустимого старта L[i].
    while (deque[head] < L[i] - 1) head++;

    dp[i] = valAt(deque[head]) + 1;
  }

  return dp[n - 1];
}

// Основная функция решения задачи: матрица → минимальное число камер.
function minChambers(matrix) {
  return minMountainPartition(spiralRead(matrix));
}
