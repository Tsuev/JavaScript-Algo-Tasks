// Задача: Opalwind Ferry Reconciling
// Сложность: medium
// Дата генерации: 2026-11-25

// Условие задачи
// Паром «Opalwind» выполняет рейс, и его журнал состоит из n записей. Каждая запись — это целое число: положительное значение k означает, что на борт поднялись k пассажиров, отрицательное значение −k означает, что k пассажиров сошли на берег. Вместимость парома равна C.
// 
// Журнал называется корректным, если при последовательном чтении записей слева направо количество пассажиров на борту всегда находится в диапазоне от 0 до C включительно, а после последней записи равно 0.
// 
// Некоторые записи могли быть сделаны ошибочно. Можно вычеркнуть любое подмножество записей; оставшиеся записи читаются в исходном порядке. Нужно вычеркнуть минимальное количество записей так, чтобы оставшийся журнал стал корректным. Пустой журнал (все записи вычеркнуты) считается корректным.
// 
// Формат входных данных:
// В первой строке заданы два целых числа n и C (1 ≤ n ≤ 2000, 0 ≤ C ≤ 2000) — количество записей и вместимость парома.
// В следующих n строках записаны целые числа a_i (1 ≤ |a_i| ≤ 10^4) — записи журнала. Положительное число означает посадку, отрицательное — высадку.
// 
// Формат результата:
// Выведите одно целое число — минимальное количество записей, которые нужно вычеркнуть.
// 
// Пример 1:
// Вход:
// 4 2
// 1
// -1
// 2
// -2
// Выход:
// 0
// Пояснение: журнал уже корректен: 0 → 1 → 0 → 2 → 0.
// 
// Пример 2:
// Вход:
// 5 2
// 1
// 1
// 1
// -2
// -1
// Выход:
// 2
// Пояснение: можно вычеркнуть третью запись (1) и последнюю (−1). Останется 1, 1, −2: 0 → 1 → 2 → 0 — корректно. Меньше двух вычеркнуть нельзя.
// 
// Пример 3:
// Вход:
// 3 0
// 1
// -1
// 2
// Выход:
// 3
// Пояснение: при вместимости 0 ни одну запись оставить нельзя, поэтому вычёркиваем все три.

/**
 * Минимальное число записей, которые нужно вычеркнуть,
 * чтобы журнал парома стал корректным.
 *
 * @param {number[]} records — записи журнала (плюс — посадка, минус — высадка)
 * @param {number} capacity — вместимость парома
 * @returns {number}
 */
function reconcileFerryLog(records, capacity) {
  const C = capacity;
  const n = records.length;

  // dp[load] — максимум сохранённых записей после обработки префикса,
  // при котором на борту находится load пассажиров. -1 — состояние недостижимо.
  let dp = new Int32Array(C + 1).fill(-1);
  dp[0] = 0;

  for (const delta of records) {
    const next = new Int32Array(C + 1).fill(-1);

    for (let load = 0; load <= C; load++) {
      if (dp[load] < 0) continue;

      // Вычеркнуть текущую запись: состояние не меняется.
      if (dp[load] > next[load]) {
        next[load] = dp[load];
      }

      // Оставить запись, если количество пассажиров останется допустимым.
      const newLoad = load + delta;
      if (newLoad >= 0 && newLoad <= C) {
        const kept = dp[load] + 1;
        if (kept > next[newLoad]) {
          next[newLoad] = kept;
        }
      }
    }

    dp = next;
  }

  // К концу рейса на борту должно быть 0 пассажиров.
  const maxKept = Math.max(0, dp[0]);
  return n - maxKept;
}
