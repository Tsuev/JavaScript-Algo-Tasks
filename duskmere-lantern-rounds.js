// Условие задачи
// В городе Дасмир фонарщики каждую ночь проводят раунд освещения. Вдоль круговой улицы стоят n фонарей. У каждого фонаря есть яркость a[i]. За один раунд яркость каждого фонаря заменяется на сумму яркостей его самого и двух соседей (левого и правого), взятую по модулю 1 000 000 007. Фонари стоят по кругу, поэтому у первого сосед слева — последний, а у последнего сосед справа — первый. Если n = 1, то левый и правый сосед — это тот же самый фонарь, поэтому его яркость утраивается. Нужно определить яркости всех фонарей после k раундов.
// 
// Формат входных данных:
// В первой строке заданы n и k (1 ≤ n ≤ 200, 0 ≤ k ≤ 10^18). Во второй строке n целых чисел a[i] (0 ≤ a[i] < 1 000 000 007) — начальные яркости.
// 
// Формат выходных данных:
// Выведите n чисел — яркости после k раундов, по модулю 1 000 000 007.
// 
// Пример 1:
// Вход:
// 3 1
// 1 2 3
// Выход:
// 6 6 6
// 
// Пример 2:
// Вход:
// 2 1
// 1 2
// Выход:
// 5 4
// 
// Пример 3:
// Вход:
// 1 2
// 5
// Выход:
// 45
// 
// Пример 4:
// Вход:
// 3 0
// 1 2 3
// Выход:
// 1 2 3

/**
 * Решение задачи «Duskmere Lantern Rounds».
 * Возвращает массив яркостей после k раундов.
 */
const MOD = 1000000007;
const MOD_BIG = 1000000007n;

// Безопасное умножение по модулю MOD.
// Обычное a * b может превысить 2^53, поэтому используем BigInt.
function mulMod(a, b) {
  return Number((BigInt(a) * BigInt(b)) % MOD_BIG);
}

// Умножение двух многочленов по модулю x^n - 1.
// Это в точности циклическая свёртка: (p * q)[k] = sum_{i+j ≡ k (mod n)} p[i] * q[j].
function multiplyPoly(p, q, n) {
  const res = new Array(n).fill(0);
  for (let i = 0; i < n; i++) {
    if (p[i] === 0) continue;
    for (let j = 0; j < n; j++) {
      if (q[j] === 0) continue;
      const idx = (i + j) % n;
      res[idx] = (res[idx] + mulMod(p[i], q[j])) % MOD;
    }
  }
  return res;
}

// Возведение многочлена в степень exp по модулю x^n - 1.
function powerPoly(base, exp, n) {
  let result = new Array(n).fill(0);
  result[0] = 1; // единичный многочлен
  let cur = base.slice();
  let e = typeof exp === 'bigint' ? exp : BigInt(exp);
  while (e > 0n) {
    if (e & 1n) {
      result = multiplyPoly(result, cur, n);
    }
    cur = multiplyPoly(cur, cur, n);
    e >>= 1n;
  }
  return result;
}

function solveLanternRounds(n, k, a) {
  // Приводим начальные яркости к диапазону [0, MOD)
  const arr = a.map(x => ((x % MOD) + MOD) % MOD);

  // Многочлен одного раунда: яркость фонаря складывается из него самого
  // и двух соседей. В циклической свёртке это коэффициенты при x^0, x^1 и x^{n-1}.
  const base = new Array(n).fill(0);
  base[0] = (base[0] + 1) % MOD;               // сам фонарь
  base[1 % n] = (base[1 % n] + 1) % MOD;       // правый сосед
  base[(n - 1) % n] = (base[(n - 1) % n] + 1) % MOD; // левый сосед

  // После k раундов преобразование — это свёртка с base^k.
  const poly = powerPoly(base, k, n);

  // Применяем итоговое преобразование к начальному вектору яркостей.
  return multiplyPoly(arr, poly, n);
}
