// Задача: Prism Refraction Paths
// Сложность: hard
// Дата генерации: 2026-09-14

// Условие задачи
// Сечение стеклянной призмы моделируется треугольной решёткой из n строк. В строке i (нумерация с нуля) находится i+1 клеток с индексами j = 0..i. Клетка (i, j) характеризуется целым показателем преломления a[i][j].
// 
// Луч света входит в призму сверху — в клетку (0, 0). На каждом шаге луч переходит в следующую строку и попадает ровно в одну из двух соседних снизу клеток:
//   • влево — в клетку (i+1, j);
//   • вправо — в клетку (i+1, j+1).
// Шаг вниз-влево возможен только если a[i+1][j] <= a[i][j], а шаг вниз-вправо — только если a[i+1][j+1] <= a[i][j]. Если показатель преломления нижней клетки больше, свет туда не проходит (полное внутреннее отражение).
// 
// Преломлением называется смена направления между двумя последовательными шагами: если луч сначала шёл влево, а затем вправо (или наоборот) — это одно преломление. Самый первый шаг преломлением не считается, так как направление ещё не задано.
// 
// Луч считается дошедшим, если после ровно n-1 шагов он оказался в последней строке (i = n-1). Требуется посчитать количество дошедших лучей, у которых ровно K преломлений. Ответ вывести по модулю 1 000 000 007.
// 
// Формат входа:
//   • a — массив из n строк, где a[i] содержит i+1 целых чисел (1 <= a[i][j] <= 10^9);
//   • K — целое число (0 <= K <= n).
// 
// Формат выхода:
//   • одно целое число — количество путей по модулю 1_000_000_007.
// 
// Ограничения: 1 <= n <= 300, 0 <= K <= n.
// 
// Пример 1:
//   Вход:  a = [[5], [3, 4], [1, 2, 6]], K = 0
//   Выход: 1
//   Пояснение: единственный путь без преломлений — 5 -> 3 -> 1 (два шага влево).
// 
// Пример 2:
//   Вход:  a = [[5], [3, 4], [1, 2, 6]], K = 1
//   Выход: 2
//   Пояснение: пути 5 -> 3 -> 2 (влево, затем вправо) и 5 -> 4 -> 2 (вправо, затем влево).
// 
// Пример 3:
//   Вход:  a = [[7], [7, 7], [7, 7, 7]], K = 0
//   Выход: 2
//   Пояснение: все шаги разрешены; без преломлений ровно два пути — «влево, влево» и «вправо, вправо».
// 
// Пример 4:
//   Вход:  a = [[1], [2, 1], [1, 1, 1]], K = 0
//   Выход: 1
//   Пояснение: из (0,0) со значением 1 нельзя спуститься в клетку со значением 2, поэтому первый шаг возможен только вправо — в (1,1); дальше без преломлений можно снова шагнуть вправо — в (2,2).

// Считает количество путей луча света через призму-треугольник
// ровно с K преломлениями, по модулю 1_000_000_007.
// Время O(n^2 * K), память O(n * K).
function prismRefractionPaths(a, K) {
  const MOD = 1_000_000_007;
  const n = a.length;

  // Призма из одной строки: луч уже в единственной клетке, шагов нет,
  // значит и преломлений быть не может.
  if (n === 1) return K === 0 ? 1 : 0;

  // За n-1 шагов направление может смениться не более n-2 раз.
  if (K < 0 || K > n - 2) return 0;

  // W = K+1 — сколько различных значений счётчика преломлений отслеживаем.
  const W = K + 1;

  // dpL[j*W + k] — сколько путей пришло в клетку j текущей строки так,
  //   что последний шаг был ВЛЕВО и накоплено ровно k преломлений.
  // dpR[j*W + k] — то же самое, но последний шаг был ВПРАВО.
  let dpL = new Uint32Array(n * W);
  let dpR = new Uint32Array(n * W);

  // Первый шаг из (0,0) задаёт начальное направление и НЕ считается преломлением.
  if (a[1][0] <= a[0][0]) dpL[0 * W + 0] = 1; // влево  -> клетка (1,0)
  if (a[1][1] <= a[0][0]) dpR[1 * W + 0] = 1; // вправо -> клетка (1,1)

  // Построчно заполняем динамику: из строки row переходим в строку row+1.
  for (let row = 1; row < n - 1; row++) {
    const nextL = new Uint32Array(n * W);
    const nextR = new Uint32Array(n * W);

    for (let j = 0; j <= row; j++) {
      const base = j * W;
      const ref = a[row][j];
      // Проходить ли свет вниз зависит от показателя преломления текущей клетки.
      const canLeft = a[row + 1][j] <= ref;       // шаг в (row+1, j)
      const canRight = a[row + 1][j + 1] <= ref;  // шаг в (row+1, j+1)
      if (!canLeft && !canRight) continue;

      for (let k = 0; k <= K; k++) {
        const vL = dpL[base + k];
        const vR = dpR[base + k];
        if (vL === 0 && vR === 0) continue;

        if (canLeft) {
          // Продолжаем движение влево: направление не меняется, преломления нет.
          if (vL) nextL[base + k] = (nextL[base + k] + vL) % MOD;
          // Меняем «вправо» на «влево»: это преломление, счётчик растёт.
          if (vR && k < K) nextL[base + k + 1] = (nextL[base + k + 1] + vR) % MOD;
        }
        if (canRight) {
          const idx = (j + 1) * W;
          // Продолжаем движение вправо: преломления нет.
          if (vR) nextR[idx + k] = (nextR[idx + k] + vR) % MOD;
          // Меняем «влево» на «вправо»: добавляем преломление.
          if (vL && k < K) nextR[idx + k + 1] = (nextR[idx + k + 1] + vL) % MOD;
        }
      }
    }
    dpL = nextL;
    dpR = nextR;
  }

  // Складываем все лучи, дошедшие до последней строки ровно с K преломлениями.
  let answer = 0;
  const last = n - 1;
  for (let j = 0; j <= last; j++) {
    answer = (answer + dpL[j * W + K]) % MOD;
    answer = (answer + dpR[j * W + K]) % MOD;
  }
  return answer;
}
