// Задача: Thistlefen Ferry Timetabling
// Сложность: medium
// Дата генерации: 2026-11-06

// Условие задачи
// Паром в городе Thistlefen переправляет пассажиров через реку.
// 
// У парома вместимость C человек и время переправы в одну сторону T минут. В момент 0 паром стоит у левого берега. Пассажиры подходят к левому берегу в моменты a_1, ..., a_N. Паром может подождать, взять на борт не более C пассажиров (обслуживая очередь по порядку: кто пришёл раньше, тот садится раньше), переплыть на правый берег за T минут и высадить их. Если остались пассажиры, паром пустым возвращается назад (ещё T минут), после чего может снова брать пассажиров у левого берега. Садиться на паром пассажир может только в момент не раньше своего прихода.
// 
// Нужно спланировать рейсы так, чтобы последний пассажир оказался на правом берегу как можно раньше. Возвращаться после последнего рейса не требуется.
// 
// Найдите минимальный момент времени, когда все пассажиры окажутся на правом берегу.
// 
// Формат входных данных:
// В первой строке заданы три целых числа N, C, T.
// Во второй строке заданы N целых чисел a_i — моменты прихода пассажиров (в произвольном порядке).
// 
// Формат результата:
// Одно целое число — минимальное время, к которому последний пассажир будет на правом берегу.
// 
// Ограничения:
// 1 ≤ N ≤ 2·10^5, 1 ≤ C ≤ N, 1 ≤ T ≤ 10^9, 0 ≤ a_i ≤ 10^9.
// 
// Пример 1:
// Вход:
// 3 2 1
// 0 1 2
// Выход:
// 3
// Пояснение: один пассажир уплывает в 0 и прибывает в 1; паром возвращается в 2, забирает двух оставшихся и прибывает в 3.
// 
// Пример 2:
// Вход:
// 1 1 5
// 7
// Выход:
// 12
// 
// Пример 3:
// Вход:
// 3 2 10
// 0 0 0
// Выход:
// 30
// Пояснение: например, сначала отправляем одного пассажира в 0, затем двоих в 20; последний прибывает в 30.

function minFerryCompletion(arrivals, capacity, crossTime) {
  // Сортируем времена прихода: паром обслуживает пассажиров в порядке очереди.
  const a = [...arrivals].sort((x, y) => x - y);
  const n = a.length;
  if (n === 0) return 0;

  // gap — минимальный интервал между двумя отправлениями: доплыть и вернуться.
  const gap = 2 * crossTime;

  // dp[i] — минимальный момент отправления рейса, на котором уезжает i-й пассажир
  // (после этого рейса первые i пассажиров уже переправлены).
  const dp = new Array(n + 1).fill(0);
  dp[0] = Number.NEGATIVE_INFINITY;

  for (let i = 1; i <= n; i++) {
    // Чтобы не делать лишних рейсов, последний рейс грузим по максимуму.
    // Тогда предыдущий переправленный пассажир имеет номер i - capacity.
    const prev = Math.max(0, i - capacity);
    // Отправление не раньше прихода последнего пассажира рейса и не раньше
    // возвращения парома после предыдущего рейса.
    dp[i] = Math.max(dp[prev] + gap, a[i - 1]);
  }

  // Последнему рейсу ещё нужно доплыть до правого берега.
  return dp[n] + crossTime;
}
