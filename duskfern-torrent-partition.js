// Задача: Duskfern Torrent Partition
// Сложность: medium
// Дата генерации: 2026-11-15

// Условие задачи
// «Сумеречный поток» (Duskfern Torrent) разбит на n кусков, кусок с номером i имеет размер w[i] (натуральное число). Поток раздаётся k пиратам: каждому пирату достаётся непустой непрерывный отрезок кусков, отрезки идут в порядке исходной последовательности, не пересекаются и вместе покрывают все n кусков. Внутри своего отрезка пират качает куски последовательно, поэтому время пирата равно сумме размеров его кусков, а общее время раздачи — максимуму этих сумм по всем пиратам.
// 
// Нужно разбить поток на k отрезков так, чтобы максимальная сумма по отрезкам была как можно меньше.
// 
// Дополнительно нужно вернуть само разбиение. Чтобы ответ был однозначным, среди всех оптимальных разбиений берётся то, которое получается «жадным набором справа налево»: сначала последнему пирату отдаём как можно больше кусков (не превышая найденный оптимум), затем предпоследнему — как можно больше из оставшихся, и так далее; при этом на каждый ещё не заполненный блок всегда остаётся хотя бы по одному куску.
// 
// ФОРМАТ ВХОДА: n (1 ≤ n ≤ 200000), k (1 ≤ k ≤ n), массив w из n натуральных чисел, 1 ≤ w[i] ≤ 10^9.
// 
// ФОРМАТ ВЫХОДА: объект { best, parts }, где best — минимально возможное максимальное время, а parts — массив длины k из сумм блоков слева направо. Гарантируется, что сумма всех parts равна сумме w, все parts[i] > 0 и max(parts) = best.
// 
// ПРИМЕР 1: n = 7, k = 4, w = [1,2,3,4,5,6,7]. Ответ: best = 9, parts = [6,9,6,7]. Пояснение: разбиение [1,2,3] | [4,5] | [6] | [7] даёт суммы 6, 9, 6, 7, максимум 9; меньше 9 не получится, так как при пределе 8 минимальное число блоков равно 5.
// 
// ПРИМЕР 2: n = 3, k = 3, w = [5,1,4]. Ответ: best = 5, parts = [5,1,4]. Каждый пират получает ровно один кусок.
// 
// ПРИМЕР 3: n = 5, k = 2, w = [1,1,1,1,1]. Ответ: best = 3, parts = [2,3]. Жадный набор справа налево оставляет последнему пирату три единицы, первому — две.

/**
 * Разбиение потока на k непрерывных блоков с минимальным максимумом суммы.
 *
 * Идея: искомый ответ лежит между самым большим куском и суммой всех кусков,
 * а свойство «уложиться в предел limit, сделав не более k блоков» монотонно
 * по limit. Значит, предел можно найти двоичным поиском.
 */
function solveDuskfernTorrent(n, k, w) {
  // Проверяем: хватает ли k блоков, чтобы каждый блок весил не больше limit.
  // Жадно набираем блок слева направо до упора — так blocks будет минимальным.
  const canSplit = (limit) => {
    let blocks = 1;
    let cur = 0;
    for (const x of w) {
      if (cur + x <= limit) {
        cur += x;
      } else {
        // Текущий блок переполнен: начинаем следующий.
        blocks++;
        cur = x;
        if (blocks > k) return false; // дальше проверять смысла нет
      }
    }
    return blocks <= k;
  };

  // Нижняя граница — самый крупный кусок (его нельзя разделить между пиратами),
  // верхняя — весь поток целиком достаётся одному пирату.
  let lo = 0;
  let hi = 0;
  for (const x of w) {
    if (x > lo) lo = x;
    hi += x;
  }

  // Двоичный поиск минимального предела, при котором хватает k блоков.
  while (lo < hi) {
    const mid = Math.floor((lo + hi) / 2);
    if (canSplit(mid)) {
      hi = mid;      // возможно, можно ещё меньше
    } else {
      lo = mid + 1;  // mid слишком мал
    }
  }
  const best = lo;

  // Восстановление разбиения. Идём с конца: каждый блок набираем как можно
  // длиннее, но так, чтобы для ещё не заполненных блоков слева осталось
  // хотя бы по одному куску (условие start >= b). Так как best — минимально
  // возможный предел, набранные суммы не превысят best, а левый край дойдёт до нуля.
  const parts = new Array(k);
  let end = n - 1;
  for (let b = k - 1; b >= 0; b--) {
    let sum = 0;
    let start = end;
    while (start >= b && sum + w[start] <= best) {
      sum += w[start];
      start--;
    }
    parts[b] = sum;   // блок занимает куски start+1 .. end
    end = start;
  }

  return { best, parts };
}
