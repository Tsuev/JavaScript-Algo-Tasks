// Условие задачи
// Условие задачи «Cascade Gear Alignment».
// 
// Мотор вращает шестерёнку 1, а та через каскад приводит в движение всю передачу из n шестерёнок, выстроенных в ряд. Шестерёнка i имеет a_i зубьев, соседние шестерёнки сцеплены между собой. Сцепленные шестерёнки вращаются в противоположные стороны, а их углы поворота связаны передаточным отношением: если шестерёнка i повернулась на угол φ_i, то шестерёнка i+1 повернётся на угол φ_{i+1} = -φ_i · a_i / a_{i+1}.
// 
// На каждой шестерёнке нарисована метка. Изначально каскад выровнен: все метки смотрят строго вверх. Мотор начинает вращать шестерёнку 1. В какой-то момент все метки снова одновременно окажутся направленными вверх — каскад снова выровнен.
// 
// Найдите минимальное положительное число ПОЛНЫХ оборотов T, которое должна сделать шестерёнка 1, чтобы каскад впервые снова оказался выровнен.
// 
// Разбор условия:
// — Направление вращения (по часовой или против) на «метку вверх» не влияет: метка снова смотрит вверх, когда шестерёнка повернулась ровно на целое число полных оборотов, то есть когда |φ_i| кратно 2π.
// — За T полных оборотов шестерёнки 1 шестерёнка i поворачивается на угол ±2π · T · a_1 / a_i. Значит метка i снова вверху тогда и только тогда, когда T · a_1 / a_i — целое число.
// — Поэтому T · a_1 обязано быть общим кратным всех чисел a_i, а наименьшее такое произведение — это НОК(a_1, …, a_n). Отсюда T = НОК(a_1, …, a_n) / a_1 (целое, потому что a_1 делит НОК).
// 
// Формат входных данных: массив a натуральных чисел (количества зубьев по порядку каскада); 1 ≤ n ≤ 100, 1 ≤ a_i ≤ 10^9.
// 
// Формат результата: строка с десятичной записью минимального T. Число может быть очень большим (НОК может содержать десятки простых множителей), поэтому ответ возвращается именно строкой.
// 
// Примеры:
// 1) a = [4, 6] → «3». НОК = 12, T = 12/4 = 3 (вторая шестерёнка делает 3·4/6 = 2 полных оборота).
// 2) a = [6, 10, 15] → «5». НОК = 30, T = 30/6 = 5 (2-я: 5·6/10 = 3 оборота, 3-я: 5·6/15 = 2 оборота; меньше 5 не подходит).
// 3) a = [7] → «1». Одна шестерёнка вернётся в исходное положение после 1 полного оборота.
// 4) a = [1, 2, 3, 5, 7, 11, 13] → «30030». НОК = 30030, а первая шестерёнка имеет 1 зуб, значит T равно самому НОК.

/**
 * Cascade Gear Alignment
 *
 * Идея решения:
 * Шестерёнка i снова смотрит меткой вверх ровно тогда, когда она сделала
 * целое число полных оборотов. За T оборотов ведущей шестерёнки i-я делает
 * T * a[0] / a[i] оборотов, значит T * a[0] должно делиться на каждое a[i].
 * Минимальное T * a[0] — это НОК всех количеств зубьев, отсюда
 * T = НОК(a) / a[0].
 *
 * Числа могут быть огромными, поэтому всё считаем в BigInt,
 * а результат возвращаем строкой.
 */

// НОД двух BigInt (алгоритм Евклида).
function gcd(a, b) {
  if (a < 0n) a = -a;
  if (b < 0n) b = -b;
  while (b !== 0n) {
    const t = a % b;
    a = b;
    b = t;
  }
  return a;
}

// НОК двух BigInt. Сначала делим, потом умножаем — так промежуточный
// результат меньше, а ответ тот же.
function lcm(a, b) {
  return (a / gcd(a, b)) * b;
}

/**
 * @param {number[]} a — количества зубьев шестерёнок каскада по порядку
 * @returns {string} — минимальное число полных оборотов ведущей шестерёнки
 */
function solve(a) {
  // Считаем НОК всех количеств зубьев.
  let commonMultiple = 1n;
  for (const teeth of a) {
    commonMultiple = lcm(commonMultiple, BigInt(teeth));
  }

  // НОК делится на a[0], так что деление всегда целое.
  const turns = commonMultiple / BigInt(a[0]);
  return turns.toString();
}
