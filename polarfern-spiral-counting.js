// Условие задачи
// Polarfern Spiral Counting
// 
// «Полярный папоротник» растёт по спирали: семечко с номером k (k = 0, 1, 2, …) появляется на расстоянии r_k = √k от центра и под углом φ_k = 360° · ((k·p) mod q) / q, отсчитанным против часовой стрелки от положительного направления оси X. Пара (p, q) задаёт угол расхождения; например, p = 89, q = 233 даёт ≈ 137.5° — «золотой» угол настоящих папоротников и подсолнухов.
// 
// Так как r_k = √k, семечки распределены по диску равномерно по площади, и номера k, попадающие в кольцо r_lo ≤ r ≤ r_hi, образуют непрерывный отрезок целых чисел [r_lo², r_hi²].
// 
// Заданы p, q и Q запросов. Каждый запрос — это сектор кольца: лучи от угла θ_lo до угла θ_hi (в градусах, против часовой стрелки) и кольцо от r_lo до r_hi. Если θ_lo > θ_hi, сектор проходит через направление 0°, то есть является объединением [θ_lo, 360°) и [0°, θ_hi). Если θ_lo = θ_hi, сектор пуст. Углы θ_lo и θ_hi всегда целые.
// 
// Семечко попадает в сектор, если выполнены оба условия:
//   1) r_lo ≤ √k ≤ r_hi;
//   2) θ_lo ≤ φ_k < θ_hi (с учётом возможного перехода через 0°).
// 
// Для каждого запроса посчитайте количество таких семечек.
// 
// Формат входных данных
// 
// Первая строка: два целых числа p и q (1 ≤ p ≤ q ≤ 2·10^5).
// Вторая строка: целое число Q (1 ≤ Q ≤ 10^5).
// Далее Q строк, в каждой четыре целых числа: r_lo, r_hi, θ_lo, θ_hi (0 ≤ r_lo ≤ r_hi ≤ 10^6; 0 ≤ θ_lo, θ_hi ≤ 360).
// 
// Формат результата
// 
// Q строк, в i-й — одно целое число: количество семечек папоротника внутри i-го сектора. Ответ помещается в 64-битное целое (не превосходит числа семечек в диске радиуса 10^6, то есть 10^12).
// 
// Пример 1
// 
// Вход:
// 2 5
// 3
// 0 2 0 180
// 1 2 60 300
// 0 3 300 60
// 
// Выход:
// 3
// 4
// 2
// 
// Пояснение к примеру. p = 2, q = 5, соседние семечки расходятся на 144°. Первые семечки:
//   k=0: r=0.00, φ=0°
//   k=1: r=1.00, φ=144°
//   k=2: r=1.41, φ=288°
//   k=3: r=1.73, φ=72°
//   k=4: r=2.00, φ=216°
//   k=5: r=2.24, φ=0°
//   k=6: r=2.45, φ=144°
//   ...
// Запрос 1: кольцо 0..2 (k = 0..4), углы [0°, 180°). Подходят k = 0, 1, 3 → 3.
// Запрос 2: k = 1..4, углы [60°, 300°). Подходят все четыре семечка → 4.
// Запрос 3: k = 0..9, сектор [300°, 360°) ∪ [0°, 60°). Углов ≥ 300° нет вовсе, а угол 0° дают k = 0 и k = 5 → 2.
// 
// Пример 2
// 
// Вход:
// 89 233
// 2
// 0 10 0 360
// 0 1 0 360
// 
// Выход:
// 101
// 2
// 
// (В кольце 0..10 лежат семечки k = 0..100 — всего 101; в кольце 0..1 — семечки k = 0 и k = 1.)

// Задача «Polarfern Spiral Counting».
//
// Ключевые наблюдения:
//  1. Так как r_k = sqrt(k), кольцо r_lo..r_hi — это просто отрезок номеров k из [r_lo^2, r_hi^2].
//  2. Угол семечка k равен 360 * m / q, где m = (k*p) mod q. Значит, угловой сектор
//     [a, b) — это целочисленный отрезок [ceil(a*q/360), ceil(b*q/360) - 1] для m.
//  3. Пусть g = gcd(p, q), period = q/g, step = p/g. Тогда m = (k*p) mod q = g * ((k*step) mod period),
//     то есть последовательность «угловых слотов» j(k) = (k*step) mod period периодична с длиной period,
//     и внутри периода j пробегает каждое значение 0..period-1 ровно один раз (step взаимно прост с period).
//  4. Поэтому для любого N количество подходящих семечек среди k = 0..N равно
//        (полных периодов) * (ширина допустимого диапазона j) + ответ для «хвоста» из rem семечек.
//     Хвосты всех запросов считаются офлайн одним проходом дерева Фенвика.

function gcd(a, b) {
  while (b !== 0) {
    const t = a % b;
    a = b;
    b = t;
  }
  return a;
}

// Целочисленное деление с округлением вверх для неотрицательных x и положительного d.
function ceilDiv(x, d) {
  return Math.floor((x + d - 1) / d);
}

/**
 * Основная функция решения.
 *
 * @param {number} p — числитель шага расхождения: угол семечка k равен 360° * (k*p mod q) / q
 * @param {number} q — знаменатель шага расхождения
 * @param {Array<[number, number, number, number]>} queries — запросы [rLo, rHi, thetaLo, thetaHi]
 * @returns {number[]} по одному ответу на каждый запрос
 */
function polarfernSpiralCounting(p, q, queries) {
  const g = gcd(p, q);
  const period = q / g; // длина цикла по номеру семечка
  const step = p / g;   // шаг перестановки внутри периода, gcd(step, period) = 1

  // js[c] = угловой слот семечка c внутри периода: (c * step) mod period.
  // Это перестановка чисел 0..period-1, считаем её один раз за O(period).
  const js = new Int32Array(period);
  for (let c = 0, j = 0; c < period; c++) {
    js[c] = j;
    j += step;
    if (j >= period) j -= period;
  }

  const answers = new Array(queries.length).fill(0);
  const pending = []; // отложенные вопросы вида «сколько c < P дают j(c) в [jLo, jHi]»

  for (let qi = 0; qi < queries.length; qi++) {
    const [rLo, rHi, thLo, thHi] = queries[qi];

    // Кольцо по расстоянию превращается в отрезок номеров семечек.
    const kLo = rLo * rLo;
    const kHi = rHi * rHi;

    // Угловой сектор — это либо один интервал, либо два, если он проходит через 0°.
    const parts = [];
    if (thLo < thHi) {
      parts.push([thLo, thHi]);
    } else if (thLo > thHi) {
      parts.push([thLo, 360]);
      parts.push([0, thHi]);
    }
    // при thLo === thHi сектор пуст, parts остаётся пустым

    let total = 0;
    for (const [a, b] of parts) {
      // Условие a <= 360*m/q < b переводим в целочисленный отрезок для m.
      const mLo = ceilDiv(a * q, 360);
      const mHi = ceilDiv(b * q, 360) - 1;

      // Внутри периода m всегда кратно g, то есть m = g*j, где j — угловой слот.
      let jLo = ceilDiv(mLo, g);
      let jHi = Math.floor(mHi / g);
      if (jLo < 0) jLo = 0;
      if (jHi > period - 1) jHi = period - 1;
      if (jLo > jHi) continue; // в этом секторе не бывает семечек

      // За один полный период ровно width семечек имеют допустимый угол,
      // потому что внутри периода каждый слот встречается ровно один раз.
      const width = jHi - jLo + 1;

      // Считаем количество на префиксе k = 0..N через разность F(kHi) - F(kLo - 1).
      for (const [N, sign] of [[kHi, 1], [kLo - 1, -1]]) {
        if (N < 0) continue;
        const cnt = N + 1;                     // семечки с номерами 0..N
        const full = Math.floor(cnt / period); // сколько целых периодов укладывается
        const rem = cnt - full * period;       // и сколько семечек осталось в хвосте
        total += sign * full * width;
        if (rem > 0) pending.push({ P: rem, jLo, jHi, sign, qi });
      }
    }
    answers[qi] = total;
  }

  // Офлайн-обработка хвостов: идём по c = 0, 1, 2, ... и складываем слоты js[c] в дерево Фенвика.
  // Запросы сортируем по длине префикса P, чтобы указатель двигался только вперёд.
  pending.sort((x, y) => x.P - y.P);

  const bit = new Int32Array(period + 1);
  const addSlot = (slot) => {
    for (let i = slot + 1; i <= period; i += i & -i) bit[i] += 1;
  };
  // Сумма по слотам [0, i)
  const prefixSum = (i) => {
    let s = 0;
    for (; i > 0; i -= i & -i) s += bit[i];
    return s;
  };

  let filled = 0;
  for (const req of pending) {
    while (filled < req.P) {
      addSlot(js[filled]);
      filled++;
    }
    const inRange = prefixSum(req.jHi + 1) - prefixSum(req.jLo);
    answers[req.qi] += req.sign * inRange;
  }

  return answers;
}
