// Условие задачи
// «Опалиновый Разлом» — это карта, заданная прямоугольной сеткой размера n × m. В каждой клетке записано целое число — сопротивление опалиновой породы (чем больше число, тем опаснее клетка).
// 
// Путешественник стоит в клетке (sr, sc) и хочет попасть в клетку (tr, tc). За один шаг он может перейти в одну из четырёх соседних клеток (вверх, вниз, влево, вправо). Стоимостью маршрута называется максимальное сопротивление среди ВСЕХ клеток, которые маршрут посещает, включая начальную и конечную. Нужно найти минимально возможную стоимость маршрута.
// 
// Иными словами, для каждого порога T проверим, существует ли путь из старта в цель, проходящий только по клеткам с сопротивлением ≤ T. Ответ — наименьший такой T. Простой поиск «в лоб» по всем T слишком медленный, поэтому задачу решают как поиск минимаксного пути.
// 
// Формат входных данных (аргументы функции minRiftCost):
// - grid — двумерный массив n × m целых чисел, 1 ≤ grid[r][c] ≤ 10^9;
// - start — пара [sr, sc] в 0-индексации;
// - target — пара [tr, tc] в 0-индексации.
// 
// Формат результата: одно целое число — минимальная стоимость маршрута.
// 
// Ограничения: 1 ≤ n, m ≤ 1000; 1 ≤ n * m ≤ 10^6; start и target всегда внутри сетки.
// 
// Пример 1:
// Вход:
// grid = [[1, 9, 1],
//         [1, 9, 1],
//         [1, 1, 1]]
// start = [0, 0], target = [0, 2]
// Выход: 1
// Пояснение: прямой путь по верхней строке упирается в 9, но можно обойти снизу по клеткам со значением 1.
// 
// Пример 2:
// Вход:
// grid = [[5, 3, 9, 7],
//         [2, 8, 4, 6]]
// start = [0, 0], target = [1, 3]
// Выход: 8
// Пояснение: любой маршрут вынужден пройти либо через 8 (нижняя строка), либо через 9. Минимальный возможный максимум равен 8.
// 
// Пример 3:
// Вход:
// grid = [[4]], start = [0, 0], target = [0, 0]
// Выход: 4
// Пояснение: старт совпадает с целью, стоимость — сопротивление самой клетки.

// Минимальная куча (min-heap) для алгоритма Дейкстры.
// Хранит тройки [стоимость, строка, столбец] и всегда отдаёт наименьшую стоимость.
class MinHeap {
  constructor() {
    this.data = [];
  }

  get size() {
    return this.data.length;
  }

  push(item) {
    const a = this.data;
    a.push(item);
    let i = a.length - 1;
    // Просеиваем новый элемент вверх, пока он меньше родителя.
    while (i > 0) {
      const parent = (i - 1) >> 1;
      if (a[parent][0] <= a[i][0]) break;
      [a[parent], a[i]] = [a[i], a[parent]];
      i = parent;
    }
  }

  pop() {
    const a = this.data;
    const top = a[0];
    const last = a.pop();
    if (a.length > 0) {
      a[0] = last;
      let i = 0;
      // Просеиваем корень вниз, пока свойство кучи не восстановится.
      for (;;) {
        const left = 2 * i + 1;
        const right = 2 * i + 2;
        let smallest = i;
        if (left < a.length && a[left][0] < a[smallest][0]) smallest = left;
        if (right < a.length && a[right][0] < a[smallest][0]) smallest = right;
        if (smallest === i) break;
        [a[i], a[smallest]] = [a[smallest], a[i]];
        i = smallest;
      }
    }
    return top;
  }
}

/**
 * Ищет минимально возможное значение «максимума по пути» из start в target.
 *
 * Идея: обычная Дейкстра считает сумму весов, а здесь ценой пути служит
 * максимум из весов посещённых клеток. Релаксация меняется на
 * nextCost = max(стоимость_до_соседа, сопротивление_соседа), а приоритетная
 * очередь по-прежнему выдаёт вершины в порядке возрастания стоимости.
 * Поэтому как только из очереди достаётся цель, найденный ответ оптимален.
 *
 * Сложность: O(n * m * log(n * m)) по времени и O(n * m) по памяти.
 */
function minRiftCost(grid, start, target) {
  const n = grid.length;
  const m = grid[0].length;
  const [sr, sc] = start;
  const [tr, tc] = target;

  // dist[r][c] — лучшая (минимальная) стоимость пути из старта в клетку (r, c).
  const INF = Infinity;
  const dist = Array.from({ length: n }, () => new Array(m).fill(INF));
  dist[sr][sc] = grid[sr][sc];

  const heap = new MinHeap();
  heap.push([grid[sr][sc], sr, sc]);

  // Смещения для четырёх соседей.
  const dr = [-1, 1, 0, 0];
  const dc = [0, 0, -1, 1];

  while (heap.size > 0) {
    const [cost, r, c] = heap.pop();

    // Устаревшая запись: для этой клетки уже найден более дешёвый путь.
    if (cost > dist[r][c]) continue;

    // Первое извлечение цели — это ответ: вершины приходят по возрастанию стоимости.
    if (r === tr && c === tc) return cost;

    for (let k = 0; k < 4; k++) {
      const nr = r + dr[k];
      const nc = c + dc[k];
      if (nr < 0 || nr >= n || nc < 0 || nc >= m) continue;

      // Стоимость пути — максимум из уже накопленного максимума и веса соседа.
      const nextCost = Math.max(cost, grid[nr][nc]);
      if (nextCost < dist[nr][nc]) {
        dist[nr][nc] = nextCost;
        heap.push([nextCost, nr, nc]);
      }
    }
  }

  // Сетка связна по 4-соседям, поэтому сюда мы попасть не должны.
  return -1;
}

