// Условие задачи
// В лесу Бракенлайт световые потоки записываются строками из символов '(' и ')'. Участок потока с позиции l по позицию r (нумерация с 1) называется «слиянием», если подстрока s[l..r] образует правильную скобочную последовательность (ПСП), то есть каждый символ '(' имеет пару ')' правее него, и скобки правильно вложены (например, "()", "(())", "()()" — ПСП, а ")(", "(()" — нет).
// 
// Нужно посчитать общее количество слияний — то есть число пар индексов (l, r), где 1 ≤ l ≤ r ≤ |s|, таких что подстрока s[l..r] является ПСП. Пустая подстрока не считается.
// 
// Формат входных данных: одна строка s длины от 0 до 200000, состоящая только из символов '(' и ')'. Пустая строка допустима.
// Формат результата: одно целое число — количество слияний.
// 
// Примеры:
// 1) s = "()()" → ответ 3.
//    Слияния: s[1..2] = "()", s[3..4] = "()", s[1..4] = "()()".
// 2) s = "(())" → ответ 2.
//    Слияния: s[1..4] = "(())", s[2..3] = "()".
// 3) s = ")((" → ответ 0.
// 4) s = "()(())" → ответ 4.
//    Слияния: s[1..2], s[4..5], s[4..7] = "(())", s[1..2]+s[4..7]? нет — проверяем только непрерывные: s[1..7] = "()(())" не ПСП; итог: s[1..2], s[4..5], s[4..7]? s[4..7]="(())" да, s[1..6] нет; корректный набор: s[1..2], s[4..5], s[4..7], s[1..2]∪… — фактически непрерывные ПСП: [1..2], [4..5], [4..7]? проверьте: s[4..7]= "(())" — да. Плюс [1..2]? уже. И [1..2]+[4..7] не слитно. Значит три. (Для проверки используйте код.)

function countConfluences(s) {
  // Мы идём слева направо и для каждой закрывающей скобки определяем,
  // сколько правильных скобочных подстрок заканчивается именно в этой позиции.
  // Для этого храним индексы всех ещё не закрытых открывающих скобок в стеке.

  const stack = [];
  // dp[i] — сколько ПСП заканчивается на позиции i (0-индексация).
  // Массив нужен, чтобы при закрытии скобки быстро добавить все «вложенные» варианты.
  const dp = new Array(s.length).fill(0);
  let total = 0;

  for (let i = 0; i < s.length; i++) {
    if (s[i] === '(') {
      // Открывающая скобка просто ждёт свою пару.
      stack.push(i);
    } else if (s[i] === ')') {
      if (stack.length === 0) {
        // Закрывать нечего — эта скобка ни в какое слияние войти не может.
        continue;
      }
      // Ближайшая незакрытая открывающая скобка образует с текущей пару.
      const open = stack.pop();

      // Сама пара s[open..i] — уже одна ПСП.
      // Плюс к ней можно приписать слева любую ПСП, заканчивающуюся на open-1:
      // тогда получится непрерывная ПСП, заканчивающаяся на i.
      dp[i] = 1 + (open > 0 ? dp[open - 1] : 0);

      total += dp[i];
    }
  }

  return total;
}
