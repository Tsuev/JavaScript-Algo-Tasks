// Задача: Rune Cascade Forge
// Сложность: hard
// Дата генерации: 2026-09-18

// Условие задачи
// В Рунной Каскадной Кузнице есть ряд из N рун. Каждая руна обладает силой — целым положительным числом. Вы можете выполнять операцию «каскад»: выбрать две соседние руны с одинаковой силой X и объединить их в одну руну с силой X+1. Эту операцию можно повторять в любом порядке. Каскад означает, что после объединения новая руна может сразу же объединиться с соседней руной той же силы, и так далее, но по сути это просто последовательность операций.
// 
// Ваша задача — получить руну максимально возможной силы. Вы можете остановиться в любой момент. Найдите максимальную силу руны, которую можно получить.
// 
// Формат входных данных:
// Первая строка содержит целое число N (1 ≤ N ≤ 500) — количество рун.
// Вторая строка содержит N целых чисел a_i (1 ≤ a_i ≤ 10^9) — начальные силы рун.
// 
// Формат выходных данных:
// Выведите одно целое число — максимальную силу руны, которую можно получить.
// 
// Пример 1:
// Вход:
// 5
// 3 3 3 3 3
// Выход:
// 5
// Пояснение: Можно объединить четыре руны силы 3 в руну силы 5, оставив пятую руну силы 3. Итоговая максимальная сила — 5.
// 
// Пример 2:
// Вход:
// 3
// 1 2 1
// Выход:
// 2
// Пояснение: Нет двух соседних рун с одинаковой силой, поэтому максимальная сила — 2.
// 
// Пример 3:
// Вход:
// 4
// 3 3 3 3
// Выход:
// 5
// Пояснение: Четыре руны силы 3 можно объединить в одну руну силы 5.

function solve(n, a) {
  // dp[i][j] — сила единой руны, если отрезок i..j можно полностью объединить,
  // иначе -1.
  const dp = Array.from({ length: n }, () => new Array(n).fill(-1));
  let ans = 0;

  // База: отрезок из одной руны.
  for (let i = 0; i < n; i++) {
    dp[i][i] = a[i];
    if (a[i] > ans) ans = a[i];
  }

  // Перебираем длину отрезка.
  for (let len = 2; len <= n; len++) {
    for (let i = 0; i + len - 1 < n; i++) {
      const j = i + len - 1;
      // Ищем точку разбиения k, где левая часть и правая часть
      // объединяются в руны одинаковой силы.
      for (let k = i; k < j; k++) {
        if (dp[i][k] !== -1 && dp[i][k] === dp[k + 1][j]) {
          dp[i][j] = dp[i][k] + 1;
          if (dp[i][j] > ans) ans = dp[i][j];
          break; // нашли одно разбиение — этого достаточно
        }
      }
    }
  }

  return ans;
}
